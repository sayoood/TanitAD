def main() -> int:
    s = SRC.read_text(encoding="utf-8")
    n_hs = s.count("HSGATE8")
    for old, new, n in REPL:
        k = s.count(old)
        want = n_hs if n is None else n
        if k != want:
            raise SystemExit(f"[make_mdfix_verdict] anchor count {k} != {want}: {old[:80]!r}")
        s = s.replace(old, new)
    if "HSGATE8" in s or "REGISTERED_HSGATE" in s.split("def clause1_hsgate", 1)[1].split("def clause1b_hsgate", 1)[0]:
        raise SystemExit("[make_mdfix_verdict] residual HSGATE8 / REGISTERED_HSGATE in clause 1 after the build")
    DST.write_text(s, encoding="utf-8")
    src = SRC.read_text(encoding="utf-8").splitlines(keepends=True)
    (HERE / "ship_r8_mdfix_verdict.DIFF.txt").write_text("".join(difflib.unified_diff(src, s.splitlines(keepends=True), SRC.name, DST.name)), encoding="utf-8")
    print(f"[make_mdfix_verdict] built {DST.name}: {len(REPL)} replacements ({n_hs} HSGATE8 -> MDFIX8)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
