"""make_mdfix_verdict.py -- builds code/ship_r8_mdfix_verdict.py from code/ship_r8_hsgate_verdict.py (LEFT UNTOUCHED) by anchored replacements and writes
ship_r8_mdfix_verdict.DIFF.txt.  PREREG_HSGATE_MDFIX PHASE B (bar G3).  Every anchor must occur the stated number of times or the build refuses.  NEW file."""
import difflib
from pathlib import Path

