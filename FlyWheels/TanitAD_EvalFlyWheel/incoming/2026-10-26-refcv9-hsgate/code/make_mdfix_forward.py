def main() -> int:
    s = SRC.read_text(encoding="utf-8")
    n_hs = s.count("HSGATE8")
    for old, new, n in REPL:
        k = s.count(old)
        want = n_hs if n is None else n
        if k != want:
            raise SystemExit(f"[make_mdfix_forward] anchor count {k} != {want}: {old[:80]!r}")
        s = s.replace(old, new)
    if "HSGATE8" in s or "gate_decide(" in s:
        raise SystemExit("[make_mdfix_forward] residual HSGATE8 / gate_decide after the build")
    DST.write_text(s, encoding="utf-8")
    src = SRC.read_text(encoding="utf-8").splitlines(keepends=True)
    (HERE / "ship_r8_mdfix_forward.DIFF.txt").write_text("".join(difflib.unified_diff(src, s.splitlines(keepends=True), str(SRC.name), str(DST.name))),
                                                          encoding="utf-8")
    print(f"[make_mdfix_forward] built {DST.name}: {len(REPL)} replacements ({n_hs} HSGATE8 -> MDFIX8)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
