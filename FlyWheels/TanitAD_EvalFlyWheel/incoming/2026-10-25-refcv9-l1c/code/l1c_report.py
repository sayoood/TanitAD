"""l1c_report.py -- writes RESULT.md MECHANICALLY from result/{VERDICT.json, L1C_RESULT.json, L1C_NEXT.json, L1C_ROC.json} (no judgement, no new numbers).
    python -X utf8 l1c_report.py <result_dir> <out RESULT.md>
Every number is copied from an artifact; the artifact paths are named.  Evidence class MEASURED (ours); tier T1 (open loop on logged eval139 frames); estimator: paired
episode-cluster bootstrap B 2000 (answers 'another draw of EPISODES' only; ONE training seed; inference-seed floor applies).
"""
import json
import sys
from pathlib import Path

d, out = Path(sys.argv[1]), Path(sys.argv[2])
V = json.loads((d / "VERDICT.json").read_text(encoding="utf-8"))
R = json.loads((d / "L1C_RESULT.json").read_text(encoding="utf-8"))
N = json.loads((d / "L1C_NEXT.json").read_text(encoding="utf-8")) if (d / "L1C_NEXT.json").exists() else None
ROC = json.loads((d / "L1C_ROC.json").read_text(encoding="utf-8")) if (d / "L1C_ROC.json").exists() else None
S2 = R["surfaces"]["S2"]


def f(c):
    if not c or c.get("delta") is None:
        return "n/a"
    s = " SEP" if (c["lo"] > 0 or c["hi"] < 0) else ""
    return f"{c['delta']:+.4f} [{c['lo']:+.4f}, {c['hi']:+.4f}]{s}"


P = R["population"]
L = ["# RESULT - refcv9 L1C: the progress head fitted on a CLEAN calibration split (generated by code/l1c_report.py from result/*.json)", "",
     f"**Outcome: {V['outcome']}**", "",
     f"* controls: {json.dumps(V['controls'])}  (valid = {V['valid']})",
     f"* bars: {json.dumps(V['bars'])}; four-family rows worse at both seeds: {V['guard_worse_at_both_seeds']}; braking AUC H2c vs H0: {V['braking_auc_H2c_vs_H0']}",
     f"* branch: {R['branch']}; tier T1 (open loop, logged eval139 frames); estimator: paired episode-cluster bootstrap, B 2000, episodes only (models fixed); ONE training seed; "
     f"inference-seed floor |{V['inference_seed_floor_os_m']:.4f}| m", "",
     "## Population (artifact: result/L1C_RESULT.json)", "",
     f"* fresh calibration split: {P['n_ids_split']} clips (rig A {P['rig_counts']['A']} / B {P['rig_counts']['B']}; r0-passing {P['r0_pass']}); clips in tree {P['fresh_clips_in_tree']}; "
     f"S2 rows all {P['fresh_rows_all_S2']} / compliant {P['fresh_rows_compliant_S2']} ({P['fresh_episodes_compliant_S2']} episodes); S6 rows all {P['fresh_rows_all_S6']} / compliant {P['fresh_rows_compliant_S6']}",
     f"* eval139 S2 compliant: {json.dumps(P['eval_S2'])}", "",
     "## S2 compliant, ADE minus the human-anchored pose prior (E1) and the pairs", "", "| arm | E1 s0 | E1 s1 |", "|---|---|---|"]
for a in S2["seeds"]["0"]["E1_minus_ha0_ext_pose"]:
    L.append(f"| {a} | {f(S2['seeds']['0']['E1_minus_ha0_ext_pose'][a])} | {f(S2['seeds']['1']['E1_minus_ha0_ext_pose'][a])} |")
L += ["", "| pair (ADE) | s0 | s1 |", "|---|---|---|"]
for p in S2["seeds"]["0"]["paired"]:
    L.append(f"| {p} | {f(S2['seeds']['0']['paired'][p])} | {f(S2['seeds']['1']['paired'][p])} |")
for p in ("H2c-H0", "H2c-H2cs"):
    L += ["", f"four families, {p} (S2; distance keeping and strategic state n = 0: no lead-agent / route label on this surface)", "", "| metric | s0 | s1 |", "|---|---|---|"]
    for k in S2["seeds"]["0"]["four_families"][p]:
        L.append(f"| {k} | {f(S2['seeds']['0']['four_families'][p][k])} | {f(S2['seeds']['1']['four_families'][p][k])} |")
L += ["", f"fit: H2c k={S2['fit']['H2c']['k']} lambda={S2['fit']['H2c']['lambda']} n={S2['fit']['H2c']['n']} episodes={S2['fit']['H2c']['n_episodes']}; "
      f"H2cs lambda={S2['fit']['H2cs']['lambda']}", "",
      f"## D-fresh {json.dumps(V['D_fresh'])}  |  D-platform {json.dumps(V['D_platform'], default=str)}", ""]
if R["D_fresh"].get("speed_v0_ms"):
    L.append(f"speed v0 (m/s) fresh {json.dumps(R['D_fresh']['speed_v0_ms']['fresh'])} vs eval139 {json.dumps(R['D_fresh']['speed_v0_ms']['eval139'])}; share above 14 m/s {json.dumps(R['D_fresh']['frac_v0_gt_14ms'])}")
if S2.get("sensitivity"):
    L += ["", "## Sensitivities (BESIDE; no bar)", "", "| subset | n rows | k | H2c-H2cs s0 | H2c-H2cs s1 | H2c-H0 s0 | H2c-H0 s1 |", "|---|---|---|---|---|---|---|"]
    for nm, v in S2["sensitivity"].items():
        if "skipped" in v:
            L.append(f"| {nm} | skipped: {v['skipped']} | | | | | |")
        else:
            L.append(f"| {nm} | {v['n_rows']} | {v['k']} | {f(v['seeds']['0']['H2c-H2cs'])} | {f(v['seeds']['1']['H2c-H2cs'])} | {f(v['seeds']['0']['H2c-H0'])} | {f(v['seeds']['1']['H2c-H0'])} |")
if ROC is not None:
    L += ["", "## Braking AUC (S6 compliant; l2_roc.py unchanged) seed 0 / seed 1", "", "| arm | AUC s0 | AUC s1 |", "|---|---|---|"]
    for a in ROC["seeds"]["0"]["auc"]:
        L.append(f"| {a} | {ROC['seeds']['0']['auc'][a]:.4f} | {ROC['seeds']['1']['auc'][a]:.4f} |")
    L += ["", f"readings (vs H0 / vs H2cs): H2c {ROC['readings'].get('L1C_H2c')}; H2cs {ROC['readings'].get('L1C_H2cs')}"]
if N is not None:
    L += ["", "## Next-lever arms (EXPLORATORY; A2.8) - artifact result/L1C_NEXT.json", "", f"N1 H2cn (MLP on the fresh rows): {json.dumps(N['N1_H2n_fit'])}", "",
          "| pair (ADE) | s0 | s1 |", "|---|---|---|"]
    for p in N["seeds"]["0"]["paired"]:
        L.append(f"| {p} | {f(N['seeds']['0']['paired'][p])} | {f(N['seeds']['1']['paired'][p])} |")
    L += ["", "N2 POOL = cross-fit on eval episodes with the fresh rows added to every fold (POST-HOC, no bar: needs its own pre-registration before it is quoted)."]
L += ["", "## Next lever (A2.8, mapped mechanically from the outcome)", ""]
o = V["outcome"]
if o.startswith("O1"):
    L.append("- SHIP-R8 battery request on the upgraded stage (needs the PI's go); refcv9 design: progress head + a reserved clean calibration split.")
elif o.startswith("O2"):
    L.append("- the nonlinear head (N1 above) fitted on the same split, then the learning-curve-implied number of further fresh clips (sensitivity block).")
elif o.startswith("O3"):
    L.append("- D-fresh flagged: draw a distribution-matched fresh split (rig / speed matched, same universe); not flagged: close L1 for refcv8 and carry the progress head to the refcv9 design as a calibrated-split object.")
else:
    L.append("- the failing control is the next lever (see controls above).")
L += ["", "Artifacts: result/VERDICT.json, result/VERDICT_TABLES.md, result/L1C_RESULT.json, result/L1C_ROC.json, result/L1C_NEXT.json, result/arms_S{2,6}_s{0,1}.npz; banks and caches on F:/l1c (bank/, tree/, kit_fresh/)."]
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", out)
