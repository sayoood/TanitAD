def sha256_file(p) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def load_mbr(x8_dir: str):
    p = os.path.join(x8_dir, "fan_mbr_x8.py")
    if sha256_file(p) != MBR_X8_SHA256:
        raise SystemExit(f"[pk] {p} is not the frozen fan_mbr_x8.py ({MBR_X8_SHA256[:12]}...)")
    if x8_dir not in sys.path:
        sys.path.insert(0, x8_dir)
    spec = importlib.util.spec_from_file_location("fan_mbr_x8", p)
    m = importlib.util.module_from_spec(spec)
    sys.modules["fan_mbr_x8"] = m
    spec.loader.exec_module(m)
    return m


# ------------------------------------------------------------------------------------------ pickers (pure)
def picks_from_capture(z, MB) -> dict:
    """z = the capture npz (fan_extras.npz of fan_roll_r8_pk.py).  Returns {arm: sel [N] int64} + the plans and the membership flags."""
    fan = np.asarray(z["anchor_traj"], np.float32)
    n = fan.shape[0]
    ar = np.arange(n)
    own = np.asarray(z["sel_idx"]).astype(np.int64).reshape(-1)
    base = np.asarray(z["sel_idx_base"]).astype(np.int64).reshape(-1)
    keep = np.asarray(z["e9_keep"]).astype(bool)
    s = np.asarray(z[FROZEN_CELL[0]], np.float64)
    s = np.where(np.isfinite(s), s, -1e30)
    mbr = MB.mbr_pick(fan[:, :, :4].astype(np.float64), np.where(keep, s, -1e30), FROZEN_CELL[1], FROZEN_CELL[2])
    sel = {"ship": own, "base": base, "mbr32": np.asarray(mbr, np.int64)}
    out = {"sel": sel, "plan": {k: fan[ar, v] for k, v in sel.items()},
           "in_e9_keep": {k: keep[ar, v] for k, v in sel.items()},
           "K3a_ship_plan_minus_traj_max_abs_m": float(np.abs(fan[ar, own] - np.asarray(z["traj"], np.float32)).max()),
           "base_plan_minus_traj_base_max_abs_m": (float(np.abs(fan[ar, base] - np.asarray(z["traj_base"], np.float32)).max())
                                                   if "traj_base" in z.files else None),
           "n_e9_keep_lt_32": int((keep.sum(1) < FROZEN_CELL[1]).sum()), "e9_keep_count_min": int(keep.sum(1).min())}
    return out


# ------------------------------------------------------------------------------------------ npz io
def _load_all(f):
    z = np.load(f, allow_pickle=True)
    return {k: z[k] for k in z.files}


def _save_all(f, d: dict):
    tmp = str(f) + ".tmp.npz"
    np.savez_compressed(tmp, **d)
    os.replace(tmp, f)


def _eq(a, b) -> bool:
    if a.dtype != b.dtype or a.shape != b.shape:
        return False
    if a.dtype.kind == "f":
        return bool(np.array_equal(a, b, equal_nan=True))
    if a.dtype.kind == "O":
        return bool(all(np.array_equal(x, y) for x, y in zip(a.ravel(), b.ravel())))
    return bool(np.array_equal(a, b))


# ------------------------------------------------------------------------------------------ the splice
def splice_tree(bank: str, dst: str, plans: dict, label: str) -> dict:
    """plans = {seed: {"clip": [N], "ws": [N], "plan8": [N, 8, 2] float32, "sel": [N] int64}}.  Writes dst; returns a manifest."""
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(bank, dst)
    deleted = []
    for f in sorted(os.listdir(dst)):
        if os.path.isfile(os.path.join(dst, f)) and any(fnmatch.fnmatch(f, p) for p in ROOT_DELETE):
            os.remove(os.path.join(dst, f))
            deleted.append(f)
    rec = {"label": label, "bank": bank, "dst": dst, "root_deleted": deleted, "seeds": {}}
    for s, P in plans.items():
        key = {(int(c), int(w)): i for i, (c, w) in enumerate(zip(P["clip"], P["ws"]))}
        if len(key) != len(P["clip"]):
            raise SystemExit(f"[pk] {label} s{s}: duplicate (clip, ws) in the plan rows")
        srec = {"n_plan_rows": len(key), "files": {}, "joined": 0}
        # extras
        ef = os.path.join(dst, f"dump_s{s}", "refcv6_extras.npz")
        E = _load_all(ef)
        rows = np.asarray([key[(int(c), int(w))] for c, w in zip(E["clip_index"], E["ws"])], np.int64)   # KeyError = a window that does not join
        if len(rows) != len(key) or len(set(rows.tolist())) != len(rows):
            raise SystemExit(f"[pk] {label} s{s}: extras windows {len(rows)} do not join 1:1 with the plan rows {len(key)}")
        E["nav_true.traj"] = P["plan8"][rows].astype(E["nav_true.traj"].dtype)
        E["nav_true.sel_idx"] = P["sel"][rows].astype(E["nav_true.sel_idx"].dtype)
        _save_all(ef, E)
        srec["joined"] = int(len(rows))
        for pat in SURF_DIRS:
            d = os.path.join(dst, pat.format(s=s))
            slots = [int(x) for x in json.load(open(os.path.join(d, "manifest.json"), encoding="utf-8"))["grid"]["slots"]]
            nf, nw = 0, 0
            for f in sorted(glob.glob(os.path.join(d, "ep*.npz"))):
                A = _load_all(f)
                c = int(np.asarray(A["clip_index"]).ravel()[0])
                r = np.asarray([key[(c, int(w))] for w in np.asarray(A["ws"]).ravel()], np.int64)
                A["os"] = P["plan8"][r][:, slots].astype(A["os"].dtype)
                _save_all(f, A)
                df = os.path.join(d, "decisions", os.path.basename(f))
                D = _load_all(df)
                if not np.array_equal(np.asarray(D["ws"]).ravel(), np.asarray(A["ws"]).ravel()):
                    raise SystemExit(f"[pk] {df}: decisions ws != panel ws")
                D["plan_full_nav_true"] = P["plan8"][r].astype(D["plan_full_nav_true"].dtype)
                for k in ("sel_idx_nav_true", "sel_idx"):
                    if k in D:
                        D[k] = P["sel"][r].astype(D[k].dtype)
                _save_all(df, D)
                nf += 1
                nw += len(r)
            srec["files"][pat.format(s=s)] = {"n_files": nf, "n_windows": nw, "slots": slots}
        rec["seeds"][str(s)] = srec
    rec["spliced_fields"] = ["os (dump/panel/s6 ep*.npz, manifest slots)", "decisions: plan_full_nav_true, sel_idx_nav_true, sel_idx",
                             "dump extras: nav_true.traj, nav_true.sel_idx"]
    json.dump(rec, open(os.path.join(dst, f"SPLICE_{os.path.basename(dst)}.json"), "w", encoding="utf-8"), indent=1)
    return rec


def compare_trees(a: str, b: str) -> dict:
    """Every npz under a (recursively) against b: per-array equality.  Returns the differing (file, key) pairs."""
    diff, n_files, n_arrays, missing = [], 0, 0, []
    for f in sorted(glob.glob(os.path.join(a, "**", "*.npz"), recursive=True)):
        rel = os.path.relpath(f, a)
        g = os.path.join(b, rel)
        if not os.path.exists(g):
            missing.append(rel)
            continue
        A, B = _load_all(f), _load_all(g)
        n_files += 1
        if set(A) != set(B):
            diff.append((rel, "KEYSET"))
        for k in A:
            if k in B:
                n_arrays += 1
                if not _eq(A[k], B[k]):
                    diff.append((rel, k))
    return {"n_files": n_files, "n_arrays": n_arrays, "missing_in_b": missing, "differing": diff}


def bank_plans(bank: str) -> dict:
    out = {}
    for s in (0, 1):
        E = np.load(os.path.join(bank, f"dump_s{s}", "refcv6_extras.npz"))
        out[s] = {"clip": E["clip_index"].astype(np.int64), "ws": E["ws"].astype(np.int64),
                  "plan8": E["nav_true.traj"].astype(np.float32), "sel": E["nav_true.sel_idx"].astype(np.int64)}
    return out


def cmd_identity(a) -> int:
    t0 = time.time()
    plans = bank_plans(a.bank)
    dst = os.path.join(a.archive, TREE_OF_ARM["identity"])
    rec = splice_tree(a.bank, dst, plans, "identity")
    cmp_id = compare_trees(a.bank, dst)
    mplans = {s: {k: v.copy() for k, v in p.items()} for s, p in plans.items()}
    mplans[0]["plan8"][0, :, 0] += 1.0                      # DELIBERATE REGRESSION: window 0 of seed 0, +1 m in x at every slot
    mdst = os.path.join(a.archive, TREE_OF_ARM["mutation"])
    splice_tree(a.bank, mdst, mplans, "mutation")
    cmp_mu = compare_trees(a.bank, mdst)
    shutil.rmtree(mdst)
    c0, w0 = int(plans[0]["clip"][0]), int(plans[0]["ws"][0])
    expect_mut = {"dump_s0/refcv6_extras.npz:nav_true.traj"}
    got_mut = {f"{f.replace(os.sep, '/')}:{k}" for f, k in cmp_mu["differing"]}
    out = {"tool": "build_picker_trees.py identity", "prereg_sha256": PREREG_SHA256, "addendum1_sha256": ADDENDUM1_SHA256,
           "generated": time.strftime("%FT%T%z"), "bank": a.bank, "identity_tree": dst, "splice": rec,
           "K8_identity": {"n_files": cmp_id["n_files"], "n_arrays": cmp_id["n_arrays"], "missing": cmp_id["missing_in_b"],
                           "differing": cmp_id["differing"], "PASS": bool(not cmp_id["differing"] and not cmp_id["missing_in_b"] and cmp_id["n_files"] > 0)},
           "K8_mutation": {"window": {"seed": 0, "clip_index": c0, "ws": w0, "change": "+1.0 m in x at all 8 slots"},
                           "differing": sorted(got_mut), "n_differing": len(got_mut),
                           "DETECTED": bool(expect_mut <= got_mut and any(":os" in x for x in got_mut) and any(":plan_full_nav_true" in x for x in got_mut))},
           "wall_s": round(time.time() - t0, 1)}
    out["K8_PASS"] = bool(out["K8_identity"]["PASS"] and out["K8_mutation"]["DETECTED"])
    json.dump(out, open(a.out_json, "w", encoding="utf-8"), indent=1, default=str)
    print(f"K8 identity PASS={out['K8_identity']['PASS']} ({cmp_id['n_files']} files, {cmp_id['n_arrays']} arrays) mutation DETECTED="
          f"{out['K8_mutation']['DETECTED']} ({len(got_mut)} arrays) {'ZZPKK8PASSZZ' if out['K8_PASS'] else 'ZZPKK8FAILZZ'}", flush=True)
    return 0 if out["K8_PASS"] else 4


def cmd_build(a) -> int:
    t0 = time.time()
    MB = load_mbr(a.x8_dir)
    fans = dict(x.split("=", 1) for x in a.fan)
    arms = [x for x in a.arms.split(",") if x]
    plans = {arm: {} for arm in arms}
    picks_rec = {}
    for sk, path in sorted(fans.items()):
        s = int(sk.lstrip("s"))
        z = np.load(path, allow_pickle=True)
        P = picks_from_capture(z, MB)
        ci, ws = np.asarray(z["clip_index"], np.int64), np.asarray(z["ws"], np.int64)
        np.savez_compressed(os.path.join(a.archive, f"PICKS_s{s}.npz"), clip_index=ci, ws=ws,
                            **{f"sel_{k}": v for k, v in P["sel"].items()}, **{f"in_e9_{k}": v for k, v in P["in_e9_keep"].items()})
        picks_rec[str(s)] = {"fan": path, "fan_sha256": sha256_file(path), "n_windows": int(len(ci)),
                             "K3a_ship_plan_minus_traj_max_abs_m": P["K3a_ship_plan_minus_traj_max_abs_m"],
                             "base_plan_minus_traj_base_max_abs_m": P["base_plan_minus_traj_base_max_abs_m"],
                             "n_windows_e9_keep_lt_32": P["n_e9_keep_lt_32"], "e9_keep_count_min": P["e9_keep_count_min"],
                             "agree_with_ship": {k: float((v == P["sel"]["ship"]).mean()) for k, v in P["sel"].items()},
                             "pick_outside_e9_keep_frac": {k: float((~v).mean()) for k, v in P["in_e9_keep"].items()}}
        for arm in arms:
            plans[arm][s] = {"clip": ci, "ws": ws, "plan8": P["plan"][arm].astype(np.float32), "sel": P["sel"][arm]}
    trees = {}
    for arm in arms:
        dst = os.path.join(a.archive, TREE_OF_ARM[arm])
        trees[arm] = splice_tree(a.bank, dst, plans[arm], arm)
    out = {"tool": "build_picker_trees.py build", "prereg_sha256": PREREG_SHA256, "addendum1_sha256": ADDENDUM1_SHA256,
           "generated": time.strftime("%FT%T%z"), "frozen_cell": list(FROZEN_CELL), "fan_mbr_x8_sha256": MBR_X8_SHA256,
           "picks": picks_rec, "trees": trees, "script_sha256": sha256_file(__file__), "wall_s": round(time.time() - t0, 1)}
    json.dump(out, open(a.out_json, "w", encoding="utf-8"), indent=1, default=str)
    print("BUILT", {k: v["dst"] for k, v in trees.items()}, "ZZPKBUILDOKZZ", flush=True)
    return 0


