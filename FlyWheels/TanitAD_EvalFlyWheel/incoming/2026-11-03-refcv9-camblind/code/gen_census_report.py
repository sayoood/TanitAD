"""gen_census_report.py -- regenerate CENSUS_AND_IDENTITY.md (the census table with its resolved file:line pins, and the identity table with its exact values).

    CUDA_VISIBLE_DEVICES=-1 PYTHONPATH='<tree>/stack;<tree>/stack/scripts;<tree>/taniteval;<tree>/stack/tests' \
        python gen_census_report.py <tree>/stack <out.md>

Runs the SAME rig, sweeps and instruments as stack/tests/test_camblind_r9.py (it imports that module's fixture builder), on CPU, in ~10 s.
"""
from __future__ import annotations

import sys
from pathlib import Path

import torch

import test_camblind_r9 as T
from tanitad.eval import camblind_r9 as CB


def _rows_md(rows, donor=False):
    head = "| key | class | pixel-derived | d(planner output) | d(any planner tap) | taps that moved |\n|---|---|---|---|---|---|\n"
    out = []
    for r in rows:
        out.append("| `%s` | %s | %s | %r | %r | %s |" % (r["key"], r["cls"], "yes" if r.get("pixel_derived", True) else "no", r["max_plan"], r["max_all"],
                                                       ", ".join(k for k, v in r["taps"].items() if v["max_abs"] > 0) or "-"))
    return head + "\n".join(out)


def main(stack_root, out_path):
    rig = T._build_rig()
    m, b, d, keys = rig["model"], rig["batch"], rig["donor"], rig["keys"]
    _, ok_rows, hooked = CB.identity_sweep(m, b, d, instrument=T.CORRECT, keys=keys, ports=T._ports, census=T.SYN)
    _, mut_rows, _ = CB.identity_sweep(m, b, d, instrument=T.PIXELS_ONLY, keys=keys, ports=T._ports, census=T.SYN)
    don = CB.donor_sweep(m, b, d, instrument=T.CORRECT, keys=["frames", *T.SIDECARS], ports=T._ports, census=T.SYN)
    for r in don:
        r["pixel_derived"] = True
    drop = {}
    for dropped in ("frames", "bev_sidecar", "box_sidecar"):
        sw = tuple(k for k in ("frames", "future_frames", *T.SIDECARS) if k != dropped)
        _, rows, _ = CB.identity_sweep(m, b, d, keys=["frames", *T.SIDECARS, "map_fine"], ports=T._ports, census=T.SYN,
                                       instrument=lambda o, dd, sw=sw: CB.swap_item(o, dd, census=T.SYN, swap_keys=sw))
        drop[dropped] = CB.violations(rows)
    md = ["# C9 census and sensitivity identity (generated by gen_census_report.py; tiny rig, CPU)", "",
          "census sha256 `%s`; CAMERA item keys `%s`; CAMERA model inputs `%s`; CAMERA argv flags `%s`" % (
              CB.census_sha256(), list(CB.camera_keys("item")), list(CB.camera_keys("model_input")), list(CB.camera_keys("argv"))), "",
          "## 1. Census (every dataset-item key, model-forward input and path-valued argv flag; pins resolved against the tree)", "",
          CB.render_census_md(stack_root), "",
          "## 2. Identity: perturb the window's OWN key alone; taps = %s" % sorted(hooked), "",
          "### 2a. CORRECT instrument (every CAMERA key from the donor) -- violations: %s" % (CB.violations(ok_rows) or "none"), "", _rows_md(ok_rows), "",
          "### 2b. MUTATION: swap pixels only (`frames`, `future_frames`) -- violations: %s" % CB.violations(mut_rows), "", _rows_md(mut_rows), "",
          "### 2c. CONTROL: perturb the DONOR's camera under the correct instrument (must move the planner)", "", _rows_md(don), "",
          "### 2d. RED: drop ONE camera key from the swap -> the identity names it", ""]
    md += ["- dropped `%s` -> %s" % (k, v) for k, v in drop.items()]
    Path(out_path).write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", out_path, len(md), "lines; violations ok/mut:", len(CB.violations(ok_rows)), len(CB.violations(mut_rows)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
