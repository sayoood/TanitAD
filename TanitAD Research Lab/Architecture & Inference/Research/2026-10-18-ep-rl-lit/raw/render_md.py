# -*- coding: utf-8 -*-
"""Renders the markdown tables embedded in REPORT.md from published_rows.py + rl_step_deltas.csv (so no number is retyped by hand)."""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from published_rows import R  # noqa: E402

BY = {r["id"]: r for r in R}


def f(v, k):
    x = v.get(k)
    if x is None:
        return "n/p"
    return ("%.2f" % x) if abs(x * 100 - round(x * 100)) > 1e-9 and False else (("%g" % x) if k != "EPDMS" else "%g" % x)


def row(i, label=None):
    r = BY[i]
    v = r["values"]
    cells = [f(v, k) for k in ("NC", "DAC", "TTC", "C", "EP", "PDMS")]
    tag = "" if r["check"] == "auto" else " (manual)"
    return "| %s | %s | %s Tab. %s p%s%s |" % (label or r["row"], " | ".join(cells), r["paper"], r["table"], r["pdf_page"], tag)


Q1 = [
    ("dz_a13_dinov3L", "DriveZero, DINOv3 ViT-L, 4 cams (THE TARGET)"),
    ("dz_t4_human", "Human driver log replay (DriveZero Tab. 4)"),
    ("drivor_train", "DrivoR, navtrain only"),
    ("drivor_trainval", "DrivoR, navtrain+navval"),
    ("drivor_sim134", "DrivoR, +134k SimScale"),
    ("clover", "CLOVER"),
    ("rap_dino", "RAP-DINO"),
    ("flowr2a", "FlowR2A, ResNet-34"),
    ("sdv2", "SparseDriveV2, ResNet-34"),
    ("ipad", "iPad, ResNet-34"),
    ("suprim_vitl", "DriveSuprim, ViT-L"),
    ("suprim_vitl_base", "Hydra-MDP, ViT-L (DriveSuprim's baseline row)"),
    ("hydrapp_v299", "Hydra-MDP++, V2-99"),
    ("wote", "WoTE (contrast: EP not high)"),
    ("toad_gtrs0", "GTRS (row quoted via TOAD; GTRS PDF not read)"),
    ("toad_ztrs0", "ZTRS (row quoted via TOAD; ZTRS PDF not read)"),
]
Q1B = [
    ("dz_t7_human", "ViT-S, human-trajectory supervision"),
    ("dz_t7_driverl", "ViT-S, DriveRL-teacher trajectories"),
    ("dz_t7_goalaug", "ViT-S, teacher trajectories + goal augmentation"),
]
Q1C = [
    ("hydra_w", "Hydra-MDP-V8192, no weighted confidence"),
    ("hydra_W", "  + weighted confidence W (inference rule)"),
    ("hydra_WEP", "  + continuous EP head"),
    ("hydra_PDM", "  distil only the aggregate PDM score (-PDM)"),
    ("ipad_abl_noprof", "iPad ablation: no proposal anchoring (NC DAC TTC EP only)"),
    ("ipad_abl_prof", "iPad ablation: + ProFormer proposal-anchored encoder (NC DAC TTC EP only)"),
]
H = "| row | NC | DAC | TTC | C | EP | PDMS | source |\n|---|---|---|---|---|---|---|---|\n"
out = []
out.append("<!-- TABLE Q1: generated by raw/render_md.py from raw/published_rows.py; n/p = not printed in that table -->\n" + H + "\n".join(row(i, l) for i, l in Q1) + "\n")
out.append("<!-- TABLE Q1B -->\n" + H + "\n".join(row(i, l) for i, l in Q1B) + "\n")
out.append("<!-- TABLE Q1C -->\n" + H + "\n".join(row(i, l) for i, l in Q1C) + "\n")

rows = list(csv.DictReader(open(os.path.join(HERE, "rl_step_deltas.csv"), encoding="utf-8")))
H2 = "| step | updates | dNC | dDAC | dTTC | dC | dEP | dPDMS | verdict (rule in make_tables.py) |\n|---|---|---|---|---|---|---|---|---|\n"


def c(x):
    return x if x != "" else "n/p"


body = []
for r in rows:
    pd = r["dPDMS"] if r["dPDMS"] != "" else (("EPDMS " + r["dEPDMS"]) if r["dEPDMS"] != "" else "")
    body.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (r["step"], r["updated"], c(r["dNC"]), c(r["dDAC"]), c(r["dTTC"]), c(r["dC"]), c(r["dEP"]), c(pd), r["verdict"]))
out.append("<!-- TABLE Q2 -->\n" + H2 + "\n".join(body) + "\n")
rows = list(csv.DictReader(open(os.path.join(HERE, "testtime_and_scorer_only_deltas.csv"), encoding="utf-8")))
body = []
for r in rows:
    body.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (r["step"], r["kind"], c(r["dNC"]), c(r["dDAC"]), c(r["dTTC"]), c(r["dC"]), c(r["dEP"]), c(r["dPDMS"]), r["verdict"]))
H3 = "| step | kind | dNC | dDAC | dTTC | dC | dEP | dPDMS | verdict |\n|---|---|---|---|---|---|---|---|---|\n"
out.append("<!-- TABLE Q2B -->\n" + H3 + "\n".join(body) + "\n")
with open(os.path.join(HERE, "tables_rendered.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print("\n".join(out))
