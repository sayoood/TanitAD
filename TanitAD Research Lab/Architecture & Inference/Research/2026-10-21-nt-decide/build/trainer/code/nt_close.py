#!/usr/bin/env python3
"""Close the refcv8-nt gate profile's two open items in a TREE, mechanically, for the Master Mind's literal review.

    python nt_close.py --tree <tree root (stack/ inside)> --v9-md5 <32 hex: logs/V9_MD5_FINAL> --b1 keep|drop \
        --clock-reference <labels/a1/nt_clock_reference_a1.json> --paths <paths_thor_a1.json> \
        [--base <refcv8-r101-s0.argv.json, the COMMITTED bytes>] [--ack-dir <dir holding AMENDMENT_ACK_NT.txt>]

What it writes (and nothing else):
  * ``stack/scripts/launch_gate.py``: ``_NT_V9_MD5`` = the md5 literal (closes NT-CORPUS) and ``_NT_B1_GUARD`` = the
    decision (closes NT-B1-GUARD) -- two constants, each replaced exactly once;
  * ``stack/ops/runs.d/nt-a1-s0.argv.json`` + ``nt-a1r-s1.argv.json``: regenerated by ``nt_argv.py a1`` with the md5
    and the B1 decision (the SAME generator that wrote them; the argv sha changes, so the G-MAP/G-BOX binding records
    must be produced AFTER this);
  * ``stack/tanitad/configs/refcv8_nt/nt_clock_reference_a1.json``: the clock reference, validated first by the
    GATE'S OWN loader (``launch_gate.load_clock_reference``) -- the consumer, not this tool's reading of the schema.
Then it ASSERTS, in a fresh interpreter importing the edited tree: the profile has NO open items, and
``profile_argv_rules`` refuses NEITHER committed A1 argv. The verdict is the printed JSON (``CLOSED`` true/false).
Refuses: a non-32-hex md5, an unknown B1 value, a clock reference the gate cannot load, a constant already closed to a
DIFFERENT value, and a tree whose constants do not appear exactly once."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
MD5_RE = re.compile(r"^[0-9a-f]{32}$")


class Refused(SystemExit):
    pass


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def _probe(tree: Path, code: str, *args: str) -> dict:
    """Run ``code`` in a FRESH interpreter that imports the tree's own launch_gate; it prints one JSON line."""
    env = dict(os.environ, PYTHONPATH=os.pathsep.join([str(tree / "stack"), str(tree / "stack" / "scripts")]),
               PYTHONIOENCODING="utf-8")
    r = subprocess.run([sys.executable, "-c", code, *args], capture_output=True, text=True, env=env, timeout=600)
    lines = [l for l in r.stdout.splitlines() if l.startswith("{")]
    if r.returncode != 0 or not lines:
        raise Refused(f"[nt-close] probe failed (rc {r.returncode}): {r.stderr[-600:]}")
    return json.loads(lines[-1])


def _set_const(src: str, name: str, new_literal: str, pending_literal: str) -> tuple[str, str]:
    pat = re.compile(rf"^({re.escape(name)}(?:: [^=\n]+)? = )(.+)$", re.M)
    hits = pat.findall(src)
    if len(hits) != 1:
        raise Refused(f"[nt-close] {name} appears {len(hits)} times in launch_gate.py (expected exactly 1)")
    cur = hits[0][1].strip()
    if cur not in (pending_literal, new_literal):
        raise Refused(f"[nt-close] {name} is already closed to {cur}, not {new_literal}: a re-closure is a review")
    return pat.sub(lambda m: m.group(1) + new_literal, src, count=1), cur


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tree", required=True)
    ap.add_argument("--v9-md5", required=True)
    ap.add_argument("--b1", required=True, choices=("keep", "drop"))
    ap.add_argument("--clock-reference", required=True)
    ap.add_argument("--paths", required=True)
    ap.add_argument("--base", default=None, help="refcv8-r101-s0.argv.json as COMMITTED (default: the tree's own)")
    ap.add_argument("--ack-dir", default=None, help="map /home/nvidia/r8ns/nt/inputs here for the final probe")
    a = ap.parse_args(argv)
    tree = Path(a.tree).resolve()
    md5 = a.v9_md5.strip().lower()
    if not MD5_RE.match(md5):
        raise Refused(f"[nt-close] --v9-md5 {a.v9_md5!r} is not 32 hex characters")
    gate = tree / "stack/scripts/launch_gate.py"
    runs_d = tree / "stack/ops/runs.d"
    cref_dst = tree / "stack/tanitad/configs/refcv8_nt/nt_clock_reference_a1.json"
    base = Path(a.base) if a.base else runs_d / "refcv8-r101-s0.argv.json"
    for p in (gate, base, Path(a.clock_reference), Path(a.paths)):
        if not p.is_file():
            raise Refused(f"[nt-close] missing input: {p}")
    # 1. the clock reference, read by the GATE'S OWN loader (the consumer)
    cl = _probe(tree, "import json,sys; import launch_gate as L; ref, prov = L.load_clock_reference([sys.argv[1]]); "
                      "print(json.dumps({'n': len(ref), 'prov': str(prov)[:300]}))", str(Path(a.clock_reference)))
    if int(cl["n"]) <= 0:
        raise Refused(f"[nt-close] the gate's load_clock_reference read 0 clips from {a.clock_reference}")
    # 2. the two constants
    raw = gate.read_bytes()
    crlf = b"\r\n" in raw
    src = raw.decode("utf-8").replace("\r\n", "\n")
    src, was_md5 = _set_const(src, "_NT_V9_MD5", json.dumps(md5), "_NT_PENDING")
    src, was_b1 = _set_const(src, "_NT_B1_GUARD", json.dumps(a.b1), "None")
    out_b = src.encode("utf-8")
    if crlf:
        out_b = out_b.replace(b"\n", b"\r\n")
    gate.write_bytes(out_b)
    # 3. the argvs, by the generator that wrote them
    paths = json.loads(Path(a.paths).read_text(encoding="utf-8"))
    paths["--r8-v9-md5"] = md5
    with tempfile.TemporaryDirectory() as td:
        pj = Path(td) / "paths_closed.json"
        pj.write_text(json.dumps(paths, indent=1), encoding="utf-8")
        r = subprocess.run([sys.executable, str(HERE / "nt_argv.py"), "a1", "--paths", str(pj), "--b1", a.b1,
                            "--base", str(base), "--out", str(runs_d)], capture_output=True, text=True, timeout=300)
        if r.returncode != 0:
            raise Refused(f"[nt-close] nt_argv.py failed: {r.stderr[-600:]}")
    # 4. the clock reference into the tree (the profile's clock_reference names this path)
    shutil.copyfile(a.clock_reference, cref_dst)
    # 5. the assertion, in a fresh interpreter on the EDITED tree
    pmap = json.dumps([["/home/nvidia/r8ns/nt/inputs", str(Path(a.ack_dir).resolve())]] if a.ack_dir else [])
    chk = _probe(tree, (
        "import json,sys; import launch_gate as L; p = L.PROFILES['refcv8-nt']; "
        "tau = sys.argv[1]; pm = [tuple(x) for x in json.loads(sys.argv[2])]; out = {}; "
        "out['open_items'] = [it['id'] for it in p['open_items']]; "
        "out['v9_md5'] = L._NT_V9_MD5; out['b1'] = L._NT_B1_GUARD; "
        "out['refusals'] = {n: L.profile_argv_rules(p, json.load(open(sys.argv[3] + '/' + n))['argv'], "
        "{'nav_tau_record': tau}, pm)[0] for n in ('nt-a1-s0.argv.json', 'nt-a1r-s1.argv.json')}; "
        "print(json.dumps(out))"),
        str(tree / "stack/tanitad/configs/refcv8_nav_compliance_tau_train4572.json"), pmap, str(runs_d))
    closed = (chk["open_items"] == [] and all(v == [] for v in chk["refusals"].values())
              and chk["v9_md5"] == md5 and chk["b1"] == a.b1)
    rep = {"CLOSED": closed, "v9_md5": md5, "b1": a.b1, "was": {"_NT_V9_MD5": was_md5, "_NT_B1_GUARD": was_b1},
           "clock_reference": {"src": a.clock_reference, "sha256": _sha(cref_dst.read_bytes()), "n_clips_gate_read": cl["n"]},
           "argv_sha256": {n: json.loads((runs_d / n).read_text(encoding="utf-8"))["argv_sha256"]
                           for n in ("nt-a1-s0.argv.json", "nt-a1r-s1.argv.json")},
           "launch_gate_sha256": _sha(gate.read_bytes()), "check": chk,
           "next": "the argv sha changed: produce the G-MAP/G-BOX binding records on THIS commit (nt_prelaunch.sh bind) "
                   "before the gate"}
    print(json.dumps(rep, indent=1))
    return 0 if closed else 3


if __name__ == "__main__":
    sys.exit(main())
