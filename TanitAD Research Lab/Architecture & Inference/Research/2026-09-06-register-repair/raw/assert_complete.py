#!/usr/bin/env python3
"""I21 GUARD -- assert an artifact's COMPLETION MARKER before quoting any number from it.

WHY (measured 2026-09-05/06). `.../2026-09-05-withheld-bank-panel/raw/NOISE_FLOOR.md`
was generated by a script that died on a cp1252 `UnicodeEncodeError` after writing its
first heading. The result is 1,128 bytes that OPEN like a document: a title, two
paragraphs of correct methodology, a section heading -- and then a Python traceback.
`ls` reports a plausible size, a reader skims a real header, and the file carries NO
NUMBERS AT ALL. It was cited in the live register as an evidence path for a
false-positive rate that does not appear in it.

This is `verify by CONTENT, never by presence` with a NEW failure shape: not a missing
file and not a wrong file, but a TRUNCATED one that reads like a complete one.

RULE: every generated text artifact emits, as its LAST line, a completion marker
      `<!-- ARTIFACT-COMPLETE: <NAME> -->`; every reader asserts it before quoting.

usage:
    python assert_complete.py <file> [<file> ...]
exit 0 = all COMPLETE; exit 1 = at least one INCOMPLETE / SUSPECT / UNREADABLE.

ASCII only: the dev box is cp1252 and a non-ASCII print() is fatal -- which is the
exact bug this guard exists to catch, so this file must not reintroduce it.
"""
import re
import sys

MARKER = "<!-- ARTIFACT-COMPLETE:"

# !! A crash is detected by SHAPE, not by a word. An artifact that DOCUMENTS a crash
# (the repaired NOISE_FLOOR.md's own header names `UnicodeEncodeError`) must not be
# flagged; a file that CONTAINS one must. The shape is a real traceback: the header
# line at column 0 followed by at least one `File "...", line N` frame.
_TB_HEAD = "Traceback (most recent call last):"
_FRAME = re.compile(r'^\s+File ".*", line \d+', re.M)


def crash_shape(raw):
    """Return a short reason if `raw` contains a REAL traceback, else ''."""
    i = raw.find(_TB_HEAD)
    while i != -1:
        at_col0 = (i == 0 or raw[i - 1] == "\n")
        if at_col0 and _FRAME.search(raw, i, i + 4000):
            tail = raw[i:].strip().splitlines()
            last = tail[-1][:80] if tail else ""
            return "traceback at offset %d; last line: %s" % (i, last)
        i = raw.find(_TB_HEAD, i + 1)
    return ""


def check(path):
    """Return (verdict, detail). Never claims COMPLETE from a failed read."""
    raw = None
    for enc in ("utf-8", "cp1252", "latin-1"):
        try:
            with open(path, "r", encoding=enc) as f:
                raw = f.read()
            break
        except UnicodeDecodeError:
            continue
        except OSError as e:
            return "UNREADABLE", "%s (%s)" % (type(e).__name__, e)
    if raw is None:
        return "UNREADABLE", "no encoding decoded the bytes"
    crashed = crash_shape(raw)
    if MARKER not in raw:
        return "INCOMPLETE", ("no completion marker"
                             + ("; CRASHED: " + crashed if crashed else ""))
    if crashed:
        return "SUSPECT", "marker present BUT " + crashed
    lines = raw.rstrip().splitlines()
    tail = lines[-1] if lines else ""
    if MARKER not in tail:
        return "SUSPECT", "marker present but not on the LAST line (last: %r)" % tail[:60]
    return "COMPLETE", tail.strip()


def main(argv):
    bad = 0
    for p in argv:
        v, d = check(p)
        print("%-10s %s   %s" % (v, p, d))
        if v != "COMPLETE":
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        raise SystemExit(2)
    raise SystemExit(main(sys.argv[1:]))
