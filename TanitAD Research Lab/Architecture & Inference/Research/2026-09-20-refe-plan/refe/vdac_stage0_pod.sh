#!/bin/bash
# VDAC Stage 0 on the pod, run INSIDE a P7 pause (the GPU must be empty; the pause wrapper stops P7 and resumes it afterwards).  PREREG_VDAC_P6_A5_DRAFT section 1.  See POD_PLAN.md (raw/2026-11-12-vdac-a5-build2/).
#   bash vdac_stage0_pod.sh               runs the stage
#   MODE=plan bash vdac_stage0_pod.sh     prints every command and exits (nothing runs; no teacher_env, no python)
# Fail-closed: the first failing step prints `ZZSTAGE0_FAIL <step>` and ends (rc 1); the pause wrapper's trap still resumes P7.  A reproduction failure of the forward (rc 3) ends with ZZSTAGE0_REPRO_FAILED (the files exist).
# The package is a NEW directory (STAGE0_PKG, default /workspace/refe-plan-stage0): never over refe-plan-vdac or refe-plan-p7 (gate_token.TREE_ROOTS: a changed refe/ voids a minted token).
# Frozen declarations below are values that exist BEFORE this run (repo docs / the S1a manifest); the tools refuse when the pod's bytes differ.  Values marked RUNTIME are read from the pod's file now and are a record, not a prior freeze.
set -u
WS=${VDAC_WS:-/workspace}
PKG=${STAGE0_PKG:-$WS/refe-plan-stage0}
DATA=$WS/data
ROOT=$DATA/refe_vdac
RUN=$ROOT/ha-s0
OUT=${STAGE0_OUT:-$ROOT/stage0}
STORE=$DATA/aux_drivable/label_store
H48=$ROOT/h48_logs.txt
SFT=$PKG/splits/sft_heldout_logs.txt
P6_SHA=968a469d5b9abdd279aff19b8031c53e9fec0e2683092bff12cfa93be6a4d3d1       # model_final.pt (the repo docs quote it 40 times)
AUX_SHA=281320071fea                                                         # aux_drv.pt LFS sha256 prefix (A5 draft section 1)
BANKED_SHA=6b9ac2bc1bc5989e                                                  # head_pred_update10000.npz = inputs_manifest.json head_s0_a (HF-verified 2026-11-12)
H48X_SHA=64d2f71be45154bd                                                    # head_pred_h48x.npz       = inputs_manifest.json head_s0_b
PLAN=0; [ "${MODE:-}" = "plan" ] && PLAN=1
say() { echo "$(date -u +%FT%TZ) $*"; [ "$PLAN" = 1 ] || echo "$(date -u +%FT%TZ) $*" >> "$OUT/stage0.log"; }
fail() { say "ZZSTAGE0_FAIL $*"; exit 1; }
# step <name> <command...>: prints the command; runs it unless MODE=plan; a non-zero rc fails the stage (the forward's rc 3 = reproduction check failed AFTER its files were written: recorded, not fatal here)
REPRO_FAILED=0
step() {
  local n="$1" rc; shift; say "STEP $n: $*"; [ "$PLAN" = 1 ] && return 0
  "$@"; rc=$?
  if [ "$rc" -ne 0 ]; then
    if [ "$n" = forward ] && [ "$rc" -eq 3 ]; then say "ZZSTAGE0_REPRO_FAILED forward rc 3 (the files exist; read fwd/stage0_forward.json)"; REPRO_FAILED=1; return 0; fi
    fail "$n (rc $rc)"
  fi
}
if [ "$PLAN" = 0 ]; then
  mkdir -p "$OUT" || { echo "cannot create $OUT"; exit 1; }
  source "$WS/teacher_env.sh" || fail "teacher_env"
  PY="$DRIVERL_EVAL_PYTHON"
  [ -d "$PKG/refe" ] && [ -f "$PKG/refe/vdac_stage0_forward.py" ] || fail "package $PKG is not shipped"
  [ "$(nvidia-smi --query-compute-apps=pid --format=csv,noheader | wc -l)" = "0" ] || fail "the GPU is not empty (P7 must be paused)"
else
  PY=python3
fi
export OMP_NUM_THREADS=4 PYTHONUNBUFFERED=1
cd "$PKG/refe" 2>/dev/null || [ "$PLAN" = 1 ] || fail "cd $PKG/refe"

# 1. the run's argv, regenerated by the arm's own script (deterministic; the tool cross-checks it against the namespace recorded in model_sft_A.pt)
step argv env ARM=HA-s0 MODE=argv VDAC_WS="$WS" bash -c "bash $PKG/refe/vdac_pod.sh > $OUT/ha_s0_argv.txt"
# 2. the P6 TRAIN bank's keys (CPU, no model) -> make-list (CPU): the in-sample frame list and the 256 C0-ID frames; both shas are written to FROZEN_SHAS.txt BEFORE any forward exists
step bank_keys env CUDA_VISIBLE_DEVICES= "$PY" vdac_stage0_forward.py bank-keys --argv-file "$OUT/ha_s0_argv.txt" --run-dir "$RUN" --out-dir "$OUT/bank"
step make_list env CUDA_VISIBLE_DEVICES= "$PY" vdac_stage0.py make-list --out-dir "$OUT/list" --bank-keys "$OUT/bank/bank_keys.tsv" --store "$STORE" --h48-logs "$H48" --sft-heldout "$SFT" --banked-pred "$RUN/scores/head_pred_update10000.npz"
if [ "$PLAN" = 1 ]; then LSHA='<frame_list_sha256 from list/stage0_frames.json>'; RSHA='<repro256_sha256 from list/stage0_frames.json>'; S0SHA='<RUNTIME sha256 of scores/head_pred_step0.npz>'
else
  LSHA=$("$PY" -c "import json,sys; print(json.load(open(sys.argv[1]))['frame_list_sha256'])" "$OUT/list/stage0_frames.json") || fail "read list sha"
  RSHA=$("$PY" -c "import json,sys; print(json.load(open(sys.argv[1]))['repro256_sha256'])" "$OUT/list/stage0_frames.json") || fail "read repro sha"
  S0SHA=$(sha256sum "$RUN/scores/head_pred_step0.npz" | cut -d' ' -f1)
  [ "${#LSHA}" = 64 ] && [ "${#RSHA}" = 64 ] && [ "${#S0SHA}" = 64 ] || fail "a sha256 is not 64 hex"
  printf 'frame_list_sha256 %s\nrepro256_sha256 %s\nhead_pred_step0_sha256_RUNTIME %s\n' "$LSHA" "$RSHA" "$S0SHA" > "$OUT/FROZEN_SHAS.txt"
  say "ZZSTAGE0_LIST_FROZEN list $LSHA repro256 $RSHA (written to FROZEN_SHAS.txt before the forward)"
fi
# 3. the forward (GPU): trained head on the in-sample + C0-ID frames, seed-0 initial head on the pod's step-0 frames and the h48x frames; ONE model load.  The tool refuses a busy GPU.
step forward "$PY" vdac_stage0_forward.py --mode both --run-dir "$RUN" --argv-file "$OUT/ha_s0_argv.txt" --out-dir "$OUT/fwd" --aux-sha256 "$AUX_SHA" --p6-sha256 "$P6_SHA" \
  --store "$STORE" --h48-logs "$H48" --sft-heldout "$SFT" \
  --insample-list "$OUT/list/stage0_frames.tsv" --insample-list-sha256 "$LSHA" --repro-list "$OUT/list/stage0_repro256.tsv" --repro-list-sha256 "$RSHA" \
  --banked-pred "$RUN/scores/head_pred_update10000.npz" --banked-sha256 "$BANKED_SHA" \
  --pod-step0 "$RUN/scores/head_pred_step0.npz" --pod-step0-sha256 "$S0SHA" --pod-h48x "$RUN/head_pred_h48x.npz" --pod-h48x-sha256 "$H48X_SHA" \
  --workers 8 --batch 16
say "ZZSTAGE0_FWD_DONE"
[ "$PLAN" = 1 ] && { say "ZZSTAGE0_PLAN_ONLY"; exit 0; }
cp "$RUN/scores/head_pred_step0.npz" "$OUT/head_pred_step0.npz" || fail "copy step0"      # the pod's own step-0 file travels with the outputs (S1-F's --init-pod-step0)
[ "$REPRO_FAILED" = 1 ] && { touch "$OUT/STAGE0_REPRO_FAILED"; say "ZZSTAGE0_END with a failed reproduction check"; exit 3; }
touch "$OUT/STAGE0_DONE"
say "ZZSTAGE0_DONE (pull back $OUT: list/ fwd/ FROZEN_SHAS.txt head_pred_step0.npz stage0.log)"
