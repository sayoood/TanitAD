#!/usr/bin/env python3
"""Generate refe/carvefeed_layer.py: the (new, old) reversal table of the B8 edits + peel().  usage: gen_layer.py rev_chunks.json out.py"""
import json, sys

chunks = json.load(open(sys.argv[1]))


def lit(s):
    """a multi-line string as an implicit concatenation of per-line repr literals"""
    parts = s.split("\n")
    segs = [repr(p + "\n") for p in parts[:-1]] + ([repr(parts[-1])] if parts[-1] else [])
    return "(" + "\n         ".join(segs) + ")"


body = ",\n".join(f"    ({lit(n)},\n     {lit(o)})" for n, o in chunks)
out = f'''#!/usr/bin/env python3
"""B8 layer of refe/scorer_finetune.py (raw/2026-10-18-r0e-carvefeed): the reversal table that undoes the carve-feed edits, so every older pin that compares the trainer with an older blob
(test_rl_s1b's PICKCON layer, test_rl_safeobj, test_rl_r0c) can first peel THIS layer and then keep working unchanged.  Generated by raw/2026-10-18-r0e-carvefeed/gen_layer.py from the edit script;
test_carve_feed.py proves peel(trainer) == the 821915a tip blob {{TIP_TRAINER_BLOB}}.  A trainer without the layer (the marker below is absent) is returned unchanged, so a pin test also runs on the pre-B8 trainer.
"""
TIP_TRAINER_BLOB = "869b186293150dc6c07253391aeed9f84738225f"          # refe/scorer_finetune.py at 821915a (landed by c2d4042, the PICKCON build) = the trainer BEFORE B8
MARKER = 'EPO_CON_FEEDS = ("train", "carve")'
# <<<GEN CARVEFEED_FILE_REVERSALS
CARVEFEED_FILE_REVERSALS = (
{body},
)
# >>>GEN CARVEFEED_FILE_REVERSALS


def has_layer(src: str) -> bool:
    return MARKER in src


def peel(src: str) -> str:
    """undo the B8 edits (each `new` text must occur exactly once); a trainer without the layer is returned unchanged"""
    if not has_layer(src):
        return src
    for new, old in CARVEFEED_FILE_REVERSALS:
        assert src.count(new) == 1, f"B8 reversal: the text occurs {{src.count(new)}} times (must be exactly 1): {{new[:70]!r}}"
        src = src.replace(new, old)
    return src
'''
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(out)
print("layer written", len(chunks), "chunks")
