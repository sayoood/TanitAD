#!/usr/bin/env python3
"""Generate refe/scorer1_layer.py: the SCORER1 reversal table (the same pattern as hnscreen_layer.py / carvefeed_layer.py).

    python gen_scorer1_layer.py <base scorer_finetune.py (the tip blob)> <scorer1 scorer_finetune.py> <out scorer1_layer.py>

Every older pin test that compares the trainer with an older blob first PEELS the layers on top (hnscreen_layer.peel -> scorer1_layer.peel first).  The table is mechanical: each changed block of the
line diff, with the fewest context lines that make its `new` text occur EXACTLY ONCE in the SCORER1 trainer; the generator then proves peel(new) == base byte for byte, or it refuses to write.
"""
import difflib
import hashlib
import sys


def git_blob(b: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(b) + b).hexdigest()


def main(base_p, new_p, out_p):
    base_b, new_b = open(base_p, "rb").read(), open(new_p, "rb").read()
    base, new = base_b.decode("utf-8"), new_b.decode("utf-8")
    a, b = base.splitlines(True), new.splitlines(True)
    ops = [o for o in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes() if o[0] != "equal"]
    entries = []
    for tag, i1, i2, j1, j2 in ops:
        for ctx in range(1, 40):
            lo_a, hi_a = max(0, i1 - ctx), min(len(a), i2 + ctx)
            lo_b, hi_b = max(0, j1 - ctx), min(len(b), j2 + ctx)
            old_t = "".join(a[lo_a:i1] + a[i1:i2] + a[i2:hi_a])
            new_t = "".join(b[lo_b:j1] + b[j1:j2] + b[j2:hi_b])
            if "".join(a[lo_a:i1]) == "".join(b[lo_b:j1]) and "".join(a[i2:hi_a]) == "".join(b[j2:hi_b]) and new.count(new_t) == 1:
                entries.append((new_t, old_t))
                break
        else:
            sys.exit(f"cannot make block {tag} {i1}:{i2} unique within 40 lines of context")
    # prove the table: apply the reversals in order, byte for byte
    cur = new
    for new_t, old_t in entries:
        if cur.count(new_t) != 1:
            sys.exit("a reversal entry is not unique once the earlier ones are applied (overlapping contexts): widen the blocks")
        cur = cur.replace(new_t, old_t)
    if cur != base:
        sys.exit("peel(new) != base: the table is wrong")
    marker = 'PAIR_SEED = 20261107 '
    assert marker.strip() in new
    lines = ['#!/usr/bin/env python3',
             '"""SCORER1 layer of refe/scorer_finetune.py (PREREG_SCORER1 + AMENDMENT 1): the reversal table that undoes the --pair-* / --navtest-* edits, so every older pin that compares the trainer with an',
             'older blob (test_rl_s1b, test_rl_safeobj, test_rl_r0c, test_rl_pickcon, test_carve_feed, test_hn_screen_wiring, via hnscreen_layer.peel -> carvefeed_layer.peel) first peels THIS layer, the OUTERMOST,',
             'and then keeps working unchanged.  Generated by v2/tools/gen_scorer1_layer.py; refe/test_scorer1_layer.py proves peel(trainer) == the tip blob {TIP_TRAINER_BLOB}.  A trainer without the layer',
             '(the marker below is absent) is returned unchanged.',
             '"""',
             f'TIP_TRAINER_BLOB = "{git_blob(base_b)}"          # refe/scorer_finetune.py at the tip 0fd9a3dc = the trainer BEFORE SCORER1',
             f'MARKER = {marker.strip()!r}',
             '# <<<GEN SCORER1_FILE_REVERSALS',
             'SCORER1_FILE_REVERSALS = (']
    for new_t, old_t in entries:
        lines.append(f"    ({new_t!r},\n     {old_t!r}),")
    lines += [')',
              '# >>>GEN SCORER1_FILE_REVERSALS',
              '',
              '',
              'def has_layer(src: str) -> bool:',
              '    return MARKER in src',
              '',
              '',
              'def peel(src: str) -> str:',
              '    """undo the SCORER1 edits (each `new` text must occur exactly once); a trainer without the layer is returned unchanged"""',
              '    if not has_layer(src):',
              '        return src',
              '    for new, old in SCORER1_FILE_REVERSALS:',
              '        assert src.count(new) == 1, f"SCORER1 reversal: the text occurs {src.count(new)} times (must be exactly 1): {new[:70]!r}"',
              '        src = src.replace(new, old)',
              '    return src',
              '']
    open(out_p, "wb").write("\n".join(lines).encode("utf-8"))
    print(f"{len(entries)} reversal entries; peel(new) == base proven; tip blob {git_blob(base_b)}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
