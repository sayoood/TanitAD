#!/usr/bin/env python3
"""build_realdata.py -- assemble R0 and R0b's BANKED outputs as arm directories and run r0c_read.py on them under the R0c rules.

Two directories per arm (written under realdata/):
  <ARM>_banked   exactly what was banked (kill_replay.json or kill_checks.jsonl + KILLED.json + monitor.log, sft.jsonl), recorded against C0 (arm_meta.json says so).
                 The reader must reproduce the RECORDED kill from these files alone.
  <ARM>_ownA     the SAME run read under R0c's control rule (PREREG_R0C section 2: "the control for every delta is the arm's own A"): kill_replay.json is regenerated by the REAL
                 rls1_checks.replay + RlValChecker with refdir = the run's own arm-A dumps, and rlval_BvsA_update<N>.json by r0c_ba_read.py.  Both run on the banked score dumps
                 (HF Sayood/tanitad-refe-rls1-r0 and -r0b, local copy C:/Users/Admin/rls1b_dl), the RL-val labels (pdm_val, terms_val, sets_val) and the banked sft.jsonl.
                 The RL-val scenes TSV is not on this machine: it is rebuilt from the pdm_val keys (token, log), which is complete by construction.

    C:/Users/Admin/venvs/tanitad/Scripts/python.exe build_realdata.py
"""
from __future__ import annotations

import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path[:0] = [os.path.join(PKG, "eval"), os.path.join(PKG, "refe"), HERE]
import rl_val_eval as RV  # noqa: E402
import rls1_checks as RC  # noqa: E402
import r0c_ba_read  # noqa: E402
import r0c_read  # noqa: E402

DL = "C:/Users/Admin/rls1b_dl"
X = f"{DL}/data/x"
PDM, TERMS, SETS = f"{X}/pdm_val/pdm_val", f"{X}/terms_val/terms_val", f"{X}/sets_val/sets_val"
R0B_HF = "C:/Users/Admin/AppData/Local/Temp/rrd_data/r0b/final"
BANK = {"R0": os.path.join(PKG, "raw", "2026-10-14-rls1-r0-kill"), "R0b": os.path.join(PKG, "raw", "2026-10-15-rls1b-r0b-kill")}
RUNS = {"R0": {"scores": f"{DL}/r0/final", "sft": f"{DL}/r0/final/sft.jsonl", "tags": (250, 500, 750, 1000)},
        "R0b": {"scores": f"{DL}/r0b/final", "sft": f"{R0B_HF}/sft.jsonl", "tags": (250, 500)}}
OUT = os.path.join(HERE, "realdata")


def put(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(src, dst)


def banked(arm):
    d = os.path.join(OUT, f"{arm}_banked")
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    for f in {"R0": ("kill_replay.json", "rlval_vs_C0.json"), "R0b": ("kill_checks.jsonl", "KILLED.json", "monitor.log")}[arm]:
        put(os.path.join(BANK[arm], f), os.path.join(d, f))
    put(RUNS[arm]["sft"], os.path.join(d, "sft.jsonl"))
    json.dump({"monitor_control": "C0", "note": "R0 / R0b were monitored against C0's arm A, not against their own A: the banked records, unchanged"}, open(os.path.join(d, "arm_meta.json"), "w"))
    return d


def own_a(arm):
    d = os.path.join(OUT, f"{arm}_ownA")
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    run = RUNS[arm]
    put(run["sft"], os.path.join(d, "sft.jsonl"))
    pdm, _ = RV.load_pdm(PDM)
    tsv = os.path.join(OUT, "rl_val_scenes_rebuilt_from_pdm_keys.tsv")
    with open(tsv, "w", encoding="utf-8", newline="\n") as f:
        f.write("token\tlog\n")
        for k in sorted(pdm):
            f.write(f"{k[1]}\t{k[0]}\n")
    for u in run["tags"]:                                                          # the B - A reads r0c_read.py needs (GAP 0)
        rc = r0c_ba_read.main(["--a", f"{run['scores']}/scores_update{u}_A.npz", "--b", f"{run['scores']}/scores_update{u}_B.npz", "--pdm", PDM, "--terms", TERMS,
                               "--rl-val-scenes", tsv, "--out", os.path.join(d, f"rlval_BvsA_update{u}.json")])
        assert rc == 0, f"r0c_ba_read failed for {arm} update{u}: {rc}"
    chk = RC.RlValChecker("R0c", run["scores"], PDM, TERMS, SETS, tsv)             # the REAL monitor class, refdir = the run's OWN arm-A dumps (rls1_pod.sh: REFDIR="$ARMDIR/scores")
    code, why, recs = RC.replay("R0c", d, lambda tag, files: chk(tag, {"B": f"{run['scores']}/scores_{tag}_B.npz"}))
    with open(os.path.join(d, "kill_replay.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"arm": "R0c", "kill": code, "why": why, "checks": recs}, f, indent=1)
    print(f"[{arm}_ownA] real replay under own-A control: kill={code} why={why!r}", flush=True)
    return d


def main():
    os.makedirs(OUT, exist_ok=True)
    summary = {}
    for arm in ("R0", "R0b"):
        for kind, fn in (("banked", banked), ("ownA", own_a)):
            d = fn(arm)
            rc = r0c_read.main([d])
            r = json.load(open(os.path.join(d, "R0C_READ.json")))
            summary[f"{arm}_{kind}"] = {"exit": rc, "outcome": r["outcome"], "ambiguity_kind": r["ambiguity_kind"], "recorded_kill": r["evidence"]["recorded_kill"],
                                        "derived_kill": r["evidence"]["terminal_kill_derived"], "first_g5_pair": r["evidence"]["first_g5_pair"], "reason": r["reason"][:500]}
    json.dump(summary, open(os.path.join(OUT, "SUMMARY.json"), "w"), indent=1)
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
