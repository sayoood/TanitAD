#!/usr/bin/env python3
"""Generate refe/a2_layer.py: the reversal table that undoes the A2 (--beh-*) edits of refe/scorer_finetune.py, so the SCORER1 layer
(scorer1_layer.peel, which now calls a2_layer.peel FIRST) and every older pin keep working.  usage: gen_a2_layer.py <base scorer_finetune.py> <a2 scorer_finetune.py> <out a2_layer.py>
The table is computed from the two files (difflib line opcodes + enough context to make each text unique) and PROVEN: peel(a2) == base byte for byte."""
import difflib, hashlib, sys

MARKER = "def extend_beh_head("
CTX = 1


def blob(s):
    b = s.encode("utf-8")
    return hashlib.sha1(b"blob %d\0" % len(b) + b).hexdigest()


def build(base, a2):
    bl, al = base.splitlines(True), a2.splitlines(True)
    ops = [o for o in difflib.SequenceMatcher(None, bl, al, autojunk=False).get_opcodes() if o[0] != "equal"]
    groups = []
    for o in ops:
        if groups and o[1] - groups[-1][-1][2] <= 2 * CTX:
            groups[-1].append(o)
        else:
            groups.append([o])
    out = []
    for g in groups:
        i1, i2, j1, j2 = g[0][1], g[-1][2], g[0][3], g[-1][4]
        c = CTX
        while True:
            lo_b, hi_b, lo_a, hi_a = max(0, i1 - c), min(len(bl), i2 + c), max(0, j1 - c), min(len(al), j2 + c)
            new, old = "".join(al[lo_a:hi_a]), "".join(bl[lo_b:hi_b])
            if a2.count(new) == 1 or c > 40:
                break
            c += 1
        out.append((new, old))
    return out


def peel(src, table):
    for new, old in table:
        assert src.count(new) == 1, (src.count(new), new[:80])
        src = src.replace(new, old)
    return src


