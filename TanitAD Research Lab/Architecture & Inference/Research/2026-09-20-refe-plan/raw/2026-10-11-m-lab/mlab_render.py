#!/usr/bin/env python3
"""Render results.json -> a DRAFT of eval/RESULT_M_LAB.md (tables + formula-driven sizing; numbers only come from results.json).
The agent that finishes the package must read the draft against results.json and the raw worker JSONs, fix the prose where the
numbers contradict it, and own the final text.   python mlab_render.py [--out <path>]"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.abspath(os.path.join(HERE, "..", ".."))
RAW = "raw/2026-10-11-m-lab"
R = json.load(open(os.path.join(HERE, "results.json"), encoding="utf-8"))
P = R["primary"]


def sp(d, nd=3):
    if not d:
        return "n/a"
    return f"**{d['median']:.{nd}f}** (runs {', '.join(f'{v:.{nd}f}' for v in d['values'])}; min {d['min']:.{nd}f}, max {d['max']:.{nd}f}, max/min {d['max_over_min']})"


def sz(c, f=1.0):
    sus = 4.49 * c * f
    w = math.ceil(1.5 * sus)
    return sus, w, w + 4


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(PKG, "eval", "RESULT_M_LAB.md"))
    a = ap.parse_args()
    L = []
    w = L.append
    cd = P.get("c_cached_load_plus_label_loop_total_pinned") or P.get("c_cached_load_plus_label_loop_total")
    cl = P.get("c_label_only_parts_in_ram")
    cb = P.get("c_build_plus_label_loop_total")
    cs = P.get("c_single_build_plus_label_loop_total")
    A = R["arms"]
    ncached = len(P.get("cached_runs", []))
    w("# RESULT -- M-LAB: the online PDM labeller's CPU cost c (C4 of `eval/P6_GO_SIGNAL.md`, decides P6-C)\n")
    w("> **DRAFT generated by `raw/2026-10-11-m-lab/mlab_render.py` from `results.json`; the finishing agent must read it against the raw worker JSONs and own the text.**\n")
    w("Every number is **MEASURED** on the dev box (24 logical CPUs, i9-12900F, 31.8 GB) unless marked; artifact paths are relative to the refe-plan directory. "
      "CPU = process CPU time (user+sys) of the worker, never wall time. Environment: navsim v1.1 @ 3e8291b venv (`C:/Users/Admin/navsim-crun/venv`), "
      "`OMP/MKL/OPENBLAS_NUM_THREADS=1`, `REFE_SIM_HZ=10`.\n")
    w("## Headline\n")
    if cd:
        sus, wk, vc = sz(cd["median"])
        w(f"* **c, the labeller as P6 will run it (D9 parts cached on disk, loaded per set, then `executed_plans8` + `score_plans` on 64 proposals): "
          f"{cd['median']:.3f} CPU-s/set** (median of {ncached} independent runs of ~237 sets; spread {cd['min']:.3f}-{cd['max']:.3f}). "
          f"`{RAW}/results.json` `primary.c_cached_load_plus_label_loop_total`.")
    if cl:
        w(f"* label-only with the parts already in RAM: {cl['median']:.3f} CPU-s/set (min {cl['min']:.3f}, max {cl['max']:.3f}).")
    if cb:
        w(f"* **parts built from the nuPlan scenario + label** (the offline `onpolicy_relabel_pdm.py` path, log-grouped): **{cb['median']:.3f} CPU-s/set** "
          f"(min {cb['min']:.3f}, max {cb['max']:.3f}, {len(cb['values'])} runs).")
        w(f"  The INHERITED 1.78 CPU-s/set (`eval/PREREG_SFT4.md` Amendment 3) is the same order as this figure; the offline labeller code path (`refe/onpolicy_relabel_pdm.py:58`) "
          f"calls `metric_cache_parts` for every set, so that rate necessarily included the build. "
          f"Whether the pod was really CPU-saturated at 7.65 CPUs when it reached 258 sets/min is UNVERIFIED.")
    w("")
    w("## 1. c: three-plus independent runs per mode\n")
    w("| quantity | CPU-s per 64-proposal set (median; each run; spread) |\n|---|---|")
    allrows = (("c_label_only_parts_in_ram", "label-only, parts in RAM (`executed_plans8` + `score_plans`)"),
                     ("c_score_plans_only", "of which `score_plans`"),
                     ("c_executed_plans8_only", "of which `executed_plans8` (timed on a synthetic 20-pose upsample of the banked paths)"),
                     ("c_parts_load_from_disk", "parts load: read + lzma + unpickle (cached design)"),
                     ("c_cached_load_plus_label_loop_total", "**cached design total** (load + label), loop CPU / sets"),
                     ("c_build_parts_only", "parts BUILD only (scenario build share + `metric_cache_parts`)"),
                     ("c_build_plus_label_loop_total", "**parts build + label** (log-grouped), loop CPU / sets"),
                     ("c_single_build_plus_label_loop_total", "parts build + label, ONE scenario-build call per token (no per-log amortisation; n=100/run, supplementary)"))
    for sfx, tag in (("", "unpinned (the scheduler places the process; on this hybrid CPU a saturated box can move it to a slower E-core)"),
                     ("_pinned", "PINNED to one P-core thread (no E-core migration; the sibling thread runs whatever the box runs there)")):
        w(f"| *{tag}* | |")
        for key, lab in allrows:
            if key + sfx in P:
                w(f"| {lab} | {sp(P[key + sfx])} |")
    w("")
    w(f"Sets per run: cached {P.get('cached_n_sets_per_run')}, build {P.get('build_n_sets_per_run')}, single {P.get('single_n_sets_per_run')}. "
      f"Wall per set (N=1): cached {sp(P.get('cached_wall_per_set_s'))}, build {sp(P.get('build_wall_per_set_s'))}.\n")
    w("Controls (every run, `runs/<arm>/worker0.json` `check_vs_census`): cached-mode PDMS equals the NAVSIM census (`raw/2026-10-04-lane-discipline/lane_census.jsonl`) "
      "to 1e-4 on **all** sets and 64 proposals; a deliberate wrong-proposals arm (same parts, another token's proposals) must NOT match (`ctrl_cross_token_max_abs` > 0). "
      "Build-mode agreement is lower by construction (the rebuilt cache is not NAVSIM's file; `eval/validate_pdm_targets.py`).\n")
    w("| arm | sets | fails | 5 s-guard skips | PDMS exact within 1e-4 | background logical CPUs (mean / p90 / max, of 24) |\n|---|---|---|---|---|---|")
    for t, x in sorted(A.items()):
        if x["nworkers"] == 1:
            ck = x["check"]
            w(f"| {t} | {x['n_sets']} | {ck['n_fail']} | {ck['skipped_guard']} | {ck['pdms_exact_1e4']}/{ck['pdms_total']} | "
              f"{x['background_logical_cpus']['mean']} / {x['background_logical_cpus']['p90']} / {x['background_logical_cpus']['max']} |")
    w("")
    w("## 2. Concurrent load and what it does to c\n")
    w("The box was NOT idle: the C3 pipeline, other agents' pytest/gate runs and a video render ran throughout (per-arm background load above; top processes "
      "in `runs/<arm>/summary.json` `bg_top_before/after`). CPU time is NOT load-invariant on this hybrid (P+E core, SMT) CPU: a saturated box shares cores between SMT siblings and can place the "
      "process on a slower E-core, so the spread across runs is largely load sensitivity, not noise. The pinned runs remove the E-core migration only.\n")
    for mode, d in R.get("load_dependence", {}).items():
        w(f"* {mode}: per-set CPU vs the background load during that set (n={d['n_sets']}, corr {d['corr']}, slope {d['slope_cpu_s_per_set_per_bg_logical_cpu']} CPU-s/set per background logical CPU, "
          f"intercept {d['intercept_cpu_s_per_set']}): " + "; ".join(f"bg {b['bg_busy_logical']}: {b['mean_cpu_per_set']} (n={b['n_sets']})" for b in d["bins"]) + ".")
    w("")
    w("## 3. RSS per worker (steady state)\n")
    w("| worker kind | RSS at steady state, MB (median; runs) | peak working set, MB | after import+setup, MB |\n|---|---|---|---|")
    if "rss_steady_state_cached_mb" in R:
        w(f"| cached-parts labeller (parts streamed, none retained; NO city maps loaded) | {sp(R['rss_steady_state_cached_mb'], 0)} | {sp(R['peak_wset_cached_mb'], 0)} | {sp(R['rss_after_setup_cached_mb'], 0)} |")
    if "rss_steady_state_build_mb" in R:
        w(f"| build-mode worker (scenario build + maps for the cities the run touched) | {sp(R['rss_steady_state_build_mb'], 0)} | {sp(R['peak_wset_build_mb'], 0)} | |")
    if "retain_probe" in R:
        rp = R["retain_probe"]
        w(f"\nCost of holding parts (the spec's per-worker LRU): retaining {rp['n_retained']} parts grew RSS by {rp['rss_growth_mb']} MB = **{rp['mb_per_part_in_ram']} MB per cached part in RAM** "
          f"(`runs/cached_r2_retain_n1/worker0.json`).")
    if "part_disk" in R:
        pdk = R["part_disk"]
        w(f"On disk a part is {pdk['lzma_pkl_bytes_mean'] / 1e3:.0f} kB lzma ({pdk['uncompressed_pickle_bytes_mean'] / 1e3:.0f} kB uncompressed pickle) => "
          f"~{pdk['est_cache_gb_navtrain_lzma']} GB for 103,037 scenes ({pdk['evidence_class_of_estimate']}).")
    w("")
    w("## 4. Scaling with N workers (same tokens, partitioned across N independent processes)\n")
    for key, title in (("scaling_cached", "cached design (tokens of `cached_r1`)"), ("scaling_build", "parts build + label (logs of `build_r3`; shards are uneven, so wall is set by the largest log)")):
        rows = R.get(key) or []
        if not rows:
            continue
        w(f"**{title}**\n")
        w("| N | sets | CPU-s/set | vs N=1 | sets/s (wall) | speedup | efficiency | busy workers (CPU/wall) | RSS/worker MB | background logical CPUs |\n|---|---|---|---|---|---|---|---|---|---|")
        for r in rows:
            w(f"| {r['N']} | {r['n_sets']} | {r['cpu_per_set']} | {r['cpu_per_set_vs_N1_pct']:+.1f} % | {r['sets_per_s']} | {r['speedup_vs_N1']} | {r['efficiency']} | "
              f"{r['busy_workers_equiv']} | {r['rss_end_mb_median']} | {r['background_logical_cpus_mean']} |")
        w("")
    w("## 5. Splitting a set into chunks (SPEC 3.1 latency lever)\n")
    cp = R.get("chunk_probe")
    if cp:
        a_, b_ = cp["fit_per_call_a_fixed_s"], cp["fit_per_call_b_per_proposal_s"]
        w(f"`score_plans` costs a + b*M per call: **a = {a_:.3f} s fixed** (PDM-Closed simulation + scorer setup), **b = {b_ * 1000:.2f} ms per proposal** "
          f"(`{RAW}/chunk_probe.json`, {cp['n_sets']} sets, parts in RAM). Chunk-invariance of labels: max |PDMS(chunk of 16) - PDMS(full set)| = {cp['chunk16_pdms_vs_full_max_abs_diff']:.2e}.\n")
        load = P.get("c_parts_load_from_disk", {}).get("median", 0.0)
        wkr = sz(cd["median"])[1] if cd else 12
        w(f"Micro-batch = 4 sets per ~0.9 s period; W = {wkr} workers (spec rule at the measured c). Conservative: every chunk reloads its parts (load {load:.3f} s).\n")
        w("| chunk size M | chunks/set | CPU per chunk (s) | CPU per set (s) | tasks per micro-batch | micro-batch latency (s) | fits 0.9 s? | pod vCPU at this M |\n|---|---|---|---|---|---|---|---|")
        for m in (64, 32, 16, 8):
            d = load + a_ + b_ * m
            ch = 64 // m
            c_set = ch * d
            tasks = 4 * ch
            lat = math.ceil(tasks / wkr) * d
            _, _, vc = sz(c_set)
            w(f"| {m} | {ch} | {d:.3f} | {c_set:.3f} | {tasks} | {lat:.3f} | {'yes' if lat <= 0.9 else 'NO'} | {vc} |")
        w("\nLatency here is CPU seconds on an unloaded worker; IPC of proposals/labels and queueing are NOT MEASURED. A pod core slower than this dev-box core stretches every latency proportionally.\n")
    else:
        w("(chunk probe not run)\n")
    w("## 6. Sizing by the spec's formula (SPEC_P6 3.3: needed CPU = 4.49 sets/s x c; workers = 1.5 x that; pod vCPU = workers + 2 loader + 2 trainer/IPC)\n")
    w("| basis | c (CPU-s/set) | sustained CPUs | labeller workers | **pod vCPU** | CPU-hours for the 2,575,925-set run |\n|---|---|---|---|---|---|")
    for z in R.get("spec_reference_rows", []):
        w(f"| {z['label']} | {z['c_cpu_s_per_set']} | {z['sustained_cpus']} | {z['workers_1p5x']} | {z['pod_vcpu_workers_plus_4']} | {z['total_cpu_hours_full_run']} |")
    for z in R.get("sizing", []):
        w(f"| {z['label']} | {z['c_cpu_s_per_set']} | {z['sustained_cpus']} | {z['workers_1p5x']} | **{z['pod_vcpu_workers_plus_4']}** | {z['total_cpu_hours_full_run']} |")
    w("")
    w("## 7. Recommendation (P6-C)\n")
    w("**To be written by the finishing agent from sections 1-6**, covering: (a) the vCPU count under the spec formula at the measured c, "
      "(b) the margin for a pod core slower than this i9-12900F P-core (the factor is ESTIMATED, not measured here), "
      "(c) labeller RAM = workers x (RSS + LRU depth x MB-per-part) x 1.25, trainer/loader RAM is OUTSIDE M-LAB (UNVERIFIED), "
      "(d) whether the spec's infeasible regime (c ~ 18) is anywhere near, (e) the in-situ check: the run's `labeller queue depth` and GPU-stall metrics in the first 100 steps.\n")
    w("## 8. Not measured / limits\n")
    w("* Data are the **navtest** metric cache (no navtrain cache exists on the dev box); the proposals are the banked `navtest_final` set of `model_final.pt` "
      "(`E:/Projects/TanitAD/data/refe_navtest/proptable/navtest_final/proposals.npz`), not u400's (the C3 dump had not finished).")
    w("* Dev-box CPU is an i9-12900F P-core; a pod vCPU is typically a slower hyperthread. The dev-box c is therefore a LOWER bound for the pod; the ratio is NOT MEASURED.")
    w("* IPC between trainer and worker (pickling 64x20x3 proposals, labels back), queueing and the trainer's own CPU use are NOT included.")
    w("* `executed_plans8` was timed on a synthetic 20-pose upsample of the banked 8-pose paths (its cost does not depend on the values).")
    w("* Per-phase times are quantised at the OS tick (15.6 ms); the headline is the loop total (process `cpu_times` delta over the whole loop / sets).")
    w("* Twin-route (D7) cache builds are not measured; they are build-mode work done once, before step 0.")
    open(a.out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    sys.exit(main())
