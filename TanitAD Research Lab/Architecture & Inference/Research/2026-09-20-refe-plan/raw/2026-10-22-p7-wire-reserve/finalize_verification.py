#!/usr/bin/env python3
"""Zero-token finaliser for P7-WIRE-RESERVE: turns the raw outputs of the background verification jobs into raw/VERIFICATION.md and splices it into RESULT.md.

  python finalize_verification.py            (stdlib only; safe to re-run while jobs are still going: unfinished parts are reported as NOT FINISHED, never as green)

Inputs (all under C:/Users/Admin/par18/p7wire_reserve/raw/):
  test_run.out + test_run.rc       the FULL test_session_reserve.py run on the assembled tree (P7WIRE_BASE_DIR = the pristine tip's refe/)
  mutation_check.out               raw/mutation_check.py (controls, then 13 mutations that must each go RED; M1 = the one exclusion line, against the full suite)
  baseline_summary.txt / after_summary.txt + *_<suite>.out    the existing refe suites on the pristine tip vs on the tree with this deliverable (run_suites.sh)
Verdict rules: a mutation that stays GREEN, a control that is not green, an `after` suite whose PASS marker or rc differs from `baseline`, or any unfinished job  =>  NOT GREEN.
"""
import re
import sys
from pathlib import Path

R = Path("C:/Users/Admin/par18/p7wire_reserve")
RAW = R / "raw"
BEGIN, END = "<!-- VERIFICATION:BEGIN -->", "<!-- VERIFICATION:END -->"


def rd(p):
    p = Path(p)
    return p.read_text(encoding="utf-8", errors="replace") if p.is_file() else None


def summary(name):
    t = rd(RAW / f"{name}_summary.txt")
    if t is None:
        return None, False
    rows, done = {}, False
    for ln in t.splitlines():
        if ln.strip() == "DONE":
            done = True
            continue
        m = re.match(r"(\S+) rc=(\d+) secs=(\d+) :: (.*)$", ln)
        if m:
            rows[m.group(1)] = (int(m.group(2)), int(m.group(3)), m.group(4).strip().rstrip("|").replace("|", " ; "))
    return rows, done


def main():
    out, bad = [], []
    # 1. the full new suite
    out.append("### 1. test_session_reserve.py, full run (CUDA_VISIBLE_DEVICES=-1, driverl-eval venv, P7WIRE_BASE_DIR = the pristine tip's refe/)\n")
    t, rc = rd(RAW / "test_run.out"), rd(RAW / "test_run.rc")
    if t is None or rc is None:
        out.append("NOT FINISHED (raw/test_run.rc absent: the job is still running or died; re-run: see HANDOFF.md)\n")
        bad.append("test_session_reserve full run not finished")
    else:
        keep = [ln for ln in t.splitlines() if ln.startswith(("ZZSESSRES_", "Ran ", "OK", "FAILED", "FAIL:", "ERROR:"))]
        out.append("```\n" + "\n".join(keep[-25:]) + "\n" + rc.strip() + "\n```\n")
        if not any(ln.startswith("ZZSESSRES_PASS") for ln in keep) or rc.strip() != "rc=0":
            bad.append("test_session_reserve full run is not green")
    # 2. mutation check
    out.append("### 2. raw/mutation_check.out (verbatim)\n")
    m = rd(RAW / "mutation_check.out")
    if m is None or "MUTATION_CHECK_" not in m:
        out.append("NOT FINISHED (the last line is not MUTATION_CHECK_*; partial output follows)\n```\n" + (m or "") + "\n```\n")
        bad.append("mutation check not finished")
    else:
        out.append("```\n" + m.rstrip() + "\n```\n")
        if "MUTATION_CHECK_OK" not in m:
            bad.append("mutation check is not OK")
    # 3. existing suites: baseline (pristine tip) vs after (tip + this deliverable)
    out.append("### 3. the existing refe suites: pristine tip 1664143 (baseline) vs the tree with this deliverable (after)\n")
    b, bdone = summary("baseline")
    a, adone = summary("after")
    if b is None or a is None:
        out.append("NOT FINISHED (summary files absent)\n")
        bad.append("baseline/after suites not started")
    else:
        out.append("| suite | baseline rc | baseline marker | after rc | after marker | same |\n|---|---|---|---|---|---|")
        names = list(dict.fromkeys(list(b) + list(a)))
        for n in names:
            x, y = b.get(n), a.get(n)
            same = bool(x and y and x[0] == y[0] and x[2] == y[2])
            out.append(f"| {n} | {x[0] if x else '-'} | {x[2] if x else 'not run'} | {y[0] if y else '-'} | {y[2] if y else 'not run'} | {'yes' if same else 'NO'} |")
            if not same:
                bad.append(f"suite {n}: baseline vs after differ or one is missing")
            if y and y[0] != 0:
                bad.append(f"suite {n} after rc={y[0]}")
        out.append(f"\nbaseline finished: {bdone}; after finished: {adone}\n")
        if not (bdone and adone):
            bad.append("suite runs not finished")
    verdict = "ALL GREEN" if not bad else "NOT GREEN: " + "; ".join(bad)
    body = f"**Verification verdict (generated by finalize_verification.py): {verdict}**\n\n" + "\n".join(out)
    (RAW / "VERIFICATION.md").write_text(body, encoding="utf-8", newline="\n")
    rp = R / "RESULT.md"
    txt = rd(rp)
    if txt and BEGIN in txt and END in txt:
        pre, rest = txt.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        rp.write_text(pre + BEGIN + "\n" + body + "\n" + END + post, encoding="utf-8", newline="\n")
    print(verdict)
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
