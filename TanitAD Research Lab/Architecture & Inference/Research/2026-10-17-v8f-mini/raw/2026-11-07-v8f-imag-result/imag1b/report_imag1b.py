def f(r, d=3):
    if r is None or r.get("point") is None:
        return "n/a"
    return f"{r['point']:+.{d}f} [{r['lo']:+.{d}f}, {r['hi']:+.{d}f}]"


def fp(x, d=3):
    return "n/a" if x is None else f"{x:.{d}f}"


