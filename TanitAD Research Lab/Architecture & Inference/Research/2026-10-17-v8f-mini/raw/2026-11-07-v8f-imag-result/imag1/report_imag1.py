"""PREREG_V8F_IMAG1 report: reads RESULT_IMAG1.json, checks controls 1 to 3 (and 4 from TEST_IMAG1.log) FIRST, then writes RESULT_IMAG1.md (generated; nothing is typed by hand except the
fixed text below). Tier T0 on every table. Usage: python report_imag1.py"""
import json, os, re, sys, hashlib
sys.dont_write_bytecode = True
os.chdir(os.path.dirname(os.path.abspath(__file__)))
R = json.load(open("RESULT_IMAG1.json", encoding="utf-8"))
LEV, KS, PR_ = ("1", "2", "3"), ("1", "2", "3"), ("ridge", "mlp")
TG = ("speed", "accel", "lead_gap", "lead_closing", "ttc", "yaw_rate", "curvature", "lead_present", "lon7", "agents30")
FAMILY = {"speed": "LON", "accel": "LON", "lead_gap": "LON", "lead_closing": "LON", "ttc": "LON", "yaw_rate": "LAT", "curvature": "LAT", "lead_present": "TAC", "lon7": "TAC", "agents30": "SCENE"}
CLS = ("lead_present", "lon7")
REPEAT = {"speed", "lead_gap", "lead_closing", "ttc", "lead_present", "lon7", "agents30"}
DT = {"1": 0.2, "2": 0.4, "3": 0.8}
TAGS = ("M2b_s0", "M2b_s1")
k_ = lambda *a: "|".join(str(x) for x in a)


def f(r, d=3):
    if r is None or r.get("point") is None:
        return "n/a"
    return f"{r['point']:+.{d}f} [{r['lo']:+.{d}f}, {r['hi']:+.{d}f}]"


def fp(x, d=3):
    return "n/a" if x is None else f"{x:.{d}f}"


def nm(q, row, ent=None):
    """NMSE (continuous) as 'p [lo,hi]'; classes: the score BA - majority."""
    if q in CLS:
        return f(row)
    return f"{1 - row['point']:.3f} [{1 - row['hi']:.3f}, {1 - row['lo']:.3f}]"


out = []
w = out.append
# ------------------------------------------------------------------------------------------------ controls first
test_ok = False
if os.path.exists("TEST_IMAG1.log"):
    t = open("TEST_IMAG1.log", encoding="utf-8", errors="replace").read()
    test_ok = bool(re.search(r"\d+ passed", t)) and not re.search(r"\d+ (failed|error)", t)
ctl = {}
for ds, D in R["datasets"].items():
    ctl[ds] = {"c1": D["control1"], "c2": D["control2"]["pass"], "c3": D["control3"]["pass"]}
valid = test_ok and all(v["c2"] and v["c3"] for v in ctl.values())
failed = [f"control 4 (synthetic test)"] if not test_ok else []
for ds, v in ctl.items():
    if not v["c2"]:
        failed.append(f"control 2 on {ds}")
    if not v["c3"]:
        failed.append(f"control 3 on {ds}")
banner = "VALID (controls 2, 3, 4 pass on every dataset run; control 1 reported)" if valid else "INVALID: " + ", ".join(failed) + ". Every number below is UNCONTROLLED and decides nothing."
w("# RESULT_IMAG1: the Imagination Audit, first pass (generated by report_imag1.py from RESULT_IMAG1.json)")
w(f"Card `../PREREG_V8F_IMAG1.md` prefix 9,212 bytes sha256 `{R['card_prefix_sha256'][:12]}`; IMPL_CHOICES_IMAG1.md sha256 `{R['impl_sha256'][:12]}`. **Tier T0** (a world-model diagnostic, never a driving claim). Models M2b s0 and s1, no model training; probes ridge (lambda 10) and a 2-layer MLP (64, 3 probe seeds). STRATEGIC: PAUSED (PI item 25), not read.")
w(f"\n## Read status: **{banner}**\n")
w("| control | what | eval141 | TRAIN |")
w("|---|---|---|---|")
def cv(ds, key):
    return "n/a" if ds not in ctl else ("pass" if ctl[ds][key] else "FAIL")
w(f"| 1 (reported) | in-sample vs out-of-sample Oracle NMSE | " + " | ".join(f"{ctl[ds]['c1']['in_sample_not_below_out_of_sample']} of {ctl[ds]['c1']['cells']} cells not below" if ds in ctl else "n/a" for ds in ("eval141", "train")) + " |")
w(f"| 2 | real-vs-real (offset by 0.2 s is not the future) | {cv('eval141', 'c2')} | {cv('train', 'c2')} |")
w(f"| 3 | calibration of the two-part rule (<= 5 % per family) | {cv('eval141', 'c3')} | {cv('train', 'c3')} |")
w(f"| 4 | synthetic planted effects (IMAGINES, COPIES, ANSWERS, OVERSHOOTS) | {'pass' if test_ok else 'FAIL / not run'} (TEST_IMAG1.log) | same |")
for ds, D in R["datasets"].items():
    c2 = D["control2"]
    w(f"\n**Control 2, {ds}:** {c2['n_cells']} pooled family cells (probe kind x seed x level x k x family), {c2['n_not_separated']} not separated above 0; pooled cells with the offset beating the Oracle at both seeds: {len(c2['offset_beats_oracle_cells'])}; single rows with it (beside): {len(c2['offset_beats_oracle_rows_beside'])}.")
    if c2["n_not_separated"]:
        bad = [f"{x['P']}/{x['tag'][-2:]}/L{x['l']}k{x['k']}/{x['family']}" for x in c2["cells"] if not x["separated_above_0"]][:14]
        w(f"  not separated (first {len(bad)}): " + ", ".join(bad))
    c3 = D["control3"]["families"]
    w(f"**Control 3, {ds}** (rows two-part separated on 20 permuted draws; at most 5 % allowed): " + "; ".join(f"{fam} {v['separated']}/{v['rows']} = {100 * v['share']:.2f} % ({'ok' if v['pass'] else 'FAIL'})" + (f", bootstrap-only {100 * v['share_bootstrap_only']:.1f} %" if v.get("share_bootstrap_only") is not None else "") for fam, v in c3.items()))
    for fam, v in c3.items():
        w(f"  * {fam} by row kind (separated / rows): " + "; ".join(f"{kd} {b[1]}/{b[0]}" for kd, b in v["by_kind"].items()))
    w(f"  * beside, the same 20 draws against the LATSEM2B-style cross-draw reference for every row kind (point beyond the 97.5th / 2.5th percentile of the 199 permuted-probe points): " + "; ".join(f"{fam} {100 * v['share']:.2f} %" for fam, v in D["control3"]["beside_perm_referenced_shares"].items()))
    c1 = D["control1"]
    w(f"**Control 1, {ds}:** {c1['in_sample_not_below_out_of_sample']} of {c1['cells']} continuous probe cells have the in-sample NMSE not below the scoring-fold NMSE (reported, not a bar).")
    w(f"Logistic / MLP bookkeeping: real stage {D['conv']['real']}; reference and calibration logistic fits {D['conv']['refs_fits']}, not converged {D['conv']['refs_not_converged']}. Draws: R = {D['R']} reference + {D['n_cal']} calibration; mean wall time per draw {fp(D['draw_time_s']['mean'], 1)} s on a pool of {D['draw_time_s']['pool']} (this invocation's {D['draw_time_s']['n']} tasks).")

# ------------------------------------------------------------------------------------------------ per dataset
for ds, D in R["datasets"].items():
    deciding = ds == "eval141"
    w(f"\n---\n# Dataset {ds} ({'DECIDING' if deciding else 'BESIDE: optimistic, the model trained on these clips; decides nothing'})")
    w(f"Bank {D['n_bank_frames']:,} frames, {D['n_episodes']} episodes; {D['n_windows']:,} windows (start frame 0, horizons k = 1, 2, 3 steps of each level). Estimators: episode-cluster bootstrap (B 2,000, seed 0) for every interval; paired sign flips (R 199) and label-permuted probes (R {D['R']}) for the second part of the separation. A row is 'sep' only when both parts hold.")
    # ---- IA-0
    w("\n## IA-0 health (gate)")
    w("| level | seed | RankMe enc (bank) | RankMe pred k=1 | RankMe oracle k=1 | MRR | chance | excess MRR [95 %] | 97.5th of permuted | sep (two-part) |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for l in LEV:
        for tag in TAGS:
            e = D["ia0"][k_(tag, l)]
            rk = e["rankme"]
            w(f"| L{l} | {tag[-2:]} | {rk['enc']:.1f} | {rk['pred_k1']:.1f} | {rk['oracle_k1']:.1f} | {e['mrr']:.4f} | {e['chance']:.4f} | {f(e['excess'], 4)} | {fp(e['thr97'], 4)} | {'yes' if e['separated_two_part'] else 'no'} |")
    hl = D["healthy"]
    w("\n" + ", ".join(f"**L{l}: {'HEALTHY' if hl[l] else 'UNHEALTHY (rows reported, NOT READ)'}**" for l in LEV))
    # ---- IA-1
    w("\n## IA-1 capture: probe on the encoded latent at t (NMSE for continuous targets, lower is better, 1 = marginal mean; classes: balanced accuracy minus the majority baseline, higher is better). 'E' = separated by the two-part rule.")
    for fam in ("LON", "LAT", "TAC", "SCENE"):
        w(f"\n### {fam}")
        w("| target | probe | seed | L1 | L2 | L3 | ENCODED at L1/L2/L3 (both seeds) |")
        w("|---|---|---|---|---|---|---|")
        for q in [t for t in TG if FAMILY[t] == fam]:
            for P in PR_:
                for tag in TAGS:
                    cells = []
                    for l in LEV:
                        e = D["ia1"][k_(P, tag, l, q)]
                        cells.append(nm(q, e["score"]) + (" E" if e["encoded"] else ""))
                    enc = "/".join("yes" if D["encoded"][k_(P, l, q)] else "no" for l in LEV)
                    w(f"| {q}{' (REPEAT TARGET)' if q in REPEAT else ''} (n {D['ia1'][k_(P, tag, '1', q)]['score']['n']}) | {P} | {tag[-2:]} | " + " | ".join(cells) + f" | {enc if tag == TAGS[0] else ''} |")
    if "ia1_rand" in D:
        w("\n### Random-init rows (same architecture, untrained; eval141 only; TRAIN: NOT COMPUTED, it would need the TRAIN clips re-streamed from box 2)")
        w("| target | probe | init | L1 | L2 | L3 |")
        w("|---|---|---|---|---|---|")
        for q in TG:
            for P in PR_:
                for rt in ("rand0", "rand1"):
                    w(f"| {q} | {P} | {rt} | " + " | ".join(nm(q, D["ia1_rand"][k_(rt, P, l, q)]["score"]) for l in LEV) + " |")
    # ---- IA-2
    w("\n## IA-2 probe transfer: the same probe on the PREDICTED latent, on Copy-Last and on the Oracle (NMSE; classes: BA minus majority)")
    w("Triple = predicted / Copy-Last / Oracle at that seed. Labels: UNREADABLE > IMAGINES > WORSE-THAN-COPY > COPIES, each probe at both seeds; **decision** = both probes agree. Rows of an UNHEALTHY level are marked and not read.")
    for fam in ("LON", "LAT", "TAC", "SCENE"):
        w(f"\n### {fam}")
        w("| target | L | k (h s) | n win / ep | ridge s0 | ridge s1 | mlp s0 | mlp s1 | ridge | mlp | DECISION |")
        w("|---|---|---|---|---|---|---|---|---|---|---|")
        for q in [t for t in TG if FAMILY[t] == fam]:
            for l in LEV:
                for k in KS:
                    cells = []
                    for P in PR_:
                        for tag in TAGS:
                            e = D["ia2"][k_(P, tag, l, k, q)]
                            r = e["rows"]
                            if q in CLS:
                                cells.append("/".join(f"{r[x]['point']:+.2f}" for x in ("pred", "copy", "oracle")))
                            else:
                                cells.append("/".join(f"{1 - r[x]['point']:.2f}" for x in ("pred", "copy", "oracle")))
                    lb = D["ia2_labels"][k_(l, k, q)]
                    e0 = D["ia2"][k_("ridge", TAGS[0], l, k, q)]
                    dec = lb["decision"] + ("" if lb["read"] else " (L" + l + " UNHEALTHY: NOT READ)")
                    w(f"| {q}{' (R)' if q in REPEAT else ''} | L{l} | {k} ({int(k) * DT[l]:.1f}) | {e0['n']} / {e0['nep']} | " + " | ".join(cells) + f" | {lb['ridge']} | {lb['mlp']} | **{dec}** (beside, cross-draw reference: {lb['beside_perm_referenced']}) |")
    w("\n(R) = REPEAT TARGET: this target on these windows was read by LATSEM / LATSEM2 before; no row alone is a new finding.")
    w("\n### Paired differences, score(predicted) minus score(Copy-Last) (positive = predicted better); point [95 % bootstrap] with the second-part flags (A = above, B = below, two-part)")
    w("| target | L | k | ridge s0 | ridge s1 | mlp s0 | mlp s1 |")
    w("|---|---|---|---|---|---|---|")
    for q in TG:
        for l in LEV:
            for k in KS:
                cs = []
                for P in PR_:
                    for tag in TAGS:
                        e = D["ia2"][k_(P, tag, l, k, q)]["pred_minus_copy"]
                        cs.append(f(e) + (" A" if e["above"] else "") + (" B" if e["below"] else ""))
                w(f"| {q} | L{l} | {k} | " + " | ".join(cs) + " |")
    kn = D.get("kinematic_null", {})
    if kn:
        w("\n### Kinematic null (beside, no bar): speed from constant acceleration over the last 0.4 s of logged speed, yaw rate held (NMSE)")
        w("| L | k | speed NMSE [95 %] (n) | yaw-rate NMSE [95 %] (n) |")
        w("|---|---|---|---|")
        for l in LEV:
            for k in KS:
                a, b = kn.get(k_(l, k, "speed")), kn.get(k_(l, k, "yaw_rate"))
                g_ = lambda x: "n/a" if not x or not x["nmse"] else f"{x['nmse']['point']:.3f} [{x['nmse']['lo']:.3f}, {x['nmse']['hi']:.3f}] (n {x['n']})"
                w(f"| L{l} | {k} | {g_(a)} | {g_(b)} |")
    # ---- IA-3
    w("\n## IA-3 action audit: contrast of the logged action (lon +/-1.0 m/s^2, lat +/-0.25 rad/s), decoded effect over the physical effect (speed: dv = da * h; yaw rate: d(omega))")
    w("Gain [95 %] per seed; label per seed; cosine between the imagined and physical 2x2 Jacobian (rows speed / yaw rate, columns lon / lat; raw per-unit entries; gain-unit cosine beside). ANSWERS needs gain in [0.5, 1.5], right sign, two-part separated from 0, cosine > 0.7, at both seeds.")
    for P in PR_:
        w(f"\n### probe: {P}")
        w("| L | k (h s) | lon gain s0 | lon gain s1 | lat gain s0 | lat gain s1 | cos s0 / s1 (gain-unit) | lon label (s0, s1) | lat label (s0, s1) |")
        w("|---|---|---|---|---|---|---|---|---|")
        for l in LEV:
            for k in KS:
                e = [D["ia3"][k_(P, tag, l, k)] for tag in TAGS]
                w(f"| L{l} | {k} ({int(k) * DT[l]:.1f}) | {f(e[0]['lon']['gain'], 2)} | {f(e[1]['lon']['gain'], 2)} | {f(e[0]['lat']['gain'], 2)} | {f(e[1]['lat']['gain'], 2)} | "
                  f"{e[0]['cos']['point']:.2f} / {e[1]['cos']['point']:.2f} ({e[0]['cos_gain_units_beside']:.2f} / {e[1]['cos_gain_units_beside']:.2f}) | {e[0]['lon']['label']}, {e[1]['lon']['label']} | {e[0]['lat']['label']}, {e[1]['lat']['label']} |")
    w("\n### Decision labels (both seeds, both probes agree)")
    w("| L | k | longitudinal: ridge / mlp / DECISION | lateral: ridge / mlp / DECISION |")
    w("|---|---|---|---|")
    for l in LEV:
        for k in KS:
            a, b = D["ia3_labels"][k_(l, k, "lon")], D["ia3_labels"][k_(l, k, "lat")]
            nr = "" if a["read"] else " (UNHEALTHY: NOT READ)"
            w(f"| L{l} | {k} | {a['ridge']} / {a['mlp']} / **{a['decision']}**{nr} (beside, cross-draw reference: {a['beside_perm_referenced']}) | {b['ridge']} / {b['mlp']} / **{b['decision']}**{nr} (beside: {b['beside_perm_referenced']}) |")
    w("\n### Beside, no bar: ATM inverse probe (ridge from [z_t, z_{t+k}] to the mean logged action; R^2 of acceleration / yaw rate; rows = fitted on, columns = scored on)")
    w("| seed | L | k | real->real | real->pred | pred->real | pred->pred |")
    w("|---|---|---|---|---|---|---|")
    for tag in TAGS:
        for l in LEV:
            for k in KS:
                cs = []
                for fk in ("real", "pred"):
                    for sk in ("real", "pred"):
                        c = D["inverse_probe"][tag][k_(l, k, fk, sk)]
                        cs.append(f"{c['accel']['r2']:+.2f} / {c['yaw_rate']['r2']:+.2f}")
                w(f"| {tag[-2:]} | L{l} | {k} | " + " | ".join(cs) + " |")
    w("\n### Beside, no bar: IWM action bank (16 candidate actions; MRR of the logged action's prediction ranked by distance to the encoded true future; chance exact)")
    w("| seed | L | k | MRR | chance | excess [95 %] |")
    w("|---|---|---|---|---|---|")
    for tag in TAGS:
        for l in LEV:
            for k in KS:
                e = D["action_bank"][k_(tag, l, k)]
                w(f"| {tag[-2:]} | L{l} | {k} | {e['mrr']:.4f} | {e['chance']:.4f} | {f(e['excess'], 4)} |")
    tu = D["turning"]
    w(f"\n**Turning vs straight (count, input of E7):** {tu['turning']} of {tu['windows']} windows have |mean logged yaw rate| > 0.1 rad/s = {100 * tu['share_turning']:.1f} % turning, {tu['straight']} straight ({ds}; {f(tu['interval'], 3)} share, episode-cluster bootstrap). " + ("The TRAIN windows are a 141-clip sample of M2b's training clips; the full training-set count needs box 2's cache and is not claimed." if ds == "train" else ""))
    # ---- IA-6
    w("\n## IA-6 hierarchy")
    w("TSI_l = mean(IA-1 NMSE over accel, yaw rate, closing speed) minus mean over (speed, lead present, manoeuvre, agents within 30 m; classes as 1 - balanced accuracy).")
    w("| probe | seed | TSI L1 | TSI L2 | TSI L3 | TSI(L3) - TSI(L1) [95 %] | 97.5th of permuted | sep (two-part) |")
    w("|---|---|---|---|---|---|---|---|")
    for P in PR_:
        for tag in TAGS:
            e = D["ia6"]["tsi"][k_(P, tag)]
            w(f"| {P} | {tag[-2:]} | " + " | ".join(f"{e['tsi'][l]:+.3f}" for l in LEV) + f" | {f(e['diff_L3_minus_L1'])} | {fp(e['thr97'])} | {'yes' if e['separated_two_part'] else 'no'} |")
    w(f"\n**Timescale split: {D['ia6']['split_decision']}** (per probe: {D['ia6']['split_by_probe']}).")
    w("\n| probe | seed | pair | slope y~x [95 %] | n win | CONSISTENT (interval contains 1, lower bound > 0) |")
    w("|---|---|---|---|---|---|")
    for P in PR_:
        for tag in TAGS:
            for nm_ in ("L2k1_vs_L1k2_0.4s", "L3k1_vs_L2k2_0.8s"):
                e = D["ia6"]["consistency"][k_(P, tag, nm_)]
                w(f"| {P} | {tag[-2:]} | {nm_} | {f(e)} | {e['n']} | {'yes' if e['consistent'] else 'no'} |")
    w("\nBoth seeds: " + "; ".join(f"{k.replace('|', ' ')}: {'CONSISTENT' if v else 'not consistent (slope as reported above)'}" for k, v in D["ia6"]["consistent_by_probe"].items()))
    # ---- triggers
    w("\n## What each outcome triggers (the card's commitments, evaluated exactly as IMPL_CHOICES section 7 says)")
    tr = D["triggers"]
    for kk in sorted(tr):
        if "rows" in kk:
            continue
        w(f"* `{kk}`: {tr[kk]}")
    for kk in sorted(tr):
        if "rows" in kk and tr[kk]:
            w(f"* `{kk}`: {tr[kk]}")
    w("\nNote: triggers read only the HEALTHY levels' DECISION labels (probes agree). The single-probe variants are listed beside. This section states which committed lever the outcomes call for; it launches nothing.")

fig_dir = "fig"
if os.path.isdir(fig_dir):
    pngs = sorted(p for p in os.listdir(fig_dir) if p.endswith(".png"))
    if pngs:
        w("\n## Figures (`fig/`, no camera frame; sha256 first 12)")
        for p in pngs:
            w(f"* `fig/{p}` `{hashlib.sha256(open(os.path.join(fig_dir, p), 'rb').read()).hexdigest()[:12]}`")
open("RESULT_IMAG1.md", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote RESULT_IMAG1.md", len(out), "lines;", banner)
