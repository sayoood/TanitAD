#!/usr/bin/env python3
"""Generate box2_ship/oaf_dagoaccorc_r2_lib.sh: the r2 additions of chain_v8f_dagoaccorc_r2.sh (the DAG-ORC (DAG-OACC base) re-run after the r1 chain stopped on K-REACH).

The aside MECHANISM is DAG-OACC r2's (C:/Users/Admin/box2_ship/oaf_r2_lib.sh: r2_aside_local / r2_aside_job_text / r2_aside_all and its :aside cmd subroutine), copied; this generator ASSERTS the :aside subroutine and the local rename are the
installed ones modulo the suffix (_r1_assert_stop -> _r1_kreach_stop).  What differs, and only this:
  * the suffix  _r1_kreach_stop
  * the item list: DAG-ORC (DAG-OACC base) has FOUR runs (A s0, REP s0, A s1, REP s1) and r1 got as far as TRAINING and EVALUATING A s0, so the list covers, per run, the RUN DIRECTORY, the GATE directory + .log, the pinned training argv
    (+ its .new / .chk scratch copies) and the T0 eval files.  The queue SKIPS a stage whose output exists (traindag: <run>\\summary.json; evaldag: eval\\eval_<tag>.npz), so an r1 run directory or eval file left in place would make r2
    "train" nothing and pull the REFUSED run's stale eval: they are the items that matter most.
  * wait_predecessor (overrides oaf_lib.sh's): GO only after the r1 chain's K-REACH stop (v8f_dagoaccorc_r2_chain_checks.py pred-verdict-r2).
    python build_r2_lib.py          writes ../box2_ship/oaf_dagoaccorc_r2_lib.sh (LF)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "box2_ship" / "oaf_dagoaccorc_r2_lib.sh"
OACC_R2_LIB = Path("C:/Users/Admin/box2_ship/oaf_r2_lib.sh")
SUF = "_r1_kreach_stop"
OLD_SUF = "_r1_assert_stop"
ARMS = ("dagoaccorc", "dagoaccorcrep")
SEEDS = (0, 1)


def items() -> list:
    """Every r1 artifact of the DAG-ORC chain on box 2, relative to the runs root, in cmd syntax. Absent items cost one ASIDE-ABSENT line."""
    out = []
    for s in SEEDS:                       # run directories (r1 trained and evaluated A s0; the rest are absent, and listed so a state we did not foresee is still moved)
        for a in ARMS:
            out.append(f"M2b_s{s}_{a}")
    for s in SEEDS:                       # gate directories + their logs
        for a in ARMS:
            out += [f"gate_M2b-{a}_s{s}", f"gate_M2b-{a}_s{s}.log"]
    for s in SEEDS:                       # the pinned training argv (gatedag REFUSES a pin that differs from the argv derived now) and its scratch copies
        for a in ARMS:
            p = f"dagpin\\M2b_s{s}_{a}.train.argv.txt"
            out += [p, p + ".new", p + ".chk"]
    for s in SEEDS:                       # the T0 eval files (evaldag SKIPS when eval_<tag>.npz exists)
        for a in ARMS:
            t = f"eval\\eval_M2b-{a}_s{s}"
            out += [t + ".json", t + ".npz", t + ".log", t + "_proj.npz", t + "_beta.npz"]
    assert len(out) == len(set(out))
    return out


def aside_block(suffix: str) -> str:
    return (":aside\n"
            'if not exist "%~1" (echo ASIDE-ABSENT %~1 & exit /b 0)\n'
            f'if exist "%~1{suffix}" (echo ASIDE-FAIL %~1 and its aside sibling %~nx1{suffix} both exist: refusing to overwrite or to guess & exit /b 1)\n'
            f'ren "%~1" "%~nx1{suffix}"\n'
            'if errorlevel 1 (echo ASIDE-FAIL %~1 could not be renamed & exit /b 1)\n'
            f'echo ASIDE-MOVED %~1 to %~nx1{suffix}\n'
            'exit /b 0\n')


def installed_aside_block(text: str) -> str:
    m = re.search(r"cat <<'EOF'\n(:aside\n.*?)EOF\n", text, re.S)
    assert m, "no :aside heredoc in the installed oaf_r2_lib.sh"
    return m.group(1)


HEAD = r'''#!/usr/bin/env bash
# oaf_dagoaccorc_r2_lib.sh -- the r2 additions of chain_v8f_dagoaccorc_r2.sh (the DAG-ORC (DAG-OACC base) re-run after the r1 chain STOPPED on K-REACH, 2026-10-28). GENERATED by gen/build_r2_lib.py; never hand-edited.
# SOURCED by the r2 chain right after oaf_lib.sh (this file overrides wait_predecessor). NEW FILE: oaf_lib.sh and oaf_r2_lib.sh (DAG-OACC r2's) are not touched. Needs from the chain: B L TAG ART SSH SCP BOOT0 BUSY_TAKEN CUR PY DCHECKS AFTER_OUT
# and oaf_lib.sh's stop / launch / waitrc / clean.
#
# WHAT r1 LEFT BEHIND: r1 passed its four gates, TRAINED and EVALUATED A s0 (M2b_s0_dagoaccorc), pulled it, then stopped on K-REACH (ego 19161/76898 = 0.2492, must lie in 0.3 +- 0.02: the swap and the perturbation drew from ONE RNG
# stream). REP s0, A s1 and REP s1 never trained. Nothing of it may be mistaken for r2's: the queue SKIPS a train stage whose <run>\summary.json exists and an eval stage whose eval\eval_<tag>.npz exists (r2 would "train" nothing and
# pull the refused run's stale eval), gatedag REFUSES a pinned training argv that differs from the one derived now, and a stale gate record would be pulled and asserted as if fresh. So EVERY r1 artifact is MOVED ASIDE (renamed to
# <name>_r1_kreach_stop; NEVER deleted, never overwritten) before anything else touches box 2 or E:.
#   dev box (r2_aside_local, FIRST, a rename): $ART (E:/Projects/TanitAD-artifacts/v8f-dag-orc-oacc: the four pulled gate dirs, A s0's pulled run, K-BUILD.txt), then $ART is created empty again for r2
#   box 2   (one cmd job, r2_aside_job_text): <runs>\M2b_s<S>_<arm> (run dirs), <runs>\gate_M2b-<arm>_s<S> (+ .log), <runs>\dagpin\M2b_s<S>_<arm>.train.argv.txt (+ .new / .chk), <runs>\eval\eval_M2b-<arm>_s<S>.{json,npz,log,_proj.npz,_beta.npz}
#           for arm in dagoaccorc, dagoaccorcrep and S in 0, 1
# LEFT IN PLACE ON PURPOSE: M2b_s<S> (the init checkpoints), dagger_bank\ (the iteration-1 banks), dagoacc\ (w_acc.txt), the DAG-OACC runs and their pins and evals, dagpin\bank_sha_dagoacc_s<S>.txt (rewritten by the queue, same value).
# A RELAUNCH OF r2 IS SAFE, AND r2 NEVER MOVES ITS OWN FILES: the aside runs BEFORE r2 writes anything, so "present before the aside" means "r1's".
#   dev box: <ART>_r1_kreach_stop exists -> the aside was done by an earlier launch: <ART> (if any) is r2's own progress: KEPT.
#   box 2:   <runs>\r2_aside_done_dagoaccorc.txt (written by the job's last line) exists -> ASIDE-ALREADY-DONE, nothing is touched. Without the marker, per item: absent -> ASIDE-ABSENT; present -> renamed (ASIDE-MOVED); present AND its aside copy
#            present -> ASIDE-FAIL (an unexpected state: never overwritten, never guessed, the chain stops). A job that fails midway writes no marker, so its retry moves the rest.
#   THE MARKER IS THIS CHAIN'S OWN NAME (r2_aside_done_dagoaccorc.txt), NOT DAG-OACC r2's r2_aside_done.txt: both chains use the SAME runs root, and r2's first launch (2026-10-28 03:27) found
#   DAG-OACC r2's marker (written 2026-10-27 20:21), printed ASIDE-ALREADY-DONE, moved nothing, and the queue then SKIPPED A s0's training (r1's summary.json was still there); the run-record check refused it.
#   Two chains that write the same marker into one directory share one marker.
R2_SUF=@SUF@

r2_box_items() {   # the box-2 items, relative to the runs root (cmd syntax); ONE source for the job text and for the count the chain asserts
  printf '%s\n' \
@ITEMS@
}

r2_aside_job_text() {   # r2_aside_job_text <runs root, cmd form>: the box-2 job (CRLF). RENAMES ONLY (plus the one marker line): no del / rmdir / move / copy anywhere in it
  local rs=$1 it
  {
    echo '@echo off'
    echo 'setlocal'
    echo "set \"RS=$rs\""
    echo 'set "RC=0"'
    echo 'echo ===== r2 aside %DATE% %TIME%'
    echo 'if exist "%RS%\r2_aside_done_dagoaccorc.txt" (echo ASIDE-ALREADY-DONE an earlier launch of r2 moved the r1 artifacts aside, marker %RS%\r2_aside_done_dagoaccorc.txt & goto :end)'
    while IFS= read -r it; do
      echo "call :aside \"%RS%\\$it\" || (set \"RC=1\" & goto :end)"
    done < <(r2_box_items)
    echo '>"%RS%\r2_aside_done_dagoaccorc.txt" echo DAG-ORC r2 aside done %DATE% %TIME%'
    echo ':end'
    echo 'echo ===== ZZJOB-END %DATE% %TIME% rc=%RC%'
    echo 'exit /b %RC%'
    cat <<'EOF'
@ASIDE@EOF
  } | sed 's/$/\r/'
}

r2_aside_local() {   # r2_aside_local <path>: rename <path> to <path>_r1_kreach_stop. NEVER deletes, never overwrites; an existing aside copy means <path> is r2's own progress: kept
  local d=$1 n="$1$R2_SUF"
  [ -e "$d" ] || { echo "ASIDE-ABSENT $d"; return 0; }
  [ -e "$n" ] && { echo "ASIDE-KEPT $d : the r1 copy is already aside as $n"; return 0; }
  mv "$d" "$n" || stop "r2 aside: cannot rename $d to $n"
  { [ -e "$n" ] && [ ! -e "$d" ]; } || stop "r2 aside: $d -> $n did not happen"
  echo "ASIDE-MOVED $d to $n"
}

r2_aside_all() {   # the chain's FIRST action after BOX2_BUSY is taken and the boot probe answered: the dev box's pull dir (a rename; $ART is then created empty for r2), then the box-2 job (shipped, launched, waited for like the refresh job) and its report checked
  local j=v8fdagoaccorc${TAG}_r2aside n want
  r2_aside_local "$ART"
  mkdir -p "$ART" || stop "r2 aside: cannot create $ART"
  r2_aside_job_text 'D:\tanitad\runs\v8f_mini_full' > $B/$j.cmd || stop "write the r2 aside job"
  $SCP $B/$j.cmd tanitad-box2:D:/tanitad/jobs/ || stop "ship the r2 aside job"
  rm -f $L/$j.log
  launch $j || stop "launch the r2 aside job"
  waitrc $j 40
  clean $j | grep -a '^ASIDE-'
  n=$(clean $j | grep -ac '^ASIDE-')
  if clean $j | grep -aq '^ASIDE-ALREADY-DONE'; then want=1; else want=$(r2_box_items | wc -l); fi
  [ "$n" = "$want" ] || stop "the r2 aside job reported $n ASIDE lines, expected $want"
  clean $j | grep -aq '^ASIDE-FAIL' && stop "the r2 aside job reported an ASIDE-FAIL"
  echo "$(date '+%m-%d %H:%M') r2 aside done: the r1 artifacts are moved aside (dev box: ${ART}${R2_SUF}; box 2: *${R2_SUF}, $want lines)"
}

wait_predecessor() {   # r2's: OVERRIDES oaf_lib.sh's (which GOes after ANY predecessor STOP). GO only when AFTER_OUT (the r1 DAG-ORC chain's log) ENDED in exactly the K-REACH stop for M2b_s0_dagoaccorc and BOX2_BUSY is released
                       # (v8f_dagoaccorc_r2_chain_checks.py pred-verdict-r2: DONE, any other STOP, a guard stop, a disk-floor stop, a second STOP, text after the stop -> HALT). BUSY: re-check a few times, then HALT. WAIT: poll (OAF_POLL_S = 300 s).
  local v w k=0 poll=${OAF_POLL_S:-300} grace=${OAF_GRACE_S:-20}
  echo "$(date '+%m-%d %H:%M') waiting for the r1 chain ($AFTER_OUT: GO only when it ENDED in exactly the K-REACH stop for M2b_s0_dagoaccorc; log present: $([ -f "$AFTER_OUT" ] && echo yes || echo NO))"
  while :; do
    v=$($PY "$(cygpath -m $DCHECKS)" pred-verdict-r2 --out "$(cygpath -m "$AFTER_OUT")" --busy "$(cygpath -m "$B/BOX2_BUSY.txt")"); w=${v%% *}
    case $w in
      GO) echo "$(date '+%m-%d %H:%M') predecessor verdict: $v"; return 0 ;;
      HALT) stop "predecessor verdict: $v" ;;
      BUSY) k=$((k+1)); [ $k -gt 3 ] && stop "predecessor verdict: $v (still held after $k checks)"; sleep $grace ;;
      WAIT) k=0; sleep $poll ;;
      *) stop "pred-verdict-r2 printed no verdict ('$v')" ;;
    esac
  done
}
'''


def render() -> str:
    inst = OACC_R2_LIB.read_text(encoding="utf-8")
    want = installed_aside_block(inst).replace(OLD_SUF, SUF)
    got = aside_block(SUF)
    assert want == got, "the :aside subroutine is not DAG-OACC r2's (modulo the suffix)\n--- installed\n" + want + "\n--- ours\n" + got
    # the local rename and the job-text skeleton are the installed ones too (modulo names): check the load-bearing lines
    for needle in ('  [ -e "$d" ] || { echo "ASIDE-ABSENT $d"; return 0; }', '  mv "$d" "$n" || stop "r2 aside: cannot rename $d to $n"',
                   "    echo 'if exist \"%RS%\\r2_aside_done.txt\" (echo ASIDE-ALREADY-DONE an earlier launch of r2 moved the first attempt artifacts aside, marker %RS%\\r2_aside_done.txt & goto :end)'"):
        assert needle in inst, needle
    t = HEAD.replace("@SUF@", SUF).replace("@ASIDE@", got)
    its = items()
    t = t.replace("@ITEMS@", " \\\n".join("    '" + i + "'" for i in its))
    assert not re.search(r"@(SUF|ITEMS|ASIDE)@", t), "an unfilled placeholder"
    assert "\r" not in t
    return t


def main() -> int:
    t = render()
    OUT.write_bytes(t.encode("utf-8"))
    print("wrote", OUT, len(t), "bytes;", len(items()), "box-2 items")
    return 0


if __name__ == "__main__":
    sys.exit(main())
