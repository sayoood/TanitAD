"""read_accgain10k.py -- card PREREG_V8F_PROOF_ADD63 (ACCGAIN10K): the read (numpy only). Written from read_causlim10k.py (card ADD61) with the runs, pairs, controls and names of this
card. Controls e1 and a1 to a9 first; the names, the levels and the differences only if every control passed (else the read prints the controls and nothing else). No rule, no training.
Tier line: T1-kin (kinematic rollout on the model's own actions); never driving performance.
Runs (readout causal_g, 10 steps, both model seeds): R0G0 (gain 0), R0G50 (0.5), R0Gm25 (-0.25), R0G0X (gain 0, --path-exec). Controls: R0GID1 (gain 1, 10 steps, model seed 0, must
equal the banked R0C10) and R0GID0 (gain 0, 5 steps, model seed 0, must equal the banked R0Z5). Reused: R0 (pinned), R0C10 (gain 1), R0Bk10 (backward), R0Z5 (control a2 only).
Pairs: D1 = R0G50 minus R0G0, D2 = R0C10 minus R0G50, ZP = R0G0 minus R0, PX = R0G0X minus R0G0; beside: R0Gm25 minus R0G0, R0Gm25 minus R0Bk10, R0G0X minus R0,
each new run minus R0C10. Named cells: LONGITUDINAL speed_mae_mps and along_mae_m, LATERAL heading_mae_deg and yaw_rate_mae_degps, TACTICAL ade_tac_m."""
import argparse
import glob
import hashlib
import io
import json
import os
import re
import sys

import numpy as np

SEEDS = (0, 1)
DT = 0.2
CKPT_SHA_PREFIX = {0: "2fd4b747532f55b2", 1: "f13df8ce026eed31"}                       # card ADD46: UE_s0, UE_s1
WRAPPER_SHA_PREFIX = "93879db8c0233867"                                               # sha256 of v8f_t1_eval_reader_rule_rzg.py as generated by make_accgain10k.py (update if regenerated)
CARD = "PREREG_V8F_PROOF_ADD63"
PRE = "ACCGAIN10K"
# run -> (readout gain, path_exec, replan steps)
RUNS = {"I10R0GID1": (1.0, False, 10), "I10R0GID0": (0.0, False, 5), "I10R0G0": (0.0, False, 10), "I10R0G50": (0.5, False, 10), "I10R0Gm25": (-0.25, False, 10), "I10R0G0X": (0.0, True, 10)}
NEW_RUNS = [("I10R0GID1", 0), ("I10R0GID0", 0)] + [(arm, k) for arm in ("I10R0G0", "I10R0G50", "I10R0Gm25", "I10R0G0X") for k in SEEDS]      # ten rollouts
REUSED = ("I10R0", "I10R0C10", "I10R0Bk10")
ARMS_ALL = REUSED + ("I10R0G0", "I10R0G50", "I10R0Gm25", "I10R0G0X")
NAMED = {"LONGITUDINAL": ["LONGITUDINAL:speed_mae_mps", "LONGITUDINAL:along_mae_m"], "LATERAL": ["LATERAL:heading_mae_deg", "LATERAL:yaw_rate_mae_degps"], "TACTICAL": ["TACTICAL:ade_tac_m"]}
TIER_LINE = "TIER: T1-kin (kinematic rollout on the model's own actions); never driving performance"
TOL = 1e-6
PAIRS = {"D1": ("I10R0G50", "I10R0G0"), "D2": ("I10R0C10", "I10R0G50"), "ZP": ("I10R0G0", "I10R0"), "PX": ("I10R0G0X", "I10R0G0"),
         "beside_Gm25_minus_G0": ("I10R0Gm25", "I10R0G0"), "beside_Gm25_minus_Bk10": ("I10R0Gm25", "I10R0Bk10"), "beside_G0X_minus_R0": ("I10R0G0X", "I10R0"),
         "beside_G0_minus_C10": ("I10R0G0", "I10R0C10"), "beside_G50_minus_C10": ("I10R0G50", "I10R0C10"), "beside_Gm25_minus_C10": ("I10R0Gm25", "I10R0C10"),
         "beside_G0X_minus_C10": ("I10R0G0X", "I10R0C10")}


def jl(p):
    return json.load(io.open(p, encoding="utf-8")) if p and os.path.exists(p) else None


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest() if p and os.path.exists(p) else ""


def txt(p):
    return io.open(p, encoding="utf-8", errors="replace").read() if p and os.path.exists(p) else ""


def dump(pull, arm, k, keys=("g", "cl", "fl", "v0", "eid")):
    files = sorted(glob.glob(os.path.join(pull, "%s_s%d" % (arm, k), "dump_%s_s%d_m10_causal_heads" % (arm, k), "ep*.npz")))
    if len(files) != 141:
        return None
    out = {n: [] for n in keys}
    for f in files:
        z = np.load(f)
        for n in keys:
            out[n].append(np.asarray(z[n], np.float64))
    return {n: np.concatenate(v) for n, v in out.items()}


def speeds(tr):
    p = np.concatenate([np.zeros((len(tr), 1, 2)), tr], 1)
    return np.linalg.norm(np.diff(p, axis=1), axis=-1) / DT


def rs_of(d, key="cl"):
    """share of windows whose last-step speed lies more than 5 m/s above the logged one (finite rollouts)."""
    s, sg = speeds(d[key]), speeds(d["g"])
    fin = np.isfinite(d[key]).all(axis=(1, 2))
    return round(float(((s[:, -1] - sg[:, -1])[fin] > 5.0).mean()), 4)


def rlog(pull, arm, k):
    return jl(os.path.join(pull, "%s_s%d" % (arm, k), "ticks", "readout_log_%s_s%d.json" % (arm, k)))


def controls(a, hw, q3):
    C = {}
    e1 = jl(a.e1)
    C["e1_pod_read_reproduces_bank"] = {"file": os.path.basename(a.e1) if e1 else None, "PASS": bool(e1 and e1.get("PASS") is True)}
    for name, fn, banked in (("a1_gain1_rerun_equals_banked_R0C10", "CMP_R0GID1.txt", "I10R0C10"), ("a2_gain0_5steps_rerun_equals_banked_R0Z5", "CMP_R0GID0.txt", "I10R0Z5")):
        m = re.search(r"CMP files=(\d+) differing=(\d+)", txt(os.path.join(a.pull, "small_accgain", fn)))
        C[name] = {"line": m.group(0) if m else None, "banked": banked, "PASS": bool(m and m.group(1) == "141" and m.group(2) == "0")}
    a3, a5, a6, shs, wsh, rs, D = {}, {}, {}, {}, {}, {}, {}
    for arm in REUSED:
        for k in SEEDS:
            D[(arm, k)] = dump(a.pull, arm, k)
    for arm, k in NEW_RUNS:
        D[(arm, k)] = dump(a.pull, arm, k)
    for arm, k in NEW_RUNS:
        key = "%s_s%d" % (arm, k)
        g, px, m_steps = RUNS[arm]
        d = D[(arm, k)]
        pr = txt(os.path.join(a.pull, key, "ticks", "run_%s.txt" % key))
        mm = re.search(r"ckpt sha256 ([0-9a-f]{64})", pr)
        shs[key] = bool(mm and mm.group(1).startswith(CKPT_SHA_PREFIX[k]))
        mw = re.search(r"wrapper sha256 ([0-9a-f]{64})", pr)
        wsh[key] = mw.group(1) if mw else ""
        RL = rlog(a.pull, arm, k)
        a6[key] = {"dump_files": None if d is None else 141, "windows": None if d is None else int(len(d["g"]))}
        a6[key]["PASS"] = bool(d is not None and len(d["g"]) == 2399)
        if RL is None or d is None:
            a3[key] = {"PASS": None, "why": "readout log or dump missing"}
            a5[key] = {"PASS": None, "why": "dump missing"} if m_steps == 10 else {"PASS": True, "not_applicable": "5-step control"}
            continue
        dv, dga = RL.get("max_abs_speed_minus_last_step"), RL.get("max_abs_acceleration_minus_gain_executed")
        a3[key] = {"readout": RL.get("readout"), "acc_gain": RL.get("acc_gain"), "path_exec": RL.get("path_exec"), "replan_steps": RL.get("replan_steps"), "calls": RL.get("calls"),
                   "max_speed_diff": dv, "max_acceleration_diff": dga}
        a3[key]["PASS"] = bool(RL.get("readout") == "causal_g" and RL.get("acc_gain") == g and RL.get("path_exec") is px and RL.get("replan_steps") == m_steps and (RL.get("calls") or 0) > 0
                               and dv is not None and dga is not None and dv <= TOL and dga <= TOL)
        if m_steps == 10:                                   # the first 10 executed steps against the banked pinned R0, same model seed, model and prior
            r0 = D[("I10R0", k)]
            if r0 is None or d["cl"].shape[1] < 10 or r0["cl"].shape != d["cl"].shape:
                a5[key] = {"PASS": False, "why": "shape or missing R0"}
            else:
                dm = float(np.nanmax(np.abs(d["cl"][:, :10] - r0["cl"][:, :10])))
                dp = float(np.nanmax(np.abs(d["fl"][:, :10] - r0["fl"][:, :10])))
                eq = bool(np.array_equal(d["cl"][:, :10], r0["cl"][:, :10], equal_nan=True) and np.array_equal(d["fl"][:, :10], r0["fl"][:, :10], equal_nan=True))
                a5[key] = {"max_abs_diff_model": dm, "max_abs_diff_prior": dp, "PASS": bool(eq and dm == 0.0 and dp == 0.0)}
        else:
            a5[key] = {"PASS": True, "not_applicable": "5-step control"}
        rs[key] = {"model": rs_of(d, "cl"), "prior": rs_of(d, "fl")}
    for arm in REUSED:
        for k in SEEDS:
            d = D.get((arm, k))
            if d is not None:
                rs["%s_s%d" % (arm, k)] = {"model": rs_of(d, "cl"), "prior": rs_of(d, "fl")}
    cnt = (hw or {}).get("counts", {})
    t_out = txt(a.test_out)
    w1, w2 = sha(a.wrapper), sha(a.test_wrapper)
    printed = (re.findall(r"wrapper rzg sha256 ([0-9a-f]{64})", t_out) or [""])[-1]
    ru = jl(a.reused) or {"files": {}}
    base = os.path.dirname(os.path.dirname(os.path.abspath(a.reused)))
    bad = [p for p, h in ru["files"].items() if not os.path.exists(os.path.join(base, p)) or sha(os.path.join(base, p)) != h]
    C["a3_gain_applied_in_the_readout_log"] = {"per_run": a3, "PASS": (None if (len(a3) != len(NEW_RUNS) or any(v["PASS"] is None for v in a3.values())) else bool(all(v["PASS"] for v in a3.values())))}
    C["a4_tool_check"] = {"wrapper_sha256": w1[:16], "test_wrapper_sha256": w2[:16], "printed_by_check": printed[:16],
                          "check_line": (re.findall(r"^ZZ CHECK-ACC-GAIN.*$", t_out, re.M) or [None])[-1],
                          "PASS": bool(re.search(r"^ZZ CHECK-ACC-GAIN all hold: True\s*$", t_out, re.M) is not None)}
    C["a5_first_block_equals_banked_R0"] = {"per_run": a5, "PASS": (None if any(v["PASS"] is None for v in a5.values()) or len(a5) != len(NEW_RUNS) else bool(all(v["PASS"] for v in a5.values())))}
    C["a6_counts"] = {"per_run": a6, "n_windows_total": cnt.get("n_windows_total"), "n_lead_windows": cnt.get("n_lead_windows"),
                      "PASS": bool(hw and len(a6) == len(NEW_RUNS) and all(v["PASS"] for v in a6.values()) and cnt.get("n_windows_total") == 2399 and cnt.get("n_lead_windows") == 642 and cnt.get("PASS") is True)}
    C["a7_reused_result_files"] = {"n_reused_files": len(ru["files"]), "differing": bad, "PASS": bool(len(ru["files"]) == 7 and not bad)}
    C["a8_reader_controls"] = {"headway": bool(hw and hw["controls"].get("ALL_PASS")), "family": bool(q3 and q3["controls"].get("ALL_PASS"))}
    C["a8_reader_controls"]["PASS"] = bool(C["a8_reader_controls"]["headway"] and C["a8_reader_controls"]["family"])
    C["a9_checkpoints_and_wrapper"] = {"checkpoint_prefix_per_run": shs, "wrapper_sha256": w1[:16], "runs_with_this_wrapper_sha256": sorted(k for k, v in wsh.items() if v and v == w1),
                                       "PASS": bool(len(shs) == len(NEW_RUNS) and all(shs.values()) and w1 and w1 == w2 and w1 == printed and w1.startswith(WRAPPER_SHA_PREFIX)
                                                    and len(wsh) == len(NEW_RUNS) and all(v == w1 for v in wsh.values()))}
    return C, rs, D


def cells_of(q3, A, B):
    return {c: {"D": round(float(v["D"]), 4), "interval": [round(float(v["A_lo"]), 4), round(float(v["A_hi"]), 4)], "per_seed": [round(float(x), 4) for x in v["d_s"]], "verdict": v["verdict"]}
            for c, v in q3["pairs"]["%s_minus_%s" % (A, B)]["families"].items()}


def ucf(hw, A, B):
    out = {}
    for c in ("U", "C", "F"):
        v = hw["pairs"]["%s_minus_%s" % (A, B)]["cells"][c]
        out[c] = {"per_seed": [round(float(x), 4) for x in v["d_s"]], "pooled": round(float(v["D"]), 4), "interval": [round(float(v["A_lo"]), 4), round(float(v["A_hi"]), 4)]}
    return out


def reading(cells, fam):
    vs = [cells[c]["verdict"] for c in NAMED[fam]]
    if all(v == "BETTER" for v in vs):
        return "BETTER"
    if all(v == "WORSE" for v in vs):
        return "WORSE"
    if not any(v in ("BETTER", "WORSE") for v in vs):
        return "NOT-SEPARATED"
    return "MIXED"


def below(d):
    return bool(all(x < 0 for x in d["per_seed"]) and d["interval"][1] < 0)


def above(d):
    return bool(all(x > 0 for x in d["per_seed"]) and d["interval"][0] > 0)


def line(v):
    return "  ".join("%s %+.4f [%+.4f, %+.4f] %s" % (c, v[c]["pooled"], v[c]["interval"][0], v[c]["interval"][1], v[c]["per_seed"]) for c in ("U", "C", "F"))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--read-dir", required=True)
    ap.add_argument("--pull", required=True)
    ap.add_argument("--reused", required=True)
    ap.add_argument("--wrapper", required=True)
    ap.add_argument("--test-wrapper", required=True)
    ap.add_argument("--test-out", required=True)
    ap.add_argument("--e1", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    hw, q3 = jl(os.path.join(a.read_dir, "hw", "RESULT_HEADWAY.json")), jl(os.path.join(a.read_dir, "q3", "RESULT_Q3.json"))
    C, rs, D = controls(a, hw, q3)
    ok = all(v.get("PASS") is True for v in C.values())
    res = {"card": CARD, "tier": TIER_LINE, "controls": C, "controls_all_pass": bool(ok), "names": None}
    print(TIER_LINE)
    print("== controls (e1, a1 to a9)")
    for k, v in C.items():
        print("   %s %s %s" % (k, "PASS" if v.get("PASS") is True else ("FAIL" if v.get("PASS") is False else "NOT COMPUTABLE"), json.dumps(v)[:900]))
    if ok:
        lv = hw["levels"]
        levels = {arm: {c: [round(float(x), 4) for x in lv[arm]["cells"][c]["per_seed"]] for c in ("U", "C", "F")} for arm in ARMS_ALL if arm in lv}
        pairs, cells, fams = {}, {}, {}
        for nm, (A, B) in PAIRS.items():
            pairs[nm] = {"A": A, "B": B, "headway": ucf(hw, A, B)}
            cells[nm] = cells_of(q3, A, B)
            fams[nm] = {f: reading(cells[nm], f) for f in NAMED}
        names = {}
        for f in NAMED:
            r1, r2 = fams["D1"][f], fams["D2"][f]
            names["dose_" + f] = "%s-%s-%s" % (PRE, f, "RISES-WITH-OWN-ACCELERATION" if (r1 == "WORSE" and r2 == "WORSE") else ("FALLS-WITH-OWN-ACCELERATION" if (r1 == "BETTER" and r2 == "BETTER") else "NOT-MONOTONE"))
        u1, u2 = pairs["D1"]["headway"]["U"], pairs["D2"]["headway"]["U"]
        names["dose_U"] = "%s-U-%s" % (PRE, "RISES-WITH-OWN-ACCELERATION" if (above(u1) and above(u2)) else ("FALLS-WITH-OWN-ACCELERATION" if (below(u1) and below(u2)) else "NOT-MONOTONE"))
        suffix = {"BETTER": "BETTER-THAN-PINNED-AT-2S", "WORSE": "WORSE-THAN-PINNED-AT-2S", "MIXED": "MIXED-AT-2S", "NOT-SEPARATED": "NOT-SEPARATED-FROM-PINNED-AT-2S"}
        for f in NAMED:
            names["zero_" + f] = "%s-ZERO-%s-%s" % (PRE, f, suffix[fams["ZP"][f]])
        uz = pairs["ZP"]["headway"]["U"]
        names["zero_U"] = "%s-ZERO-U-%s" % (PRE, "ABOVE-PINNED-AT-2S" if above(uz) else ("BELOW-PINNED-AT-2S" if below(uz) else "NOT-SEPARATED-FROM-PINNED-AT-2S"))
        for f in NAMED:
            names["path_" + f] = "%s-PATH-%s-%s" % (PRE, f, fams["PX"][f])
        acc = {}
        for arm, k in NEW_RUNS:
            RL = rlog(a.pull, arm, k)
            acc["%s_s%d" % (arm, k)] = None if RL is None else {"mean_abs_acceleration_read": RL.get("mean_abs_acceleration_read"), "max_abs_acceleration_read": RL.get("max_abs_acceleration_read")}
        for arm in REUSED:
            for k in SEEDS:
                RL = rlog(a.pull, arm, k)
                acc["%s_s%d" % (arm, k)] = None if RL is None else {"mean_abs_acceleration_read": RL.get("mean_abs_acceleration_read"), "max_abs_acceleration_read": RL.get("max_abs_acceleration_read")}
        res.update(names=names, levels=levels, pairs=pairs, cells=cells, families=fams, reported_no_bar={"acceleration_read_per_run": acc, "RS_share_ending_above_5mps_model_and_prior": rs})
        print("== names")
        for k, v in names.items():
            print("   %-16s %s" % (k, v))
        print("== levels of the model alone U C F (per model seed)")
        for arm, v in levels.items():
            print("   %-10s U %s  C %s  F %s" % (arm, v["U"], v["C"], v["F"]))
        print("== pairs: U C F (pooled, interval, per seed) and the family reading over the named cells")
        for nm, p in pairs.items():
            print("   %-24s %s minus %s | %s | %s" % (nm, p["A"], p["B"], line(p["headway"]), fams[nm]))
        print("== cells (all ten per pair; the named ones decide the readings)")
        for nm, cs in cells.items():
            for c, v in cs.items():
                print("   %-24s %-30s D %+8.4f [%+.4f, %+.4f] %s %s%s" % (nm, c, v["D"], v["interval"][0], v["interval"][1], v["per_seed"], v["verdict"], " *" if any(c in NAMED[f] for f in NAMED) else ""))
        print("== reported, no bar: acceleration read per run (mean / largest absolute, m/s2) and RS per run and model seed")
        for key in sorted(acc):
            print("   %-16s %s | RS %s" % (key, acc[key], rs.get(key)))
    else:
        print("== a control did not pass: no name, no level, no difference; the read is reported as written")
    print("STRATEGIC: as note N1 of card ADD46 (T0 first tick: the banked read of the two models without the rule; along the rollout NOT COMPUTED, n = 0, no instrument)")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    json.dump(res, io.open(a.out, "w", encoding="utf-8", newline="\n"), indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
