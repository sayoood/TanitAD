#!/usr/bin/env python3
"""make_results_tables.py -- render raw/SMOOTH_T1.json (and raw/THREADREP.json) as the Markdown tables of RESULTS.md.  No number is typed by hand: every cell is a field of the JSON."""
import json
import sys

sys.dont_write_bytecode = True
RAW = sys.argv[1]
r = json.load(open(f"{RAW}/SMOOTH_T1.json", encoding="utf-8"))
t = json.load(open(f"{RAW}/THREADREP.json", encoding="utf-8"))
ORDER = ["ADE6", "speed MAE", "along-track MAE", "accel MAE", "DK-VIOL", "DK-HW", "DK-TG", "heading MAE", "yaw-rate MAE", "curvature MAE", "cross-track MAE", "L1 lateral-accel MAE", "L2 curvature MAE (GT>=5.2)",
         "TAC-LAT", "TAC-LON", "S-POS@30", "S-POS@50", "S-POS@80", "M1 crawl share"]
CRAWL = ("yaw-rate MAE", "curvature MAE", "L2 curvature MAE (GT>=5.2)", "M1 crawl share")
NAME = {"CTRL": "DAG-OACC", "SOUP": "SOUP"}


def cell(row):
    d, lo, hi, sep = row["delta"], row["lo"], row["hi"], row["separated"]
    better = (d > 0) if row["direction"] == "higher" else (d < 0)
    flag = "B" if (sep and better) else ("W" if sep else ".")
    return f"{d:+.4f} [{lo:+.4f}, {hi:+.4f}] {flag}"


out = ["<!-- generated by code/make_results_tables.py from raw/SMOOTH_T1.json: no hand-typed number -->", "",
       "Cell = `delta [95% interval] flag`; flag **B** = separated on the better side of the row's direction, **W** = separated on the worse side, `.` = not separated. Estimator: paired episode-cluster bootstrap, B = 2,000, seed 0 (answers another draw of EPISODES only). Tier T1-kin. Units as in `dagland/gapdecomp/RESULTS.md`. n = windows / episodes of the row's pool. On S-POS@k the P10 side is the CTRV of the run's own ticks (a within-run contrast), so X - P10 is not (X - Y) + (Y - P10) on those three rows.", ""]

out += ["### Table A. The outcome rule, condition by condition (descriptive: the controls refuse the outcome, see section 1)", "",
        "| arm | seed | D1 ADE6 X - P10 | D2 no separated-worse row (X - P10) | separated-worse rows (X - P10) | D3 each family has a separated-better row | ADE6 X - Y | all four crawl rows X - Y separated-better | non-crawl rows X - Y separated-worse | separated-worse rows of 19 (X - Y) | MOVED cond. | HARMS cond. |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for arm in ("CTRL", "SOUP"):
    for s in ("s0", "s1"):
        ps, rows = r["arms"][arm]["per_seed"][s], r["arms"][arm]["rows"][s]
        A, XY = ps["A"], ps["XY"]
        fam = ", ".join(f"{f[:3]}:{'Y' if v else 'N'}" for f, v in A["D3_by_family"].items())
        out.append(f"| {NAME[arm]} | {s} | {'PASS' if A['D1'] else 'FAIL'} ({rows['XP']['ADE6']['delta']:+.4f} m) | {'PASS' if A['D2'] else 'FAIL'} | {', '.join(A['separated_worse_rows']) or 'none'} | {'PASS' if A['D3'] else 'FAIL'} ({fam}) | "
                   f"{XY['ade6_delta']:+.4f} m | {'yes' if XY['crawl_all_separated_better'] else 'no'} | {', '.join(XY['non_crawl_separated_worse']) or 'none'} | {XY['n_separated_worse_all']} | {'met' if XY['MOVED_seed'] else 'not met'} | {'met' if XY['HARMS_seed'] else 'not met'} |")
out += ["", "| arm | DOMINANT | HARMS (either seed) | MOVED (both seeds) | outcome by the committed rule |", "|---|---|---|---|---|"]
for arm in ("CTRL", "SOUP"):
    a = r["arms"][arm]
    out.append(f"| {NAME[arm]} | {'yes' if a['DOMINANT'] else 'no'} | {'yes' if a['HARMS_condition'] else 'no'} | {'yes' if a['MOVED_condition'] else 'no'} | **{a['outcome']}** |")

out += ["", "### Table B. ADE6 and the four crawl rows, both arms, both seeds", "",
        "`share removed` = -(X - Y) / (Y - P10) at the point estimates: the share of the Y - P10 gap that S removed (ESTIMATED arithmetic on two point estimates, no interval).", "",
        "| arm | seed | row | X - P10 | X - Y | Y - P10 | share removed |", "|---|---|---|---|---|---|---|"]
for arm in ("CTRL", "SOUP"):
    for s in ("s0", "s1"):
        rows = r["arms"][arm]["rows"][s]
        for lab in ("ADE6",) + CRAWL:
            xp, xy, yp = rows["XP"][lab], rows["XY"][lab], rows["YP"][lab]
            cl = f"{-xy['delta'] / yp['delta']:.2f}" if lab != "ADE6" else "n/a"
            out.append(f"| {NAME[arm]} | {s} | {lab} | {cell(xp)} | {cell(xy)} | {cell(yp)} | {cl} |")
out.append("")

for arm in ("CTRL", "SOUP"):
    for s in ("s0", "s1"):
        rows = r["arms"][arm]["rows"][s]
        out += [f"### Table C. {NAME[arm]} {s}: all 19 rows, X (arm + S) against P10 and against Y (the same checkpoint, no S)", "", "| family | row | n | X - P10 | X - Y | Y - P10 |", "|---|---|---|---|---|---|"]
        for lab in ORDER:
            xp, xy, yp = rows["XP"][lab], rows["XY"][lab], rows["YP"][lab]
            out.append(f"| {xp['family']} | {lab} | {xp['n']} | {cell(xp)} | {cell(xy)} | {cell(yp)} |")
        out.append("")

out += ["### Table E. Rows by flag within each family (B / W / not separated), X - P10 and X - Y", "", "| arm | seed | family (rows) | X - P10: B / W / . | X - Y: B / W / . |", "|---|---|---|---|---|"]
FAMS = ("PRIMARY", "LONGITUDINAL", "LATERAL", "TACTICAL", "STRATEGIC", "crawl")
for arm in ("CTRL", "SOUP"):
    for s in ("s0", "s1"):
        rows = r["arms"][arm]["rows"][s]
        for f in FAMS:
            labs = [l for l in ORDER if rows["XP"][l]["family"] == f]
            def cnt(tab):
                b = sum(1 for l in labs if rows[tab][l]["separated"] and ((rows[tab][l]["delta"] > 0) if rows[tab][l]["direction"] == "higher" else (rows[tab][l]["delta"] < 0)))
                w = sum(1 for l in labs if rows[tab][l]["separated"]) - b
                return f"{b} / {w} / {len(labs) - b - w}"
            out.append(f"| {NAME[arm]} | {s} | {f} ({len(labs)}) | {cnt('XP')} | {cnt('XY')} |")
out.append("")
out += ["### Table D. Thread-noise replicate: the largest change of any row delta between the card's rollouts (1 thread) and the same four rollouts at 2 threads", "",
        "| arm / seed | max abs change, X - P10 rows | rows whose flag or sign changed | max abs change, X - Y rows | rows whose flag or sign changed |", "|---|---|---|---|---|"]
for arm in ("CTRL", "SOUP"):
    for s in ("s0", "s1"):
        d = t["arms"][arm]["rows"][s]["vs_card_rollouts"]
        out.append(f"| {NAME[arm]} {s} | {d['XP']['max_abs_delta_diff']:.2e} | {len(d['XP']['rows_whose_separated_flag_or_sign_differs'])} | {d['XY']['max_abs_delta_diff']:.2e} | {len(d['XY']['rows_whose_separated_flag_or_sign_differs'])} |")
out += ["", "| arm | outcome, card rollouts (1 thread) | outcome, replicate (2 threads) |", "|---|---|---|"]
for arm in ("CTRL", "SOUP"):
    out.append(f"| {NAME[arm]} | {t['arms'][arm]['outcome_of_card_rollouts']} | {t['arms'][arm]['outcome']} |")
out.append("")
open(f"{RAW}/RESULTS_TABLES.md", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote", f"{RAW}/RESULTS_TABLES.md")
