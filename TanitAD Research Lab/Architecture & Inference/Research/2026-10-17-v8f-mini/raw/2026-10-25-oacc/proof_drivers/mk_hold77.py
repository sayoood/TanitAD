TOKEN = re.compile(rb"hf_[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}")


def git(*a):
    r = subprocess.run(["git", "-C", MIR, "-c", "safe.directory=*", *a], capture_output=True)
    return r.stdout if r.returncode == 0 else None


def blob_at_tip(rel):
    b = git("rev-parse", f"{TIP}:{rel}")
    return b.decode().strip() if b else None


def put(kind, rel, data):
    assert not TOKEN.search(data), f"token-shaped string in {rel}"
    p = os.path.join(H, kind, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(data)


def hash_object(path):
    return subprocess.run(["git", "-C", MIR, "-c", "safe.directory=*", "hash-object", "--no-filters", path], capture_output=True, check=True).stdout.decode().strip()


for n in ("hold_v8f_oacc_instr", "landed_hold_v8f_oacc_instr"):
    assert not os.path.exists("C:/Users/Admin/qland/" + n), n
done = open(W + "tmp/final4.done", encoding="utf-8").read().strip().splitlines()
