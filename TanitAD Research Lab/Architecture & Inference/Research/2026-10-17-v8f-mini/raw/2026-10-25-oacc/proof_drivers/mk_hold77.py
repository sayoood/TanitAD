rows = [ln.split(None, 4) for ln in open(W + "FILES.txt", encoding="utf-8") if ln.startswith(("NEW ", "MODIFIED "))]
n_new = n_mod = 0
for st, _by, nb, rb, rel in rows:
    rel = rel.rstrip("\r\n")
    src = W + rel
    assert hash_object(src) == nb, f"FILES.txt is stale for {rel}"
    data = open(src, "rb").read()
    if st == "NEW":
        assert blob_at_tip(rel) is None, f"NEW path exists at the tip: {rel}"
        put("stage", rel, data)
        n_new += 1
    else:
        t = blob_at_tip(rel)
        assert t == rb, f"the tip moved under {rel}: {t} != {rb} (re-base the hunk)"
        put("mods-rw", rel, data)
        n_mod += 1
