"""PREREG_V8F_LORA: the results table, GENERATED from the banked artifacts in this directory (no number is typed by hand; a missing artifact is printed as MISSING, never skipped).

    python make_results.py [--dir <this directory>]

Reads: identity_control.json, bitwise_cache_path.out, test_v8f_lora.out, test_existing_v8f_new_tree.out / _pre_tree.out, mutate_lora.json / .out, smoke_report.json, eval_route_*.
Prints the table to stdout and keeps the same text as make_results.out (a script log, like the other .out files here).
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def rows(node, path=""):
    """Every dict that carries rel_l2 + max_abs (a ``stats`` block), with its path."""
    if isinstance(node, dict):
        if "rel_l2" in node and "max_abs" in node:
            yield path, node
        else:
            for k, v in node.items():
                yield from rows(v, f"{path}/{k}" if path else k)


def fmt(x):
    if isinstance(x, float):
        return f"{x:.4g}"
    return str(x)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(Path(__file__).resolve().parent))
    a = ap.parse_args(argv)
    d = Path(a.dir)
    out = ["# PREREG_V8F_LORA -- RESULTS (generated by make_results.py from the banked artifacts in this directory; nothing typed by hand)", ""]

    def need(name):
        p = d / name
        if not p.is_file():
            out.append(f"MISSING: {p}")
            out.append("")
            return None
        return p

    # ---- identity control
    out += ["## 1. Identity control (CPU; LoRA B = 0 encoder vs the cached tokens / vs the builder's own function)", ""]
    p = need("identity_control.json")
    if p:
        r = json.load(open(p, encoding="utf-8"))
        m = r["meta"]
        out.append(f"torch {m['torch']}, device {m['device']}, threads {m['threads']}; weights sha256 {m['model_safetensors_sha256'][:16]} == builder's {m['builder_model_sha256'][:16]}: "
                   f"{m['model_safetensors_sha256'] == m['builder_model_sha256']}; builder encode_episode sha256 == pin: {m['builder_encode_episode_sha256'] == m['builder_pin']}; "
                   f"finished: {m.get('finished')}; tau: {m['tau']}")
        out.append("")
        out.append("| case / block | n_values | max_abs | mean_abs | ref_mean_abs | frac_bitwise_equal | rel_L2 | rel_L2 per-row max |")
        out.append("|---|---|---|---|---|---|---|---|")
        for case, v in r["cases"].items():
            if isinstance(v, dict) and "skipped" in v:
                out.append(f"| {case} | SKIPPED: {v['skipped']} | | | | | | |")
                continue
            n = 0
            for pth, s in rows(v, case):
                n += 1
                out.append(f"| {pth} | {s.get('n_values')} | {fmt(s['max_abs'])} | {fmt(s.get('mean_abs'))} | {fmt(s.get('ref_mean_abs'))} | {fmt(s.get('frac_bitwise_equal'))} | {fmt(s['rel_l2'])} | {fmt(s.get('rel_l2_per_row_max'))} |")
            if n == 0:
                out.append(f"| {case} | (no stats block found; see the JSON) | | | | | | |")
        out.append("")
        out.append("Cases present: " + ", ".join(r["cases"]) + ("  (run in two invocations: " + json.dumps(m.get("run_in_two_invocations", {}).get("why", "")) + ")" if "run_in_two_invocations" in m else ""))
        out.append("")

    # ---- cache path bit-for-bit
    out += ["## 2. `--encoder cache` is today's trainer, bit for bit (PRE tree vs NEW tree, M1 and M2b)", ""]
    p = need("bitwise_cache_path.out")
    if p:
        out += ["```", p.read_text(encoding="utf-8", errors="replace").strip()[-1500:], "```", ""]

    # ---- tests
    out += ["## 3. Tests (CPU, `CUDA_VISIBLE_DEVICES=-1`)", ""]
    for name, what in (("test_v8f_lora.out", "new file `stack/tests/test_v8f_lora.py` (final code state)"),
                       ("test_existing_v8f_new_tree.out", "existing `test_v8f_mini/hist/grid/window_start.py` on the NEW tree"),
                       ("test_existing_v8f_pre_tree.out", "the same four files on the PRE (pristine) tree = the control")):
        p = d / name
        if not p.is_file():
            out.append(f"- {what}: MISSING {p}")
            continue
        txt = p.read_text(encoding="utf-8", errors="replace")
        last = [l for l in txt.splitlines() if re.search(r"\d+ (passed|failed)", l)]
        out.append(f"- {what}: `{last[-1].strip() if last else 'NO SUMMARY LINE (crashed?)'}`")
        bad = [l.split(" - ")[0] for l in txt.splitlines() if l.startswith(("FAILED", "ERROR"))]
        for b in bad[:12]:
            out.append(f"    - {b}")
    out.append("")

    # ---- mutants
    out += ["## 4. Mutation harness (each mutant = one source edit in a scratch copy; the named tests must go RED; the unmutated copy GREEN)", ""]
    p = need("mutate_lora.json")
    if p:
        mj = json.load(open(p, encoding="utf-8"))
        out.append("| mutant | result | pytest | first red test(s) | s |")
        out.append("|---|---|---|---|---|")
        for x in mj:
            out.append(f"| {x['mutant']} | {x['result']} | {x['pytest']} | {'; '.join(t.split('::')[-1] for t in x['failed_tests'][:2])} | {x['seconds']:.0f} |")
        out.append("")
        ok = mj and mj[0]["mutant"] == "UNMUTATED" and mj[0]["result"] == "GREEN" and all(x["result"] == "RED" for x in mj[1:])
        out.append(f"VERDICT: {'ALL MUTANTS RED, BASELINE GREEN' if ok else 'NOT clean: see the rows above'} ({sum(x['result'] == 'RED' for x in mj[1:])} of {len(mj) - 1} mutants RED)")
        out.append("")

    # ---- smoke
    out += ["## 5. CPU smoke proof (mechanics only; real DINOv3-L fp32 weights, real PNG frames, the trainer's synthetic world; CPU numbers, NOT the GPU smoke)", ""]
    p = need("smoke_report.json")
    if p:
        sr = json.load(open(p, encoding="utf-8"))
        out.append("verdict: " + json.dumps(sr.get("verdict"), indent=None))
        out.append("")
        for k in ("cpu_fp32_mechanics_proof", "wall_s", "rc"):
            if k in sr:
                out.append(f"- {k}: {sr[k]}")
        out.append("- projection (ESTIMATED from CPU per-frame costs; not a GPU projection): " + json.dumps(sr.get("projection_ESTIMATED"), indent=None)[:1500])
        out.append("")
    p = d / "smoke_steps.jsonl"
    if p.is_file():
        out.append("| step | total | lora_A abs_sum | lora_B abs_sum | frozen dinov3 abs_sum | n_unique_frames |")
        out.append("|---|---|---|---|---|---|")
        for l in p.read_text(encoding="utf-8").splitlines():
            s = json.loads(l)
            g = s.get("groups", {})
            out.append(f"| {s.get('step')} | {fmt(s.get('terms', {}).get('total'))} | {fmt(g.get('lora_A', {}).get('abs_sum'))} | {fmt(g.get('lora_B', {}).get('abs_sum'))} | "
                       f"{fmt(g.get('control_frozen_dinov3', {}).get('abs_sum'))} | {s.get('timing', {}).get('n_unique_frames')} |")
        out.append("")

    # ---- eval route
    out += ["## 6. Eval route on the one real dev-box eval clip (B = 0, fp32 CPU): the cache builder's own function at the merged weights vs the existing cache clip", ""]
    p = need("eval_route_zero_lora.out")
    if p:
        out += ["```", p.read_text(encoding="utf-8", errors="replace").strip()[-900:], "```", ""]
    p = d / "eval_route_base_feature_diff.json"
    if p.is_file():
        out.append("mean |new - base| per feature key: " + p.read_text(encoding="utf-8").strip().replace("\n", " "))
        out.append("")
    text = "\n".join(out) + "\n"
    (d / "make_results.out").write_text(text, encoding="utf-8")          # a script log, like the other .out files here
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
