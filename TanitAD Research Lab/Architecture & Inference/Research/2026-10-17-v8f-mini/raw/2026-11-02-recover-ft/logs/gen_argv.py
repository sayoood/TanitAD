"""Generate ARGV_ARMS.txt: the six RECOVER-FT argv lines from the card's section 2, derived from DAG-OACC's own argv.json (MEASURED) and asserted equal to the card's base string."""
import json
import shlex

OACC = "E:/Projects/TanitAD-artifacts/v8f-dagoacc"
CARD_BASE_S0 = ("--arm M2b --seed 0 --grid pool4x10 --out D:\\tanitad\\runs\\v8f_mini_full\\M2b_s0_recft_<R|C0|C0rep> --cache-dir D:\\tanitad\\cache_full --v9-train D:\\tanitad\\data\\v9\\v9_labels_train.npz "
                "--v9-train-md5 83e30bd3791f0767707eade5f4671759 --lead-train D:\\tanitad\\data\\v9\\lead_train4572.npz --speed-train D:\\tanitad\\data\\v9\\refcv6_speed_max_v8_train.jsonl "
                "--join-train D:\\tanitad\\runs\\v8f_mini_full\\join_train.npz --p10 D:\\tanitad\\runs\\v8f_mini_full\\p10\\p10_prior.pt --kin-mode yaw --tracks D:\\tanitad\\cache_full\\native_tracks.pt "
                "--exclude 540:600 --batch 64 --steps-mult 4 --device cuda --init-ckpt D:\\tanitad\\runs\\v8f_mini_full\\M2b_s0_dagoacc\\ckpt_last.pt --steps 3000 --lr 1e-4 --warmup 100 "
                "--p-gt-start 0.2 --p-gt-end 0.2 --ego-perturb-p 0 --w-acc 49.6969")
BANK_SHA = {0: "90c43c66f52f250d41ff23e837d5fb31d1592cf2aad14afacd7ded011734b589", 1: "a06c8289b20854a6933264e95dca201ea7d9e2723fd0b2248872f56361ea689a"}
RUNS = "D:\\tanitad\\runs\\v8f_mini_full"


def base(s, arm, seed):
    a = json.load(open(f"{OACC}/M2b_s{s}_dagoacc/argv.json"))["argv"]
    out, i = [], 0
    while i < len(a):
        if a[i] in ("--dagger-p", "--dagger-bank", "--dagger-bank-sha256", "--dagger-seed"):
            i += 2
            continue
        if a[i] == "--out":
            out += ["--out", f"{RUNS}\\M2b_s{s}_recft_{arm}"]
            i += 2
            continue
        if a[i] == "--init-ckpt":
            out += ["--init-ckpt", f"{RUNS}\\M2b_s{s}_dagoacc\\ckpt_last.pt"]
            i += 2
            continue
        if a[i] == "--seed":
            out += ["--seed", str(seed)]
            i += 2
            continue
        out.append(a[i])
        i += 1
    return out


def line(s, arm):
    seed = s + (10 if arm == "C0rep" else 0)
    b = base(s, arm, seed)
    extra = {"R": ["--recover-p", "0.3", "--recover-dev-bank", f"{RUNS}\\dagger_bank_dag2\\s{s}", "--recover-dev-bank-sha256", BANK_SHA[s], "--recover-target", "rejoin", "--recover-rejoin-steps", "10", "--recover-seed", str(s)],
             "C0": ["--recover-p", "0"], "C0rep": ["--recover-p", "0"]}[arm]
    return " ".join(b + extra)


card = CARD_BASE_S0.replace("<R|C0|C0rep>", "R")
mine = " ".join(base(0, "R", 0))
assert mine == card, "the argv derived from DAG-OACC's argv.json differs from the card's base string:\n" + mine + "\n" + card
rows = ["# RECOVER-FT: the six registered argv lines (PREREG_RECOVER_FT_FROZEN.md section 2), in the card's run order. Generated by gen_argv.py from DAG-OACC's argv.json (MEASURED, E:/Projects/TanitAD-artifacts/v8f-dagoacc/M2b_s{0,1}_dagoacc/argv.json)",
        "# and asserted equal to the card's base string at s0 (minus --dagger-*, with the card's --out and --init-ckpt). Every line is one training argv for `python stack/scripts/v8f_mini_train.py <argv>` on box 2 (the paths are box 2's). The out dir carries the arm name.",
        "# C0 names ONLY --recover-p 0; C0rep is C0 with --seed 10+s (init identical). R names the seven registered recover flags (the a-priori law is not used by any of the six).", ""]
for tag, s, arm in (("R_0", 0, "R"), ("C0_0", 0, "C0"), ("R_1", 1, "R"), ("C0_1", 1, "C0"), ("C0rep_0", 0, "C0rep"), ("C0rep_1", 1, "C0rep")):
    rows += [f"## {tag}", line(s, arm), ""]
open("E:/Projects/TanitAD-artifacts/dagland/recover_ft/ARGV_ARMS.txt", "w", newline="\n").write("\n".join(rows))
print("\n".join(rows[4:7]))
print("argv tokens R:", len(shlex.split(line(0, "R"), posix=False)), "C0:", len(shlex.split(line(0, "C0"), posix=False)))
