def kshare_problems(sm: dict, window_sha: str) -> list:
    bad = []
    missing = [k for k in LAUNCH_KEYS if k not in sm]
    if missing:
        return [f"summary.json lacks {missing}: only the new build writes them (a stale or resurrected run is REFUSED)"]
    lw = findk(sm, "launch_intent_w")
    if type(lw) is not float or lw != LI_W or sm.get("launch_intent_w") != LI_W or (sm.get("levers") or {}).get("launch_intent_w") != LI_W:
        bad.append(f"launch_intent_w summary {sm.get('launch_intent_w')!r} / levers {(sm.get('levers') or {}).get('launch_intent_w')!r} != {LI_W!r}")
    n, e, r = sm["launch_n"], sm["launch_eligible"], sm["launch_rows"]
    if not (isint(n) and isint(e) and isint(r)):
        return bad + [f"launch_n / launch_eligible / launch_rows are not ints: {n!r} / {e!r} / {r!r}"]
    if r != e:
        bad.append(f"launch_rows {r} != launch_eligible {e}: a row seen by the loop had no GT-valid along-track label (the registered denominator is every window)")
    if not (e > 0 and 0 < n <= e):
        bad.append(f"launch_n {n} / launch_eligible {e}: the lever saw no launch row or no eligible row")
        return bad
    sh = share_of(n, e, LI_W)
    lo, hi = SHARE_TARGET - SHARE_TOL, SHARE_TARGET + SHARE_TOL
    if not (lo - 1e-12 <= sh <= hi + 1e-12):
        bad.append(f"K-SHARE: launch_weight_share recomputed {sh:.6f} from launch_n {n}, launch_eligible {e}, W {LI_W} is outside 1/3 +- {SHARE_TOL} = [{lo:.4f}, {hi:.4f}]")
    rec = sm["launch_weight_share"]
    if not (isinstance(rec, float) and math.isfinite(rec)) or abs(rec - sh) > 1e-9:
        bad.append(f"the record's own launch_weight_share {rec!r} != the recomputed {sh!r}")
    f = n / e
    flo, fhi = F_MEASURED - MASK_TOL, F_MEASURED + MASK_TOL
    if not (flo <= f <= fhi):
        bad.append(f"K-MASK: launch_n / launch_eligible = {f:.6f} is outside f = {F_MEASURED:.6f} +- {MASK_TOL} = [{flo:.4f}, {fhi:.4f}]")
    if sm.get("train_window_list_sha256") != window_sha:
        bad.append(f"K-MASK: train_window_list_sha256 {str(sm.get('train_window_list_sha256'))[:12]} != DAG-OACC's {window_sha[:12]}")
    return bad


def kshare(a) -> int:
    sm = json.load(open(a.summary, encoding="utf-8"))
    bad = kshare_problems(sm, a.window_sha)
    n, e = sm.get("launch_n"), sm.get("launch_eligible")
    sh = share_of(n, e, LI_W) if isint(n) and isint(e) and e > 0 else None
    print("LAUNCH-INTENT K-SHARE:", "PASS" if not bad else "FAIL", "|", LABEL[(a.arm, int(a.seed))] if a.arm in ARMS and a.seed in ("0", "1") else a.arm, "| launch", n, "/", e, "=", (round(n / e, 6) if isint(n) and isint(e) and e > 0 else None), "(K-MASK: f 0.1619 +- 0.02)", "| weight share",
          (round(sh, 6) if sh is not None else None), "(must lie in 1/3 +- 0.02)", "| rows", sm.get("launch_rows"), "(== eligible)", "|", bad if bad else "ok")
    return 1 if bad else 0


def one_lever(a) -> int:
    ref = json.load(open(a.ref_argv_json, encoding="utf-8"))["argv"]
    line = G.argv_of(open(a.line, encoding="utf-8").read())
    try:
        exp = G.expected_from_ref(ref, int(a.seed), a.arm)
    except ValueError as e:
        print("NOT-ONE-LEVER", e)
        return 1
    ok = G.drop(line) == exp
    print("ONE-LEVER" if ok else "NOT-ONE-LEVER")
    return 0 if ok else 1


def bands_cmd(a) -> int:
    b = bands(LI_W)
    print(f"K-SHARE: launch_weight_share = (1+W)n/((1+W)n+eligible-n) with W {LI_W} must lie in 1/3 +- {SHARE_TOL} = [{b['share'][0]:.4f}, {b['share'][1]:.4f}]; launch_rows == launch_eligible; levers.launch_intent_w == {LI_W} (a record without the key is REFUSED)")
    print(f"K-MASK : launch_n / launch_eligible must lie in f = {F_MEASURED:.6f} +- {MASK_TOL} = [{b['mask'][0]:.4f}, {b['mask'][1]:.4f}]; train_window_list_sha256 = DAG-OACC's")
    print(f"at the measured f the share is {b['share_at_f']:.6f} (inside the band: {b['share'][0] <= b['share_at_f'] <= b['share'][1]})")
    return 0 if b["share"][0] <= b["share_at_f"] <= b["share"][1] else 1


def _count_pair(sm, kn, ke):
    n, e = sm.get(kn), sm.get(ke)
    return n, e, isint(n) and isint(e) and e > 0 and 0 <= n <= e


def rep_licence(a) -> list:
    """PREREG_V8F_LAUNCH_INTENT section 4, the REP reuse licence, conditions 1 and 2 on a banked DAG-ORC r2 REP pull. Conditions 3 and 4 are not checkable here."""
    seed = int(a.seed)
    bad = []
    rd, od = a.rep_dir, a.oacc_dir
    for d in (rd, od):
        for f in ("summary.json", "selfcheck.json", "argv.json", "launch_gate_token.json"):
            if not os.path.isfile(os.path.join(d, f)):
                bad.append(f"{os.path.join(d, f)} is missing")
    if bad:
        print("REP-LICENCE s%d: FAIL (REP must be trained anew)" % seed, bad)
        return bad
    J = lambda d, f: json.load(open(os.path.join(d, f), encoding="utf-8"))      # noqa: E731
    sm, sc, aj, tok = J(rd, "summary.json"), J(rd, "selfcheck.json"), J(rd, "argv.json"), J(rd, "launch_gate_token.json")
    osm, oaj, otok = J(od, "summary.json"), J(od, "argv.json"), J(od, "launch_gate_token.json")
    # ---- condition 1: finished, and its run record passes (swap share 0.1 +- 0.02, ego exactly 0, composition flag absent, levers.ego_perturb_stream exactly 0)
    if sm.get("done") is not True or sm.get("steps") != 3000:
        bad.append(f"condition 1: REP did not finish (done {sm.get('done')!r}, steps {sm.get('steps')!r})")
    if (sm.get("arm"), sm.get("seed")) != ("M2b", 10 + seed):
        bad.append(f"condition 1: REP arm / seed {(sm.get('arm'), sm.get('seed'))} != ('M2b', {10 + seed})")
    if sc.get("declared_vs_built") != "PASS" or tok.get("verdict") != "PASS":
        bad.append("condition 1: REP's selfcheck / launch-gate token is not a PASS")
    n, e, ok = _count_pair(sm, "dagger_n", "dagger_eligible")
    if not ok or abs(n / e - SWAP_BAND[0]) > SWAP_BAND[1] + 1e-12:
        bad.append(f"condition 1: REP swap share {n}/{e} is not in {SWAP_BAND[0]} +- {SWAP_BAND[1]}")
    n, e, ok = _count_pair(sm, "ego_perturb_n", "ego_perturb_eligible")
    if not ok or n != 0:
        bad.append(f"condition 1: REP ego_perturb_n {n!r} / eligible {e!r} (must be EXACTLY 0 with eligible > 0)")
    if findk(sm, "ego_perturb_with_dagger") not in (False, None):
        bad.append(f"condition 1: REP built ego_perturb_with_dagger {findk(sm, 'ego_perturb_with_dagger')!r} (the composition flag must be absent)")
    for what, rec in (("summary.json", sm), ("selfcheck.json", sc)):
        st = (rec.get("levers") or {}).get("ego_perturb_stream", "<absent>")
        if type(st) is not int or st != 0:
            bad.append(f"condition 1: REP {what} levers.ego_perturb_stream {st!r} (must be exactly the int 0; absent fails)")
    if ((sm.get("levers") or {}).get("ego_perturb") or {}).get("ego_perturb_p") != 0.0:
        bad.append("condition 1: REP built ego_perturb_p is not 0.0")
    lw = (sm.get("levers") or {}).get("launch_intent_w", None)
    if lw not in (None, 0.0) or any(k in sm for k in ("launch_n", "launch_eligible", "launch_rows", "launch_weight_share")):
        bad.append(f"condition 1: REP carries a launch lever (levers.launch_intent_w {lw!r}): REP must be the no-lever arm (a build before the lever carries no key; a build with it carries 0.0)")
    # the REP argv is DAG-OACC's apart from --out and --seed (PREREG section 4: compare_rep_argv.out)
    ra, oa = aj.get("argv") or [], oaj.get("argv") or []
    if not ra or G.drop(ra, names=("--out", "--seed")) != G.drop(oa, names=("--out", "--seed")):
        bad.append("condition 1: REP's argv.json is not DAG-OACC's banked argv apart from --out and --seed")
    elif ra[ra.index("--seed") + 1] != str(10 + seed) or oa[oa.index("--seed") + 1] != str(seed):
        bad.append(f"condition 1: REP --seed {ra[ra.index('--seed') + 1]} / DAG-OACC --seed {oa[oa.index('--seed') + 1]} are not {10 + seed} / {seed}")
    if a.log and not os.path.isfile(a.log):
        bad.append(f"condition 1: the DAG-ORC r2 chain log {a.log} is missing")
    elif a.log:
        txt = open(a.log, encoding="utf-8", errors="replace").read().replace("\r", "")
        run = f"dagoaccorcrep s{seed}"
        if not re.search(rf"^DAG-ORC \(DAG-OACC base\) run record: PASS \| {run} \|", txt, re.M):
            bad.append(f"condition 1: the DAG-ORC r2 chain log has no 'run record: PASS | {run}' line")
        if re.search(r"^DAG-ORC \(DAG-OACC base\) (run record|K-REACH): FAIL \| dagoaccorcrep", txt, re.M) or "run record: [" in txt:
            bad.append("condition 1: the DAG-ORC r2 chain log carries a FAIL for REP")
    # ---- condition 2: its launch-gate token carries DAG-OACC's init / bank / w_acc / excluded / data; its summary DAG-OACC's window list
    for k in ("init_ckpt_sha256", "bank_sha256", "w_acc", "excluded_sha256"):
        if tok.get(k) is None or tok.get(k) != otok.get(k):
            bad.append(f"condition 2: REP token {k} {str(tok.get(k))[:16]} != DAG-OACC's {str(otok.get(k))[:16]}")
    if (tok.get("binding") or {}).get("data_sha256") != (otok.get("binding") or {}).get("data_sha256"):
        bad.append("condition 2: REP token binding.data_sha256 != DAG-OACC's")
    if tok.get("init_ckpt_sha256") != a.init_sha or tok.get("bank_sha256") != a.bank_sha.lower() or tok.get("w_acc") != float(a.w_acc):
        bad.append("condition 2: REP token init / bank / w_acc are not the chain's pinned values")
    if tok.get("run") != f"M2b_s{seed}_dagoaccorcrep":
        bad.append(f"condition 2: REP token run {tok.get('run')!r}")
    for k in ("train_window_list_sha256", "train_sha256", "excluded_sha256", "n_windows"):
        if sm.get(k) is None or sm.get(k) != osm.get(k):
            bad.append(f"condition 2: REP summary {k} {str(sm.get(k))[:16]} != DAG-OACC's {str(osm.get(k))[:16]}")
    if sm.get("train_window_list_sha256") != a.window_sha:
        bad.append("condition 2: REP train_window_list_sha256 is not the chain's pinned value")
    print("REP-LICENCE s%d:" % seed, "PASS (conditions 1 and 2)" if not bad else "FAIL (REP must be trained anew: 2 runs, about 1.4 h, before any LAUNCH-INTENT row is read)", "|", rd, "|",
          "NOT CHECKED HERE: condition 3 (the T1-kin dumps' settings and the reader's pins: dev box) and condition 4 (the build term: K-BUILD, the flag-off golden on the launch commit)" if not bad else bad)
    return bad


DONE_RE = re.compile(r"^ZZV8FMINI-DONE \S+ \S+ tip [0-9a-f]{40}: PREREG_V8F_DAG_ORC Amendment 1 \(DAG-OACC base\) r2: 4 runs \(dagoaccorc 0 dagoaccorcrep 0 dagoaccorc 1 dagoaccorcrep 1\)")


def pred_verdict_li(out_text: str, busy_exists: bool) -> tuple:
    """The predecessor rule. The DAG-ORC r2 chain's log must END in its DONE marker and nothing else. Markers are ANCHORED at the start of a line (a dated 'waiting for ^ZZV8FMINI-STOP' echo is not a stop)."""
    lines = [x.rstrip() for x in out_text.replace("\r", "").split("\n")]
    body = [x for x in lines if x.strip()]
    done = [x for x in lines if x.startswith("ZZV8FMINI-DONE")]
    stop = [x for x in lines if x.startswith("ZZV8FMINI-STOP")]
    guard = [x for x in lines if "ZZGUARD-STOP" in x]
    floor = [x for x in lines if "ZZDISK-FLOOR-STOP" in x]
    ctrl = [x for x in lines if x.startswith("ZZDAGOACCORC-CONTROL-FAIL")]
    if guard:
        return "HALT", "the predecessor was stopped by the GUARD (" + guard[-1][:160] + "): the box may be hot"
    if stop:
        return "HALT", "the predecessor chain STOPPED (" + stop[-1][:200] + "): LAUNCH-INTENT starts only after a clean DONE"
    if floor or ctrl:
        return "HALT", "the predecessor log carries a named stop (" + (floor + ctrl)[-1][:160] + ")"
    if not done:
        return "WAIT", "no end marker yet"
    if len(done) != 1:
        return "HALT", f"{len(done)} ZZV8FMINI-DONE lines in the predecessor log (exactly one is expected)"
    if not body or body[-1] != done[0]:
        return "HALT", "text after the predecessor's DONE marker (last line: " + (body[-1][:160] if body else "<empty>") + ")"
    if not DONE_RE.match(done[0]):
        return "HALT", "the DONE marker is not the DAG-ORC (DAG-OACC base) r2 chain's: " + done[0][:200]
    txt = "\n".join(lines)
    for run in R2_RUNS:
        if not re.search(rf"^\d\d-\d\d \d\d:\d\d {run} pulled to \S+", txt, re.M):
            return "HALT", f"the predecessor's DONE is not backed by a pull of {run}"
        s = run.split("_")[1][1:]
        arm = run.split("_")[2]
        if not re.search(rf"^DAG-ORC \(DAG-OACC base\) run record: PASS \| {arm} s{s} \|", txt, re.M):
            return "HALT", f"the predecessor's DONE is not backed by a run-record PASS for {arm} s{s}"
        if not re.search(rf"^DAG-ORC \(DAG-OACC base\) K-REACH: PASS \| {arm} \|", txt, re.M):
            return "HALT", f"the predecessor's DONE is not backed by a K-REACH PASS for {arm}"
    if re.search(r"^DAG-ORC \(DAG-OACC base\) (run record|K-REACH): FAIL", txt, re.M):
        return "HALT", "the predecessor log carries a FAIL line"
    if busy_exists:
        return "BUSY", "the predecessor ended DONE but its BOX2_BUSY.txt is not released (yet)"
    return "GO", "the DAG-ORC r2 chain ended DONE and released the box: " + done[0][:120]


