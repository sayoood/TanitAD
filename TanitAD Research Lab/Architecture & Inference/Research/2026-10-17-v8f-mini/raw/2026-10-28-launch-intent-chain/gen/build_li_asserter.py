def expected_from_ref(ref: list, seed: int, arm: str = ARM) -> list:
    """The registered argv built from the PAIR CONTROL's banked argv (``ref``, ``--out`` dropped): the reference + ``--launch-intent-w <W_A>`` at the END, nothing else.
    Raises ValueError when the reference does not have the shape the rule needs (the control's: no launch flag, no perturbation law, no composition flag, ``--ego-perturb-p 0`` and ``--seed`` = the run's TRAINER seed:
    S for launchintent, 10 + S for launchintentrep, so a swapped reference, DAG-OACC's for A_rep or REP's for A, is refused)."""
    if arm not in ARMS:
        raise ValueError(f"unknown arm {arm!r}")
    ts = seed + ARMS[arm]
    r = drop(ref)
    if LI_FLAG in r or COMPOSE in r or any(k in r for k in EGO_LAW):
        raise ValueError("the reference (DAG-OACC) argv must not carry the launch flag, the composition flag or any law flag")
    if r.count("--ego-perturb-p") != 1 or r.count("--seed") != 1:
        raise ValueError("the reference argv must name --ego-perturb-p and --seed exactly once")
    kp, ks = r.index("--ego-perturb-p"), r.index("--seed")
    if r[kp + 1] != "0" or r[ks + 1] != str(ts):
        raise ValueError(f"the reference argv must carry --ego-perturb-p 0 and --seed {ts} ({arm} s{seed}), it has {r[kp + 1]!r} and {r[ks + 1]!r}")
    return r + [LI_FLAG, LI_W_STR]


