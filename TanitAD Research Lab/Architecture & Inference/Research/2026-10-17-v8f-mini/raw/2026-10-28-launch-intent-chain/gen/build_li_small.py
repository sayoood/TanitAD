#!/usr/bin/env python3
"""Build the small LAUNCH-INTENT chain files (box2_ship/):

  v8f_guard_launchintent.sh        = the INSTALLED v8f_guard_dagoaccorc.sh with EXACT-COUNT renames of its scratch files, so no sibling chain's guard shares a file name with this one
                                     (v8f_guard_tail.jsonl / v8f_guard_sc.json / v8f_guard_rate.log -> v8f_guard_launchintent_*, the default chain log and current-run file -> this chain's). The logic is byte-identical.
  wake_v8flaunchintent.sh          the waker: script polling, not model turns. Wakes on: the FOUR gates (once, by a transition seen after the waker started: NO persistent marker, so a sibling's marker cannot silence it), each pull,
                                     any stop (ZZV8FMINI-STOP, a guard stop, ZZLAUNCHINTENT-CONTROL-FAIL, ZZDISK-FLOOR-STOP), and the end (ZZV8FMINI-DONE).
  run_chain_v8f_launchintent.cmd   the direct-start launcher (CRLF): AFTER_OUT = the DAG-ORC r2 chain's log.

    python build_li_small.py          writes ../box2_ship/ (LF; the .cmd keeps CRLF)
"""
from __future__ import annotations

import sys

import common as C

GUARD_SRC = C.INSTALLED / "v8f_guard_dagoaccorc.sh"

WAKER = r'''#!/usr/bin/env bash
# Waker for the LAUNCH-INTENT box-2 chain (chain_v8f_launchintent.out). GENERATED by gen/build_li_small.py. Exits on: the chain's end / stop marker, a guard stop, a named stop (K-SHARE control fail, disk floor),
# the FOUR gates passing (A_0, A_1, A_rep,0, A_rep,1: ONCE: a transition seen after this waker started, counted by the TOKEN lines -- the asserter prints `LAUNCH-INTENT gate: PASS` twice per gate, once in `check` and once in `token`; NO marker file is read or written, so
# a sibling chain's marker can neither silence nor trigger it), or each run's pull landing on E:. Script polling, not model turns.
#   LI_LOG_DIR (default /c/Users/Admin/box2_ship/logs) / LI_WAKE_POLL_S (60) / LI_WAKE_N (1500) are the test hooks.
L=${LI_LOG_DIR:-/c/Users/Admin/box2_ship/logs}; O=$L/chain_v8f_launchintent.out; GO=$L/v8flaunchintent_guard.out
POLL=${LI_WAKE_POLL_S:-60}; N=${LI_WAKE_N:-1500}
np0=$(grep -ac ' pulled to ' $O 2>/dev/null); np0=${np0:-0}
ng0=$(grep -ac '^gate token written for' $O 2>/dev/null); ng0=${ng0:-0}
NG=4      # one token per run: A_0, A_1, A_rep,0, A_rep,1
for i in $(seq 1 $N); do
  grep -aq '^ZZV8FMINI-STOP\|^ZZV8FMINI-DONE' $O 2>/dev/null && { echo "CHAIN END"; tail -15 $O; exit 0; }
  grep -aq ZZGUARD-STOP $GO 2>/dev/null && { echo "GUARD: $(grep -a ZZGUARD-STOP $GO | tail -1)"; tail -8 $O; exit 4; }
  grep -aq '^ZZLAUNCHINTENT-CONTROL-FAIL\|^ZZDISK-FLOOR-STOP' $O 2>/dev/null && { echo "NAMED STOP: $(grep -a '^ZZLAUNCHINTENT-\|^ZZDISK-' $O | tail -2)"; tail -6 $O; exit 0; }
  ng=$(grep -ac '^gate token written for' $O 2>/dev/null); ng=${ng:-0}
  [ "$ng" -ge $NG ] && [ "$ng0" -lt $NG ] && { echo "GATES PASSED"; grep -a '^LAUNCH-INTENT gate' $O; tail -4 $O; exit 0; }
  n=$(grep -ac ' pulled to ' $O 2>/dev/null); [ "${n:-0}" -gt "$np0" ] && { echo "NEW PULL"; grep -a ' pulled to ' $O | tail -1; tail -6 $O; exit 0; }
  sleep $POLL
done
echo "WAKER TIMEOUT"; tail -5 $O
'''

RUNNER = (
    '@echo off\r\n'
    'rem PREREG_V8F_LAUNCH_INTENT arm A (W 1.58926): FOUR runs on box 2 (A_0, A_1, A_rep,0, A_rep,1). NOT RUN: needs the PI\'s go for box-2 time, the landed queue stage, and PREREG_SHA + READER_SHA filled (LAUNCH.txt; the trainer and model are pinned to the landed commit). '
    'AFTER_OUT = the DAG-ORC r2 chain\'s log: the chain GOes ONLY if it ENDED in its DONE marker with BOX2_BUSY released; a STOP, a guard stop or text after the end HALTs.\r\n'
    '"C:\\Program Files\\Git\\bin\\bash.exe" -lc "AFTER_OUT=/c/Users/Admin/box2_ship/logs/chain_v8f_dagoaccorc_r2.out bash /c/Users/Admin/box2_ship/chain_v8f_launchintent.sh < /dev/null > /c/Users/Admin/box2_ship/logs/chain_v8f_launchintent.out 2>&1" < NUL\r\n'
)


def guard() -> str:
    t = GUARD_SRC.read_text(encoding="utf-8")
    assert "\r" not in t
    t = C.rep(t, "v8f_guard_tail.jsonl", "v8f_guard_launchintent_tail.jsonl", 2)
    t = C.rep(t, "v8f_guard_sc.json", "v8f_guard_launchintent_sc.json", 2)
    t = C.rep(t, "v8f_guard_rate.log", "v8f_guard_launchintent_rate.log", 1)
    t = C.rep(t, "$L/chain_v8f_mini.out", "$L/chain_v8f_launchintent.out", 1)
    t = C.rep(t, "$L/v8f_current.txt", "$L/v8flaunchintent_current.txt", 1)
    t = C.rep(t, "# COPY of v8f_guard_dagoacc.sh for PREREG_V8F_DAG_ORC's chain RE-BASED ON DAG-OACC (Amendment 1): byte-identical logic",
              "# COPY of the installed v8f_guard_dagoaccorc.sh for the LAUNCH-INTENT chain (gen/build_li_small.py): byte-identical logic, ONLY the scratch-file names (tail / sc / rate), the default chain log and the current-run file are this chain's (so no sibling guard shares a file name)", 1)
    return t


def main() -> int:
    C.write_lf(C.SHIP / "v8f_guard_launchintent.sh", guard())
    C.write_lf(C.SHIP / "wake_v8flaunchintent.sh", WAKER)
    (C.SHIP / "run_chain_v8f_launchintent.cmd").write_bytes(RUNNER.encode("utf-8"))
    print("wrote run_chain_v8f_launchintent.cmd", len(RUNNER), "bytes (CRLF)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
