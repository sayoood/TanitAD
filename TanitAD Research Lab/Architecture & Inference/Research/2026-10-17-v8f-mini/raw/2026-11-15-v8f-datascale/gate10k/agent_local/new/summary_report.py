"""summary_report.py (pod, CPU): turns the gate item records into /root/dscale10k/gate/GATE_RESULTS_BLOCK1.md (tables of MEASURED values, regression arms, token facts)."""
import glob
import hashlib
import json
import os

D = "/root/dscale10k"
G = D + "/gate"


def L(n):
    p = f"{G}/{n}.json"
    return json.load(open(p)) if os.path.isfile(p) else None


def red(d):
    return ", ".join(f"{r['arm']}: {'RED' if r['red'] else 'NOT RED'}" for r in (d or {}).get("regression", [])) or "none"


o = ["# GATE_RESULTS_BLOCK1 (generated by summary_report.py from the item records in /root/dscale10k/gate/; MEASURED on the pod)", ""]
o += ["| item | pass | key numbers | regression arms |", "|---|---|---|---|"]
c = L("clock")
if c:
    r = c["record"]
    o.append(f"| G-CLOCK | {c['pass']} | 10k p99 {r['tenk_p99_s']:.4f} s (n {r['n_tenk']}) vs corpus p99 {r['corpus_p99_s']:.4f} s (n {r['n_corpus']}); +0.2 s shift reads 10k p99 {r['regression_tenk_p99_shifted_s']:.4f} s; no pose step for {r['n_tenk_no_pose_dt']} 10k / {r['n_corpus_no_pose_dt']} corpus clips | {red(c)} |")
e = L("eval")
if e:
    b = e["record"]["B"]
    o.append(f"| G-EVAL | {e['pass']} | strict load {b['strict_load_ok']}, cfg equal {b['cfg_equal_built']}, params {b['n_params']}, {b['n_windows']} windows / {b['n_episodes']} episodes, grid sha256 {b['grid_sha256'][:12]} equals the OBD-CTL bank's | {red(e)} |")
k = L("ckptproc")
rs = L("resume")
if k and rs:
    rr = rs["record"]
    o.append(f"| G-CKPT | {k['pass'] and rs['pass']} | round trip bit-equal (B, U); crash at 30, checkpoint at step {rr.get('ckpt_step_at_crash')}, resumed to step {rr.get('resume_final_step')}; resumed equals uninterrupted bitwise: {rr.get('resumed_equals_straight_bitwise')} ({rr.get('n_tensors_differ_resumed_vs_straight')} tensors differ) | {red(k)}; {red(rs)} |")
s = L("suite")
if s:
    o.append(f"| G-SUITE | {s['pass']} | study tree manifest sha256 {s['record']['tree_manifest_sha256'][:12]} equals /root/strat1/base (baseline {s['record']['base_counts']['n_tests']} tests, {s['record']['base_counts']['n_fail']} failed, {s['record']['base_counts']['n_error']} errors, {s['record']['base_counts']['n_skip']} skipped) | {red(s)} |")
i = L("init")
if i:
    ci = i["record"]["c_init_report"]
    o.append(f"| G-HYG / C-INIT | {i['pass']} | n_trainable B_s0 {i['record']['B_s0']['n_trainable']}, U_s0 {i['record']['U_s0']['n_trainable']}, B_rep {i['record']['B_rep']['n_trainable']}; step-0 parameters B_s0 = U_s0: {ci['B_s0_vs_U_s0_params_equal']}, B_rep = B_s0: {ci['B_rep_vs_B_s0_params_equal']} | {red(i)} |")
cc = L("cachecheck")
if cc:
    o.append(f"| C-CACHE | {cc['pass']} | {cc['record']['n_equal']} of {cc['record']['n']} clip files equal the union manifest md5 ({cc['record']['bytes'] / 1e9:.0f} GB, {cc['record']['wall_s']} s) | {red(cc)} |")
se = L("sess")
if se:
    o.append(f"| C-SESS | report | {se['record']['verdict']}; proxy: {se['record']['report_only_proxy']['tenk_clips_sharing_an_eval_chunk']} 10k clips share a storage chunk with an eval-141 clip | - |")
sb = L("stageb")
if sb:
    r = sb["record"]["B_s0.B"]
    dp = r["G-DAGGER"]["dagger_probe"]
    o.append(f"| stage-B C-BANK / G-DAGGER (B_s0, real stage-B argv, complete 4-shard bank from the pilot checkpoint) | {sb['pass']} | n_shards {r['C-BANK']['n_shards']}, coverage {r['C-BANK']['coverage']}; dagger loss_diff {dp.get('loss_diff')}, grad_diff_all {dp.get('grad_diff_all')}, p=0 controls {dp.get('control_p0_loss_diff')} / {dp.get('control_p0_grad_diff')}, prior {dp.get('control_prior_grad_diff')} | {red(sb)} |")
    u = sb["record"]["U_s0.B_smoke"]
    o.append(f"| stage-B U_s0 smoke (--max-clips 200) | {not u['C-BANK']['problems'] and not u['G-DAGGER']['problems']} | n_shards {u['C-BANK']['n_shards']}; dagger pass {u['G-DAGGER']['dagger_probe_pass']}, grad_diff_all {u['G-DAGGER']['grad_diff_all']} | - |")
o += ["", "## Tokens (minted by `dscale10k_check.py mint` only)", "", "| arm.stage | token sha256 (body) | required checks all PASS | verify (runner refusal logic + 4 tampered variants) |", "|---|---|---|---|"]
for a in ("B_s0", "U_s0", "B_rep"):
    p = f"{G}/tokens/{a}.A/gate_token.json"
    v = L(f"verify_{a}.A")
    if os.path.isfile(p):
        t = json.load(open(p))
        o.append(f"| {a}.A | {t['body_sha256'][:16]} | {all(x['pass'] for x in t['checks'].values())} ({len(t['checks'])} checks) | {v['pass'] if v else 'not run'}; {red(v)} |")
    else:
        o.append(f"| {a}.A | NOT MINTED | - | - |")
p = f"{G}/tokens_dry/B_s0.B/gate_token.json"
o.append(f"| B_s0.B (DRY, pilot checkpoint + pilot bank, cannot start a run) | {'written' if os.path.isfile(p) else 'NOT WRITTEN (see mint_dry_B_s0.B.log)'} | - | - |")
open(f"{G}/GATE_RESULTS_BLOCK1.md", "w").write("\n".join(o) + "\n")
print("\n".join(o))
