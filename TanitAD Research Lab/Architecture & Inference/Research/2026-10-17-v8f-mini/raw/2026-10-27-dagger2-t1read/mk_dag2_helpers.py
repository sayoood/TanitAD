def rd(p):
    return open(p, encoding="utf-8", newline="").read()


def apply(t, subs, what):
    for old, new, n in subs:
        c = t.count(old)
        if c != n:
            sys.exit(f"{what}: anchor count {c} != {n} for: {old[:90]!r}")
        t = t.replace(old, new)
    return t


def write(name, text, orig, difname):
    open(os.path.join(HERE, name), "w", encoding="utf-8", newline="").write(text)
    d = "".join(difflib.unified_diff(orig.splitlines(True), text.splitlines(True), "dagt1/" + difname, name, n=0))
    open(os.path.join(HERE, difname.replace(".py", "").replace(".sh", "").replace("dagt1_", "").replace("dag_t1_", "") + ".diff"), "w", encoding="utf-8", newline="").write(d)
    print(name, len(text), "bytes;", d.count("\n"), "diff lines")


