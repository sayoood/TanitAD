"""mk_dag2_helpers.py -- derives dag2t1_pullcheck.py and dag2_t1_chain.sh from the dagt1 originals (E:/Projects/TanitAD-artifacts/dagt1/) by EXACT-COUNT substitutions.
Every substitution must occur exactly the stated number of times, or the derivation stops (the mk_t1kf_arm.py discipline).  The diffs against the originals are written to
pullcheck.diff and chain.diff next to this file, so a reviewer reads the change and not two 30 KB files.   python mk_dag2_helpers.py"""
