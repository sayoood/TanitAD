def _npz_cmp(pa, pb, need_all=True):
    """Arrays of npz pa (partner) against npz pb (new run). Numeric arrays: equal exactly (NaN equal to NaN). -> (ok, n_numeric, list of differing or missing keys,
    list of non-numeric keys that differ, reported only)."""
    import numpy as np
    bad, other, n = [], [], 0
    with np.load(pa, allow_pickle=True) as A, np.load(pb, allow_pickle=True) as B:
        for k in A.files:
            if k not in B.files:
                if need_all:
                    bad.append("missing:" + k)
                continue
            x, y = A[k], B[k]
            if x.dtype.kind in "biufc" and y.dtype.kind in "biufc":
                n += 1
                if x.shape != y.shape or not np.array_equal(x, y, equal_nan=x.dtype.kind in "fc"):
                    bad.append(k)
            elif not (x.shape == y.shape and np.array_equal(x, y)):
                other.append(k)
    return not bad, n, bad, other


