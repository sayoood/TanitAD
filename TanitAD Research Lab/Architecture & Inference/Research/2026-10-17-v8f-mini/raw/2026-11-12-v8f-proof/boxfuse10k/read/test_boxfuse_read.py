def rd(p):
    return io.open(p, encoding="utf-8", newline="").read()


def sha16_clean(p):
    return hashlib.sha256(rd(p).replace("\r", "").encode("utf-8")).hexdigest()[:16]


def payload(ivs=None):
    """ivs {(P, measure letter): (lo, hi)}; default: nothing separated. Every field the names stage prints is present."""
    ivs = ivs or {}
    inv = {PAIR_OF[p][0] + "|" + PAIR_OF[p][1] + "|" + mk: iv for (p, mk), iv in ivs.items()}
    st = {}
    for S in RG.SETTINGS:
        pairs = {pk: {mk: {"interval": list(inv.get("%s|%s|%s" % (S, pk, mk), (-0.01, 0.01))), "mean": 0.0} for mk in "UCF"} for pk in RG.PAIRS[S]}
        levels = {arm: {"C": 0.0, "U": 0.05, "F": 0.2} for arm in RG.arms_of(S)}
        seeds = {arm: {c: [0.0, 0.1] for c in "CUF"} for arm in RG.arms_of(S)}
        st[S] = {"pairs": pairs, "levels": levels, "levels_per_seed": seeds, "counts": {"n_windows": 100, "n_lead_windows": 40, "n_episodes_with_lead": 20}, "instrument_bar_met": True,
                 "families": {pk: {"LONGITUDINAL": "NOT-SEPARATED", "LATERAL": "NOT-SEPARATED", "TACTICAL": "NOT-SEPARATED"} for pk in RG.PAIRS[S]},
                 "strategic": {"pairs": {pk: {"reading": "NOT-SEPARATED"} for pk in RG.PAIRS[S]}}}
    return {"settings": st}


