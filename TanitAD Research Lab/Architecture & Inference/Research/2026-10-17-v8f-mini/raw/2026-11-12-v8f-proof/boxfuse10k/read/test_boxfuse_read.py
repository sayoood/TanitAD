def run_line(name, S, m, wrap, form, tail=""):
    ln = LINE % ("I10%s_s%d" % (name, m), RG.SPEC[S]["every"], "causal_g")
    ln = ln.replace("form RR", "form " + form).replace("model seed 0 reader seed 0", "model seed %d reader seed %d" % (m, m)).replace("28" * 32, wrap)
    return ln + " started 2026-11-23T10:57:07Z" + tail


def write_run(pull, name, m, first, ci, fr, present, gaps, clos, sha=None, done=True, ndump=3):
    d = os.path.join(pull, "I10%s_s%d" % (name, m))
    os.makedirs(os.path.join(d, "ticks"), exist_ok=True)
    h = len(ci) // 2
    for nm, sl in (("rule_log_I10%s_s%d.npz", slice(0, h)), ("rule_log_mid_I10%s_s%d.npz", slice(h, len(ci)))):
        z = dict(ci=ci[sl], j=fr[sl], present=present[sl], g_src=gaps[sl].copy(), c_src=clos[sl])
        if sha is not None:
            z.update(vis_gap_file_sha256=np.array(sha), vis_closing=np.array(1))
        np.savez(os.path.join(d, "ticks", nm % (name, m)), **z)
    io.open(os.path.join(d, "ticks", "run_I10%s_s%d.txt" % (name, m)), "w", encoding="utf-8", newline="\n").write(first + "\nrc 0 finished x\n")
    if done:
        io.open(os.path.join(d, "T1_DONE"), "w").write("")
    dd = os.path.join(d, "dump_I10%s_s%d_m10_causal_heads" % (name, m))
    os.makedirs(dd, exist_ok=True)
    for i in range(ndump):
        np.savez(os.path.join(dd, "ep%03d.npz" % i), x=np.zeros(1))


def sha_of(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def make_world(base, fault=None):
    """-> (a, m, wsha). fault None: every control passes; otherwise one planted defect (see FAULTS)."""
    base = str(base)
    pull = os.path.join(base, "pull")
    os.makedirs(pull, exist_ok=True)
    nk = 12
    ci, fr = np.repeat(np.arange(3), nk), np.tile(np.arange(nk), 3)
    n = len(ci)
    clips = np.array(["c0", "c1", "c2"])
    has = np.ones(n, bool)
    has[[2, 14, 30]] = False
    reader_gap = 20.0 + 0.2 * np.arange(n)
    file_gap, paths = {}, {}
    for nm, sc in (("VGAPJE", 1.0), ("VGAPJE90", 0.9)):
        g = np.where(has, (15.0 + 0.9 * fr + 0.3 * ci) * sc, np.nan)
        paths[nm] = os.path.join(base, nm + ".npz")
        np.savez(paths[nm], clip_index=ci, frame=fr, gap=g, has_out=has, clips=clips, seed=np.int64(-1))
        file_gap[nm] = g
    shas = {nm: sha_of(p) for nm, p in paths.items()}
    rec = {"card": RG.CARD, "pass_j0": True, "pass_j1": True, "pass_j2": True, "pass_j3": True, "pass_j4": True,
           "files": {nm: {"sha256": shas[nm]} for nm in shas}, "counts": {"n_rows_with_output": 3, "n_picked": 3, "n_gated": 2}}
    if fault and fault.startswith("pass_j"):
        rec[fault] = False
    if fault == "card":
        rec["card"] = "PREREG_V8F_PROOF_ADD130"
    if fault == "hash":
        rec["files"]["VGAPJE"]["sha256"] = "0" * 64
    rpath = os.path.join(base, "BOXFUSE10K_GAPFILES_RECORD.json")
    json.dump(rec, io.open(rpath, "w", encoding="utf-8"))
    wrap = RG.WRAPPER_SHA + "0" * 48
    ones = np.ones(n, bool)
    clos = np.where(np.arange(n) % 2 == 0, 0.5, 0.0)
    for S in RG.SETTINGS:
        for m in RG.SEEDS:
            ref_first = run_line(RG.run_name(S, "GEc"), S, m, wrap, "RR")
            write_run(pull, RG.run_name(S, "RR"), m, run_line(RG.run_name(S, "RR"), S, m, wrap, "RR"), ci, fr, ones, reader_gap + 1e-5, clos)
            write_run(pull, RG.run_name(S, "GEc"), m, ref_first, ci, fr, ones, reader_gap + 1e-5, clos)
            for S2, arm in RG.new_pairs():
                if S2 != S:
                    continue
                nm = RG.NEW_FILES[arm]
                g = np.where(has, file_gap[nm], reader_gap) + 1e-5
                clz, sha, done, ndump, first = clos, shas[nm], True, 3, run_line(RG.run_name(S, arm), S, m, wrap, "RR", " vis-gap-file /w/%s.npz gap file sha256 %s vis-closing 1" % (nm, shas[nm]))
                if fault == "gap_value" and (S, arm, m) == ("CONV", "JEc", 1):
                    g[1] += 0.5
                if fault == "meta" and (S, arm, m) == ("CONV", "JEc", 0):
                    sha = "2" * 64
                if fault == "meta90" and (S, arm, m) == ("K0", "JA90", 1):
                    sha = shas["VGAPJE"]                                                       # the rule log names the other file of the card
                if fault == "closing_zero" and (S, arm, m) == ("K0", "JA90", 0):
                    clz = np.zeros(n)
                if fault == "done" and (S, arm, m) == ("K0", "JEc", 1):
                    done = False
                if fault == "dump" and (S, arm, m) == ("K0", "JA90", 1):
                    ndump = 2
                if fault == "wrapper_run" and (S, arm, m) == ("CONV", "JEc", 1):
                    first = first.replace(wrap, "e" * 64)
                if fault == "arg" and (S, arm, m) == ("K0", "JEc", 0):
                    first = first.replace("kappa 0.2", "kappa 0.3")
                write_run(pull, RG.run_name(S, arm), m, first, ci, fr, ones, g, clz, sha=sha, done=done, ndump=ndump)
    chk = os.path.join(base, "CHECK_WRAPPER_V_DONE.txt")
    io.open(chk, "w", encoding="utf-8").write("a\n" + ("ZZ CHECK-WRAPPER-V FAIL" if fault == "check_file" else RG.CHECK_LAST) + "\n\n")
    hs = os.path.join(base, "CHECK_WRAPPER_V.hashes")
    io.open(hs, "w", encoding="utf-8").write("sha %s\n" % RG.WRAPPER_SHA)
    tq, tr = os.path.join(base, "q_pytest.out"), os.path.join(base, "r_pytest.out")
    io.open(tq, "w", encoding="utf-8").write("....\n12 passed in 3.1s\n")
    io.open(tr, "w", encoding="utf-8").write("....\n== 30 passed, 2 warnings in 9.0s ==\n")
    a = argparse.Namespace(pull=pull, gap_record=rpath, gap_files=dict(paths), wrapper_check=chk, wrapper_hashes=hs, tests_queue=tq, tests_read=tr, tests_mtime_queue=1000.0,
                           tests_mtime_read=1010.0 if fault != "tests_time" else 1300.0, queue_start=1100.0, controls_start=1200.0, done_marker="", expect_dumps=3)
    if fault == "missing_gap_file":
        a.gap_files["VGAPJE90"] = os.path.join(base, "nothing_here.npz")
    lv = {S: {arm: dict(zip("CUF", v)) for arm, v in RG.EXPECTED[S].items()} for S in RG.SETTINGS}
    for S in RG.SETTINGS:
        for arm in RG.NEW_ARMS[S]:
            lv[S][arm] = {"C": 0.0, "U": 0.1, "F": 0.2}
    if fault == "level":
        lv["K0"]["A90"]["U"] += 0.001
    st = {S: {"levels": lv[S], "grid_all_pass": True, "strategic_a": True, "strategic_b": fault != "engine"} for S in RG.SETTINGS}
    return a, {"settings": st}, RG.WRAPPER_SHA


