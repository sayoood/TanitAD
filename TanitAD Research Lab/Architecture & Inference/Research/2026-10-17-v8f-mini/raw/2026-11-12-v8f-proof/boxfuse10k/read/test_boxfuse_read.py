def test_every_name_of_the_card_is_reachable_from_the_rule():
    """all 27 sign patterns of the three measures, applied to every named pair: the set of names reached is exactly the set the card section 4 gives (39 names)"""
    iv = {-1: (-0.03, -0.002), 0: (-0.01, 0.01), 1: (0.002, 0.03)}
    seen = set()
    for combo in itertools.product((-1, 0, 1), repeat=3):
        ivs = {(p, mk): iv[s] for p in PAIR_OF for mk, s in zip("UCF", combo)}
        seen |= set(RG.all_names(payload(ivs)).values())
        summ = {n.rsplit("JOINED-GAP-", 1)[1] for n in RG.all_names(payload(ivs)).values() if "JOINED-GAP-" in n}
        want = "TRADES" if (-1 in combo and 1 in combo) else ("HELPS" if -1 in combo else ("COSTS" if 1 in combo else "NOT-SEPARATED"))
        assert summ == {want}, (combo, summ)
    expect = set()
    for p in PAIR_OF:
        for mw in ("UNSAFE", "CONTACT", "FALLING-BEHIND"):
            expect |= {"BOXFUSE10K-%s-LOWERS-%s" % (p, mw), "BOXFUSE10K-%s-RAISES-%s" % (p, mw), "BOXFUSE10K-%s-%s-NOT-SEPARATED" % (p, mw)}
        expect |= {"BOXFUSE10K-%s-JOINED-GAP-%s" % (p, t) for t in ("HELPS", "COSTS", "TRADES", "NOT-SEPARATED")}
    assert len(expect) == 39 and seen == expect


