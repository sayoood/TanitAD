# mk_pod_ruleown.py : builds two scripts that run ON THE POD through bash -s (card PREREG_V8F_PROOF_ADD34 and stage 2 of note PREREG_V8F_PROOF_ADD32_N1).
#   pod_ruleown_tree.sh : creates /workspace/v8proof/tree_ruleown from tree_ruletrain plus the changed and new files, verifies every sha256 of PINS.txt and of the
#                         PIN lines of the arms file, writes the arms files of the chains ruleown_a (GOW, GOW4; 2,000 steps) and ruledose2_a (GRW6; 6,000 steps).
#                         No GPU, trains nothing.
#   pod_ruleown_gate.sh : dry-gates GOW_s0, GOW4_s0 and GRW6_s0 (one selfcheck each, with the real-data live step), checks the token kinds, prints the probes.
#                         Refuses to run as a fourth GPU job. Trains nothing.
import base64, io, os, tarfile, hashlib

SRC = "F:/TanitAD-scratch/v8proof/ruletrain2"
HERE = os.path.dirname(os.path.abspath(__file__))
OWN = ["GOW_s0", "GOW_s1", "GOW4_s0", "GOW4_s1"]
DOSE = ["GRW6_s0", "GRW6_s1"]


def sha(b):
    return hashlib.sha256(b).hexdigest()


pins = []
for ln in io.open(os.path.join(SRC, "PINS.txt"), encoding="utf-8").read().splitlines():
    t = ln.split()
    if not t or t[0].startswith("#"):
        continue
    if t[0] == "changed":
        pins.append((t[0], t[1], t[-1]))
    elif t[0] in ("new", "same"):
        pins.append((t[0], t[1], t[2]))
files = []
for kind, rel, h in pins:
    q = os.path.join(SRC, "patched", rel[len("stack/"):])
    if kind in ("changed", "new"):
        b = open(q, "rb").read()
        assert sha(b) == h, "PINS mismatch on the local file " + rel
        assert b"\r\n" not in b, "CRLF in " + rel
        files.append((rel[len("stack/"):], b))
assert files, "no changed or new file"

arms = io.open(os.path.join(SRC, "ARMS_RULEOWN.txt"), encoding="utf-8").read().splitlines()
pin_lines = [l for l in arms if l.startswith("PIN|")]
arm = {l.split("|")[1]: l for l in arms if l.startswith("ARM|")}
assert sorted(arm) == sorted(OWN + DOSE), sorted(arm)
pin_map = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, tree, rel, h = l.split("|")
    assert tree == "/workspace/v8proof/tree_ruleown", tree
    if rel in pin_map:
        assert pin_map[rel] == h, "arms PIN differs from PINS.txt: " + rel
for name in OWN + DOSE:
    a = arm[name]
    assert a.count("|HIER|") == 1, name
    assert "--init-ckpt /workspace/v8proof/runs/spatial/G_s%s/ckpt_last.pt" % name[-1] in a, name
    assert "--lr 1e-4 --warmup 100" in a, name
    if name.startswith("GOW4"):
        assert "--steps 2000 " in a and "--w-rule-own 4.0" in a and "--rule-relabel" not in a, name
    elif name.startswith("GOW"):
        assert "--steps 2000 " in a and "--w-rule-own 1.0" in a and "--rule-relabel" not in a, name
    else:
        assert "--steps 6000 " in a and "--rule-relabel on" in a and "--rule-relabel-weight 4" in a and "--w-rule-own" not in a, name

buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tf:
    for rel, b in files:
        ti = tarfile.TarInfo(rel)
        ti.size = len(b)
        ti.mode = 0o644
        tf.addfile(ti, io.BytesIO(b))
b64 = base64.encodebytes(buf.getvalue()).decode("ascii")

allpins = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, _tree, rel, h = l.split("|")
    allpins.setdefault(rel, h)

T = []
T.append("# pod_ruleown_tree.sh : generated by mk_pod_ruleown.py. Runs ON THE POD (bash -s). No GPU, trains nothing.")
T.append("set -u")
T.append("W=/workspace/v8proof; cd $W || exit 1")
T.append("[ -d $W/tree_ruletrain ] || { echo 'REFUSED: tree_ruletrain absent'; exit 1; }")
T.append("[ -e $W/chain2/arms_ruleown_a.txt ] || [ -e $W/chain2/arms_ruledose2_a.txt ] && { echo 'REFUSED: an arms file of this card exists'; exit 1; }")
T.append("if [ ! -d $W/tree_ruleown ]; then cp -r $W/tree_ruletrain $W/tree_ruleown; echo 'tree_ruleown copied from tree_ruletrain'; else echo 'tree_ruleown exists, files are written again'; fi")
T.append("base64 -d > $W/ruleown_patch.tgz <<'B64EOF'")
T.append(b64.rstrip("\n"))
T.append("B64EOF")
T.append("tar -xzf $W/ruleown_patch.tgz -C $W/tree_ruleown/stack || { echo 'REFUSED: untar failed'; exit 1; }")
T.append("bad=0")
for rel, h in sorted(allpins.items()):
    T.append("h=$(sha256sum $W/tree_ruleown/%s 2>/dev/null | cut -c1-64); [ \"$h\" = \"%s\" ] || { echo \"PIN MISMATCH %s $h\"; bad=1; }" % (rel, h, rel))
T.append("[ $bad = 0 ] && echo 'pins: all %d sha256 equal' || { echo 'REFUSED: pin mismatch'; exit 1; }" % len(allpins))
T.append("for g in G_s0 G_s1; do [ -f $W/runs/spatial/$g/ckpt_last.pt ] || { echo \"REFUSED: no base checkpoint $g\"; exit 1; }; done")
T.append("cd $W/chain2 || exit 1")
T.append("for f in gate_token3.py gate_token4.py chain_arms_ft.sh chain_arms_ft6.sh dry_gate.sh; do [ -f $f ] || { echo \"REFUSED: $f absent\"; exit 1; }; done")
T.append("echo \"tools: gate_token3.py $(sha256sum gate_token3.py | cut -c1-16) gate_token4.py $(sha256sum gate_token4.py | cut -c1-16) chain_arms_ft.sh $(sha256sum chain_arms_ft.sh | cut -c1-16) chain_arms_ft6.sh $(sha256sum chain_arms_ft6.sh | cut -c1-16)\"")
T.append("cat > arms_ruleown_a.txt <<'ARMSEOF'")
T.append("# RULEOWN (PREREG_V8F_PROOF_ADD34): four fine-tunes of 2,000 steps from the banked checkpoints of arm G with the own-plan rule term; GOW weight 1.0, GOW4 weight 4.0.")
T.extend(pin_lines)
for n in OWN:
    T.append(arm[n].replace("|HIER|", "|HIERFT|", 1))
T.append("ARMSEOF")
T.append("cat > arms_ruledose2_a.txt <<'ARMSEOF'")
T.append("# RULETRAIN note PREREG_V8F_PROOF_ADD32_N1, stage 2: two fine-tunes of 6,000 steps with --rule-relabel on and a weight of 4 on the relabelled samples.")
T.extend(pin_lines)
for n in DOSE:
    T.append(arm[n].replace("|HIER|", "|HIERFT6|", 1))
T.append("ARMSEOF")
T.append("for f in arms_ruleown_a.txt arms_ruledose2_a.txt; do echo \"== $f sha256 $(sha256sum $f | cut -c1-64) PIN $(grep -c '^PIN|' $f) ARM $(grep -c '^ARM|' $f)\"; grep '^ARM|' $f | cut -d'|' -f2,4,5,8 | cut -c1-260; done")
T.append("C2_CARD=PREREG_V8F_PROOF_ADD34 bash chain_arms_ft.sh dryx arms_ruleown_a.txt --dry-run | grep '^TRAIN GOW_s0' | cut -c1-900")
T.append("C2_CARD=PREREG_V8F_PROOF_ADD32 bash chain_arms_ft.sh dryx arms_ruletrain_a.txt --dry-run | grep '^TRAIN GFT_s0' | sed -e 's|tree_ruletrain|tree_ruleown|' -e 's|/runs/[a-z_0-9]*/GFT_s0|/runs/X/A|' -e 's|^TRAIN GFT_s0|TRAIN A|' > /tmp/own_gft.txt")
T.append("C2_CARD=PREREG_V8F_PROOF_ADD34 bash chain_arms_ft.sh dryx arms_ruleown_a.txt --dry-run | grep '^TRAIN GOW_s0' | sed -e 's| --w-rule-own 1.0||' -e 's|/runs/[a-z_0-9]*/GOW_s0|/runs/X/A|' -e 's|^TRAIN GOW_s0|TRAIN A|' > /tmp/own_gow.txt")
T.append("cmp -s /tmp/own_gft.txt /tmp/own_gow.txt && echo 'argv of GOW_s0 equals that of GFT_s0 apart from tree, name, out folder and the flag' || { echo 'ARGV DIFFERS'; diff /tmp/own_gft.txt /tmp/own_gow.txt | cut -c1-300 | head -n 6; }")
T.append("echo \"memory.max $(cat /sys/fs/cgroup/memory.max) ; $(grep -E '^anon ' /sys/fs/cgroup/memory.stat)\"; nvidia-smi --query-compute-apps=pid,used_memory --format=csv,noheader | tr '\\n' ';'; echo")

G = []
G.append("# pod_ruleown_gate.sh : generated by mk_pod_ruleown.py. Runs ON THE POD (bash -s). Dry gates only (one selfcheck per arm), trains nothing.")
G.append("set -u")
G.append("W=/workspace/v8proof; cd $W/chain2 || exit 1")
G.append("n=$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .); [ \"${n:-0}\" -lt 3 ] || { echo \"REFUSED: $n GPU jobs running, a dry gate would be the fourth\"; exit 1; }")
G.append("a=$(grep -E '^anon ' /sys/fs/cgroup/memory.stat | cut -d' ' -f2); m=$(cat /sys/fs/cgroup/memory.max); [ $((m - a)) -gt 20000000000 ] || { echo 'REFUSED: less than 20 GB of the memory limit free'; exit 1; }")
for arm_name, card, f in (("GOW_s0", "PREREG_V8F_PROOF_ADD34", "arms_ruleown_a.txt"), ("GOW4_s0", "PREREG_V8F_PROOF_ADD34", "arms_ruleown_a.txt"), ("GRW6_s0", "PREREG_V8F_PROOF_ADD32", "arms_ruledose2_a.txt")):
    G.append("bash dry_gate.sh %s %s %s > $W/chains/ruleown_dry_%s.out 2>&1; echo \"dry gate %s rc $?\"; tail -n 5 $W/chains/ruleown_dry_%s.out | cut -c1-300" % (f, arm_name, card, arm_name, arm_name, arm_name))
G.append("SC=$W/runs/motion_dry/GOW_s0/out/selfcheck.json; GA=$W/chains/ruleown_dry_gate_argv.txt")
G.append("C2_CARD=PREREG_V8F_PROOF_ADD34 bash chain_arms.sh dryrun_GOW_s0 arms_ruleown_a.txt --dry-run | grep '^TRAIN GOW_s0: ' | sed 's|^TRAIN GOW_s0: ||' | tr ' ' '\\n' | tail -n +3 > $GA; echo --selfcheck-only >> $GA")
G.append("$W/../venv/bin/python gate_token3.py make --selfcheck $SC --argv-file $GA --out $W/chains/ruleown_dry_token_ft.json --kind HIERFT --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIERFT rc ${PIPESTATUS[0]} (must be 0)\"")
G.append("$W/../venv/bin/python gate_token3.py make --selfcheck $SC --argv-file $GA --out $W/chains/ruleown_dry_token_full.json --kind HIER --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIER rc ${PIPESTATUS[0]} (must be 1)\"")
G.append("$W/../venv/bin/python - <<'PYEOF'")
G.append("import json")
G.append("for a in ('GOW_s0', 'GOW4_s0', 'GRW6_s0'):")
G.append("    try:")
G.append("        s = json.load(open('/workspace/v8proof/runs/motion_dry/%s/out/selfcheck.json' % a)); i = s.get('info', {}); lv = s.get('levers', {})")
G.append("        print('SELFCHECK', a, 'dvb', s.get('declared_vs_built'), 'live', (s.get('live') or {}).get('pass'), 'steps_total', s.get('steps_total'), 'init_applied', (lv.get('init_ckpt') or {}).get('applied'), 'w_rule_own', lv.get('w_rule_own'), 'rule_relabel', lv.get('rule_relabel'), 'rule_relabel_weight', lv.get('rule_relabel_weight'))")
G.append("        print('   own probe', json.dumps(s.get('rule_own_probe'))[:700])")
G.append("        print('   relabel probe', json.dumps(s.get('rule_relabel_probe'))[:300], '| info', json.dumps({k: v for k, v in i.items() if 'rule' in k and not isinstance(v, dict)})[:300])")
G.append("        lt = (s.get('live') or {})")
G.append("        print('   live keys', sorted(k for k in lt if 'loss' in k or 'rule' in k or 'term' in k)[:20], json.dumps({k: lt[k] for k in lt if ('loss' in k or 'rule' in k) and isinstance(lt[k], (int, float))})[:400])")
G.append("    except Exception as e:")
G.append("        print('SELFCHECK', a, 'ERR', e)")
G.append("PYEOF")
for name, lines in (("pod_ruleown_tree.sh", T), ("pod_ruleown_gate.sh", G)):
    p = os.path.join(HERE, name)
    io.open(p, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("written", p, os.path.getsize(p), "bytes")
print(len(allpins), "pins;", [r for r, _b in files])
