def arms_of(part):
    return (A_ARMS if part in ("A", "ALL") else ()) + (B_ARMS if part in ("B", "ALL") else ())


def settings(part="ALL"):
    out = {}
    for st, P, grid, suf in (("AGE", 30, "30", "P30Hb20"), ("FRESH", 0, "full", "Hb20")):
        arms = [x for x in arms_of(part) if st == "AGE" or x == "TK"]
        if not arms:
            continue
        runs = {"RRe_" + x: "RQ50e%sKF5%s" % (x, suf) for x in arms}
        runs.update({f: EC.SETTINGS[st]["runs"][f] for f in EEST + BANKED})
        out[st] = {"P": P, "grid": grid, "spread": "R0Hb20", "runs": runs}
    return out


def pairs_of(new, st):
    """-> (pairs {name: (form A, form B)}, part {name: 'A'|'B'}) for the new forms present in the setting"""
    avail = set(new) | set(EEST) | set(BANKED)
    P, pt = {}, {}

    def add(nm, x, y, p):
        if x in avail and y in avail:
            P[nm], pt[nm] = (x, y), p
    for nm, y in (("TOK-VS-RR", "RR"), ("TOK-VS-EST-L25", "RRe_L25"), ("TOK-VS-EST-N10", "RRe_N10"), ("TOK-VS-LABEL-CLOSING", "RRc"), ("TOK-VS-NO-RULE", "R0K")):
        add(nm, "RRe_TK", y, "A")
    if st == "AGE":
        add("TOK-VS-SHUF", "RRe_TK", "RRe_STK", "A")
        add("SHUF-VS-RR", "RRe_STK", "RR", "A")
        for x in XARMS:
            add(x + "-VS-RR", "RRe_" + x, "RR", "B")
            add(x + "-VS-LABEL-CLOSING", "RRe_" + x, "RRc", "B")
            add(x + "-VS-NO-RULE", "RRe_" + x, "R0K", "B")
        add("W50-VS-TOK", "RRe_W50", "RRe_TK", "B")
        add("W50-VS-EST-L25", "RRe_W50", "RRe_L25", "B")
        add("S70-VS-W70", "RRe_S70", "RRe_W70", "B")
    return P, pt


