def arm_table(levels, runs):
    """per form (the order of the card): C, U, F per seed and pooled (mean over the seeds), and the share of the contact gap between RR and RRc that the form removes, (C_RR - C_X) / (C_RR - C_RRc), per seed and
    pooled (None when the gap is 0). Names nothing."""
    rows = []
    rr, rc = levels[runs["RR"]]["C"], levels[runs["RRc"]]["C"]

    def per(v):
        return [float(x) for x in np.asarray(v, np.float64).reshape(-1)[:len(SEEDS)]]

    def share(c_x, c_rr, c_rc):
        gap = c_rr - c_rc
        return None if gap == 0.0 else (c_rr - c_x) / gap
    for f in TABLE_ORDER:
        if f not in runs:
            continue
        lv = levels[runs[f]]
        row = {"form": f, "run": runs[f]}
        for k in ("C", "U", "F"):
            p = per(lv[k])
            row[k] = {"per_seed": p, "pooled": float(np.mean(p))}
        crr, crc, cx = per(rr), per(rc), row["C"]["per_seed"]
        row["share_of_gap_RR_to_RRc"] = {"per_seed": [share(cx[i], crr[i], crc[i]) for i in range(len(cx))], "pooled": share(row["C"]["pooled"], float(np.mean(crr)), float(np.mean(crc)))}
        rows.append(row)
    return rows


def shares_of(table):
    return {r["form"][len("RRe_"):]: r["share_of_gap_RR_to_RRc"]["pooled"] for r in table if r["form"] in NEW_FORMS}


def render_table(res):
    L = []
    if res.get("names") is None:
        return L
    for st, p in (res.get("settings") or {}).items():
        if not p or not isinstance(p.get("table"), list):
            continue
        L.append("== table by arm %s (levels of the windows with a lead; per seed and pooled; share of the RR-to-RRc contact gap; reported, names nothing)" % st)
        for r in p["table"]:
            sg = r["share_of_gap_RR_to_RRc"]
            fm = lambda v: "n/a" if v is None else "%.3f" % v                                    # noqa: E731
            L.append("   %-9s C %s pooled %.4f  U %s pooled %.4f  F %s pooled %.4f  share %s pooled %s" % (r["form"], ["%.4f" % x for x in r["C"]["per_seed"]], r["C"]["pooled"], ["%.4f" % x for x in r["U"]["per_seed"]],
                                                                                                   r["U"]["pooled"], ["%.4f" % x for x in r["F"]["per_seed"]], r["F"]["pooled"], [fm(x) for x in sg["per_seed"]], fm(sg["pooled"])))
    return L


