def cname(pair, setting, kind, word):
    return "%s-%s-%s-%s-%s" % (PRE, pair, setting, kind, word)


def pair_names(setting, pair, wd):
    out = {}
    for kind in ("C", "U", "F"):
        if wd[kind] is not None:
            out["%s_%s_%s" % (pair, setting, kind)] = cname(pair, setting, kind, wd[kind])
    for f in FAMS:
        out["%s_%s_%s" % (pair, setting, f)] = cname(pair, setting, f, wd["fam"][f])
    return out


def decide(conds):
    """three-valued: False when one condition is False (it decides without the others), None when one is not available, else True"""
    if any(c is False for c in conds):
        return False
    if any(c is None for c in conds):
        return None
    return True


def c_lower(w):
    return None if w is None or w["C"] is None else bool(w["C"] == "LOWER")


def c_nh(w, k):
    return None if w is None or w[k] is None else bool(w[k] in NOT_HIGHER)


def no_worse(w):
    return None if w is None else bool(all(w["fam"][f] != "WORSE" for f in FAMS))


def wd_get(words, st, pair):
    return (words.get(st) or {}).get(pair)


def verdict_names(words, expected, shares):
    """words[setting][pair] = {"C","U","F","fam"} or None (withheld or not run); expected = {"A": bool, "B": bool}; shares = {arm: pooled share of the RR-to-RRc contact gap or None}. -> (names, why)."""
    names, why = {}, {}

    def put(key, cond, yes, no, label):
        if cond is None:
            why[key] = "not written: a word this name needs is not available (withheld by a control, not run, or the headway instrument is not qualified): %s" % label
        else:
            names[key] = PRE + "-" + (yes if cond else no)
    if expected.get("A"):
        r_a, r_f = wd_get(words, "AGE", "TOK-VS-RR"), wd_get(words, "FRESH", "TOK-VS-RR")
        sup = decide([c_lower(r_a), c_nh(r_a, "U"), no_worse(r_a), c_nh(r_f, "C"), c_nh(r_f, "U"), no_worse(r_f)])
        put("VERDICT_TK", sup, "TK-SUPPORTED", "TK-NOT-SUPPORTED", "TK-SUPPORTED")
        for st, r in (("AGE", r_a), ("FRESH", r_f)):
            if "VERDICT_TK" in names and r is not None and r["F"] is not None:
                names["VERDICT_TK_BESIDE_F_" + st] = cname("TOK-VS-RR", st, "F", r["F"])
        put("VERDICT_TK_BEYOND_L25", decide([c_lower(wd_get(words, "AGE", "TOK-VS-EST-L25"))]), "TK-BEYOND-L25", "TK-NOT-BEYOND-L25", "TK-BEYOND-L25")
        sh = wd_get(words, "AGE", "TOK-VS-SHUF")
        put("VERDICT_TK_GAIN", decide([c_lower(sh), c_nh(sh, "U")]), "TK-GAIN-FROM-THE-SCENE", "TK-GAIN-NOT-SHOWN-FROM-THE-SCENE", "TK-GAIN-FROM-THE-SCENE")
        if "VERDICT_TK_GAIN" in names:
            sr = wd_get(words, "AGE", "SHUF-VS-RR")
            if sr is None or sr["C"] is None:
                why["VERDICT_TK_GAIN_BESIDE_SHUF_VS_RR"] = "the name of SHUF-VS-RR (C, AGE) is not available (withheld, not run, or the headway instrument is not qualified)"
            else:
                names["VERDICT_TK_GAIN_BESIDE_SHUF_VS_RR"] = cname("SHUF-VS-RR", "AGE", "C", sr["C"])
    if not expected.get("B"):
        return names, why
    rem, at = {}, {}
    for x in XARMS:
        rr, lc = wd_get(words, "AGE", x + "-VS-RR"), wd_get(words, "AGE", x + "-VS-LABEL-CLOSING")
        rem[x] = decide([c_lower(rr), c_nh(rr, "U")])
        at[x] = decide([c_nh(lc, "C")])
        put("ARM_%s_REMOVES" % x, rem[x], x + "-REMOVES-CONTACT", x + "-NOT-SHOWN", x + " REMOVES-CONTACT")
        put("ARM_%s_LABEL_LEVEL" % x, at[x], x + "-AT-LABEL-LEVEL", x + "-ABOVE-LABEL-LEVEL", x + " AT-LABEL-LEVEL")
    found, unresolved = None, None
    for nn, x in ((50, "W50"), (70, "W70"), (90, "W90")):
        if rem[x] is None:
            unresolved = x
            break
        if rem[x] is False:
            continue
        sh_ = shares.get(x)
        if sh_ is not None and sh_ >= HALF:
            found = nn
            break
    if found is not None:
        names["VERDICT_REQUIREMENT"] = "%s-REQUIREMENT-R%02d" % (PRE, found)
    elif unresolved is not None:
        why["VERDICT_REQUIREMENT"] = "not written: the REMOVES-CONTACT name of %s is not available, and no lower level reached half" % unresolved
    else:
        names["VERDICT_REQUIREMENT"] = PRE + "-NO-TESTED-LEVEL-REACHES-HALF"
    put("VERDICT_SPREAD_ALONE", decide([c_lower(wd_get(words, "AGE", "W00-VS-RR"))]), "SPREAD-ALONE-REMOVES-CONTACT", "SPREAD-ALONE-NOT-SHOWN", "SPREAD-ALONE")
    pair_ = [(rem["W70"], rem["S70"]), (at["W70"], at["S70"])]
    if any(a_ is None or b_ is None for a_, b_ in pair_):
        why["VERDICT_REQUIREMENT_MARK"] = "not decided: a name of W70 or S70 is not available"
    else:
        names["S70_BESIDE_W70"] = "%s | %s" % (names["ARM_S70_REMOVES"] + " / " + names["ARM_S70_LABEL_LEVEL"], names["ARM_W70_REMOVES"] + " / " + names["ARM_W70_LABEL_LEVEL"])
        if any(a_ != b_ for a_, b_ in pair_):
            names["VERDICT_REQUIREMENT_MARK"] = MARK_TIME
    return names, why


def failed_sets(controls):
    """sorts the controls that did not pass: glob (inherited: no name, no value), B (part B), SHUF (surrogate), a2 {setting: failed arms}"""
    f = {"glob": [], "B": [], "SHUF": [], "a2": {}}
    for k, v in controls.items():
        if v.get("PASS") is True:
            continue
        if k in ("a0_tables", "a1_tables") or k.startswith("a3_"):
            f["B"].append(k)
        elif k in ("a4_u1", "a4_u4") or k.startswith("a4_u3_"):
            f["SHUF"].append(k)
        elif k.startswith("a2_"):
            bad = sorted({n.split(":")[0] for n, r in (v.get("runs") or {}).items() if r.get("ok") is not True})
            f["a2"][k[3:]] = bad or list(NEW_ARMS)
        else:
            f["glob"].append(k)
    return f


def blocked_reason(failed, st, pair, forms, part):
    if part == "B" and failed["B"]:
        return "withheld: control %s did not pass (guards part B)" % ", ".join(failed["B"])
    if pair in ("TOK-VS-SHUF", "SHUF-VS-RR") and failed["SHUF"]:
        return "withheld: control %s did not pass (guards the surrogate arm)" % ", ".join(failed["SHUF"])
    bad = failed["a2"].get(st) or []
    used = [f[len("RRe_"):] for f in forms if f in NEW_FORMS]
    if any(x in bad for x in used):
        return "withheld: control a2 did not pass for a run of this pair at %s" % st
    return None


def all_names(words, quals, pair_forms, pair_part, failed, expected, shares):
    """-> (names, why). words[st][pair]; pair_forms[st][pair] = (form A, form B); pair_part[st][pair] = 'A'|'B'. A pair whose guarding control failed has no name and its words are not used by a verdict."""
    names, why, w2 = {}, {}, {}
    for st in words:
        w2[st] = {}
        if not quals.get(st):
            why["HEADWAY_" + st] = "U, C and F of the setting %s are not reported: the headway instrument is not qualified on its grid" % st
        for pair, w in words[st].items():
            r = blocked_reason(failed, st, pair, pair_forms[st][pair], pair_part[st][pair])
            if r:
                why["%s_%s" % (pair, st)] = r
                w2[st][pair] = None
                continue
            w2[st][pair] = w
            names.update(pair_names(st, pair, w))
    vn, vw = verdict_names(w2, expected, shares)
    names.update(vn)
    why.update(vw)
    return names, why


# ============================================================================================ controls
def ctl_rec(rec, shas, key, want):
    """a control read from TAB_TABLES_RECORD.json: the record's control `key` says PASS and the sha256 of every table file in `want` read here equals the record's entry"""
    try:
        if not isinstance(rec, dict):
            return {"PASS": False, "why": "the table record is missing"}
        d, tabs = rec.get(key), rec.get("tables")
        if not isinstance(d, dict) or d.get("PASS") is not True:
            return {"PASS": False, "why": "the record's control %s does not say PASS" % key, "record_pass_top_level": rec.get("pass")}
        if not isinstance(tabs, dict) or not want:
            return {"PASS": False, "why": "the record holds no table hashes or no table was expected"}
        bad = sorted(n for n in want if shas.get(n) is None or tabs.get(n) != shas.get(n))
        return {"PASS": bool(not bad), "record_says_pass": True, "tables_checked": len(want), "tables_not_equal_to_the_record": bad, "record_pass_top_level": rec.get("pass")}
    except Exception as ex:                                                                   # noqa: BLE001
        return {"PASS": False, "why": "%s: %s" % (type(ex).__name__, str(ex)[:200])}


def ctl_a3(lv_new, lv_ref, tol=A3_TOL):
    """levels C, U, F per seed of the L100 runs equal those of the banked RRc runs within one window of 325 (1/325 in rate)"""
    try:
        d = {k: [abs(float(x) - float(y)) for x, y in zip(lv_new[k], lv_ref[k])] for k in ("C", "U", "F")}
        mx = max(max(v) for v in d.values())
        return {"PASS": bool(mx <= tol), "largest_difference": mx, "tolerance": tol, "per_level": d}
    except Exception as ex:                                                                   # noqa: BLE001
        return {"PASS": False, "why": "%s: %s" % (type(ex).__name__, str(ex)[:200])}


def log_input(z):
    """a rule log or a later-look log -> (c_src on the looks with a lead read present, est_ok on them, looks logged, looks with est_ok) or None"""
    try:
        pr = np.asarray(z["present"], bool)
        cs = np.asarray(z["c_src"], np.float64)
        eo = np.asarray(z["est_ok"], bool)
        return cs[pr], eo[pr], int(len(pr)), int(eo.sum())
    except Exception:                                                                         # noqa: BLE001
        return None


def join_inputs(a, b):
    if a is None or b is None:
        return None
    return np.concatenate([a[0], b[0]]), np.concatenate([a[1], b[1]]), a[2] + b[2], a[3] + b[3]


def ctl_a4_u3(stats, st):
    """stats: {(form, seed): (c_src present, est_ok present, n looks, n ok) or None}. Over the looks with a lead read present (both logs, both seeds): sd of the STK input within 0.80 to 1.25 times that of the TK input,
    |mean| of the STK input <= 0.15 m/s, share of those looks marked full >= 0.90. PASS = the three hold (judged at AGE)."""
    have = all(stats.get((f, s)) is not None for f in ("RRe_STK", "RRe_TK") for s in SEEDS)
    if not have:
        return {"PASS": False, "complete": False, "setting": st}
    cs = np.concatenate([stats[("RRe_STK", s)][0] for s in SEEDS])
    ct = np.concatenate([stats[("RRe_TK", s)][0] for s in SEEDS])
    okp = np.concatenate([stats[("RRe_STK", s)][1] for s in SEEDS])
    sd_s, sd_t = (float(np.std(cs)) if len(cs) else None), (float(np.std(ct)) if len(ct) else None)
    ratio = sd_s / sd_t if sd_s is not None and sd_t not in (None, 0.0) else None
    mean_s = float(np.mean(cs)) if len(cs) else None
    share = float(np.mean(okp)) if len(okp) else None
    c1, c2, c3 = bool(ratio is not None and SD_LO <= ratio <= SD_HI), bool(mean_s is not None and abs(mean_s) <= MEAN_MAX), bool(share is not None and share >= SHARE_MIN)
    return {"PASS": bool(c1 and c2 and c3), "complete": True, "sd_stk": sd_s, "sd_tk": sd_t, "sd_ratio": ratio, "mean_stk": mean_s, "share_full_present_looks": share, "sd_ratio_within_0.80_1.25": c1,
            "mean_within_0.15": c2, "share_at_least_0.90": c3, "setting": st, "judged": bool(st == "AGE")}


def ctl_r1s(texts, n_files, n_clips, preroll, wrapper, shas):
    """run text of every new run: form RRe, cycle 10, rule every 5, readout K, bound, pre-roll, wrapper, return code 0, one dump file per clip, and the file hash of the est line equals the table's."""
    out, ok = {}, bool(texts)
    for f in NEWS:
        for s in SEEDS:
            p = CR.parse_run_text(texts.get((f, s)))
            pe = EC.parse_est_looks(texts.get((f, s)))
            sha_ok = bool(pe is not None and pe["file_sha256"] == shas.get((f[len("RRe_"):], s)))
            good = EC.run_text_ok(p, preroll, wrapper) and n_files.get((f, s)) == n_clips and sha_ok
            out["%s:seed%d" % (f, s)] = {"ok": bool(good), "parsed": p, "dump_files": n_files.get((f, s)), "clips_of_the_grid": n_clips, "est_line_file_equals_table": sha_ok}
            ok = ok and good
    return {"PASS": bool(ok), "runs": out}


def ctl_x1s(rule, mid):
    """as card ADD79 x1 for the new forms: a closing that is not 0 on at least one present row in both logs, finite where present, exactly 0.0 on present rows without a full history, form RRe in the rule log;
    the banked RR run feeds 0 on every row of both logs"""
    out, ok = {}, bool(rule) and bool(mid)
    for f in NEWS + ("RR",):
        for s in SEEDS:
            res, good = {}, True
            for tag, lg in (("rule_log", rule), ("mid_log", mid)):
                r = lg.get((f, s))
                if not r:
                    res[tag], good = {"ok": False, "why": "no log"}, False
                    continue
                if f == "RR":
                    g1 = r["rows"] > 0 and r["present_nonzero"] == 0 and r["max_abs_closing"] == 0.0 and r["closing_finite_where_present"]
                else:
                    g1 = r["present"] > 0 and r["present_nonzero"] > 0 and r["closing_finite_where_present"] and r.get("est_ok_present") is not None and r["est_ok_present"] > 0 and r.get("fallback_closing_exactly_zero") is True
                    if tag == "rule_log":
                        g1 = g1 and r["form"] == "RRe"
                res[tag] = dict(r, ok=bool(g1))
                good = good and g1
            out["%s:seed%d" % (f, s)] = dict(res, ok=bool(good))
            ok = ok and good
    return {"PASS": bool(ok), "runs": out}


def ctl_m1s(rows):
    """later-look row counts of the new runs equal those of the banked RR run of the same seed, and are not empty"""
    out, ok = {}, bool(rows)
    for s in SEEDS:
        base = rows.get(("RR", s))
        for f in NEWS:
            n = rows.get((f, s))
            good = bool(n and base and n == base)
            out["%s:seed%d" % (f, s)] = {"ok": good, "rows": n, "rows_banked_RR": base}
            ok = ok and good
    return {"PASS": bool(ok), "runs": out}


def ctl_u2(tables, logs, arms, tol=TOL_U2):
    """tables: {(E, seed): surrogate table arrays or None}; logs: {(form, seed): {"rule": arrays or None, "mid": arrays or None}} with ci, j, k, c_est, est_ok. In all eight runs and both logs: on the rows with est_ok True
    c_est equals the table at (ci, j) to 1e-9; est_ok is True exactly where the table holds a finite value at (ci, j); c_est is NaN where est_ok is False; rows of the first look (rule log k == 0; mid-look log: its
    smallest tick) are among the compared rows."""
    out, ok, worst = {}, True, 0.0
    for e in arms:
        for s in SEEDS:
            tab = tables.get((e, s))
            for tag in ("rule", "mid"):
                z = (logs.get(("RRe_" + e, s)) or {}).get(tag)
                nm = "%s:seed%d:%s_log" % (e, s, tag)
                if tab is None or z is None:
                    out[nm], ok = {"ok": False, "why": "table or log missing"}, False
                    continue
                look = EC.est_lookup(tab)
                eo = np.asarray(z["est_ok"], bool)
                ce = np.asarray(z["c_est"], np.float64)
                ci, j, kk = np.asarray(z["ci"]), np.asarray(z["j"]), np.asarray(z["k"])
                tv_all, found_all = look(ci, j)
                pattern_bad = int(((found_all & np.isfinite(tv_all)) != eo).sum())
                tv, found = tv_all[eo], found_all[eo]
                d = np.abs(ce[eo] - tv)
                bad = (~found) | ~np.isfinite(tv) | ~np.isfinite(ce[eo]) | ~(d <= tol)
                first = 0 if tag == "rule" else (int(kk.min()) if len(kk) else 0)
                n_first = int(((kk == first) & eo).sum())
                nan_ok = bool(np.all(np.isnan(ce[~eo])))
                mx = float(np.max(d[~bad])) if (~bad).any() else None
                good = bool(eo.any() and not bad.any() and n_first > 0 and nan_ok and pattern_bad == 0)
                out[nm] = {"ok": good, "rows_compared": int(eo.sum()), "rows_first_look_compared": n_first, "rows_failing": int(bad.sum()), "est_ok_pattern_mismatch": pattern_bad, "nan_where_not_ok": nan_ok,
                           "largest_difference": mx, "tolerance": tol}
                ok = ok and good
                worst = max(worst, mx or 0.0)
    return {"PASS": bool(ok), "largest_difference_overall": worst, "runs": out}


def ctl_h1(RH, n_boot=300, n_ep=40, per=10, seed=11, sd=0.3):
    """planted name rule: a pair with a known sign reads the expected name through the engine and the name builder of this reader; seeds of opposite sign read NOT-SEPARATED"""
    rng = np.random.default_rng(seed)
    n = n_ep * per
    inv = np.repeat(np.arange(n_ep), per)
    out, ok = {}, True
    for case, eff, want in (("lower", (-1.0, -1.0), "LOWER"), ("higher", (1.0, 1.0), "HIGHER"), ("opposite_seeds", (-1.0, 1.0), "NOT-SEPARATED"), ("no_effect", (0.0, 0.0), "NOT-SEPARATED")):
        ys = [rng.normal(0.0, sd, n) for _ in SEEDS]
        xs = [y + e + rng.normal(0.0, sd, n) for y, e in zip(ys, eff)]
        got = R.u_name(HS.pair(RH, xs, ys, inv, n_ep, n_boot))
        nm = cname("TOK-VS-RR", "AGE", "C", got)
        out[case] = {"want": want, "got": got, "name": nm}
        ok = ok and got == want and nm == cname("TOK-VS-RR", "AGE", "C", want)
    return dict(out, PASS=bool(ok))


def assemble(controls, payload):
    """controls_all_pass: every control passed. The payload (names, values) is kept when no inherited control failed; the card controls withhold only what they guard (inside all_names)."""
    ok = bool(controls) and all(v.get("PASS") is True for v in controls.values())
    fs = failed_sets(controls)
    res = {"card": CARD, "tier": TIER_LINE, "controls": controls, "controls_all_pass": bool(ok and payload), "controls_failed": fs, "names": None, "why_not_written": None, "settings": None}
    if payload and not fs["glob"]:
        res.update(payload)
    return res


def read_e_json(path, jl):
    """-> (ok, reason, json or None). The read of card ADD79 is required: the file has to be there, be the result of that card and say controls_all_pass true."""
    if not path:
        return False, "no --estclose-json was given", None
    ej = jl(path)
    if ej is None:
        return False, "the file %s is not there or not readable" % path, None
    if ej.get("card") != PARENT_CARD:
        return False, "the file is not the result of card ADD79", None
    if ej.get("controls_all_pass") is not True:
        return False, "the read of card ADD79 has not all its controls passed", None
    return True, "", ej


