# mk_pod_leadsup.py : builds pod_leadsup_setup.sh (runs ON THE POD through bash -s). The script creates /workspace/v8proof/tree_leadsup from tree_target plus the
# five patched files, verifies every sha256 of PINS.txt, writes the three arms files of card PREREG_V8F_PROOF_ADD24 and dry-gates LS_s0. It trains nothing.
import base64, io, os, sys, tarfile, hashlib

SRC = "F:/TanitAD-scratch/v8proof/spatial/leadsup"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "pod_leadsup_setup.sh")

files = ["tanitad/models/v8f_mini.py", "tanitad/data/v8f_mini_data.py", "scripts/v8f_mini_train.py", "scripts/lead_dump.py", "tests/test_v8f_lead_sup.py"]
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tf:
    for f in files:
        p = os.path.join(SRC, "patched", f)
        b = open(p, "rb").read()
        assert b"\r\n" not in b, "CRLF in " + f
        ti = tarfile.TarInfo(f)
        ti.size = len(b)
        ti.mode = 0o644
        tf.addfile(ti, io.BytesIO(b))
b64 = base64.encodebytes(buf.getvalue()).decode("ascii")

pins = []
for ln in io.open(os.path.join(SRC, "PINS.txt"), encoding="utf-8").read().splitlines():
    t = ln.split()
    if not t or t[0].startswith("#"):
        continue
    if t[0] == "changed":
        pins.append((t[1], t[-1]))
    elif t[0] in ("new", "same"):
        pins.append((t[1], t[2]))
for rel, sha in pins:                                   # local check of the changed and new files against PINS
    q = os.path.join(SRC, "patched", rel[len("stack/"):])
    if os.path.exists(q):
        assert hashlib.sha256(open(q, "rb").read()).hexdigest() == sha, rel

arms = io.open(os.path.join(SRC, "ARMS_LEADSUP.txt"), encoding="utf-8").read().splitlines()
pin_lines = [l for l in arms if l.startswith("PIN|")]
arm = {l.split("|")[1]: l for l in arms if l.startswith("ARM|")}
assert sorted(arm) == ["LSD_s0", "LSD_s1", "LS_s0", "LS_s1"], sorted(arm)


def lsh(line):
    assert "--w-lead-sup 1.0|" in line and "levers.w_lead_sup=1 " in line
    out = line.replace("--w-lead-sup 1.0|", "--w-lead-sup 10.0|").replace("levers.w_lead_sup=1 ", "levers.w_lead_sup=10 ")
    return out.replace("ARM|LS_s", "ARM|LSH_s")


head = "# LEADSUP (PREREG_V8F_PROOF_ADD24): arm G of card ADD12 plus a supervised lead head on the level-1 grid states. Baseline = G_s0 .. G_s5."
sets = {"leadsup_a": [arm["LS_s0"], arm["LS_s1"]], "leadsup_b": [arm["LSD_s0"], arm["LSD_s1"]], "leadsup_c": [lsh(arm["LS_s0"]), lsh(arm["LS_s1"])]}

S = []
S.append("#!/usr/bin/env bash")
S.append("# pod_leadsup_setup.sh : generated by mk_pod_leadsup.py. Runs ON THE POD (bash -s). Trains nothing.")
S.append("set -u")
S.append("W=/workspace/v8proof; cd $W || exit 1")
S.append("[ -d $W/tree_target ] || { echo 'REFUSED: tree_target absent'; exit 1; }")
S.append("if [ ! -d $W/tree_leadsup ]; then cp -r $W/tree_target $W/tree_leadsup; echo 'tree_leadsup copied from tree_target'; else echo 'tree_leadsup exists, files are written again'; fi")
S.append("base64 -d > $W/leadsup_patch.tgz <<'B64EOF'")
S.append(b64.rstrip("\n"))
S.append("B64EOF")
S.append("tar -xzf $W/leadsup_patch.tgz -C $W/tree_leadsup/stack || { echo 'REFUSED: untar failed'; exit 1; }")
S.append("bad=0")
for rel, sha in pins:
    S.append("h=$(sha256sum $W/tree_leadsup/%s 2>/dev/null | cut -c1-64); [ \"$h\" = \"%s\" ] || { echo \"PIN MISMATCH %s $h\"; bad=1; }" % (rel, sha, rel))
S.append("[ $bad = 0 ] && echo 'pins: all %d sha256 equal PINS.txt' || { echo 'REFUSED: pin mismatch'; exit 1; }" % len(pins))
S.append("cd $W/chain2 || exit 1")
for name, lines in sets.items():
    S.append("cat > arms_%s.txt <<'ARMSEOF'" % name)
    S.append(head)
    S.extend(pin_lines)
    S.extend(lines)
    S.append("ARMSEOF")
S.append("for f in arms_leadsup_a.txt arms_leadsup_b.txt arms_leadsup_c.txt; do echo \"== $f $(sha256sum $f | cut -c1-64)\"; grep -c '^PIN|' $f; grep '^ARM|' $f | cut -d'|' -f2,4,5,6,7,8; done")
S.append("echo '== G_s0 of arms_spatial.txt for comparison'; grep '^ARM|G_s0|' arms_spatial.txt | cut -d'|' -f2,4,5,6,7,8")
S.append("echo \"memory.max $(cat /sys/fs/cgroup/memory.max) ; $(grep -E '^anon ' /sys/fs/cgroup/memory.stat)\"")
S.append("nvidia-smi --query-gpu=name,memory.used,utilization.gpu --format=csv,noheader")
S.append("echo \"trainers running: $(pgrep -f v8f_mini_train.py | wc -l)\"")
S.append("bash dry_gate.sh arms_leadsup_a.txt LS_s0 PREREG_V8F_PROOF_ADD24 > $W/chains/leadsup_dry_LS_s0.out 2>&1; echo \"dry gate rc $?\"; tail -n 8 $W/chains/leadsup_dry_LS_s0.out | cut -c1-300")
io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(S) + "\n")
print("written", OUT, os.path.getsize(OUT), "bytes;", len(pins), "pins;", {k: [l.split("|")[1] for l in v] for k, v in sets.items()})
