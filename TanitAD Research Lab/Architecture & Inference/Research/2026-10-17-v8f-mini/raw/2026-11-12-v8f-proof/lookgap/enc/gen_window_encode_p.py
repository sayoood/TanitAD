#!/usr/bin/env python3
"""Makes window_encode_p.py from the pilot's window_encode.py (card ADD99 kit) by counted, asserted edits, for card ADD108 stage B.

Why: the pilot's tool writes arm D and arm B. This card needs ONE arm, P: the tokens of the two windows (32 and 16 degrees) both centred at
the (ctr_az, ctr_el) of every frame, read from `<clip>.npz` in the folder of --box-dir (a "direction folder": the pilot's box-file format, with
has_lead True and a finite direction on every frame). The variant keeps the pilot's B code path: same load_box_dirs, same window_grid on the
same batches, same window_sample, the same Encoder.window_tokens call on the lead frames, the same float16 cast. What is added: an arm name
(--arm, default P; the arm folder is tok/<arm>), and the arm D tokens are neither sampled nor encoded when every frame has a direction.
When a frame has no direction (has False, only possible with the pilot's own box folder) the pilot's path is kept as it is: that frame gets arm D's
window and arm D's tokens, from the same D encode of all frames as in the pilot; that is what makes the identity run (pilot box folder, arm name
B_ident) equal the pilot's arm B bytes. Nothing but the arm named by --arm is written. The pilot's tool is never edited.
Each old text must occur exactly the stated number of times, and the source file's sha256 (line ends normalised to LF) is asserted.
Output is written only if absent or byte-identical (never overwritten); nothing is deleted or moved.

Usage: gen_window_encode_p.py --src <pilot window_encode.py> --out <window_encode_p.py>
"""
import argparse
import ast
import hashlib
import os
import sys

SRC_SHA256 = "ee3919f8107065379ec96c29d4c80f7533a14b716b2e48926008c2d4b2aae7e9"

OLD_ENCODE = (
    '    """wins uint8 [n,4,3,256,256] -> (tokD, tokB) float16 [n,2,65,1024] each."""\n'
    "    import torch\n"
    "    n = wins.shape[0]\n"
    "    D = torch.from_numpy(wins[:, 0:2].reshape(n * 2, 3, WIN_PX, WIN_PX))\n"
    "    tD = enc.window_tokens(D).reshape(n, 2, 65, -1)\n"
    "    tB = tD.clone()\n"
    "    idx = np.nonzero(has)[0]\n"
    "    if idx.size:\n"
    "        Bw = torch.from_numpy(wins[idx][:, 2:4].reshape(idx.size * 2, 3, WIN_PX, WIN_PX))\n"
    "        tB[torch.from_numpy(idx)] = enc.window_tokens(Bw).reshape(idx.size, 2, 65, -1)\n"
    "    return tD.to(torch.float16).numpy(), tB.to(torch.float16).numpy()\n"
)
NEW_ENCODE = (
    '    """wins uint8 [n,4,3,256,256] -> tokB float16 [n,2,65,1024] (the tokens of the windows at the frame directions).\n'
    "    Every frame has a direction: one encoder call on all 2n window images (the pilot's call on its lead frames when all frames are lead frames).\n"
    "    Otherwise the pilot's path as it is: arm D tokens of all frames, then the direction frames' tokens written over them.\"\"\"\n"
    "    import torch\n"
    "    n = wins.shape[0]\n"
    "    idx = np.nonzero(has)[0]\n"
    "    if has.all():\n"
    "        Bw = torch.from_numpy(wins[idx][:, 2:4].reshape(idx.size * 2, 3, WIN_PX, WIN_PX))\n"
    "        tB = enc.window_tokens(Bw).reshape(idx.size, 2, 65, -1)\n"
    "    else:\n"
    "        D = torch.from_numpy(wins[:, 0:2].reshape(n * 2, 3, WIN_PX, WIN_PX))\n"
    "        tD = enc.window_tokens(D).reshape(n, 2, 65, -1)\n"
    "        tB = tD.clone()\n"
    "        if idx.size:\n"
    "            Bw = torch.from_numpy(wins[idx][:, 2:4].reshape(idx.size * 2, 3, WIN_PX, WIN_PX))\n"
    "            tB[torch.from_numpy(idx)] = enc.window_tokens(Bw).reshape(idx.size, 2, 65, -1)\n"
    "    return tB.to(torch.float16).numpy()\n"
)

# (old text, new text, expected number of occurrences)
EDITS = [
    ('"""Windows and tokens for a clip list (card sections 3 and 4). Pod only (GPU for the encoder).\n',
     '"""ONE-ARM variant of window_encode.py (generated by gen_window_encode_p.py for card ADD108): arm P = both windows at the directions of a direction folder.\n'
     'Windows and tokens for a clip list (card sections 3 and 4 of ADD99). Pod only (GPU for the encoder).\n', 1),
    # arm D grids and sampling only when some frame has no direction
    ("        if gridsD is None:\n"
     "            gridsD = [window_grid(intr, h, w, frames[i], ARM_D_WINDOWS[i][1], ARM_D_WINDOWS[i][2]) for i in range(2)]\n",
     "        if gridsD is None and not has.all():\n"
     "            gridsD = [window_grid(intr, h, w, frames[i], ARM_D_WINDOWS[i][1], ARM_D_WINDOWS[i][2]) for i in range(2)]\n", 1),
    ("            g, m = gridsD[i]\n"
     "            out[js, i] = window_sample(vid, g.expand(B, -1, -1, -1), m.expand(B, -1, -1)).numpy()\n",
     "            if not has.all():\n"
     "                g, m = gridsD[i]\n"
     "                out[js, i] = window_sample(vid, g.expand(B, -1, -1, -1), m.expand(B, -1, -1)).numpy()\n", 1),
    (OLD_ENCODE, NEW_ENCODE, 1),
    # the arm name
    ('    ap.add_argument("--box-dir", required=True)\n',
     '    ap.add_argument("--box-dir", required=True, help="direction folder: <clip>.npz with has_lead, ctr_az, ctr_el (the pilot box-file format)")\n'
     '    ap.add_argument("--arm", default="P", help="arm name = folder tok/<arm> (not D and not B: the pilot\'s own arm names)")\n', 1),
    ("    a = ap.parse_args(argv)\n    import shutil\n",
     "    a = ap.parse_args(argv)\n"
     "    assert a.arm.replace('_', '').isalnum() and a.arm not in ('D', 'B'), f\"refused arm name {a.arm!r}\"\n"
     "    import shutil\n", 1),
    ('("D", "B")', "(a.arm,)", 6),
    ("                tD, tB = encode_clip_tokens(enc, wins, has)\n", "                tB = encode_clip_tokens(enc, wins, has)\n", 1),
    ('for arm, arr in (("D", tD), ("B", tB)):', "for arm, arr in ((a.arm, tB),):", 1),
]


def lf(b):
    return b.replace(b"\r\n", b"\n")


def generate(src_bytes, check_sha=True):
    src = lf(src_bytes)
    if check_sha:
        got = hashlib.sha256(src).hexdigest()
        if got != SRC_SHA256:
            raise SystemExit("REFUSED: source sha256 %s != the asserted %s" % (got, SRC_SHA256))
    text = src.decode("utf-8")
    for old, new, n in EDITS:
        c = text.count(old)
        if c != n:
            raise SystemExit("REFUSED: old text occurs %d times, expected %d: %r" % (c, n, old[:70]))
        text = text.replace(old, new)
    ast.parse(text)
    for bad in ('("D", "B")', "tD, tB", '(("D", tD)', "return tD.to"):
        if bad in text:
            raise SystemExit("REFUSED: the variant still contains %r" % bad)
    for need in ("def load_box_dirs(", "make_windows, c, L, a.box_dir, a.torch_threads", "window_grid(intr, h, w, frames[i], az, el)"):
        if need not in text:
            raise SystemExit("REFUSED: the variant lost %r" % need)
    return text


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    text = generate(open(a.src, "rb").read())
    data = text.encode("utf-8")
    if os.path.exists(a.out):
        if open(a.out, "rb").read() == data:
            print("window_encode_p.py exists with the same bytes; sha256 %s" % hashlib.sha256(data).hexdigest()[:16])
            return 0
        raise SystemExit("REFUSED: %s exists with other content" % a.out)
    tmp = a.out + ".part"
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.replace(tmp, a.out)
    print("wrote %s sha256 %s (%d edits)" % (a.out, hashlib.sha256(data).hexdigest()[:16], len(EDITS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
