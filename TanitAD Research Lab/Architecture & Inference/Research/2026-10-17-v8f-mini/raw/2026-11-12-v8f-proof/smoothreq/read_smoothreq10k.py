def decide(conds):
    """three-valued: False when one condition is False (it decides without the others), None when one is not available, else True"""
    if any(c is False for c in conds):
        return False
    if any(c is None for c in conds):
        return None
    return True


def c_lower(w):
    return None if w is None or w["C"] is None else bool(w["C"] == "LOWER")


def c_higher(w):
    return None if w is None or w["C"] is None else bool(w["C"] == "HIGHER")


def c_nh(w, k):
    return None if w is None or w[k] is None else bool(w[k] in NOT_HIGHER)


def lvl_reaches(rem, shares):
    """rem: list of REMOVES-CONTACT values (True/False/None) of the arms of one smooth level; shares: their pooled shares of the RR-to-RRc contact gap. -> True when every arm removes contact and the mean of the shares is at
    least 0.5 (a share of None counts as not reaching half); False when one arm does not remove contact or the half is not reached; None when a REMOVES value is not available and none is False."""
    d = decide(rem)
    if d is not True:
        return d
    if any(s is None for s in shares):
        return False
    return bool(sum(shares) / len(shares) >= HALF)


def verdict_names(words, shares):
    """words[pair] = {"C","U","F","fam"} or None (withheld); shares = {arm: pooled share of the RR-to-RRc contact gap or None}. -> (names, why)."""
    names, why = {}, {}

    def put(key, cond, yes, no, label):
        if cond is None:
            why[key] = "not written: a word this name needs is not available (withheld by a control or the headway instrument is not qualified): %s" % label
        else:
            names[key] = PRE + "-" + (yes if cond else no)
    rem = {}
    for x in RR_ARMS:
        w = words.get(lab(x) + "-VS-RR")
        rem[x] = decide([c_lower(w), c_nh(w, "U")])
        put("ARM_%s_REMOVES" % lab(x), rem[x], lab(x) + "-REMOVES-CONTACT", lab(x) + "-NOT-SHOWN", lab(x) + " REMOVES-CONTACT")
    found, unresolved = None, None
    for nn, arms in ((50, ("S50",)), (70, ("S70", "S7B")), (90, ("S90",))):
        r = lvl_reaches([rem[x] for x in arms], [shares.get(x) for x in arms])
        if r is None:
            unresolved = nn
            break
        if r is True:
            found = nn
            break
    if found is not None:
        names["VERDICT_SMOOTH_REQUIREMENT"] = "%s-SMOOTH-REQUIREMENT-R%02d" % (PRE, found)
    elif unresolved is not None:
        why["VERDICT_SMOOTH_REQUIREMENT"] = "not written: the REMOVES-CONTACT name of a level-%d arm is not available, and no lower level reached half" % unresolved
    else:
        names["VERDICT_SMOOTH_REQUIREMENT"] = PRE + "-NO-TESTED-SMOOTH-LEVEL-REACHES-HALF"
    put("VERDICT_TIME_COURSE", decide([c_higher(words.get("S7B-VS-W7B"))]), "TIME-COURSE-CONFIRMED", "TIME-COURSE-NOT-CONFIRMED", "TIME-COURSE")
    put("VERDICT_SMOOTH_SPREAD_ALONE", decide([c_lower(words.get("Z00-VS-RR"))]), "SMOOTH-SPREAD-ALONE-REMOVES-CONTACT", "SMOOTH-SPREAD-ALONE-NOT-SHOWN", "SMOOTH-SPREAD-ALONE")
    sh = words.get("TOK-VS-SHUFM")
    put("VERDICT_TK_GAIN", decide([c_lower(sh), c_nh(sh, "U")]), "TK-GAIN-FROM-THE-SCENE", "TK-GAIN-NOT-SHOWN-FROM-THE-SCENE", "TK-GAIN-FROM-THE-SCENE")
    if "VERDICT_TK_GAIN" in names and names["VERDICT_TK_GAIN"].endswith("-NOT-SHOWN-FROM-THE-SCENE"):
        sr = words.get("SHUFM-VS-RR")
        if sr is None or sr["C"] is None:
            why["VERDICT_TK_GAIN_BESIDE_SHUFM_VS_RR"] = "the name of SHUFM-VS-RR (C) is not available (withheld or the headway instrument is not qualified)"
        else:
            names["VERDICT_TK_GAIN_BESIDE_SHUFM_VS_RR"] = cname("SHUFM-VS-RR", "AGE", "C", sr["C"])
    put("VERDICT_TKD_BIAS", decide([c_lower(words.get("TKD-VS-TOK"))]), "TKD-BIAS-COSTS-CONTACT", "TKD-BIAS-COST-NOT-SHOWN", "TKD-BIAS-COSTS-CONTACT")
    return names, why


def failed_sets(controls):
    """sorts the controls that did not pass: glob (inherited: no name, no value), b0, b1, b2, b4 (the card controls) and b3 {setting: failed arms}"""
    f = {"glob": [], "b0": [], "b1": [], "b2": [], "b4": [], "b3": {}}
    for k, v in controls.items():
        if v.get("PASS") is True:
            continue
        if k in ("b0_tables", "b1_tables", "b2_tables"):
            f[k[:2]].append(k)
        elif k.startswith("b4_"):
            f["b4"].append(k)
        elif k.startswith("b3_"):
            bad = sorted({n.split(":")[0] for n, r in (v.get("runs") or {}).items() if r.get("ok") is not True})
            f["b3"][k[3:]] = bad or list(NEW_ARMS)
        else:
            f["glob"].append(k)
    return f


def blocked_reason(failed, st, pair, forms):
    used = {f[len("RRe_"):] for f in forms if f.startswith("RRe_")}
    if failed["b0"] and used & set(B0_ARMS):
        return "withheld: control %s did not pass (guards the planted arms S50, S90, S7B, W7B)" % ", ".join(failed["b0"])
    if failed["b1"] and "Z00" in used:
        return "withheld: control %s did not pass (guards Z00)" % ", ".join(failed["b1"])
    if (failed["b2"] or failed["b4"]) and pair in D_PAIRS:
        return "withheld: control %s did not pass (guards the pairs of the matched surrogate)" % ", ".join(failed["b2"] + failed["b4"])
    if failed["b2"] and "TKD" in used:
        return "withheld: control %s did not pass (guards TKD)" % ", ".join(failed["b2"])
    if used & set(failed["b3"].get(st) or []):
        return "withheld: control b3 did not pass for a run of this pair at %s" % st
    return None


def withheld_set(failed, pair_forms, st="AGE"):
    return {nm for nm, fm in pair_forms.items() if blocked_reason(failed, st, nm, fm)}


def all_names(words, qualified, pair_forms, failed, shares, st="AGE"):
    """-> (names, why). A pair whose guarding control failed has no name and its words are not used by a verdict."""
    names, why, w2 = {}, {}, {}
    if not qualified:
        why["HEADWAY_" + st] = "U, C and F of the setting %s are not reported: the headway instrument is not qualified on its grid" % st
    for pair, w in words.items():
        r = blocked_reason(failed, st, pair, pair_forms[pair])
        if r:
            why["%s_%s" % (pair, st)] = r
            w2[pair] = None
            continue
        w2[pair] = w
        names.update(pair_names(st, pair, w))
    vn, vw = verdict_names(w2, shares)
    names.update(vn)
    why.update(vw)
    return names, why


