def ctl_rec(rec, shas, key, want):
    """a control read from TAB_TABLES_RECORD.json: the record's control `key` says PASS and the sha256 of every table file in `want` read here equals the record's entry"""
    try:
        if not isinstance(rec, dict):
            return {"PASS": False, "why": "the table record is missing"}
        d, tabs = rec.get(key), rec.get("tables")
        if not isinstance(d, dict) or d.get("PASS") is not True:
            return {"PASS": False, "why": "the record's control %s does not say PASS" % key, "record_pass_top_level": rec.get("pass")}
        if not isinstance(tabs, dict) or not want:
            return {"PASS": False, "why": "the record holds no table hashes or no table was expected"}
        bad = sorted(n for n in want if shas.get(n) is None or tabs.get(n) != shas.get(n))
        return {"PASS": bool(not bad), "record_says_pass": True, "tables_checked": len(want), "tables_not_equal_to_the_record": bad, "record_pass_top_level": rec.get("pass")}
    except Exception as ex:                                                                   # noqa: BLE001
        return {"PASS": False, "why": "%s: %s" % (type(ex).__name__, str(ex)[:200])}


def ctl_k4(levels, runs, tbj, reason, tol=TOL_K4):
    """levels of the banked runs recomputed here equal the result file of card ADD84 (settings/AGE/levels/<run>/{U,C,F}). The file has to be the result of that card with its controls listed; it is admitted when every control
    but a4_u3_AGE passed (the one that did not is printed); a file with another failed control, or without controls, is not admitted."""
    try:
        if not tbj or tbj.get("card") != TB_CARD:
            return {"PASS": False, "why": reason or "the file is not the result of card ADD84"}
        ctls = tbj.get("controls")
        if not isinstance(ctls, dict) or not ctls:
            return {"PASS": False, "why": "the result file of card ADD84 lists no controls"}
        notpass = sorted(k for k, v in ctls.items() if not (isinstance(v, dict) and v.get("PASS") is True))
        others = [k for k in notpass if k != "a4_u3_AGE"]
        lv = ((tbj.get("settings") or {}).get("AGE") or {}).get("levels")
        if not isinstance(lv, dict):
            return {"PASS": False, "why": "the result file of card ADD84 holds no levels for AGE", "controls_not_passed": notpass}
        d, n = [], 0
        for f in BANK84F + EEST + BANKED:
            if f not in runs:
                continue
            r = runs[f]
            if r not in lv:
                return {"PASS": False, "why": "run %s is not in the levels of the result file of card ADD84" % r, "controls_not_passed": notpass}
            for c in ("U", "C", "F"):
                d += [abs(float(x) - float(y)) for x, y in zip(levels[r][c], lv[r][c])]
            n += 1
        good = bool(d and max(d) <= tol and not others and n >= len(BANK84F))
        return {"PASS": good, "largest_difference": max(d) if d else None, "runs_compared": n, "tolerance": tol, "controls_not_passed": notpass, "controls_not_passed_besides_a4_u3_AGE": others}
    except Exception as ex:                                                                   # noqa: BLE001
        return {"PASS": False, "why": "%s: %s" % (type(ex).__name__, str(ex)[:200])}


def read_tb_json(path, jl):
    if not path:
        return {"ok": False, "reason": "no --tabclose-json was given", "json": None}
    j = jl(path)
    if j is None:
        return {"ok": False, "reason": "the file %s is not there or not readable" % path, "json": None}
    return {"ok": True, "reason": "", "json": j}


def log_input(z):
    """a rule log or a later-look log -> (c_src on the looks with a lead read present, est_ok on them, looks logged, looks with est_ok) or None"""
    try:
        pr = np.asarray(z["present"], bool)
        cs = np.asarray(z["c_src"], np.float64)
        eo = np.asarray(z["est_ok"], bool)
        return cs[pr], eo[pr], int(len(pr)), int(eo.sum())
    except Exception:                                                                         # noqa: BLE001
        return None


def join_inputs(a, b):
    if a is None or b is None:
        return None
    return np.concatenate([a[0], b[0]]), np.concatenate([a[1], b[1]]), a[2] + b[2], a[3] + b[3]


def ctl_b4(stats, st):
    """stats: {(form, seed): (c_src present, est_ok present, n looks, n ok) or None}. Over the looks with a lead read present (both logs, both seeds): sd of the STKM input within 0.80 to 1.25 times that of the TK input of the
    banked runs, the mean of the STKM input within 0.15 m/s of the mean of the TK input, share of the STKM looks marked full >= 0.90."""
    have = all(stats.get((f, s)) is not None for f in ("RRe_STKM", "RRe_TK") for s in SEEDS)
    if not have:
        return {"PASS": False, "complete": False, "setting": st}
    cs = np.concatenate([stats[("RRe_STKM", s)][0] for s in SEEDS])
    ct = np.concatenate([stats[("RRe_TK", s)][0] for s in SEEDS])
    okp = np.concatenate([stats[("RRe_STKM", s)][1] for s in SEEDS])
    sd_s, sd_t = (float(np.std(cs)) if len(cs) else None), (float(np.std(ct)) if len(ct) else None)
    ratio = sd_s / sd_t if sd_s is not None and sd_t not in (None, 0.0) else None
    mean_s, mean_t = (float(np.mean(cs)) if len(cs) else None), (float(np.mean(ct)) if len(ct) else None)
    share = float(np.mean(okp)) if len(okp) else None
    c1 = bool(ratio is not None and SD_LO <= ratio <= SD_HI)
    c2 = bool(mean_s is not None and mean_t is not None and abs(mean_s - mean_t) <= MEAN_MAX)
    c3 = bool(share is not None and share >= SHARE_MIN)
    return {"PASS": bool(c1 and c2 and c3), "complete": True, "sd_stkm": sd_s, "sd_tk": sd_t, "sd_ratio": ratio, "mean_stkm": mean_s, "mean_tk": mean_t, "share_full_present_looks": share,
            "sd_ratio_within_0.80_1.25": c1, "mean_within_0.15_of_the_mean_of_TK": c2, "share_at_least_0.90": c3, "setting": st}


def ctl_r1s(texts, n_files, n_clips, preroll, wrapper, shas):
    """run text of every new run: form RRe, cycle 10, rule every 5, readout K, bound, pre-roll, wrapper, return code 0, one dump file per clip, and the file hash of the est line equals the table's."""
    out, ok = {}, bool(texts)
    for f in NEWS:
        for s in SEEDS:
            p = CR.parse_run_text(texts.get((f, s)))
            pe = EC.parse_est_looks(texts.get((f, s)))
            sha_ok = bool(pe is not None and pe["file_sha256"] == shas.get((f[len("RRe_"):], s)))
            good = EC.run_text_ok(p, preroll, wrapper) and n_files.get((f, s)) == n_clips and sha_ok
            out["%s:seed%d" % (f, s)] = {"ok": bool(good), "parsed": p, "dump_files": n_files.get((f, s)), "clips_of_the_grid": n_clips, "est_line_file_equals_table": sha_ok}
            ok = ok and good
    return {"PASS": bool(ok), "runs": out}


def ctl_x1s(rule, mid):
    """as card ADD79 x1 for the new forms: a closing that is not 0 on at least one present row in both logs, finite where present, exactly 0.0 on present rows without a full history, form RRe in the rule log;
    the banked RR run feeds 0 on every row of both logs"""
    out, ok = {}, bool(rule) and bool(mid)
    for f in NEWS + ("RR",):
        for s in SEEDS:
            res, good = {}, True
            for tag, lg in (("rule_log", rule), ("mid_log", mid)):
                r = lg.get((f, s))
                if not r:
                    res[tag], good = {"ok": False, "why": "no log"}, False
                    continue
                if f == "RR":
                    g1 = r["rows"] > 0 and r["present_nonzero"] == 0 and r["max_abs_closing"] == 0.0 and r["closing_finite_where_present"]
                else:
                    g1 = r["present"] > 0 and r["present_nonzero"] > 0 and r["closing_finite_where_present"] and r.get("est_ok_present") is not None and r["est_ok_present"] > 0 and r.get("fallback_closing_exactly_zero") is True
                    if tag == "rule_log":
                        g1 = g1 and r["form"] == "RRe"
                res[tag] = dict(r, ok=bool(g1))
                good = good and g1
            out["%s:seed%d" % (f, s)] = dict(res, ok=bool(good))
            ok = ok and good
    return {"PASS": bool(ok), "runs": out}


def ctl_m1s(rows):
    """later-look row counts of the new runs equal those of the banked RR run of the same seed, and are not empty"""
    out, ok = {}, bool(rows)
    for s in SEEDS:
        base = rows.get(("RR", s))
        for f in NEWS:
            n = rows.get((f, s))
            good = bool(n and base and n == base)
            out["%s:seed%d" % (f, s)] = {"ok": good, "rows": n, "rows_banked_RR": base}
            ok = ok and good
    return {"PASS": bool(ok), "runs": out}


def ctl_u2(tables, logs, arms, tol=TOL_U2):
    """tables: {(E, seed): surrogate table arrays or None}; logs: {(form, seed): {"rule": arrays or None, "mid": arrays or None}} with ci, j, k, c_est, est_ok. In all eight runs and both logs: on the rows with est_ok True
    c_est equals the table at (ci, j) to 1e-9; est_ok is True exactly where the table holds a finite value at (ci, j); c_est is NaN where est_ok is False; rows of the first look (rule log k == 0; mid-look log: its
    smallest tick) are among the compared rows."""
    out, ok, worst = {}, True, 0.0
    for e in arms:
        for s in SEEDS:
            tab = tables.get((e, s))
            for tag in ("rule", "mid"):
                z = (logs.get(("RRe_" + e, s)) or {}).get(tag)
                nm = "%s:seed%d:%s_log" % (e, s, tag)
                if tab is None or z is None:
                    out[nm], ok = {"ok": False, "why": "table or log missing"}, False
                    continue
                look = EC.est_lookup(tab)
                eo = np.asarray(z["est_ok"], bool)
                ce = np.asarray(z["c_est"], np.float64)
                ci, j, kk = np.asarray(z["ci"]), np.asarray(z["j"]), np.asarray(z["k"])
                tv_all, found_all = look(ci, j)
                pattern_bad = int(((found_all & np.isfinite(tv_all)) != eo).sum())
                tv, found = tv_all[eo], found_all[eo]
                d = np.abs(ce[eo] - tv)
                bad = (~found) | ~np.isfinite(tv) | ~np.isfinite(ce[eo]) | ~(d <= tol)
                first = 0 if tag == "rule" else (int(kk.min()) if len(kk) else 0)
                n_first = int(((kk == first) & eo).sum())
                nan_ok = bool(np.all(np.isnan(ce[~eo])))
                mx = float(np.max(d[~bad])) if (~bad).any() else None
                good = bool(eo.any() and not bad.any() and n_first > 0 and nan_ok and pattern_bad == 0)
                out[nm] = {"ok": good, "rows_compared": int(eo.sum()), "rows_first_look_compared": n_first, "rows_failing": int(bad.sum()), "est_ok_pattern_mismatch": pattern_bad, "nan_where_not_ok": nan_ok,
                           "largest_difference": mx, "tolerance": tol}
                ok = ok and good
                worst = max(worst, mx or 0.0)
    return {"PASS": bool(ok), "largest_difference_overall": worst, "runs": out}


def ctl_h1(RH, n_boot=300, n_ep=40, per=10, seed=11, sd=0.3):
    """planted name rule: a pair with a known sign reads the expected name through the engine and the name builder of this reader; seeds of opposite sign read NOT-SEPARATED"""
    rng = np.random.default_rng(seed)
    n = n_ep * per
    inv = np.repeat(np.arange(n_ep), per)
    out, ok = {}, True
    for case, eff, want in (("lower", (-1.0, -1.0), "LOWER"), ("higher", (1.0, 1.0), "HIGHER"), ("opposite_seeds", (-1.0, 1.0), "NOT-SEPARATED"), ("no_effect", (0.0, 0.0), "NOT-SEPARATED")):
        ys = [rng.normal(0.0, sd, n) for _ in SEEDS]
        xs = [y + e + rng.normal(0.0, sd, n) for y, e in zip(ys, eff)]
        got = R.u_name(HS.pair(RH, xs, ys, inv, n_ep, n_boot))
        nm = cname("TOK-VS-RR", "AGE", "C", got)
        out[case] = {"want": want, "got": got, "name": nm}
        ok = ok and got == want and nm == cname("TOK-VS-RR", "AGE", "C", want)
    return dict(out, PASS=bool(ok))


def assemble(controls, payload):
    """controls_all_pass: every control passed. The payload (names, values) is kept when no inherited control failed; the card controls withhold only what they guard (inside all_names)."""
    ok = bool(controls) and all(v.get("PASS") is True for v in controls.values())
    fs = failed_sets(controls)
    res = {"card": CARD, "tier": TIER_LINE, "controls": controls, "controls_all_pass": bool(ok and payload), "controls_failed": fs, "names": None, "why_not_written": None, "settings": None}
    if payload and not fs["glob"]:
        res.update(payload)
    return res


def read_e_json(path, jl):
    """-> (ok, reason, json or None). The read of card ADD79 is required: the file has to be there, be the result of that card and say controls_all_pass true."""
    if not path:
        return False, "no --estclose-json was given", None
    ej = jl(path)
    if ej is None:
        return False, "the file %s is not there or not readable" % path, None
    if ej.get("card") != PARENT_CARD:
        return False, "the file is not the result of card ADD79", None
    if ej.get("controls_all_pass") is not True:
        return False, "the read of card ADD79 has not all its controls passed", None
    return True, "", ej


