class Text:
    def __init__(self, t):
        self.t = t.replace("\r\n", "\n")

    def once(self, a, b):
        if self.t.count(a) != 1:
            raise SystemExit(TAG + "expected once, found %d: %r" % (self.t.count(a), a[:90]))
        self.t = self.t.replace(a, b)

    def span(self, a, b, new):
        s = self.t
        if s.count(a) != 1 or s.count(b) != 1 or not s.index(a) < s.index(b):
            raise SystemExit(TAG + "anchors: %r (%d) / %r (%d)" % (a[:60], s.count(a), b[:60], s.count(b)))
        self.t = s[:s.index(a)] + new + s[s.index(b):]

    def line_from(self, a, new):
        s = self.t
        if s.count(a) != 1:
            raise SystemExit(TAG + "line anchor found %d times: %r" % (s.count(a), a[:60]))
        i = s.index(a)
        self.t = s[:i] + new + s[s.index("\n", i):]


def read_source():
    path, want = SOURCE
    t = io.open(path, "rb").read().replace(b"\r\n", b"\n")
    got = hashlib.sha256(t).hexdigest()[:16]
    if got != want:
        raise SystemExit(TAG + "the source %s has the hash %s, expected %s" % (os.path.basename(path), got, want))
    return t.decode("utf-8")


def build_queue(src):
    x = Text(src)
    lines = x.t.split("\n")
    if not (lines[0] == "#!/usr/bin/env bash" and lines[12] == "set -u" and all(v.startswith("#") for v in lines[1:12])):
        raise SystemExit(TAG + "the head of the queue source is not the expected one")
    x.t = "\n".join([lines[0]] + Q_HEADER + lines[12:])
    x.once("GE=${GM_ROOT:-/workspace/v8proof/gapmargin}", "GE=${PR_ROOT:-/workspace/v8proof/presroll}")
    x.once("GF=$GE/gapfiles\n", "GF=${PR_GAPFILES:-/workspace/v8proof/gapmargin/gapfiles}\nPD=${PR_PRESDIR:-/workspace/v8proof/preshead2/dump}\n")
    x.once("KQ=${GM_KIT:-$GE/kit_queue}", "KQ=${PR_KIT:-$GE/kit_queue}")
    x.once("WRAP=$B/v8f_t1_eval_reader_rule_rzgfhqetjv.py\n",
           "WRAPV=$B/v8f_t1_eval_reader_rule_rzgfhqetjv.py\nKW=${PR_WRAPKIT:-$GE/kit_wrap}\nWRAP=$KW/v8f_t1_eval_reader_rule_rzgfhqetjvp.py\nCKP=${PR_CHECK:-$GE/check_p}/CHECK_WRAPPER_P.out\n")
    x.once("SM=$GP/small_gm", "SM=$GP/small_pr")
    x.once("STOPS=${GM_STOP_S:-10800}", "STOPS=${PR_STOP_S:-10800}")
    x.once("LOG=$GP/gapmargin_queue.log", "LOG=$GP/presroll_queue.log")
    x.line_from('log "queue start (DRY=$DRY, resume $RESUME, stop rule $STOPS s): card ADD117',
                'log "queue start (DRY=$DRY, resume $RESUME, stop rule $STOPS s): card ADD120 (PRESROLL10K): the candidate with the joined presence input, alone and with the camera gap '
                'scaled by 0.90, at the convention and at readout K with no pre-roll, model seeds ${ARMS[*]}; the identity run first"')
    x.once('    extra+=(--rule-join "$RJOIN")\n  fi\n', '    extra+=(--rule-join "$RJOIN")\n  fi\n' + ROLL_PRES)
    x.once(RUNLINE_OLD, RUNLINE_NEW)
    x.once('  got=$(sha256sum "$WRAP" | cut -c1-16); [ "$got" = "%s" ] || stop "WRAPPER-SHA $got"\n' % WRAP_V_SHA,
           '  got=$(sha256sum "$WRAPV" | cut -c1-16); [ "$got" = "%s" ] || stop "WRAPPER-SHA $got"\n' % WRAP_V_SHA)
    x.once('  grep -q "%s" "$CHK/CHECK_WRAPPER_V.hashes" 2>/dev/null || stop "CHECK-RECORD-HAS-NOT-THIS-WRAPPER"\n' % WRAP_V_SHA,
           '  grep -q "%s" "$CHK/CHECK_WRAPPER_V.hashes" 2>/dev/null || stop "CHECK-RECORD-HAS-NOT-THIS-WRAPPER"\n' % WRAP_V_SHA + GATE_P)
