def load_pres_file(p):
    """-> {p, has_out, off, n} of a presence file of pres_dump.py (plain numpy load)"""
    with np.load(p, allow_pickle=False) as z:
        return {"p": np.asarray(z["p"], np.float64), "has_out": np.asarray(z["has_out"], bool), "off": np.asarray(z["off"], np.int64), "n": np.asarray(z["n"], np.int64)}


def pres_at(F, ci, fr):
    """-> (pf [B] float64, NaN where there is no usable value, have [B] bool): the file's row off[ci] + fr when the clip index is inside the file, the frame is in 0..n[ci]-1, has_out is true and p is finite"""
    ci, fr = np.asarray(ci, np.int64), np.asarray(fr, np.int64)
    nc = len(F["off"])
    inside = (ci >= 0) & (ci < nc)
    cc = np.where(inside, ci, 0)
    inside = inside & (fr >= 0) & (fr < F["n"][cc])
    row = np.where(inside, F["off"][cc] + fr, 0)
    inside = inside & (row < len(F["p"]))
    row = np.where(inside, row, 0)
    have = inside & F["has_out"][row] & np.isfinite(F["p"][row])
    return np.where(have, F["p"][row], np.nan), have


