def compare_arrays(x, y, logs=False):
    """x, y {key: array}: the differences of two npz files (list of texts). Equal means the same keys, and for every key the same dtype, shape and values (NaN equal to NaN). With logs=True the arrays of
    string or object dtype and any key named `meta` are left out of the value comparison (text and run-record keys); the key names are still compared."""
    out = []
    if sorted(x) != sorted(y):
        out.append("keys differ: only in the new file %s, only in the reference %s" % (sorted(set(x) - set(y)), sorted(set(y) - set(x))))
    for k in sorted(set(x) & set(y)):
        a_, b_ = np.asarray(x[k]), np.asarray(y[k])
        if logs and (k in META_KEYS or a_.dtype.kind in "OUS" or b_.dtype.kind in "OUS"):
            if k not in META_KEYS and (a_.dtype.kind in "OUS") != (b_.dtype.kind in "OUS"):
                out.append("%s: text in one file, numbers in the other" % k)
            continue
        if a_.shape != b_.shape or a_.dtype != b_.dtype:
            out.append("%s: shape/dtype %s %s against %s %s" % (k, a_.shape, a_.dtype, b_.shape, b_.dtype))
            continue
        eq = np.array_equal(a_, b_, equal_nan=True) if a_.dtype.kind in "fc" else np.array_equal(a_, b_)
        if not eq:
            out.append("%s: values differ" % k)
    return out


