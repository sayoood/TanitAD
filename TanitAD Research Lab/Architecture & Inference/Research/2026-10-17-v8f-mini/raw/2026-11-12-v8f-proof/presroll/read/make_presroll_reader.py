def _eq_nan(x, y, tol):
    x, y = np.asarray(x, np.float64), np.asarray(y, np.float64)
    with np.errstate(invalid="ignore"):
        return (np.isnan(x) & np.isnan(y)) | (np.abs(x - y) <= tol)


def pres_rows_check(logs, sides, F, counts_rec):
    """control q8 (a), (b), (c) and (e) on the rows of one new run. logs and sides: lists of dicts (the log and its side file, row for row); F the presence file of the run's model seed;
    counts_rec the parsed `vis_pres_counts` of the run record (or None). The rows are the rows of all logs in order. -> dict(failures, rows, with_file, no_file, raised, lowered, raised_mask)"""
    bad = []
    if not logs or len(logs) != len(sides):
        return {"failures": ["%d rule logs and %d side files" % (len(logs or []), len(sides or []))], "raised_mask": None}
    cols = {k: [] for k in LOG_NEED + SIDE_NEED}
    for i, (z, sd) in enumerate(zip(logs, sides)):
        miss = [k for k in LOG_NEED if k not in z] + ["side " + k for k in SIDE_NEED if k not in sd]
        if miss:
            bad.append("log %d lacks %s" % (i, miss))
            continue
        n1 = len(np.asarray(z["ci"]))
        lens = {k: len(np.asarray(sd[k])) for k in SIDE_NEED}
        lens.update({k: len(np.asarray(z[k])) for k in LOG_NEED})
        if len(set(lens.values())) != 1:
            bad.append("log %d: the log and its side file have different numbers of rows %s" % (i, sorted(lens.items())))
            continue
        for k in LOG_NEED:
            cols[k].append(np.asarray(z[k]))
        for k in SIDE_NEED:
            cols[k].append(np.asarray(sd[k]))
    if bad:
        return {"failures": bad, "raised_mask": None}
    c = {k: np.concatenate(v) for k, v in cols.items()}
    ci, j = c["ci"].astype(np.int64), c["j"].astype(np.int64)
    p, pu = c["p"].astype(np.float64), c["p_used"].astype(np.float64)
    ok, sb, pres = c["ok"].astype(bool), c["src_bad"].astype(bool), c["present"].astype(bool)
    pf, have = pres_at(F, ci, j)
    with np.errstate(invalid="ignore"):
        want = np.where(have, np.fmax(p, pf), p)
        n_a = int((~_eq_nan(pu, want, TOL_P)).sum())
        n_b = int((pres != ((pu >= PRES_P_MIN) & ok & ~sb)).sum())
        n_c = int((~_eq_nan(c["p_src"], pu, TOL_P)).sum())
        raised_m = (p < PRES_P_MIN) & (pu >= PRES_P_MIN)
        lowered_m = (p >= PRES_P_MIN) & (pu < PRES_P_MIN)
    rows, with_file = int(len(ci)), int(have.sum())
    got = {"rows": rows, "with_file": with_file, "no_file": rows - with_file, "raised": int(raised_m.sum()), "lowered": int(lowered_m.sum())}
    if n_a:
        bad.append("q8 (a): %d of %d rows with p_used not equal to the larger of p and the presence file's value (p where the file has none) within %g" % (n_a, rows, TOL_P))
    if n_b:
        bad.append("q8 (b): %d of %d rows with present not equal to (p_used >= 0.5) and ok and not src_bad" % (n_b, rows))
    if n_c:
        bad.append("q8 (c): %d of %d rows with p_src not equal to p_used within %g" % (n_c, rows, TOL_P))
    if not isinstance(counts_rec, dict):
        bad.append("q8 (e): the rule log meta carries no readable vis_pres_counts")
    else:
        for k, v in got.items():
            if counts_rec.get(k) != v:
                bad.append("q8 (e): vis_pres_counts %s is %s, recomputed from the rows %s" % (k, counts_rec.get(k), v))
