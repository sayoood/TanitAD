def make(kind):
    raw = io.open(os.path.join(src_dir(), SRC_NAME[kind]), "rb").read().replace(b"\r\n", b"\n")
    got = hashlib.sha256(raw).hexdigest()[:16]
    if got != SRC_SHA[kind]:
        raise SystemExit(TAG + "%s: source sha256 prefix %s, expected %s" % (SRC_NAME[kind], got, SRC_SHA[kind]))
    return BUILD[kind](raw.decode("utf-8"))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", choices=("reader", "driver"), default="")
    ap.add_argument("--out-dir", default=HERE)
    a = ap.parse_args(argv)
    if a.print:
        sys.stdout.write(make(a.print))
        return 0
    texts = {kind: make(kind) for kind in ("reader", "driver")}
    for kind in ("reader", "driver"):
        if os.path.exists(os.path.join(a.out_dir, OUT[kind])):
            raise SystemExit(TAG + "%s exists" % OUT[kind])
    for kind in ("reader", "driver"):
        with io.open(os.path.join(a.out_dir, OUT[kind]), "x", encoding="utf-8", newline="\n") as fh:
            fh.write(texts[kind])
        print("ZZ MAKE-GAPSPREAD-READER DONE %s sha256 prefix %s" % (OUT[kind], hashlib.sha256(texts[kind].encode("utf-8")).hexdigest()[:16]))
    return 0


