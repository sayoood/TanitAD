def _is_hex(x, n):
    return isinstance(x, str) and len(x) == n and re.fullmatch(r"[0-9a-fA-F]+", x) is not None


def ctl_e0(rec, ckpt_shas, run_texts):
    """e0 models (r0): rec is the JSON that the lead writes, {"models": {"UE_s2": {...}, "UE_s3": {...}}, "note_sha256": <64 hex>}, each model with ckpt_sha256 (64 hex), gate_pass (true), recipe_same_but_seed
    (true) and record (text). For m in 2, 3: ckpt_shas[m] (the sha256 of <w>/ckpt/UE_s<m>/A/ckpt_last.pt on disk) equals the record's hash, and the first line of every new run of model seed m (run_texts
    {key: text}) names `ckpt sha256 <hex>` that agrees with the record's hash by prefix (at least 16 characters)."""
    bad = []
    rec = rec if isinstance(rec, dict) else {}
    models = rec.get("models") if isinstance(rec.get("models"), dict) else {}
    if not _is_hex(rec.get("note_sha256"), 64):
        bad.append("the record's note_sha256 is not 64 hex characters")
    for m in SEEDS:
        e = models.get("UE_s%d" % m)
        if not isinstance(e, dict):
            bad.append("UE_s%d: no entry in the record" % m)
            continue
        h = e.get("ckpt_sha256")
        if not _is_hex(h, 64):
            bad.append("UE_s%d: ckpt_sha256 is not 64 hex characters" % m)
        disk = (ckpt_shas or {}).get(m)
        if not disk:
            bad.append("UE_s%d: no checkpoint file on disk" % m)
        elif _is_hex(h, 64) and str(disk).lower() != h.lower():
            bad.append("UE_s%d: the checkpoint on disk has sha256 %s, the record holds %s" % (m, str(disk)[:16], h[:16]))
        if e.get("gate_pass") is not True:
            bad.append("UE_s%d: gate_pass is %s" % (m, e.get("gate_pass")))
        if e.get("recipe_same_but_seed") is not True:
            bad.append("UE_s%d: recipe_same_but_seed is %s" % (m, e.get("recipe_same_but_seed")))
        if not (isinstance(e.get("record"), str) and e.get("record").strip()):
            bad.append("UE_s%d: the record carries no text" % m)
    want_keys = sorted(all_run_keys())
    if sorted(run_texts or {}) != want_keys:
        bad.append("run texts read: %d keys, expected %d" % (len(run_texts or {}), len(want_keys)))
    for k, t in sorted((run_texts or {}).items()):
        m = int(k.rsplit("_s", 1)[1])
        h = ((models.get("UE_s%d" % m) or {}).get("ckpt_sha256")) if isinstance(models.get("UE_s%d" % m), dict) else None
