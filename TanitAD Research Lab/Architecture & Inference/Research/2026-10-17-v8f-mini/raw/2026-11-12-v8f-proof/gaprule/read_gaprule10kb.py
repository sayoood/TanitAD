CARD, PRE = "PREREG_V8F_PROOF_ADD95", "GAPRULE10KB"
SEEDS = (0, 1)
PLANTED = ("GR1", "GR2", "GW05", "GC10", "GC20")
ARMS = ("G0",) + PLANTED
RUN = {a: "RLcKF5P30Hb20j" + a for a in ARMS}
BANKED = {"RR": "RQ50KF5P30Hb20", "RLc": "RLcKF5P30Hb20"}
RR_C_EXPECTED = 0.0954
TIER = "T1-kin/hb0.2 (kinematic rollout on the model's own actions), pre-roll of 30 steps (6 s)"
FAM_REASON = ("the rule changes the planned speed along the path through the distance to the lead; it does not move the path, so the lateral family is expected to be unmoved by it, "
              "and the tactical and strategic families are not read by the rule")


def below(iv):
    return iv is not None and iv[1] < 0.0


def names_of(arm, d_rr_c, d_rlc_c, d_rr_f, c_rr, c_rlc):
    """the three names of one planted arm (card section 3). d_*: interval [lo, hi] of C(X)-C(RR), C(X)-C(RLc), F(X)-F(RR); c_rr, c_rlc: pooled point values of C of the references."""
    p = PRE + "-" + arm + "-"
    H_ = 0.5 * (c_rr - c_rlc)
    n1 = p + ("CUTS-CONTACT" if d_rr_c[1] < 0.0 else "CONTACT-NOT-SHOWN")
    n2 = p + ("WITHIN-HALF-THE-GAP" if d_rlc_c[1] <= H_ else ("OUTSIDE-HALF-THE-GAP" if d_rlc_c[0] > H_ else "HALF-THE-GAP-NOT-DECIDED"))
    n3 = p + ("FALLS-BEHIND-MORE" if d_rr_f[0] > 0.0 else ("FALLS-BEHIND-LESS" if d_rr_f[1] < 0.0 else "FALLING-BEHIND-NOT-SEPARATED"))
    return {arm + "_CONTACT": n1, arm + "_HALF": n2, arm + "_PRICE": n3}


def all_names(payload):
    out = {}
    for a in PLANTED:
        pr = payload["pairs"]
        out.update(names_of(a, pr[a + "-VS-RR"]["C"]["interval"], pr[a + "-VS-RLc"]["C"]["interval"], pr[a + "-VS-RR"]["F"]["interval"], payload["levels"]["RR"]["C"], payload["levels"]["RLc"]["C"]))
    return out


def assemble_controls(controls, payload):
    ok = bool(controls) and all(isinstance(v, dict) and v.get("PASS") is True for v in controls.values())
    res = {"card": CARD, "tier": TIER, "controls": controls, "controls_all_pass": ok}
    res["payload" if ok else "withheld"] = payload
    return res


def ctl_j0(cells_g0, cells_rlc):
    """G0 equals RLc per window, per model seed: cells = {seed: {key: array}}; largest absolute difference 0 (NaN where both are NaN)."""
    worst, n = 0.0, 0
    for s in SEEDS:
        a, b = cells_g0.get(s), cells_rlc.get(s)
        if a is None or b is None or sorted(a) != sorted(b):
            return {"PASS": False, "why": "cells missing or keys differ for seed %s" % s}
        for k in a:
            x, y = np.asarray(a[k], np.float64), np.asarray(b[k], np.float64)
            if x.shape != y.shape or not np.array_equal(np.isnan(x), np.isnan(y)):
                return {"PASS": False, "why": "shape or NaN pattern of %s seed %s" % (k, s)}
            m = ~np.isnan(x)
            worst = max(worst, float(np.max(np.abs(x[m] - y[m]))) if m.any() else 0.0)
            n += int(x.size)
    return {"PASS": bool(n > 0 and worst == 0.0), "largest_abs_difference": worst, "values_compared": n}


def ctl_j1(rec, planted_dir, eval_join_sha):
    """card j1 from the record, plus: the join files on disk have the hashes of the record, and the record is for this evaluation join."""
    if not isinstance(rec, dict):
        return {"PASS": False, "why": "no planted joins record"}
    c = MPJ.j1_check(rec)
    bad = list(c["failures"])
    sa = rec.get("same_as")
    if not isinstance(sa, dict) or sa.get("all_equal") is not True:
        bad.append("no comparison with the earlier build in the record, or it differs")
    for a in ARMS:
        p = os.path.join(planted_dir or "", a + ".npz")
        if not os.path.isfile(p) or MPJ.sha_file(p) != (rec.get("arms", {}).get(a) or {}).get("sha256"):
            bad.append("%s: file missing or its sha256 is not the record's" % a)
    if eval_join_sha and rec.get("eval_join_sha256") != eval_join_sha:
        bad.append("the record is for another evaluation join")
    return {"PASS": not bad, "failures": bad, "record_j1": c}


def ctl_j2(check_text, hashes_text, wrapper_sha16):
    lines = [x for x in (check_text or "").splitlines() if x.strip()]
    ok = bool(lines and lines[-1].strip() == "ZZ CHECK-WRAPPER-J PASS" and wrapper_sha16 and wrapper_sha16 in (hashes_text or ""))
    return {"PASS": ok, "last_line": lines[-1].strip() if lines else None, "wrapper_sha16_in_check_record": bool(wrapper_sha16 and wrapper_sha16 in (hashes_text or ""))}


def ctl_j3(c_rr, c_rlc):
    """the reader recomputes C of RR and RLc from the banked rollouts; RR has to round to 0.0954 (rows 145 and 146)."""
    ok = c_rr is not None and c_rlc is not None and round(float(c_rr), 4) == RR_C_EXPECTED
    return {"PASS": bool(ok), "C_RR": c_rr, "C_RLc": c_rlc, "expected_RR": RR_C_EXPECTED}


def ctl_j4(tests_text):
    t = tests_text or ""
    m = re.findall(r"(\d+) passed", t)
    ok = bool(m) and int(m[-1]) > 0 and not re.search(r"\d+ (failed|error)", t)
    return {"PASS": ok, "passed": int(m[-1]) if m else None}


def share_rows(levels, pairs):
    """share of the contact gap C(RR)-C(RLc) that each arm removes, with the interval of C(X)-C(RR) over the point gap (reported, names nothing)."""
    gap = levels["RR"]["C"] - levels["RLc"]["C"]
    out = {}
    for a in ARMS:
        d = pairs.get(a + "-VS-RR")
        if d is None or gap == 0.0:
            out[a] = None
        else:
            lo, hi = d["C"]["interval"]
            out[a] = {"share": -d["C"]["pooled"] / gap, "interval": [-hi / gap, -lo / gap], "denominator": "point value of C(RR) minus C(RLc)"}
    return out


def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def measure(a, E, log):
    """the pod part: grid read (levels, pairs with intervals, families) of the 12 planted runs and the banked RR, RLc. -> (cells for j0, levels, pairs, families, notes)"""
    H, Q3, RH = E
    g30 = R.jl(os.path.join(a.grid_dir, "grid_p30.json"))
    J = H.load_join()
    keys = R.grid_keys(g30, [str(c) for c in J["clip"]])
    runs = dict(RUN)
    runs.update(BANKED)
    for r in runs.values():
        R.ALL_RUNS.setdefault(r, ("RLc", "K", 30, "deadreckon", "30", "plan", 5, 0.2))
    R.ALL_RUNS.setdefault(EC.SETTINGS["AGE"]["runs"]["RR"], ("RR", "K", 30, "deadreckon", "30", "plan", 5, 0.2))
    pairs_def = {}
    for x in ARMS:
        pairs_def[x + "-VS-RR"] = (RUN[x], BANKED["RR"])
        pairs_def[x + "-VS-RLc"] = (RUN[x], BANKED["RLc"])
    spread = "R0Hb20"
    run_list = [spread] + sorted(set(runs.values()))
    G = R.read_grid(a, E, "30", keys, run_list, spread, pairs_def, {}, log)
    cells = {x: {} for x in ("G0", "RLc")}
    for x, r in (("G0", RUN["G0"]), ("RLc", BANKED["RLc"])):
        for s in SEEDS:
            raw = R.load_dump_dir(R.dump_dir(a.pull, r, s))
            idx, rep = R.restrict_idx(raw["clip_index"], raw["ws"], keys)
            D = R.cut(raw, idx)
            L = H.label_windows(J, D["clip_index"], D["ws"])
            cells[x][s] = {k: np.asarray(v, np.float64) for k, v in H.window_cells(D["g"], D["cl"], L).items() if k in ("C", "U", "F")}
    lv = {k: {c: float(np.mean(G["levels"][r][c])) for c in ("C", "U", "F")} for k, r in runs.items()}
    lv_seed = {k: {c: [float(v) for v in np.asarray(G["levels"][r][c]).reshape(-1)[:2]] for c in ("C", "U", "F")} for k, r in runs.items()}
    pairs = {nm: R.ucf(p["headway"]) for nm, p in G["pairs"].items()}
    fams = {nm: {f_: R.reading(R.cells_of(p["family"]), f_) for f_ in R.NAMED} for nm, p in G["pairs"].items()}
    return cells, lv, lv_seed, pairs, fams, G["controls"].get("ALL_PASS") is True


def run_controls(a):
    log = lambda s: print(s, flush=True)                                                       # noqa: E731
    E = R.engine(a)
    cells, lv, lv_seed, pairs, fams, g_ok = measure(a, E, log)
    rec = R.jl(a.planted_record)
    ejs = MPJ.sha_file(a.eval_join) if a.eval_join and os.path.isfile(a.eval_join) else None
    rd = lambda p: io.open(p, encoding="utf-8").read() if p and os.path.isfile(p) else ""      # noqa: E731
    wc = a.wrapper_check
    controls = {"g_grid_read": {"PASS": bool(g_ok)}, "j0": ctl_j0(cells["G0"], cells["RLc"]), "j1": ctl_j1(rec, a.planted_dir, ejs),
                "j2": ctl_j2(rd(wc), rd(os.path.join(os.path.dirname(wc), "CHECK_WRAPPER_J.hashes")) if wc else "", a.wrapper_sha), "j3": ctl_j3(lv["RR"]["C"], lv["RLc"]["C"]), "j4": ctl_j4(rd(a.tests_out))}
    payload = {"levels": lv, "levels_per_seed": lv_seed, "pairs": pairs, "families": fams, "share_of_contact_gap": share_rows(lv, pairs), "family_note": FAM_REASON,
               "realised_planted_error": {x: (rec or {}).get("arms", {}).get(x, {}).get("planted_error_before_limits") for x in ARMS},
               "n_changed_by_limits": {x: (rec or {}).get("arms", {}).get(x, {}).get("n_changed_by_limits") for x in ARMS}}
    res = assemble_controls(controls, payload)
    return res


def print_arm_sections(payload):
    L = []
    for x in ARMS:
        row = [x]
        for ref in ("RR", "RLc"):
            p = payload["pairs"].get(x + "-VS-" + ref)
            if p:
                row.append("vs %s: C %s U %s F %s" % (ref, p["C"]["interval"], p["U"]["interval"], p["F"]["interval"]))
        fm = payload["families"].get(x + "-VS-RR") or {}
        row.append("families %s (%s)" % (json.dumps(fm, sort_keys=True), FAM_REASON))
        L.append("   ".join(row))
    return L


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--selftest" in argv:
        return selftest()
    ap = argparse.ArgumentParser(allow_abbrev=False)
    ap.add_argument("--stage", choices=("controls", "names"), required=True)
    for n in ("pull", "code", "grid-dir", "w", "tree", "wrapper-sha", "planted-record", "planted-dir", "eval-join", "wrapper-check", "tests-out", "controls"):
        ap.add_argument("--" + n, default="")
    ap.add_argument("--out", required=True)
    ap.add_argument("--n-boot", type=int, default=2000)
    a = ap.parse_args(argv)
    if os.path.exists(a.out):
        print("REFUSED: %s exists" % a.out)
        return 2
    if a.stage == "controls":
        res = run_controls(a)
        io.open(a.out, "w", encoding="utf-8", newline="\n").write(json.dumps(res, indent=1, default=lambda o: float(o) if hasattr(o, "item") else str(o)))
        for k, v in res["controls"].items():
            print("%s %s" % (k, "PASS" if v.get("PASS") else "FAIL"))
        print("ZZ READ-GAPRULE10K controls rc 0 controls_all_pass %s" % res["controls_all_pass"])
        return 0
    cj = json.load(io.open(a.controls, encoding="utf-8"))
    if cj.get("controls_all_pass") is not True or "payload" not in cj or any(v.get("PASS") is not True for v in cj.get("controls", {}).values()):
        print("REFUSED: the controls file is not all-pass: no name is written")
        print("ZZ READ-GAPRULE10K names rc 3 controls_all_pass False")
        return 3
    names = all_names(cj["payload"])
    res = {"card": CARD, "tier": TIER, "controls_file": os.path.abspath(a.controls), "controls_sha256": sha_file(a.controls), "names": names, "values": cj["payload"]}
    io.open(a.out, "w", encoding="utf-8", newline="\n").write(json.dumps(res, indent=1))
    for k in sorted(names):
        print(names[k])
    for line in print_arm_sections(cj["payload"]):
        print(line)
    print("ZZ READ-GAPRULE10K names rc 0 controls_all_pass True")
    return 0


def selftest():
    ok = True
    d = lambda lo, hi: {"interval": [lo, hi]}                                                  # noqa: E731
    n = names_of("GR1", [-0.05, -0.01], [0.0, 0.004], [-0.02, 0.03], 0.0954, 0.0138)
    ok &= n["GR1_CONTACT"].endswith("CUTS-CONTACT") and n["GR1_HALF"].endswith("WITHIN-HALF-THE-GAP") and n["GR1_PRICE"].endswith("FALLING-BEHIND-NOT-SEPARATED")
    n = names_of("GC20", [-0.01, 0.01], [0.05, 0.06], [0.01, 0.04], 0.0954, 0.0138)
    ok &= n["GC20_CONTACT"].endswith("CONTACT-NOT-SHOWN") and n["GC20_HALF"].endswith("OUTSIDE-HALF-THE-GAP") and n["GC20_PRICE"].endswith("FALLS-BEHIND-MORE")
    n = names_of("GW05", [-0.04, -0.01], [0.01, 0.06], [-0.04, -0.01], 0.0954, 0.0138)
    ok &= n["GW05_HALF"].endswith("HALF-THE-GAP-NOT-DECIDED") and n["GW05_PRICE"].endswith("FALLS-BEHIND-LESS")
    print("ZZ SELFTEST-READ-GAPRULE10K ok: %s" % ok)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
