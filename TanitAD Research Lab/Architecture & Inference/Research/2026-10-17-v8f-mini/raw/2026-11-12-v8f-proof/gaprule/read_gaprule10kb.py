#!/usr/bin/env python
"""read_gaprule10kb.py -- read of card PREREG_V8F_PROOF_ADD95 (GAPRULE10KB; the reader of card ADD94 with the card name, the name prefix, the join module of the new card and a j1
control that requires the comparison with the earlier build; generated by make_kit_b.py): planted gap error inside the lead rule on the model's own rollout (T1-kin/hb0.2, pre-roll of 30 steps (6 s)).
Generated by make_read_gaprule.py (block sha_file copied from smoothreq/read_smoothreq10k.py with the fragment read_gaprule_frag.txt). The engine of the model reader (EC, R, HS, H) is imported, not edited.
Stage controls: runs j0, j1, j3 here and reads j2 (--wrapper-check) and j4 (--tests-out); writes CONTROLS_FILE. With every control PASS the values are written under `payload`, else under
`withheld` and no name exists. Stage names: reads CONTROLS_FILE, refuses it unless all controls pass, writes the 15 names of card section 3 and binds the result to the controls file by sha256.
Usage: python read_gaprule10k.py --stage controls --pull PULL --code CODE --grid-dir DIR --w W --tree TREE --out CONTROLS.json --wrapper-sha HEX16 --planted-record REC.json
          --planted-dir DIR --eval-join J.npz --wrapper-check FILE --tests-out FILE [--n-boot 2000]
       python read_gaprule10k.py --stage names --controls CONTROLS.json --out RESULT.json     |   --selftest
Last line: ZZ READ-GAPRULE10K <stage> rc <rc> controls_all_pass <bool>"""
