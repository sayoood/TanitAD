# mk_pod_ruletrain.py : builds pod_ruletrain_setup.sh (runs ON THE POD through bash -s). The script creates /workspace/v8proof/tree_ruletrain from tree_leadsup plus
# the changed and new files of card PREREG_V8F_PROOF_ADD32, verifies every sha256 of PINS.txt and of the PIN lines of the arms file, writes the arms file of the one
# chain `ruletrain_a` (six fine-tunes, one at a time) and dry-gates GRT_s0. It trains nothing.
import base64, io, os, tarfile, hashlib

SRC = "F:/TanitAD-scratch/v8proof/ruletrain"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "pod_ruletrain_setup.sh")
ORDER = ["GFT_s0", "GRT_s0", "GFT_s1", "GRT_s1", "GFTb_s0", "GFTb_s1"]      # the paired comparison first, the replicates last


def sha(b):
    return hashlib.sha256(b).hexdigest()


pins = []
for ln in io.open(os.path.join(SRC, "PINS.txt"), encoding="utf-8").read().splitlines():
    t = ln.split()
    if not t or t[0].startswith("#"):
        continue
    if t[0] == "changed":
        pins.append((t[0], t[1], t[-1]))
    elif t[0] in ("new", "same"):
        pins.append((t[0], t[1], t[2]))
files = []
for kind, rel, h in pins:
    q = os.path.join(SRC, "patched", rel[len("stack/"):])
    if kind in ("changed", "new"):
        b = open(q, "rb").read()
        assert sha(b) == h, "PINS mismatch on the local file " + rel
        assert b"\r\n" not in b, "CRLF in " + rel
        files.append((rel[len("stack/"):], b))
assert files, "no changed or new file"

arms = io.open(os.path.join(SRC, "ARMS_RULETRAIN.txt"), encoding="utf-8").read().splitlines()
pin_lines = [l for l in arms if l.startswith("PIN|")]
arm = {l.split("|")[1]: l for l in arms if l.startswith("ARM|")}
assert sorted(arm) == sorted(ORDER), sorted(arm)
pin_map = {rel: h for _k, rel, h in pins}
for l in pin_lines:                                      # every PIN line of the arms file must agree with PINS.txt where both name the file
    _p, tree, rel, h = l.split("|")
    assert tree == "/workspace/v8proof/tree_ruletrain", tree
    if rel in pin_map:
        assert pin_map[rel] == h, "arms PIN differs from PINS.txt: " + rel
for name in ORDER:
    a = arm[name]
    assert "--init-ckpt /workspace/v8proof/runs/spatial/G_s%s/ckpt_last.pt" % name[-1] in a and "--steps 2000 --lr 1e-4 --warmup 100" in a, name
    assert ("--rule-relabel on" in a) == name.startswith("GRT"), name

buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tf:
    for rel, b in files:
        ti = tarfile.TarInfo(rel)
        ti.size = len(b)
        ti.mode = 0o644
        tf.addfile(ti, io.BytesIO(b))
b64 = base64.encodebytes(buf.getvalue()).decode("ascii")

S = []
S.append("#!/usr/bin/env bash")
S.append("# pod_ruletrain_setup.sh : generated by mk_pod_ruletrain.py. Runs ON THE POD (bash -s). Trains nothing.")
S.append("set -u")
S.append("W=/workspace/v8proof; cd $W || exit 1")
S.append("[ -d $W/tree_leadsup ] || { echo 'REFUSED: tree_leadsup absent'; exit 1; }")
S.append("if [ ! -d $W/tree_ruletrain ]; then cp -r $W/tree_leadsup $W/tree_ruletrain; echo 'tree_ruletrain copied from tree_leadsup'; else echo 'tree_ruletrain exists, files are written again'; fi")
S.append("base64 -d > $W/ruletrain_patch.tgz <<'B64EOF'")
S.append(b64.rstrip("\n"))
S.append("B64EOF")
S.append("tar -xzf $W/ruletrain_patch.tgz -C $W/tree_ruletrain/stack || { echo 'REFUSED: untar failed'; exit 1; }")
S.append("bad=0")
allpins = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, _tree, rel, h = l.split("|")
    allpins.setdefault(rel, h)
for rel, h in sorted(allpins.items()):
    S.append("h=$(sha256sum $W/tree_ruletrain/%s 2>/dev/null | cut -c1-64); [ \"$h\" = \"%s\" ] || { echo \"PIN MISMATCH %s $h\"; bad=1; }" % (rel, h, rel))
S.append("[ $bad = 0 ] && echo 'pins: all %d sha256 equal' || { echo 'REFUSED: pin mismatch'; exit 1; }" % len(allpins))
S.append("for g in G_s0 G_s1; do [ -f $W/runs/spatial/$g/ckpt_last.pt ] && echo \"base $g ckpt sha256 $(sha256sum $W/runs/spatial/$g/ckpt_last.pt | cut -c1-64)\" || { echo \"REFUSED: no base checkpoint $g\"; exit 1; }; done")
S.append("cd $W/chain2 || exit 1")
S.append("cat > arms_ruletrain_a.txt <<'ARMSEOF'")
S.append("# RULETRAIN (PREREG_V8F_PROOF_ADD32): six fine-tunes of 2,000 steps from the banked checkpoints of arm G; GFT control, GFTb replicate of the control, GRT with --rule-relabel on.")
S.extend(pin_lines)
for n in ORDER:                                         # kind HIERFT: the fine-tune kind of gate_token3.py (2,000 steps, init checkpoint applied)
    assert arm[n].count("|HIER|") == 1, n
    S.append(arm[n].replace("|HIER|", "|HIERFT|", 1))
S.append("ARMSEOF")
# the fine-tune variants of the chain tools: derived on the pod from the pinned originals by fixed edits, each edit checked
S.append("o1=$(sha256sum gate_token2.py | cut -c1-64); o2=$(sha256sum chain_arms.sh | cut -c1-64)")
S.append("sed -e 's|^EXPECT = {\"HIER\": (\"full\", 19164, 0.0),|EXPECT = {\"HIERFT\": (\"full\", 2000, 0.0), \"HIER\": (\"full\", 19164, 0.0),|' "
         "-e 's|^    if a.kind in (\"DAG\", \"FLATDAG\"):$|    if a.kind == \"HIERFT\" and (lv.get(\"init_ckpt\") or {}).get(\"applied\") is not True:\\n        bad.append(\"init_ckpt not applied\")\\n    if a.kind in (\"DAG\", \"FLATDAG\"):|' gate_token2.py > gate_token3.py")
S.append("[ \"$(grep -c HIERFT gate_token3.py)\" = 2 ] && [ \"$(diff gate_token2.py gate_token3.py | grep -c '^[<>]')\" = 4 ] && $W/../venv/bin/python -c 'import ast,sys; ast.parse(open(\"gate_token3.py\").read())' || { echo 'REFUSED: gate_token3.py is not the expected edit of gate_token2.py'; exit 1; }")
S.append("sed -e 's|19164|2000|g' -e 's|gate_token2\\.py|gate_token3.py|g' chain_arms.sh > chain_arms_ft.sh")
S.append("[ \"$(grep -c 19164 chain_arms_ft.sh)\" = 0 ] && [ \"$(grep -c gate_token2 chain_arms_ft.sh)\" = 0 ] && [ \"$(diff chain_arms.sh chain_arms_ft.sh | grep -c '^>')\" = \"$(grep -c '19164\\|gate_token2\\.py' chain_arms.sh)\" ] && bash -n chain_arms_ft.sh || { echo 'REFUSED: chain_arms_ft.sh is not the expected edit of chain_arms.sh'; exit 1; }")
S.append("echo \"chain tools: gate_token2.py $o1 -> gate_token3.py $(sha256sum gate_token3.py | cut -c1-64); chain_arms.sh $o2 -> chain_arms_ft.sh $(sha256sum chain_arms_ft.sh | cut -c1-64)\"; diff gate_token2.py gate_token3.py | cut -c1-200")
S.append("echo \"== arms_ruletrain_a.txt $(sha256sum arms_ruletrain_a.txt | cut -c1-64)\"; grep -c '^PIN|' arms_ruletrain_a.txt; grep '^ARM|' arms_ruletrain_a.txt | cut -d'|' -f2,4,5,6,8 | cut -c1-220")
S.append("echo \"memory.max $(cat /sys/fs/cgroup/memory.max) ; $(grep -E '^anon ' /sys/fs/cgroup/memory.stat)\"")
S.append("nvidia-smi --query-gpu=name,memory.used,utilization.gpu --format=csv,noheader")
S.append("echo \"trainers running: $(pgrep -f v8f_mini_train.py | wc -l)\"")
S.append("bash dry_gate.sh arms_ruletrain_a.txt GRT_s0 PREREG_V8F_PROOF_ADD32 > $W/chains/ruletrain_dry_GRT_s0.out 2>&1; echo \"dry gate GRT_s0 rc $?\"; tail -n 8 $W/chains/ruletrain_dry_GRT_s0.out | cut -c1-300")
S.append("bash dry_gate.sh arms_ruletrain_a.txt GFT_s0 PREREG_V8F_PROOF_ADD32 > $W/chains/ruletrain_dry_GFT_s0.out 2>&1; echo \"dry gate GFT_s0 rc $?\"; tail -n 4 $W/chains/ruletrain_dry_GFT_s0.out | cut -c1-300")
# the token tool on the dry selfcheck of GRT_s0: the fine-tune kind must pass, the full-run kind must be refused (the deliberate regression of the new kind)
S.append("SC=$W/runs/motion_dry/GRT_s0/out/selfcheck.json; GA=$W/chains/ruletrain_dry_gate_argv.txt")
S.append("C2_CARD=PREREG_V8F_PROOF_ADD32 bash chain_arms.sh dryrun_GRT_s0 arms_ruletrain_a.txt --dry-run | grep '^TRAIN GRT_s0: ' | sed 's|^TRAIN GRT_s0: ||' | tr ' ' '\\n' | tail -n +3 > $GA; echo --selfcheck-only >> $GA")
S.append("$W/../venv/bin/python gate_token3.py make --selfcheck $SC --argv-file $GA --out $W/chains/ruletrain_dry_token_ft.json --kind HIERFT --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIERFT rc ${PIPESTATUS[0]} (must be 0)\"")
S.append("$W/../venv/bin/python gate_token3.py make --selfcheck $SC --argv-file $GA --out $W/chains/ruletrain_dry_token_full.json --kind HIER --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIER rc ${PIPESTATUS[0]} (must be 1)\"")
S.append("$W/../venv/bin/python - <<'PYEOF'")
S.append("import json")
S.append("for a in ('GRT_s0', 'GFT_s0'):")
S.append("    try:")
S.append("        s = json.load(open('/workspace/v8proof/runs/motion_dry/%s/out/selfcheck.json' % a)); i = s.get('info', {}); lv = s.get('levers', {})")
S.append("        print('SELFCHECK', a, 'dvb', s.get('declared_vs_built'), 'live', (s.get('live') or {}).get('pass'), 'steps_total', s.get('steps_total'), 'init_ckpt', json.dumps(lv.get('init_ckpt'))[:200], 'rule_relabel', lv.get('rule_relabel'), 'n', i.get('rule_relabel_n'), 'changed', i.get('rule_relabel_changed'), 'detail', json.dumps(i.get('rule_relabel'))[:300], 'probe', json.dumps(s.get('rule_relabel_probe'))[:300])")
S.append("    except Exception as e:")
S.append("        print('SELFCHECK', a, 'ERR', e)")
S.append("PYEOF")
io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(S) + "\n")
print("written", OUT, os.path.getsize(OUT), "bytes;", len(allpins), "pins;", [r for r, _b in files])
