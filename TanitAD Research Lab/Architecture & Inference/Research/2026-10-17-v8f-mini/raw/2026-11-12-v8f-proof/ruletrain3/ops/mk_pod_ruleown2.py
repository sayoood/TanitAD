# mk_pod_ruleown2.py : builds two scripts that run ON THE POD through bash -s (note PREREG_V8F_PROOF_ADD34_N1, the linear form of the own-plan term).
#   pod_ruleown2_tree.sh : creates /workspace/v8proof/tree_ruleown2 from tree_ruleown plus the changed and new files, verifies every sha256 of PINS.txt and of the
#                          PIN lines of the arms file, writes the arms file of chain ruleown2_a (GOL, GOL4; 2,000 steps). No GPU, trains nothing.
#   pod_ruleown2_gate.sh : dry-gates GOL_s0 and GOL4_s0 (one selfcheck each, with the real-data live step), checks the token kind, prints the probes.
#                          Its FIRST output line is GATE-RAN or GATE-NOT-RUN; refuses to run as a fourth GPU job. Trains nothing.
import base64, io, os, tarfile, hashlib

SRC = "F:/TanitAD-scratch/v8proof/ruletrain3"
HERE = os.path.dirname(os.path.abspath(__file__))
ARMS = ["GOL_s0", "GOL_s1", "GOL4_s0", "GOL4_s1"]


def sha(b):
    return hashlib.sha256(b).hexdigest()


pins = []
for ln in io.open(os.path.join(SRC, "PINS.txt"), encoding="utf-8").read().splitlines():
    t = ln.split()
    if not t or t[0].startswith("#"):
        continue
    if t[0] == "changed":
        pins.append((t[0], t[1], t[-1]))
    elif t[0] in ("new", "same"):
        pins.append((t[0], t[1], t[2]))
files = []
for kind, rel, h in pins:
    q = os.path.join(SRC, "patched", rel[len("stack/"):])
    if kind in ("changed", "new"):
        b = open(q, "rb").read()
        assert sha(b) == h, "PINS mismatch on the local file " + rel
        assert b"\r\n" not in b, "CRLF in " + rel
        files.append((rel[len("stack/"):], b))
assert files, "no changed or new file"

arms = io.open(os.path.join(SRC, "ARMS_RULEOWNL1.txt"), encoding="utf-8").read().splitlines()
pin_lines = [l for l in arms if l.startswith("PIN|")]
arm = {l.split("|")[1]: l for l in arms if l.startswith("ARM|")}
assert sorted(arm) == sorted(ARMS), sorted(arm)
pin_map = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, tree, rel, h = l.split("|")
    assert tree == "/workspace/v8proof/tree_ruleown2", tree
    if rel in pin_map:
        assert pin_map[rel] == h, "arms PIN differs from PINS.txt: " + rel
for name in ARMS:
    a = arm[name]
    assert a.count("|HIER|") == 1, name
    assert "--init-ckpt /workspace/v8proof/runs/spatial/G_s%s/ckpt_last.pt" % name[-1] in a, name
    assert "--steps 2000 --lr 1e-4 --warmup 100" in a and "--rule-own-form l1" in a and "--rule-relabel" not in a, name
    assert ("--w-rule-own 4.0" in a) == name.startswith("GOL4") and ("--w-rule-own 1.0" in a) == (not name.startswith("GOL4")), name
    assert "levers.rule_own_form=l1" in a, name

buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tf:
    for rel, b in files:
        ti = tarfile.TarInfo(rel)
        ti.size = len(b)
        ti.mode = 0o644
        tf.addfile(ti, io.BytesIO(b))
b64 = base64.encodebytes(buf.getvalue()).decode("ascii")

allpins = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, _tree, rel, h = l.split("|")
    allpins.setdefault(rel, h)

T = []
T.append("# pod_ruleown2_tree.sh : generated by mk_pod_ruleown2.py. Runs ON THE POD (bash -s). No GPU, trains nothing.")
T.append("set -u")
T.append("W=/workspace/v8proof; cd $W || exit 1")
T.append("[ -d $W/tree_ruleown ] || { echo 'REFUSED: tree_ruleown absent'; exit 1; }")
T.append("[ -e $W/chain2/arms_ruleown2_a.txt ] && { echo 'REFUSED: the arms file of this note exists'; exit 1; }")
T.append("if [ ! -d $W/tree_ruleown2 ]; then cp -r $W/tree_ruleown $W/tree_ruleown2; echo 'tree_ruleown2 copied from tree_ruleown'; else echo 'tree_ruleown2 exists, files are written again'; fi")
T.append("base64 -d > $W/ruleown2_patch.tgz <<'B64EOF'")
T.append(b64.rstrip("\n"))
T.append("B64EOF")
T.append("tar -xzf $W/ruleown2_patch.tgz -C $W/tree_ruleown2/stack || { echo 'REFUSED: untar failed'; exit 1; }")
T.append("bad=0")
for rel, h in sorted(allpins.items()):
    T.append("h=$(sha256sum $W/tree_ruleown2/%s 2>/dev/null | cut -c1-64); [ \"$h\" = \"%s\" ] || { echo \"PIN MISMATCH %s $h\"; bad=1; }" % (rel, h, rel))
T.append("[ $bad = 0 ] && echo 'pins: all %d sha256 equal' || { echo 'REFUSED: pin mismatch'; exit 1; }" % len(allpins))
T.append("cd $W/chain2 || exit 1")
T.append("for f in gate_token3.py chain_arms_ft.sh dry_gate.sh; do [ -f $f ] || { echo \"REFUSED: $f absent\"; exit 1; }; done")
T.append("cat > arms_ruleown2_a.txt <<'ARMSEOF'")
T.append("# RULEOWN note PREREG_V8F_PROOF_ADD34_N1: four fine-tunes of 2,000 steps from the banked checkpoints of arm G with the own-plan rule term in the linear form; GOL weight 1.0, GOL4 weight 4.0.")
T.extend(pin_lines)
for n in ARMS:
    T.append(arm[n].replace("|HIER|", "|HIERFT|", 1))
T.append("ARMSEOF")
T.append("echo \"== arms_ruleown2_a.txt sha256 $(sha256sum arms_ruleown2_a.txt | cut -c1-64) PIN $(grep -c '^PIN|' arms_ruleown2_a.txt) ARM $(grep -c '^ARM|' arms_ruleown2_a.txt)\"; grep '^ARM|' arms_ruleown2_a.txt | cut -d'|' -f2,4,5,8 | cut -c1-260")
T.append("C2_CARD=PREREG_V8F_PROOF_ADD34 bash chain_arms_ft.sh dryx arms_ruleown_a.txt --dry-run | grep '^TRAIN GOW_s0' | sed -e 's|tree_ruleown|tree_ruleown2|' -e 's|/runs/[a-z_0-9]*/GOW_s0|/runs/X/A|' -e 's|^TRAIN GOW_s0|TRAIN A|' > /tmp/own2_gow.txt")
T.append("C2_CARD=PREREG_V8F_PROOF_ADD34 bash chain_arms_ft.sh dryx arms_ruleown2_a.txt --dry-run | grep '^TRAIN GOL_s0' | sed -e 's| --rule-own-form l1||' -e 's|/runs/[a-z_0-9]*/GOL_s0|/runs/X/A|' -e 's|^TRAIN GOL_s0|TRAIN A|' > /tmp/own2_gol.txt")
T.append("cmp -s /tmp/own2_gow.txt /tmp/own2_gol.txt && echo 'argv of GOL_s0 equals that of GOW_s0 apart from tree, name, out folder and the form flag' || { echo 'ARGV DIFFERS'; diff /tmp/own2_gow.txt /tmp/own2_gol.txt | cut -c1-300 | head -n 6; }")
T.append("echo \"memory.max $(cat /sys/fs/cgroup/memory.max) ; $(grep -E '^anon ' /sys/fs/cgroup/memory.stat)\"; nvidia-smi --query-compute-apps=pid,used_memory --format=csv,noheader | tr '\\n' ';'; echo")

G = []
G.append("# pod_ruleown2_gate.sh : generated by mk_pod_ruleown2.py. Runs ON THE POD (bash -s). Dry gates only (one selfcheck per arm), trains nothing.")
G.append("set -u")
G.append("W=/workspace/v8proof; cd $W/chain2 || exit 1")
G.append("n=$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .); [ \"${n:-0}\" -lt 3 ] || { echo \"GATE-NOT-RUN: $n GPU jobs running, a dry gate would be the fourth\"; exit 1; }")
G.append("a=$(grep -E '^anon ' /sys/fs/cgroup/memory.stat | cut -d' ' -f2); m=$(cat /sys/fs/cgroup/memory.max); [ $((m - a)) -gt 20000000000 ] || { echo 'GATE-NOT-RUN: less than 20 GB of the memory limit free'; exit 1; }")
G.append("echo \"GATE-RAN $(date -u +%Y-%m-%dT%H:%M:%SZ) with $n GPU jobs before\"")
for arm_name in ("GOL_s0", "GOL4_s0"):
    G.append("bash dry_gate.sh arms_ruleown2_a.txt %s PREREG_V8F_PROOF_ADD34 > $W/chains/ruleown2_dry_%s.out 2>&1; echo \"dry gate %s rc $?\"; tail -n 3 $W/chains/ruleown2_dry_%s.out | cut -c1-300" % (arm_name, arm_name, arm_name, arm_name))
G.append("SC=$W/runs/motion_dry/GOL_s0/out/selfcheck.json; GA=$W/chains/ruleown2_dry_gate_argv.txt")
G.append("C2_CARD=PREREG_V8F_PROOF_ADD34 bash chain_arms.sh dryrun_GOL_s0 arms_ruleown2_a.txt --dry-run | grep '^TRAIN GOL_s0: ' | sed 's|^TRAIN GOL_s0: ||' | tr ' ' '\\n' | tail -n +3 > $GA; echo --selfcheck-only >> $GA")
G.append("$W/../venv/bin/python gate_token3.py make --selfcheck $SC --argv-file $GA --out $W/chains/ruleown2_dry_token_ft.json --kind HIERFT --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIERFT rc ${PIPESTATUS[0]} (must be 0)\"")
G.append("$W/../venv/bin/python gate_token3.py make --selfcheck $SC --argv-file $GA --out $W/chains/ruleown2_dry_token_full.json --kind HIER --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIER rc ${PIPESTATUS[0]} (must be 1)\"")
G.append("$W/../venv/bin/python - <<'PYEOF'")
G.append("import json")
G.append("for a in ('GOL_s0', 'GOL4_s0'):")
G.append("    try:")
G.append("        s = json.load(open('/workspace/v8proof/runs/motion_dry/%s/out/selfcheck.json' % a)); lv = s.get('levers', {})")
G.append("        print('SELFCHECK', a, 'dvb', s.get('declared_vs_built'), 'live', (s.get('live') or {}).get('pass'), 'steps_total', s.get('steps_total'), 'init_applied', (lv.get('init_ckpt') or {}).get('applied'), 'w_rule_own', lv.get('w_rule_own'), 'rule_own_form', lv.get('rule_own_form'))")
G.append("        print('   own probe', json.dumps(s.get('rule_own_probe'))[:700])")
G.append("    except Exception as e:")
G.append("        print('SELFCHECK', a, 'ERR', e)")
G.append("PYEOF")
for name, lines in (("pod_ruleown2_tree.sh", T), ("pod_ruleown2_gate.sh", G)):
    p = os.path.join(HERE, name)
    io.open(p, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("written", p, os.path.getsize(p), "bytes")
print(len(allpins), "pins;", [r for r, _b in files])
