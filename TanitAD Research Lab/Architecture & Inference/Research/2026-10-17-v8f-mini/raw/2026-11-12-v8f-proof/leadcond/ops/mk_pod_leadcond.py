# mk_pod_leadcond.py : builds the scripts that run ON THE POD through bash -s for card PREREG_V8F_PROOF_ADD35 (lever --lead-cond).
#   pod_leadcond_tree.sh   : creates /workspace/v8proof/tree_leadcond from tree_ruleown2 plus the changed and new files, verifies every sha256 of PINS.txt and of the
#                            PIN lines, writes the arms file of chain leadcond_a (LFT, LC, LFTb; 6,000 steps; kind HIERFT6). No GPU, trains nothing.
#   pod_leadcond_gate.sh   : dry-gates LFT_s0 and LC_s0 (one selfcheck each with the real-data live step), checks the token kind, prints the probes and the
#                            step-0 identity of control q3. First output line GATE-RAN or GATE-NOT-RUN. Trains nothing.
#   pod_leadcond_launch.sh : starts chain leadcond_a and the rule-rollout queue LCA (LFTRL) behind it. First output line LAUNCH-RAN or LAUNCH-NOT-RUN.
import base64, io, os, tarfile, hashlib

SRC = "F:/TanitAD-scratch/v8proof/leadcond"
HERE = os.path.dirname(os.path.abspath(__file__))
CARD = "PREREG_V8F_PROOF_ADD35"
TREE = "/workspace/v8proof/tree_leadcond"
ORDER_A = ["LFT_s0", "LC_s0", "LFT_s1", "LC_s1", "LFTb_s0", "LFTb_s1"]
ALL = ORDER_A + ["LO_s0", "LO_s1", "LCO_s0", "LCO_s1"]


def sha(b):
    return hashlib.sha256(b).hexdigest()


pins = []
for ln in io.open(os.path.join(SRC, "PINS.txt"), encoding="utf-8").read().splitlines():
    t = ln.split()
    if not t or t[0].startswith("#"):
        continue
    if t[0] == "changed":
        pins.append((t[0], t[1], t[-1]))
    elif t[0] in ("new", "same"):
        pins.append((t[0], t[1], t[2]))
files = []
for kind, rel, h in pins:
    if kind in ("changed", "new"):
        b = open(os.path.join(SRC, "patched", rel[len("stack/"):]), "rb").read()
        assert sha(b) == h, "PINS mismatch on the local file " + rel
        assert b"\r\n" not in b, "CRLF in " + rel
        files.append((rel[len("stack/"):], b))
assert len(files) == 3, [r for r, _b in files]

arms = io.open(os.path.join(SRC, "ARMS_LEADCOND.txt"), encoding="utf-8").read().splitlines()
pin_lines = [l for l in arms if l.startswith("PIN|")]
arm = {l.split("|")[1]: l for l in arms if l.startswith("ARM|")}
assert sorted(arm) == sorted(ALL), sorted(arm)
pin_map = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, tree, rel, h = l.split("|")
    assert tree == TREE, tree
    if rel in pin_map:
        assert pin_map[rel] == h, "arms PIN differs from PINS.txt: " + rel
for name in ORDER_A:
    a = arm[name]
    assert a.count("|HIER|") == 1 and a.split("|")[2] == TREE, name
    assert "--lead-sup on --w-lead-sup 1.0 --init-ckpt /workspace/v8proof/runs/leadsup_a/LS_s%s/ckpt_last.pt --steps 6000 --lr 1e-4 --warmup 100" % name[-1] in a, name
    assert "--w-rule-own" not in a and "--rule-relabel" not in a, name
    assert ("--lead-cond on" in a) == name.startswith("LC_") and ("levers.lead_cond=on" in a) == name.startswith("LC_"), name
for s in "01":
    f = lambda n: arm[n + "_s" + s].split("|")
    assert f("LFT")[4:] == f("LFTb")[4:], "LFTb differs from LFT beyond its name"

buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tf:
    for rel, b in files:
        ti = tarfile.TarInfo(rel)
        ti.size = len(b)
        ti.mode = 0o644
        tf.addfile(ti, io.BytesIO(b))
b64 = base64.encodebytes(buf.getvalue()).decode("ascii")

allpins = {rel: h for _k, rel, h in pins}
for l in pin_lines:
    _p, _tree, rel, h = l.split("|")
    allpins.setdefault(rel, h)

T = []
T.append("# pod_leadcond_tree.sh : generated by mk_pod_leadcond.py. Runs ON THE POD (bash -s). No GPU, trains nothing.")
T.append("set -u")
T.append("W=/workspace/v8proof; cd $W || exit 1")
T.append("[ -d $W/tree_ruleown2 ] || { echo 'REFUSED: tree_ruleown2 absent'; exit 1; }")
T.append("[ -e $W/chains/leadcond_a ] && { echo 'REFUSED: chain leadcond_a exists'; exit 1; }")
T.append("[ -e $W/chain2/arms_leadcond_a.txt ] && { mv -n $W/chain2/arms_leadcond_a.txt $W/chain2/arms_leadcond_a.before_fix1.txt; echo 'the earlier arms file is moved aside (no chain used it; only the two dry gates of 12:58Z read it)'; }")
T.append("if [ ! -d $W/tree_leadcond ]; then cp -r $W/tree_ruleown2 $W/tree_leadcond; echo 'tree_leadcond copied from tree_ruleown2'; else echo 'tree_leadcond exists, files are written again'; fi")
T.append("base64 -d > $W/leadcond_patch.tgz <<'B64EOF'")
T.append(b64.rstrip("\n"))
T.append("B64EOF")
T.append("tar -xzf $W/leadcond_patch.tgz -C $W/tree_leadcond/stack || { echo 'REFUSED: untar failed'; exit 1; }")
T.append("bad=0")
for rel, h in sorted(allpins.items()):
    T.append("h=$(sha256sum $W/tree_leadcond/%s 2>/dev/null | cut -c1-64); [ \"$h\" = \"%s\" ] || { echo \"PIN MISMATCH %s $h\"; bad=1; }" % (rel, h, rel))
T.append("[ $bad = 0 ] && echo 'pins: all %d sha256 equal' || { echo 'REFUSED: pin mismatch'; exit 1; }" % len(allpins))
T.append("cd $W/chain2 || exit 1")
T.append("for f in gate_token4.py chain_arms_ft6.sh dry_gate.sh; do [ -f $f ] || { echo \"REFUSED: $f absent\"; exit 1; }; done")
T.append("for s in 0 1; do [ -f $W/runs/leadsup_a/LS_s$s/ckpt_last.pt ] || { echo \"REFUSED: base checkpoint LS_s$s absent\"; exit 1; }; done")
T.append("cat > arms_leadcond_a.txt <<'ARMSEOF'")
T.append("# LEADCOND card PREREG_V8F_PROOF_ADD35, chain A: six fine-tunes of 6,000 steps from the banked checkpoints of arm LS: LFT (control), LC (--lead-cond on), LFTb (the control again).")
T.extend(pin_lines)
for n in ORDER_A:
    T.append(arm[n].replace("|HIER|", "|HIERFT6|", 1))
T.append("ARMSEOF")
T.append("echo \"== arms_leadcond_a.txt sha256 $(sha256sum arms_leadcond_a.txt | cut -c1-64) PIN $(grep -c '^PIN|' arms_leadcond_a.txt) ARM $(grep -c '^ARM|' arms_leadcond_a.txt)\"; grep '^ARM|' arms_leadcond_a.txt | cut -d'|' -f2,4,5,8 | cut -c1-230")
T.append("dr() { C2_CARD=%s bash chain_arms_ft6.sh dryx arms_leadcond_a.txt --dry-run | grep \"^TRAIN $1\" | sed -e \"s|/runs/[a-z_0-9]*/$1|/runs/X/A|g\" -e \"s|^TRAIN $1|TRAIN A|\"; }" % CARD)
T.append("dr LFT_s0 > /tmp/lc_lft.txt; dr LFTb_s0 > /tmp/lc_lftb.txt; dr LC_s0 | sed -e 's| --lead-cond on||' > /tmp/lc_lc.txt")
T.append("[ -s /tmp/lc_lft.txt ] && cmp -s /tmp/lc_lft.txt /tmp/lc_lftb.txt && echo 'argv of LFTb_s0 equals that of LFT_s0 apart from name and out folder' || echo 'ARGV DIFFERS (LFTb)'")
T.append("[ -s /tmp/lc_lft.txt ] && cmp -s /tmp/lc_lft.txt /tmp/lc_lc.txt && echo 'argv of LC_s0 equals that of LFT_s0 apart from name, out folder and the flag --lead-cond on' || { echo 'ARGV DIFFERS (LC)'; diff /tmp/lc_lft.txt /tmp/lc_lc.txt | cut -c1-300 | head -n 6; }")
T.append("grep -o -- '--steps [0-9]* --lr [0-9e.-]* --warmup [0-9]*\\|--seed [0-9]*\\|--lead-sup [a-z]*\\|--init-ckpt [^ ]*' /tmp/lc_lft.txt | tr '\\n' ' '; echo")
T.append("echo \"memory.max $(cat /sys/fs/cgroup/memory.max) ; $(grep -E '^anon ' /sys/fs/cgroup/memory.stat)\"; nvidia-smi --query-compute-apps=pid,used_memory --format=csv,noheader | tr '\\n' ';'; echo")

G = []
G.append("# pod_leadcond_gate.sh : generated by mk_pod_leadcond.py. Runs ON THE POD (bash -s). Dry gates only (one selfcheck per arm), trains nothing.")
G.append("set -u")
G.append("W=/workspace/v8proof; cd $W/chain2 || exit 1")
G.append("n=$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .); [ \"${n:-0}\" -lt 3 ] || { echo \"GATE-NOT-RUN: $n GPU jobs running, a dry gate would be the fourth\"; exit 1; }")
G.append("a=$(grep -E '^anon ' /sys/fs/cgroup/memory.stat | cut -d' ' -f2); m=$(cat /sys/fs/cgroup/memory.max); [ $((m - a)) -gt 20000000000 ] || { echo 'GATE-NOT-RUN: less than 20 GB of the memory limit free'; exit 1; }")
G.append("echo \"GATE-RAN $(date -u +%Y-%m-%dT%H:%M:%SZ) with $n GPU jobs before\"")
for arm_name in ("LFT_s0", "LC_s0"):
    G.append("bash dry_gate.sh arms_leadcond_a.txt %s %s > $W/chains/leadcond_dry_%s.out 2>&1; echo \"dry gate %s rc $?\"; tail -n 2 $W/chains/leadcond_dry_%s.out | cut -c1-300" % (arm_name, CARD, arm_name, arm_name, arm_name))
G.append("SC=$W/runs/motion_dry/LC_s0/out/selfcheck.json; GA=$W/chains/leadcond_dry_gate_argv.txt")
G.append("C2_CARD=%s bash chain_arms_ft6.sh dryrun_LC_s0 arms_leadcond_a.txt --dry-run | grep '^TRAIN LC_s0: ' | sed 's|^TRAIN LC_s0: ||' | tr ' ' '\\n' | tail -n +3 > $GA; echo --selfcheck-only >> $GA" % CARD)
G.append("$W/../venv/bin/python gate_token4.py make --selfcheck $SC --argv-file $GA --out $W/chains/leadcond_dry_token_ft6.json --kind HIERFT6 --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIERFT6 rc ${PIPESTATUS[0]} (must be 0)\"")
G.append("$W/../venv/bin/python gate_token4.py make --selfcheck $SC --argv-file $GA --out $W/chains/leadcond_dry_token_ft.json --kind HIERFT --commit dry --commit-verified false | tail -n 1 | cut -c1-200; echo \"token kind HIERFT rc ${PIPESTATUS[0]} (must be 1)\"")
G.append("$W/../venv/bin/python - <<'PYEOF'")
G.append("import json")
G.append("S = {}")
G.append("for a in ('LFT_s0', 'LC_s0'):")
G.append("    try:")
G.append("        s = json.load(open('/workspace/v8proof/runs/motion_dry/%s/out/selfcheck.json' % a)); lv = s.get('levers', {}); S[a] = s")
G.append("        print('SELFCHECK', a, 'dvb', s.get('declared_vs_built'), 'live', (s.get('live') or {}).get('pass'), 'steps_total', s.get('steps_total'), 'init', json.dumps(lv.get('init_ckpt'))[:260], 'lead_sup', lv.get('lead_sup'), 'lead_cond', lv.get('lead_cond'))")
G.append("        print('   lead_cond probe', json.dumps(s.get('lead_cond_probe'))[:900])")
G.append("    except Exception as e:")
G.append("        print('SELFCHECK', a, 'ERR', e)")
G.append("def flat(d, pre=''):")
G.append("    out = {}")
G.append("    if isinstance(d, dict):")
G.append("        for k, v in d.items():")
G.append("            if isinstance(v, dict): out.update(flat(v, pre + k + '.'))")
G.append("            elif isinstance(v, (int, float)) and not isinstance(v, bool): out[pre + k] = float(v)")
G.append("    return out")
G.append("if len(S) == 2:")
G.append("    A, B = flat(S['LFT_s0'].get('live') or {}), flat(S['LC_s0'].get('live') or {})")
G.append("    common = sorted(set(A) & set(B)); only = sorted(set(A) ^ set(B))")
G.append("    worst = max([(abs(A[k] - B[k]) / max(abs(A[k]), 1e-12), k) for k in common] or [(float('nan'), '')])")
G.append("    print('Q3 live fields common %d, largest relative difference %.3e at %s; keys in one only: %s' % (len(common), worst[0], worst[1], only[:12]))")
G.append("    print('   LFT live', json.dumps(S['LFT_s0'].get('live'))[:500])")
G.append("PYEOF")

L = []
L.append("# pod_leadcond_launch.sh : generated by mk_pod_leadcond.py. Runs ON THE POD (bash -s). Starts chain leadcond_a (six fine-tunes of 6,000 steps, card %s)" % CARD)
L.append("# and the rule-rollout queue LCA (LFTRL) behind it. Each arm passes its own gate token in the chain.")
L.append("set -u")
L.append("W=/workspace/v8proof; cd $W/chain2 || exit 1")
L.append("[ -e $W/chains/leadcond_a ] && { echo 'LAUNCH-NOT-RUN: chains/leadcond_a exists'; exit 1; }")
L.append("[ -e $W/distrule/rtrule_LCA_queue.log ] && { echo 'LAUNCH-NOT-RUN: queue LCA exists'; exit 1; }")
L.append("[ -f $W/chains/ruledose_a/ruledose_a_DONE.txt ] || { echo 'LAUNCH-NOT-RUN: predecessor marker absent'; exit 1; }")
L.append("n=$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .); [ \"${n:-0}\" -lt 3 ] || { echo \"LAUNCH-NOT-RUN: $n GPU jobs running\"; exit 1; }")
L.append("a=$(grep -E '^anon ' /sys/fs/cgroup/memory.stat | cut -d' ' -f2); m=$(cat /sys/fs/cgroup/memory.max); [ $((m - a)) -gt 20000000000 ] || { echo 'LAUNCH-NOT-RUN: less than 20 GB of the memory limit free'; exit 1; }")
L.append("echo \"LAUNCH-RAN $(date -u +%Y-%m-%dT%H:%M:%SZ) with $n GPU jobs before, anon $a\"")
L.append("C2_CARD=%s C2_WAIT_FOR=$W/chains/ruledose_a/ruledose_a_DONE.txt C2_IDLE_MIB=30000 nohup setsid bash chain_arms_ft6.sh leadcond_a arms_leadcond_a.txt > $W/chains/leadcond_a_launch.out 2>&1 < /dev/null &" % CARD)
L.append("sleep 2; cd $W/distrule || exit 1")
L.append("nohup setsid bash pod_rtrule_generic.sh LCA leadcond_a LFTRL_s0:LFT_s0 LFTRL_s1:LFT_s1 > $W/distrule/rtrule_LCA_launch.out 2>&1 < /dev/null &")
L.append("sleep 50")
L.append("echo \"chain processes: $(pgrep -f '[c]hain_arms_ft6.sh leadcond_a' | wc -l) ; queue processes: $(pgrep -f '[p]od_rtrule_generic.sh LCA' | wc -l) ; trainers: $(pgrep -f '[v]8f_mini_train.py' | wc -l)\"")
L.append("tail -n 4 $W/chains/leadcond_a_launch.out 2>/dev/null | cut -c1-260; tail -n 1 $W/distrule/rtrule_LCA_launch.out 2>/dev/null | cut -c1-200")
L.append("nvidia-smi --query-compute-apps=pid,used_memory --format=csv,noheader | tr '\\n' ';'; echo; grep -E '^anon ' /sys/fs/cgroup/memory.stat")

for name, lines in (("pod_leadcond_tree.sh", T), ("pod_leadcond_gate.sh", G), ("pod_leadcond_launch.sh", L)):
    p = os.path.join(HERE, name)
    io.open(p, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("written", p, os.path.getsize(p), "bytes")
print(len(allpins), "pins;", [r for r, _b in files])
