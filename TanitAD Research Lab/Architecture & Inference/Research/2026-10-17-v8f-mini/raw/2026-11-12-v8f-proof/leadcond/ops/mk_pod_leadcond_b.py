# mk_pod_leadcond_b.py <form: sq|l1> <weight: 1|4> : chain B of card PREREG_V8F_PROOF_ADD35 (LO = the own-plan term, LCO = the term with --lead-cond on),
# with the form and weight that section 4 of the card picks from the read of the linear arms. Builds two scripts:
#   pod_leadcond_b_setup.sh : runs ON THE POD through bash -s; writes chain2/arms_leadcond_b.txt, prints its sha256 and the argv checks. No GPU.
#   pod_leadcond_b_auto.sh  : pushed to the pod and started with nohup; waits for runs/leadcond_z/Q3B_DONE.txt (control q3b-ii; stops if Q3B_FAIL.txt appears),
#                             then for a free GPU slot, dry-gates LO_s0 and LCO_s0, and only if both pass starts chain leadcond_b and the rule-rollout queue LCB.
import io, os, sys

form, weight = sys.argv[1], sys.argv[2]
assert form in ("sq", "l1") and weight in ("1", "4"), (form, weight)
SRC = "F:/TanitAD-scratch/v8proof/leadcond"
HERE = os.path.dirname(os.path.abspath(__file__))
CARD = "PREREG_V8F_PROOF_ADD35"
TREE = "/workspace/v8proof/tree_leadcond"
ORDER_B = ["LO_s0", "LCO_s0", "LO_s1", "LCO_s1"]

arms = io.open(os.path.join(SRC, "ARMS_LEADCOND.txt"), encoding="utf-8").read().splitlines()
pin_lines = [l for l in arms if l.startswith("PIN|")]
arm = {l.split("|")[1]: l for l in arms if l.startswith("ARM|")}
out = []
for n in ORDER_B:
    a = arm[n]
    assert a.count("|HIER|") == 1 and a.count(" --w-rule-own 4.0 --rule-own-form l1") == 1 and a.count(" levers.w_rule_own=4 levers.rule_own_form=l1") == 1, n
    a = a.replace("|HIER|", "|HIERFT6|", 1)
    a = a.replace(" --w-rule-own 4.0 --rule-own-form l1", " --w-rule-own %s.0%s" % (weight, " --rule-own-form l1" if form == "l1" else ""))
    a = a.replace(" levers.w_rule_own=4 levers.rule_own_form=l1", " levers.w_rule_own=%s%s" % (weight, " levers.rule_own_form=l1" if form == "l1" else ""))
    assert ("--lead-cond on" in a) == n.startswith("LCO") and ("levers.lead_cond=on" in a) == n.startswith("LCO"), n
    assert "--steps 6000 --lr 1e-4 --warmup 100" in a and "/leadsup_a/LS_s%s/ckpt_last.pt" % n[-1] in a, n
    out.append(a)
term_flags = " --w-rule-own %s.0%s" % (weight, " --rule-own-form l1" if form == "l1" else "")

S = []
S.append("# pod_leadcond_b_setup.sh : generated by mk_pod_leadcond_b.py %s %s. Runs ON THE POD (bash -s). No GPU, trains nothing." % (form, weight))
S.append("set -u")
S.append("W=/workspace/v8proof; cd $W/chain2 || exit 1")
S.append("[ -e $W/chains/leadcond_b ] && { echo 'REFUSED: chain leadcond_b exists'; exit 1; }")
S.append("[ -e arms_leadcond_b.txt ] && { echo 'REFUSED: arms_leadcond_b.txt exists'; exit 1; }")
S.append("[ -f arms_leadcond_a.txt ] || { echo 'REFUSED: arms_leadcond_a.txt absent'; exit 1; }")
S.append("cat > arms_leadcond_b.txt <<'ARMSEOF'")
S.append("# LEADCOND card PREREG_V8F_PROOF_ADD35, chain B: four fine-tunes of 6,000 steps from the banked checkpoints of arm LS with the own-plan rule term (form %s, weight %s; section 4 of the card): LO (term), LCO (term and --lead-cond on)." % (form, weight))
S.extend(pin_lines)
S.extend(out)
S.append("ARMSEOF")
S.append("[ \"$(grep '^PIN|' arms_leadcond_a.txt | sha256sum | cut -c1-64)\" = \"$(grep '^PIN|' arms_leadcond_b.txt | sha256sum | cut -c1-64)\" ] && echo 'PIN lines equal to those of chain A' || { echo 'REFUSED: PIN lines differ from chain A'; exit 1; }")
S.append("echo \"== arms_leadcond_b.txt sha256 $(sha256sum arms_leadcond_b.txt | cut -c1-64) PIN $(grep -c '^PIN|' arms_leadcond_b.txt) ARM $(grep -c '^ARM|' arms_leadcond_b.txt)\"; grep '^ARM|' arms_leadcond_b.txt | cut -d'|' -f2,4,5,8 | cut -c1-260")
S.append("dr() { C2_CARD=%s bash chain_arms_ft6.sh dryx $1 --dry-run | grep \"^TRAIN $2\" | sed -e \"s|/runs/[a-z_0-9]*/$2|/runs/X/A|g\" -e \"s|^TRAIN $2|TRAIN A|\"; }" % CARD)
S.append("dr arms_leadcond_a.txt LFT_s0 > /tmp/lcb_lft.txt; dr arms_leadcond_a.txt LC_s0 > /tmp/lcb_lc.txt")
S.append("dr arms_leadcond_b.txt LO_s0 | sed -e 's|%s||' > /tmp/lcb_lo.txt; dr arms_leadcond_b.txt LCO_s0 | sed -e 's|%s||' > /tmp/lcb_lco.txt" % (term_flags, term_flags))
S.append("[ -s /tmp/lcb_lft.txt ] && cmp -s /tmp/lcb_lft.txt /tmp/lcb_lo.txt && echo 'argv of LO_s0 equals that of LFT_s0 apart from name, out folder and the term flags' || echo 'ARGV DIFFERS (LO)'")
S.append("[ -s /tmp/lcb_lc.txt ] && cmp -s /tmp/lcb_lc.txt /tmp/lcb_lco.txt && echo 'argv of LCO_s0 equals that of LC_s0 apart from name, out folder and the term flags' || echo 'ARGV DIFFERS (LCO)'")
S.append("dr arms_leadcond_b.txt LCO_s0 | grep -o -- '--w-rule-own [0-9.]*\\|--rule-own-form [a-z0-9]*\\|--lead-cond [a-z]*\\|--steps [0-9]*' | tr '\\n' ' '; echo")

A = []
A.append("# pod_leadcond_b_auto.sh : generated by mk_pod_leadcond_b.py %s %s. Runs ON THE POD (nohup). Waits for control q3b-ii, then for a free GPU slot, dry-gates LO_s0 and LCO_s0" % (form, weight))
A.append("# and, only if both pass, starts chain leadcond_b (four fine-tunes of 6,000 steps, card %s) and the rule-rollout queue LCB behind it." % CARD)
A.append("set -u")
A.append("W=/workspace/v8proof; Z=$W/runs/leadcond_z; LOG=$Z/lcb_auto.log; cd $W/chain2 || exit 1")
A.append("ts() { date -u +%Y-%m-%dT%H:%M:%SZ; }")
A.append("say() { echo \"[$(ts)] $*\" >> $LOG; }")
A.append("[ -e $W/chains/leadcond_b ] && { say 'chain leadcond_b exists, nothing done'; exit 0; }")
A.append("say 'auto start: waits for Q3B_DONE.txt'")
A.append("k=0; while [ ! -f $Z/Q3B_DONE.txt ]; do [ -f $Z/Q3B_FAIL.txt ] && { say 'Q3B_FAIL.txt present: chain B is NOT started'; echo \"q3b failed ($(ts))\" > $Z/LCB_NOT_STARTED.txt; exit 1; }; k=$((k+1)); [ $k -gt 600 ] && { say 'no q3b result in 10 h'; echo \"no q3b result ($(ts))\" > $Z/LCB_NOT_STARTED.txt; exit 1; }; sleep 60; done")
A.append("say \"q3b: $(head -n 1 $Z/Q3B_DONE.txt)\"")
A.append("k=0; while :; do n1=$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .); sleep 45; n2=$(nvidia-smi --query-compute-apps=pid --format=csv,noheader 2>/dev/null | grep -c .); [ \"$n1\" -lt 3 ] && [ \"$n2\" -lt 3 ] && break; k=$((k+1)); [ $k -gt 480 ] && { say 'no free GPU slot in 8 h'; echo \"no slot ($(ts))\" > $Z/LCB_NOT_STARTED.txt; exit 1; }; sleep 45; done")
A.append("a=$(grep -E '^anon ' /sys/fs/cgroup/memory.stat | cut -d' ' -f2); m=$(cat /sys/fs/cgroup/memory.max); [ $((m - a)) -gt 20000000000 ] || { say 'less than 20 GB of the memory limit free'; echo \"memory ($(ts))\" > $Z/LCB_NOT_STARTED.txt; exit 1; }")
A.append("for arm in LO_s0 LCO_s0; do")
A.append("  bash dry_gate.sh arms_leadcond_b.txt $arm %s > $W/chains/leadcond_dry_$arm.out 2>&1; rc=$?" % CARD)
A.append("  say \"dry gate $arm rc $rc: $(tail -n 1 $W/chains/leadcond_dry_$arm.out | cut -c1-200)\"")
A.append("  [ $rc = 0 ] && grep -q \"ZZ DRY $arm PASS\" $W/chains/leadcond_dry_$arm.out || { echo \"dry gate $arm did not pass ($(ts))\" > $Z/LCB_NOT_STARTED.txt; exit 1; }")
A.append("done")
A.append("/workspace/venv/bin/python - >> $LOG 2>&1 <<'PYEOF'")
A.append("import json")
A.append("for a in ('LO_s0', 'LCO_s0'):")
A.append("    s = json.load(open('/workspace/v8proof/runs/motion_dry/%s/out/selfcheck.json' % a)); lv = s.get('levers', {})")
A.append("    print('SELFCHECK', a, 'dvb', s.get('declared_vs_built'), 'live', (s.get('live') or {}).get('pass'), 'steps_total', s.get('steps_total'), 'lead_cond', lv.get('lead_cond'), 'w_rule_own', lv.get('w_rule_own'), 'form', lv.get('rule_own_form'))")
A.append("    print('   own probe', json.dumps(s.get('rule_own_probe'))[:600])")
A.append("    print('   lead_cond probe', json.dumps(s.get('lead_cond_probe'))[:600])")
A.append("PYEOF")
A.append("C2_CARD=%s C2_WAIT_FOR=$Z/Q3B_DONE.txt C2_IDLE_MIB=30000 nohup setsid bash chain_arms_ft6.sh leadcond_b arms_leadcond_b.txt > $W/chains/leadcond_b_launch.out 2>&1 < /dev/null &" % CARD)
A.append("sleep 2; cd $W/distrule || exit 1")
A.append("nohup setsid bash pod_rtrule_generic.sh LCB leadcond_b LORL_s0:LO_s0 LORL_s1:LO_s1 LCORL_s0:LCO_s0 LCORL_s1:LCO_s1 > $W/distrule/rtrule_LCB_launch.out 2>&1 < /dev/null &")
A.append("sleep 40; say \"chain leadcond_b started: chain processes $(pgrep -f '[c]hain_arms_ft6.sh leadcond_b' | wc -l), queue processes $(pgrep -f '[p]od_rtrule_generic.sh LCB' | wc -l); $(tail -n 1 $W/chains/leadcond_b/chain.log 2>/dev/null | cut -c1-140)\"")
A.append("echo \"started $(ts)\" > $Z/LCB_STARTED.txt")

for name, lines in (("pod_leadcond_b_setup.sh", S), ("pod_leadcond_b_auto.sh", A)):
    p = os.path.join(HERE, name)
    io.open(p, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("written", p, os.path.getsize(p), "bytes")
print("form", form, "weight", weight, "term flags:", term_flags)
