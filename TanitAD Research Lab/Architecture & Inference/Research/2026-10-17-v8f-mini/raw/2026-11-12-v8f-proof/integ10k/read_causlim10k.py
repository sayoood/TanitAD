def speeds(tr):
    p = np.concatenate([np.zeros((len(tr), 1, 2)), tr], 1)
    return np.linalg.norm(np.diff(p, axis=1), axis=-1) / DT


def rs_of(d, key="cl"):
    """share of windows whose last-step speed lies more than 5 m/s above the logged one (finite rollouts)."""
    s, sg = speeds(d[key]), speeds(d["g"])
    fin = np.isfinite(d[key]).all(axis=(1, 2))
    return round(float(((s[:, -1] - sg[:, -1])[fin] > 5.0).mean()), 4)


def ade_w(d, key):
    return np.linalg.norm(d[key] - d["g"], axis=-1).mean(1)


def boot(diff, eid, n=2000, seed=20261119):
    """episode-cluster bootstrap of the mean of a per-window difference: episodes drawn with replacement, the statistic is the window mean of the drawn episodes."""
    ids = np.unique(eid)
    sums = np.array([diff[eid == e].sum() for e in ids])
    cnts = np.array([(eid == e).sum() for e in ids], np.float64)
    rng = np.random.default_rng(seed)
    pick = rng.integers(0, len(ids), size=(n, len(ids)))
    st = sums[pick].sum(1) / cnts[pick].sum(1)
    return [round(float(np.quantile(st, 0.025)), 4), round(float(np.quantile(st, 0.975)), 4)]


def ticks_of(nb, T):
    """rows of a limit log by tick: the log holds, chunk after chunk, T calls of nb rows each. -> list over ticks of row-index arrays in dump order, or None."""
    nb = np.asarray(nb, np.int64)
    if len(nb) % T:
        return None
    start = np.concatenate([[0], np.cumsum(nb)])
    rows = [[] for _ in range(T)]
    for c in range(len(nb)):
        if nb[c] != nb[c - c % T]:
            return None
        rows[c % T].append(np.arange(start[c], start[c + 1]))
    return [np.concatenate(r) for r in rows]


def share_beyond(cl, m, a_max, b_lim=B_LIM, tol=0.25, boundary=False):
    """share of steps whose chord acceleration lies above a_max + tol or below -(b_lim + tol). boundary False: inside each executed block (never across a tick), the definition of
    control f5 of card ADD56 (read_feasc10k.py). boundary True: only the steps at a block boundary, the first step of a block against the last step of the block before."""
    s = speeds(cl)
    acc = np.diff(s, axis=1) / DT                                  # acc[:, i] = from step i+1 to step i+2 (1-based steps)
    inside = np.array([(i + 1) % m != 0 for i in range(acc.shape[1])])
    x = acc[:, ~inside] if boundary else acc[:, inside]
    f = np.isfinite(x)
    return float((((x > a_max + tol) | (x < -(b_lim + tol))) & f).sum() / max(int(f.sum()), 1))


