    one = {w1, w2, mt.group(1) if mt else None, *wsh.values()}
    C["k9_model_and_wrapper"] = {"n_runs": len(sh), "ckpt_not_equal": [n for n, v in sh.items() if not v], "wrapper_sha256": w1[:16], "card": WRAPPER_SHA_PREFIX, "one_sha_everywhere": bool(len(one) == 1 and None not in one and w1),
                                 "PASS": bool(len(sh) == 7 and all(sh.values()) and w1 and w1.startswith(WRAPPER_SHA_PREFIX) and len(one) == 1 and None not in one)}
    # ---- reported without a bar, from the logs
    rep = {}
    for arm, k in NEW_RUNS:
        if arm == "I10RLcFID":
            continue
        key = "%s_s%d" % (arm, k)
