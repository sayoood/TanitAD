def jl(p):
    return json.load(io.open(p, encoding="utf-8")) if p and os.path.exists(p) else None


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest() if p and os.path.exists(p) else ""


def txt(p):
    return io.open(p, encoding="utf-8", errors="replace").read() if p and os.path.exists(p) else ""


def npz(path):
    return np.load(path, allow_pickle=True) if os.path.exists(path) else None


def tick_dir(pull, arm, k):
    return os.path.join(pull, "%s_s%d" % (arm, k), "ticks")


def rlog(pull, arm, k, kind=""):
    """kind '' = tick log, 'mid' = later-look log, 'rd' = reader side file of the tick log, 'midrd' = reader side file of the later looks, 'p1' = plan after the rule at the first tick"""
    n = "%s_s%d" % (arm, k)
    d = tick_dir(pull, arm, k)
    name = {"": "rule_log_%s.npz", "mid": "rule_log_mid_%s.npz", "rd": "rule_log_%s_rd.npz", "midrd": "rule_log_mid_%s_rd.npz", "p1": "p1_first_%s.npz"}[kind] % n
    return npz(os.path.join(d, name))


def dump(pull, arm, k, keys=("cl", "g", "ws", "clip_index")):
    files = sorted(glob.glob(os.path.join(pull, "%s_s%d" % (arm, k), "dump_%s_s%d_m10_causal_heads" % (arm, k), "ep*.npz")))
    if len(files) != 141:
        return None
    out = {n: [] for n in keys}
    for f in files:
        z = np.load(f)
        for n in keys:
            out[n].append(np.asarray(z[n], np.float64 if n in ("cl", "g") else np.int64))
    return {n: np.concatenate(v) for n, v in out.items()}


def wkey(ci, t0):
    return np.asarray(ci, np.int64) * 1000000 + np.asarray(t0, np.int64)


def align(ka, kb):
    """index arrays (ia, ib) with ka[ia] == kb[ib] for every row, or None when the two key sets are not the same unique set"""
    ka, kb = np.asarray(ka, np.int64), np.asarray(kb, np.int64)
    if len(ka) != len(kb) or len(np.unique(ka)) != len(ka) or len(np.unique(kb)) != len(kb):
        return None
    ia, ib = np.argsort(ka), np.argsort(kb)
    return (ia, ib) if np.array_equal(ka[ia], kb[ib]) else None


def maxdiff(x, y):
    x, y = np.asarray(x, np.float64), np.asarray(y, np.float64)
    if x.shape != y.shape or not np.array_equal(np.isfinite(x), np.isfinite(y)):
        return float("inf")
    f = np.isfinite(x)
    return float(np.max(np.abs(x[f] - y[f]))) if f.any() else 0.0


def path_arcs(plan, pts):
    """arc coordinate of pts [N,M,2] on the polyline origin + plan [N,L,2] (nearest non-degenerate segment, orthogonal projection clipped to the segment). [N,M]"""
    plan, pts = np.asarray(plan, np.float64), np.asarray(pts, np.float64)
    V = np.concatenate([np.zeros((len(plan), 1, 2)), plan], 1)
    A, d = V[:, :-1], V[:, 1:] - V[:, :-1]
    L = np.linalg.norm(d, axis=-1)
    cum = np.concatenate([np.zeros((len(plan), 1)), np.cumsum(L, 1)], 1)[:, :-1]
    q = pts[:, :, None, :]
    l2 = (L ** 2)[:, None, :]
    with np.errstate(invalid="ignore", divide="ignore"):
        t = np.clip(((q - A[:, None]) * d[:, None]).sum(-1) / np.where(l2 > 1e-18, l2, 1.0), 0.0, 1.0)
    proj = A[:, None] + t[..., None] * d[:, None]
    dist = np.where((L > 1e-9)[:, None, :], np.linalg.norm(q - proj, axis=-1), np.inf)
    j = np.argmin(dist, axis=-1)[..., None]
    arc = np.take_along_axis(np.broadcast_to(cum[:, None, :], dist.shape), j, -1)[..., 0]
    tt = np.take_along_axis(t, j, -1)[..., 0]
    ll = np.take_along_axis(np.broadcast_to(L[:, None, :], dist.shape), j, -1)[..., 0]
    return arc + tt * ll


def rows_equal_first(a, b, h):
    """per window: executed steps 1..h of the dumps a and b are equal (NaN equal)"""
    x, y = a["cl"][:, :h], b["cl"][:, :h]
    return ((x == y) | (np.isnan(x) & np.isnan(y))).all(axis=(1, 2))


