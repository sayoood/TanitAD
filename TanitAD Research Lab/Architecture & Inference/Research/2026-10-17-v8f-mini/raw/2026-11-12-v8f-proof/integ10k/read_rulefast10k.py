        nw = None if dd_ is None else len(dd_["ws"])
        L, Lm = rlog(a.pull, arm, k), rlog(a.pull, arm, k, "mid")
        ntick[key] = None if L is None else (int(len(L["ci"])), nw * 3 if nw else None)
