#!/usr/bin/env python
"""make_presattrc_reader.py -- card PREREG_V8F_PROOF_ADD115 (PRESATTRC10K). Writes the reader and the pod driver of this card from those of card ADD114
(presattr/read/read_presattr10k.py and podread_presattr10k.sh) by asserted substitutions. Only the tables change: one setting CONV (pinned readout, no pre-roll,
pinned grid, the rule every 10 steps, one rule log per run), its run names, its banked levels for the identity control, the card and name prefix, the folders.
Every function of the source reader is kept as it is. The selftest of the source reader is tied to its own two settings: the generated reader refuses --selftest,
and the generated driver runs the selftest of the source reader from its own kit folder before the controls stage.

  python make_presattrc_reader.py [--print reader|driver]
"""
import argparse
import hashlib
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.normpath(os.path.join(HERE, "..", "..", "presattr", "read"))
SRC = {"reader": ("read_presattr10k.py", "26a9097f22577750"), "driver": ("podread_presattr10k.sh", "04eb1dc2b7cbc889")}
OUT = {"reader": "read_presattrc10k.py", "driver": "podread_presattrc10k.sh"}
TAG = "ZZ MAKE-PRESATTRC-READER STOP: "

SPEC_NEW = '''SPEC = {
    "CONV": {"P": 0, "readout": "pinned", "every": None, "grid": "full", "grid_file": "pinned",
             "runs": {"RLc": "RLcHb20", "LA": "RQ50Hb20aLA", "PL": "RLcHb20pLE", "GEc": "RQ50Hb20gGEc", "RR": "RQ50Hb20"}},
}
'''
EXPECTED_NEW = '''EXPECTED = {                                                        # banked levels, (C, U, F), card ADD115 section 5 control f3 (row 179)
    "CONV": {"GEc": (0.0016, 0.0569, 0.2329), "RR": (0.0280, 0.0783, 0.2593), "RLc": (0.0016, 0.0320, 0.2243)},
}
'''
TIER_NEW = ('TIER = ("T1-kin/hb0.2 (kinematic rollout on the model\'s own actions, executor of record v8f_t1_eval_hb.py with the heading bound 0.2 1/m); '
            'CONV: pinned readout, no pre-roll, pinned grid")')
DRIVER_HEAD = [
    "# podread_presattrc10k.sh -- pod-side read of card PREREG_V8F_PROOF_ADD115 (PRESATTRC10K). CPU only (CUDA_VISIBLE_DEVICES=-1 is set here), no rollout.",
    "# Generated by make_presattrc_reader.py from the driver of card ADD114. Stage controls: needs the done marker of the rollout queue of this card and no stop marker, links the two new run names (both seeds)",
    "#   and the banked runs of the convention (and the spread run) into the pull folder of the readers, runs the selftest of the source reader of card ADD114 from its own kit folder first, then",
    "#   read_presattrc10k.py --stage controls (writes $OUT/PRESATTRC10K_CONTROLS.json). The planted join is the one of card ADD114 ($V/presattr/joins). The time arguments of the tests control are filled here with",
    "#   stat -c %Y (the two lead test outputs in $GE/lead_tests), the first token of the first line of PRESATTRC10K_START.txt (`<epoch seconds> <ISO time>Z pid <pid>`) and date +%s at the start of the stage.",
    "# Stage names: read_presattrc10k.py --stage names on that controls file (the reader refuses unless all eight controls pass), writes $OUT/PRESATTRC10K_RESULT.json, $OUT/read_names.log and $OUT/read_names.out.",
    "# The eight controls print as e0 to e7; they are the controls f0 to f7 of card ADD115 in that order. Never reads twice into one file. It deletes, moves and stops nothing.",
    "# Usage: bash podread_presattrc10k.sh controls|names",
    "# Prints only the lines e<i> PASS|FAIL, the reader's last line and: ZZ PODREAD-PRESATTRC10K <stage> DONE rc <n> <time>   (or ZZ PODREAD-PRESATTRC10K STOP <why>).",
]


class Sub(object):
    def __init__(self, text):
        self.t = text.replace("\r\n", "\n")

    def once(self, a, b):
        if self.t.count(a) != 1:
            raise SystemExit(TAG + "expected once, found %d: %r" % (self.t.count(a), a[:90]))
        self.t = self.t.replace(a, b)

    def span(self, a, b, new):
        s = self.t
        if s.count(a) != 1 or s.count(b) != 1 or not s.index(a) < s.index(b):
            raise SystemExit(TAG + "anchors: %r (%d) / %r (%d)" % (a[:60], s.count(a), b[:60], s.count(b)))
        self.t = s[:s.index(a)] + new + s[s.index(b):]

    def line_from(self, a, new):
        s = self.t
        if s.count(a) != 1:
            raise SystemExit(TAG + "line anchor found %d times: %r" % (s.count(a), a[:60]))
        i = s.index(a)
        self.t = s[:i] + new + s[s.index("\n", i):]


def build_reader(src_text):
    S = Sub(src_text)
    S.once('CARD, PRE = "PREREG_V8F_PROOF_ADD114", "PRESATTR10K"', 'CARD, PRE = "PREREG_V8F_PROOF_ADD115", "PRESATTRC10K"')
    S.once('SETTINGS = ("K0", "K30")', 'SETTINGS = ("CONV",)')
    S.span("SPEC = {\n", "NEW_ARMS = {", SPEC_NEW)
    S.line_from("NEW_ARMS = {", 'NEW_ARMS = {"CONV": ("LA", "PL")}                                     # the runs of card ADD115; the other cells are banked')
    S.span("EXPECTED = {", "LEVEL_TOL = 1e-4", EXPECTED_NEW)
    S.line_from("TIER = (", TIER_NEW)
    S.once('        pre = "PRESATTR10K-" + S + "-"', '        pre = "PRESATTRC10K-" + S + "-"')
    S.once('DONE_RE = re.compile(r"^ZZ PRESATTR10K DONE \\S+ all steps done$")', 'DONE_RE = re.compile(r"^ZZ PRESATTRC10K DONE \\S+ all steps done$")')
    S.once('        a.tests_queue = a.tests_queue or WS + "/presattr/lead_tests/lead_pytest_queue.out"', '        a.tests_queue = a.tests_queue or WS + "/presattrc/lead_tests/lead_pytest_queue.out"')
    S.once('        a.tests_read = a.tests_read or WS + "/presattr/lead_tests/lead_pytest_read.out"', '        a.tests_read = a.tests_read or WS + "/presattrc/lead_tests/lead_pytest_read.out"')
    S.once("    if a.selftest:\n        return selftest()\n",
           '    if a.selftest:\n        print("REFUSED: the selftest is that of the source reader of card ADD114; run it from that file")\n        return 2\n')
    n = S.t.count("READ-PRESATTR10K")
    if n < 4:
        raise SystemExit(TAG + "the reader's own last-line tag was found %d times" % n)
    S.t = S.t.replace("READ-PRESATTR10K", "READ-PRESATTRC10K")
    first = S.t.split("\n", 1)
    S.t = ("# GENERATED by make_presattrc_reader.py from read_presattr10k.py (sha256 prefix %s) for card PREREG_V8F_PROOF_ADD115 (PRESATTRC10K): one setting CONV. The docstring and the\n"
           "# comments below are those of the source and speak of its two settings; the tables SETTINGS, SPEC, NEW_ARMS, EXPECTED, TIER, CARD and PRE are those of card ADD115. No function is changed.\n"
           % SRC["reader"][1]) + first[0] + "\n" + first[1]
    t = S.t
    for must in ('"CONV": {"P": 0, "readout": "pinned", "every": None', '"CONV": {"GEc": (0.0016, 0.0569, 0.2329)', 'PRE = "PREREG_V8F_PROOF_ADD115", "PRESATTRC10K"'):
        if must not in t:
            raise SystemExit(TAG + "missing after the substitutions: " + must[:50])
    for bad in ('"PRESATTR10K"', '"PRESATTR10K-"', "ZZ PRESATTR10K DONE", 'SETTINGS = ("K0"', '"K30": {"P": 30'):
        if bad in t:
            raise SystemExit(TAG + "left over: " + bad)
    return t


def build_driver(src_text):
    S = Sub(src_text)
    lines = S.t.split("\n")
    if lines[0] != "#!/usr/bin/env bash" or "set -u" not in lines[:20]:
        raise SystemExit(TAG + "the head of the driver is not the expected one")
    k = lines.index("set -u")
    if not all(x.startswith("#") for x in lines[1:k]):
        raise SystemExit(TAG + "the head of the driver has a line that is no comment")
    S.t = "\n".join([lines[0]] + DRIVER_HEAD + lines[k:])
    S.once("GE=$V/presattr; K=$GE/kit_read; OUT=$GE/read; LT=$GE/lead_tests; PJ=$GE/joins",
           "GE=$V/presattrc; K=$GE/kit_read; OUT=$GE/read; LT=$GE/lead_tests; PJ=$V/presattr/joins; K114=$V/presattr/kit_read")
    S.once('for f in "$K/read_presattr10k.py" "$MODEL"; do', 'for f in "$K/read_presattr10k.py" "$K114/read_presattr10k.py" "$MODEL"; do')
    S.once('"$PY" "$K/read_presattr10k.py" --selftest', '"$PY" "$K114/read_presattr10k.py" --selftest')
    S.once('"$LT/lead_pytest_read.out" "$W/longroll/grid_p30.json" "$PINNED"', '"$LT/lead_pytest_read.out" "$PINNED"')
    S.line_from("  for x in I10RLcKF5Hb20 ", "  for x in I10RLcHb20 I10RQ50Hb20aLA I10RLcHb20pLE I10RQ50Hb20gGEc I10RQ50Hb20 I10R0Hb20; do")
    t = S.t.replace('"$K/read_presattr10k.py"', '"$K/read_presattrc10k.py"').replace("PRESATTR10K", "PRESATTRC10K")
    if t.count('"$K114/read_presattr10k.py"') != 2 or t.count('"$K/read_presattrc10k.py"') < 4:
        raise SystemExit(TAG + "driver counts: source reader %d, generated reader %d" % (t.count('"$K114/read_presattr10k.py"'), t.count('"$K/read_presattrc10k.py"')))
    for bad in ("KF5", "grid_p30", "PRESATTR10K", "GE=$V/presattr;"):
        if bad in t:
            raise SystemExit(TAG + "driver left over: " + bad)
    return t


BUILD = {"reader": build_reader, "driver": build_driver}


def make(kind):
    name, sha16 = SRC[kind]
    raw = io.open(os.path.join(SRC_DIR, name), "rb").read().replace(b"\r\n", b"\n")
    got = hashlib.sha256(raw).hexdigest()[:16]
    if got != sha16:
        raise SystemExit(TAG + "%s: source sha256 prefix %s, expected %s" % (name, got, sha16))
    return BUILD[kind](raw.decode("utf-8"))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", choices=("reader", "driver"), default="")
    a = ap.parse_args(argv)
    if a.print:
        sys.stdout.write(make(a.print))
        return 0
    for kind in ("reader", "driver"):
        t = make(kind)
        with io.open(os.path.join(HERE, OUT[kind]), "x", encoding="utf-8", newline="\n") as fh:
            fh.write(t)
        print("ZZ MAKE-PRESATTRC-READER DONE %s sha256 prefix %s" % (OUT[kind], hashlib.sha256(t.encode("utf-8")).hexdigest()[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
