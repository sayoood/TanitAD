#!/usr/bin/env python3
"""Makes window_encode_d.py from the pilot's window_encode.py (card ADD99 kit) by counted, asserted edits.

Why: window_encode.py writes BOTH arms (tok/D and tok/B, 27 MB per clip each) and needs a box folder; this card needs arm D only
(a box folder does not exist for the new clips, and arm B would double the disk). The variant computes the D tokens by the same
functions in the same order: the grids of the two fixed windows, window_sample, Encoder.window_tokens on the same batches, the same
float16 cast. What is removed: the box file read, the B grids and B sampling, the B encode, the B files and the B ledger/manifest.
Each old text must occur exactly the stated number of times, and the source file's sha256 (line ends normalised to LF) is asserted.
Output is written only if absent or byte-identical (never overwritten); nothing is deleted or moved.

Usage: gen_window_encode_d.py --src <pilot window_encode.py> --out <window_encode_d.py>
"""
import argparse
import ast
import hashlib
import os
import sys

SRC_SHA256 = "ee3919f8107065379ec96c29d4c80f7533a14b716b2e48926008c2d4b2aae7e9"

# (old text, new text, expected number of occurrences)
EDITS = [
    ('"""Windows and tokens for a clip list (card sections 3 and 4). Pod only (GPU for the encoder).\n',
     '"""ARM D ONLY variant of window_encode.py (generated by gen_window_encode_d.py for card ADD106; no box folder, no arm B file).\n'
     'Windows and tokens for a clip list (card sections 3 and 4 of ADD99). Pod only (GPU for the encoder).\n', 1),
    # no box file: the arm D windows do not depend on it
    ("    has, baz, bel = load_box_dirs(box_dir, clip, n) if box_dir else (np.zeros(n, bool), np.zeros(n), np.zeros(n))\n",
     "    has = np.zeros(n, bool)                                       # arm D only: no lead boxes are read\n", 1),
    # two windows per frame instead of four
    ("    out = np.zeros((n, 4, 3, WIN_PX, WIN_PX), np.uint8)\n",
     "    out = np.zeros((n, 2, 3, WIN_PX, WIN_PX), np.uint8)\n", 1),
    # the B grids and B sampling
    ("            az = np.where(has[js], baz[js], ARM_D_WINDOWS[i][1])\n"
     "            el = np.where(has[js], bel[js], ARM_D_WINDOWS[i][2])\n"
     "            gb, mb = window_grid(intr, h, w, frames[i], az, el)\n"
     "            out[js, 2 + i] = window_sample(vid, gb, mb).numpy()\n",
     "", 1),
    # encode: arm D only
    ("    tB = tD.clone()\n"
     "    idx = np.nonzero(has)[0]\n"
     "    if idx.size:\n"
     "        Bw = torch.from_numpy(wins[idx][:, 2:4].reshape(idx.size * 2, 3, WIN_PX, WIN_PX))\n"
     "        tB[torch.from_numpy(idx)] = enc.window_tokens(Bw).reshape(idx.size, 2, 65, -1)\n"
     "    return tD.to(torch.float16).numpy(), tB.to(torch.float16).numpy()\n",
     "    return tD.to(torch.float16).numpy()\n", 1),
    ("    ap.add_argument(\"--box-dir\", required=True)\n", "", 1),
    ('("D", "B")', '("D",)', 6),
    ("make_windows, c, L, a.box_dir, a.torch_threads", "make_windows, c, L, None, a.torch_threads", 1),
    ("                tD, tB = encode_clip_tokens(enc, wins, has)\n", "                tD = encode_clip_tokens(enc, wins, has)\n", 1),
    ('for arm, arr in (("D", tD), ("B", tB)):', 'for arm, arr in (("D", tD),):', 1),
    ('"n_lead_frames": int(has.sum()), ', "", 1),
    (" lead={int(has.sum())}", "", 1),
]


def lf(b):
    return b.replace(b"\r\n", b"\n")


def generate(src_bytes, check_sha=True):
    src = lf(src_bytes)
    if check_sha:
        got = hashlib.sha256(src).hexdigest()
        if got != SRC_SHA256:
            raise SystemExit("REFUSED: source sha256 %s != the asserted %s" % (got, SRC_SHA256))
    text = src.decode("utf-8")
    for old, new, n in EDITS:
        c = text.count(old)
        if c != n:
            raise SystemExit("REFUSED: old text occurs %d times, expected %d: %r" % (c, n, old[:70]))
        text = text.replace(old, new)
    ast.parse(text)
    for bad in ('"B"', "tB", " = load_box_dirs(", "a.box_dir", "baz[", "bel["):
        if bad in text:
            raise SystemExit("REFUSED: the variant still contains %r" % bad)
    return text


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    text = generate(open(a.src, "rb").read())
    data = text.encode("utf-8")
    if os.path.exists(a.out):
        if open(a.out, "rb").read() == data:
            print("window_encode_d.py exists with the same bytes; sha256 %s" % hashlib.sha256(data).hexdigest()[:16])
            return 0
        raise SystemExit("REFUSED: %s exists with other content" % a.out)
    tmp = a.out + ".part"
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.replace(tmp, a.out)
    print("wrote %s sha256 %s (%d edits)" % (a.out, hashlib.sha256(data).hexdigest()[:16], len(EDITS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
