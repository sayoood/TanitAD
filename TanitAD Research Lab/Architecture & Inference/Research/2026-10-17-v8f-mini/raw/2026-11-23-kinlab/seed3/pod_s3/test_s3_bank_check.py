"""test_s3_bank_check.py -- the whole file: s3_bank_check.py passes a bank whose generator record names UE_s2.A with coverage >= 0.5, and refuses every other. CPU, stdlib. S3_TEST_BANKCHK names the tool under test (mutant runner)."""
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.environ.get("S3_TEST_BANKCHK", os.path.join(HERE, "s3_bank_check.py"))
UE2 = "6d4345258e07dee15b1c5171268182967189df1cdc13b89b81d26aae71c3f327"
GEN = {"readout": "causal_g", "acc_gain": 1.0, "path_exec": True, "kappa_max": "0.2"}


def bank(**kw):
    d = tempfile.mkdtemp(dir=os.environ.get("S3_TMP") or None)
    b = {"common": {"ckpt_sha256": UE2, "generator": dict(GEN), "partial": False, "train": {"n_windows": 985048}}, "coverage": {"fraction": 0.7969, "blocked": False, "min": 0.5}}
    c = {"pass": True, "readout": "causal_g1x"}
    for k, v in kw.items():
        if k == "ckpt":
            b["common"]["ckpt_sha256"] = v
        elif k == "gen":
            b["common"]["generator"] = v
        elif k == "partial":
            b["common"]["partial"] = v
        elif k == "nwin":
            b["common"]["train"]["n_windows"] = v
        elif k == "cov":
            b["coverage"]["fraction"] = v
        elif k == "blocked":
            b["coverage"]["blocked"] = v
        elif k == "bcpass":
            c["pass"] = v
        elif k == "bcro":
            c["readout"] = v
    json.dump(b, open(f"{d}/bank.json", "w"))
    json.dump(c, open(f"{d}/BANK_CHECK.json", "w"))
    return d


def run(d, win=985048):
    r = subprocess.run([sys.executable, TOOL, "--bank", d, "--expect-windows", str(win), "--out", f"{d}/S3_BANK_CHECK.json"], capture_output=True, text=True)
    return r.returncode, r.stdout


def main():
    fails = []

    def case(name, kw, want_ok, win=985048):
        d = bank(**kw)
        rc, out = run(d, win)
        o = json.load(open(f"{d}/S3_BANK_CHECK.json"))
        good = (rc == 0 and "ZZ S3-BANK-CHECK PASS" in out and o["pass"] is True) if want_ok else (rc != 0 and "PASS" not in out and o["pass"] is False)
        print("PASS" if good else "FAIL", name)
        if not good:
            fails.append(name)
        return o
    o = case("good bank", {}, True)
    assert o["generator_ckpt_sha256"] == UE2 and o["coverage_fraction"] == 0.7969 and o["partial"] is False
    case("refuse a bank generated by UE_s0.A", {"ckpt": "2fd4b747532f55b24523c578948cb713fb80fa0e698586c329dd23ba6e6df914"}, False)
    case("refuse a bank with no ckpt record", {"ckpt": None}, False)
    case("refuse coverage 0.4999", {"cov": 0.4999}, False)
    case("accept coverage exactly 0.5", {"cov": 0.5}, True)
    case("refuse a blocked bank", {"blocked": True}, False)
    case("refuse a partial bank", {"partial": True}, False)
    case("refuse another generator (causal_g1)", {"gen": {"readout": "causal_g", "acc_gain": 1.0, "path_exec": False, "kappa_max": "0.2"}}, False)
    case("refuse a stock bank check that failed", {"bcpass": False}, False)
    case("refuse a stock bank check of another readout", {"bcro": "causal_g1"}, False)
    case("refuse a window count that is not the expected one", {"nwin": 1000}, False)
    case("refuse expect-windows 0", {}, False, win=0)
    print("RESULT", "ALL PASS" if not fails else f"{len(fails)} FAILED: {fails}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
