#!/usr/bin/env python3
"""Write ../DRY_RUN.out: the r2 chain's OFFLINE runs (touch nothing: no box 2, no BOX2_BUSY, no E: write outside the scratch dir):
  1. --dry-run against the queue at the remote tip c7963d7 (git show, local object) with r1's REAL log as the predecessor
  2. --check-tree on an export of c7963d7's four trainer files + queue  (EXPECTED: REFUSED -- the trainer fix is staged, not landed; exactly the STREAM_PATTERN is missing)
  3. --check-tree on the same export with the STAGED fix (dagland/compose_fix/stage trainer + data)  (EXPECTED: PASS, 43 patterns)
  4. --wait-only against r1's live log (EXPECTED: ZZOAF-WAIT-GO)
  python make_dry_run.py
"""
from __future__ import annotations

import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
R2 = HERE.parent
SHIP = R2 / "box2_ship"
INST = Path("C:/Users/Admin/box2_ship")
MIR = "C:/Users/Admin/tanitad-push"
TIP = "c7963d725eaa3fb6630d433ab4fc802535c97d78"
PK = "TanitAD Research Lab/Architecture & Inference/Research/2026-10-17-v8f-mini"
QP = PK + "/code/v8f_mini_box2_queue.cmd"
FILES = ["stack/scripts/v8f_mini_train.py", "stack/tanitad/models/v8f_mini.py", "stack/tanitad/data/v8f_mini_data.py", "stack/tanitad/data/v8f_dagger.py", QP]
FIX = Path("E:/Projects/TanitAD-artifacts/dagland/compose_fix/stage")
BASH = "C:/Program Files/Git/bin/bash.exe"
SCR = Path("F:/TanitAD-scratch/dagorc_r2_tmp/dry")
AFTER = "/c/Users/Admin/box2_ship/logs/chain_v8f_dagoaccorc.out"


def bp(p):
    return str(p).replace("\\", "/")


def gitshow(rev, f):
    return subprocess.run(["git", "-C", MIR, "-c", "safe.directory=*", "show", f"{rev}:{f}"], capture_output=True, check=True).stdout


def run(ship, args, env):
    e = {**os.environ, "MSYS_NO_PATHCONV": "0", "TMPDIR": bp(ship) + "/tmp", "OAF_SHIP_DIR": bp(ship), **env}
    p = subprocess.run([BASH, "-c", f'cd "{bp(ship)}" && bash ./chain_v8f_dagoaccorc_r2.sh {args}'], capture_output=True, stdin=subprocess.DEVNULL, env=e, timeout=300)
    return p.returncode, (p.stdout or b"").decode("utf-8", "replace").replace("\r", "") + (p.stderr or b"").decode("utf-8", "replace").replace("\r", "")


def main() -> int:
    shutil.rmtree(SCR, ignore_errors=True)
    ship = SCR / "ship"
    (ship / "tmp").mkdir(parents=True)
    for f in ("chain_v8f_dagoaccorc_r2.sh", "oaf_dagoaccorc_r2_lib.sh", "v8f_dagoaccorc_r2_chain_checks.py", "gate_dagoaccorc_r2_assert.py"):
        shutil.copy(SHIP / f, ship / f)
    for f in ("oaf_lib.sh", "v8f_oaf_chain_checks.py", "v8f_guard_dagoaccorc.sh"):
        shutil.copy(INST / f, ship / f)
    q = SCR / "queue_tip.cmd"
    q.write_bytes(gitshow(TIP, QP))
    qsha = hashlib.sha256(q.read_bytes()).hexdigest()
    trees = {}
    for tag, fix in (("tip", False), ("fix", True)):
        root = SCR / f"tree_{tag}"
        for f in FILES:
            d = root / f
            d.parent.mkdir(parents=True, exist_ok=True)
            d.write_bytes(gitshow(TIP, f))
        if fix:
            for f in ("stack/scripts/v8f_mini_train.py", "stack/tanitad/data/v8f_mini_data.py"):
                (root / f).write_bytes((FIX / f).read_bytes())
        trees[tag] = root
    pat = next(x for x in (SHIP / "chain_v8f_dagoaccorc_r2.sh").read_text(encoding="utf-8").split("\n") if x.startswith("STREAM_PATTERN="))
    rec = next(x for x in (SHIP / "chain_v8f_dagoaccorc_r2.sh").read_text(encoding="utf-8").split("\n") if x.startswith("STREAM_RECORD="))
    out = [f"# OFFLINE RUNS of chain_v8f_dagoaccorc_r2.sh (touch nothing: no box 2, no BOX2_BUSY, no write outside {bp(SCR)}; generated by gen/make_dry_run.py, 2026-10-28)",
           f"# ship dir = the r2 files + the INSTALLED oaf_lib.sh / v8f_oaf_chain_checks.py / v8f_guard_dagoaccorc.sh;  remote tip = {TIP[:7]} (git ls-remote origin agent/arch-inf-20260803 returned it today)",
           f"# queue = v8f_mini_box2_queue.cmd at {TIP[:7]} (git show, local object), sha256 {qsha}",
           f"# registered {pat}", f"# registered {rec}",
           "# the trainer fix (dagland/compose_fix/stage) is STAGED, NOT LANDED on the remote tip: section 2 must therefore be a REFUSAL, and that is the chain working, not a defect", ""]
    rc, o = run(ship, "--dry-run", dict(V8F_QUEUE=bp(q), AFTER_OUT=AFTER))
    out += ["=" * 100, f"1. --dry-run   (V8F_QUEUE=<queue at {TIP[:7]}> AFTER_OUT={AFTER})   rc={rc}", "=" * 100, o.rstrip("\n"), ""]
    rc2, o2 = run(ship, f'--check-tree "{bp(trees["tip"])}"', {})
    out += ["=" * 100, f"2. --check-tree <export of the four trainer files + the queue at {TIP[:7]}>   rc={rc2}   (EXPECTED 1: the fix is not landed)", "=" * 100, o2.rstrip("\n"), ""]
    rc3, o3 = run(ship, f'--check-tree "{bp(trees["fix"])}"', {})
    out += ["=" * 100, f"3. --check-tree <the same export with the STAGED fix's trainer + data>   rc={rc3}   (EXPECTED 0: 43 patterns)", "=" * 100, o3.rstrip("\n"), ""]
    rc4, o4 = run(ship, "--wait-only", dict(AFTER_OUT=AFTER, OAF_POLL_S="1", OAF_GRACE_S="1"))
    out += ["=" * 100, f"4. --wait-only   (AFTER_OUT={AFTER}, r1's LIVE log; BOX2_BUSY.txt absent in the scratch ship dir)   rc={rc4}   (EXPECTED 0: ZZOAF-WAIT-GO)", "=" * 100, o4.rstrip("\n"), ""]
    (R2 / "DRY_RUN.out").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("rc:", rc, rc2, rc3, rc4)
    print("touched nothing under ship:", sorted(x.name for x in ship.iterdir()))
    return 0 if (rc, rc2, rc3, rc4) == (0, 1, 0, 0) else 1


if __name__ == "__main__":
    sys.exit(main())
