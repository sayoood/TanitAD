"""Collect the logs, the counts and the mutation table into the deliverable dir: stage/, diff.patch, SHA256SUMS.txt, RESULTS.md, logs/."""
import difflib
import glob
import hashlib
import json
import os
import re
import shutil

W = "F:/TanitAD-scratch/compose_fix"
L = f"{W}/logs"
D = "E:/Projects/TanitAD-artifacts/dagland/compose_fix"
BASE = "e7ea20d1287599409d1758971ded62b2fc4ef375"
CHANGED = ["stack/scripts/v8f_mini_train.py", "stack/tanitad/data/v8f_mini_data.py", "stack/tests/test_v8f_ego_dagger_compose.py"]
GOLDEN = "stack/tests/ego_dagger_compose_golden.json"
SUITES = ["test_v8f_ego_dagger_compose", "test_v8f_ego_perturb", "test_v8f_dagger_train", "test_v8f_dagger", "test_v8f_init_ckpt_o_interface", "test_launch_gate_v8f", "test_v8f_orc_chain"]
NEW_TESTS_HEAD = "test_v8f_ego_dagger_compose.py::"


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def read(p):
    return open(p, encoding="utf-8", errors="replace", newline="").read()


os.makedirs(f"{D}/logs", exist_ok=True)
# ---- stage/ (changed files at repo paths) + diff.patch (against the pristine e7ea20d1 export) + SHA256SUMS
shutil.rmtree(f"{D}/stage", ignore_errors=True)
patch = []
for f in CHANGED:
    os.makedirs(os.path.dirname(f"{D}/stage/{f}"), exist_ok=True)
    shutil.copyfile(f"{W}/tree/{f}", f"{D}/stage/{f}")
    a, b = read(f"{W}/pristine/{f}").splitlines(keepends=True), read(f"{W}/tree/{f}").splitlines(keepends=True)
    patch += list(difflib.unified_diff(a, b, fromfile=f"a/{f}", tofile=f"b/{f}", n=3))
open(f"{D}/diff.patch", "w", encoding="utf-8", newline="\n").write("".join(patch))
sums = [f"{sha(f'{D}/stage/{f}')}  {f}" for f in CHANGED]
open(f"{D}/SHA256SUMS.txt", "w", encoding="utf-8", newline="\n").write("\n".join(sums) + "\n")
base_sums = [f"{sha(f'{W}/pristine/{f}')}  {f}  (e7ea20d1)" for f in CHANGED]
gold_same = sha(f"{W}/tree/{GOLDEN}") == sha(f"{W}/pristine/{GOLDEN}")
crlf = {f: read(f"{D}/stage/{f}").count("\r") for f in CHANGED}

out = ["# RESULTS (generated by assemble.py from the logs in ./logs)", "",
       f"Base: landed tip `{BASE}` (the commit that carries `--ego-perturb-with-dagger`). CPU only (`CUDA_VISIBLE_DEVICES=-1`), one pytest file at a time, `python -m pytest stack/tests/<file>` from the tree root. "
       "Nothing was committed, pushed or staged in git; `stage/` holds the changed files at repo paths.", "",
       "## 1. The golden is untouched", "",
       f"`stack/tests/ego_dagger_compose_golden.json` sha256 in the fixed tree == in e7ea20d1: **{gold_same}** ({sha(f'{W}/tree/{GOLDEN}')[:16]}...). The flag-off bit-identity test "
       "(`test_flag_off_reproduces_the_unmodified_tip_bit_for_bit`) reads it unchanged and is in the first suite below.", ""]

# ---- the RED-on-old / GREEN-on-fix proof
def summarize(name):
    f = f"{L}/{name}.log"
    if not os.path.exists(f):
        return None, [], ""
    t = read(f)
    last = [l for l in t.strip().splitlines() if re.search(r" (passed|failed|skipped|error)", l)]
    failed = re.findall(r"^(?:FAILED|ERROR) (\S+)", t, re.M)
    return (last[-1].strip() if last else "NO SUMMARY LINE (killed?)"), failed, t


out += ["## 2. The new tests: RED on e7ea20d1, GREEN on the fix", ""]
red_sum, red_failed, red_text = summarize("red_on_old")
grn_sum, grn_failed, _ = summarize("green_new")
out += [f"* new tests on the UNMODIFIED e7ea20d1 code (tree `compose_fix/oldnew`): **{red_sum}**",
        f"* the same tests on the FIXED tree: **{grn_sum}**", ""]
out += ["Why each fails on the old code (first assertion line of each failure, from `logs/red_on_old.log`):", "", "```"]
for m in re.finditer(r"^E\s+(AssertionError: .*|AttributeError: .*|KeyError: .*|assert .*)$", red_text, re.M):
    out.append(m.group(1)[:300])
out += ["```", "",
        "The three BEHAVIOURAL failures (the `equal_seeds_...` rows and `..._selection_uniforms_are_not_one_stream_...`) and the run-level one (`..._trainer_run_at_the_box2_shape_...`) fail on the *numbers* "
        "(P(perturbed | not swapped) 0.0000 at 0.5/0.5 and ~0.222 at 0.1/0.3, the two uniform rows equal, the run-level share ~0.246); the remaining failures are the new API (`EGO_PERTURB_COMPOSED_STREAM`, "
        "`levers.ego_perturb_stream`, the G-DVB stream read-back, the resume guard) that e7ea20d1 does not have.", ""]
for tag, name in (("FIXED", "suite_test_v8f_ego_dagger_compose"), ("e7ea20d1 (old code, new tests)", "red_on_old")):
    for p in glob.glob(f"{W}/tmp/bt_{name}/run*/*box2*/summary.json"):
        s = json.load(open(p, encoding="utf-8"))
        out.append(f"* run-level (box-2 shape: equal seeds 0/0, p 0.1/0.3, vmax 8, batch 64, 200 steps), {tag}: ego_perturb_n / ego_perturb_eligible = {s['ego_perturb_n']} / {s['ego_perturb_eligible']} = "
                   f"{s['ego_perturb_n'] / s['ego_perturb_eligible']:.4f}; dagger_n / dagger_eligible = {s['dagger_n']} / {s['dagger_eligible']} = {s['dagger_n'] / s['dagger_eligible']:.4f}; "
                   f"levers.ego_perturb_stream = {s['levers'].get('ego_perturb_stream')}  (`{os.path.basename(os.path.dirname(os.path.dirname(os.path.dirname(p))))}`)")
        shutil.copyfile(p, f"{D}/logs/summary_box2_{'fixed' if tag == 'FIXED' else 'old'}.json")
out.append("")

# ---- suites
out += ["## 3. Suites (the fixed tree), one file at a time", "", "| file | result | failed |", "|---|---|---|"]
for s in SUITES:
    summ, failed, _ = summarize(f"suite_{s}")
    out.append(f"| {s} | {summ if summ else 'NOT RUN'} | {', '.join(x.split('::')[-1] for x in failed) or '-'} |")
out.append("")

# ---- mutation table
out += ["## 4. Mutation proof (the changed test file must go RED on each mutant)", ""]
mp = f"{D}/mutation.txt"
out.append("```")
out.append(read(mp).strip() if os.path.exists(mp) else "mutation.txt NOT WRITTEN")
out += ["```", ""]
out += ["Rows `M17a`-`M17h` are new in this change; `M17a` (stage does not set the stream) and `M17b` (stream set, gated and recorded, but `_seed_of` ignores it) are the \"stream separation removed\" mutants "
        "and are killed by the BEHAVIOURAL tests (the draws), not only by the record or the gate. `M01`-`M16` are the previous build's 19 mutants, re-run on the fixed tree (M16's anchor moved with the checkpoint line).", ""]

# ---- sha256
out += ["## 5. sha256 of the changed files", "", "```", "fixed (stage/):", *sums, "", "base (e7ea20d1):", *base_sums, "", f"CR bytes in the staged files (LF-only expected): {crlf}", "```", ""]
open(f"{D}/RESULTS.md", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

# ---- logs
for f in glob.glob(f"{L}/*.log") + glob.glob(f"{L}/*.out") + glob.glob(f"{L}/*.progress") + glob.glob(f"{L}/*.done"):
    shutil.copyfile(f, f"{D}/logs/{os.path.basename(f)}")
for f in ("run_mutations.py", "assemble.py", "run_k.sh", "pipe_suites.sh", "pipe_mut.sh", "pipe_final.sh", "dry_anchors.py"):
    os.makedirs(f"{D}/tools", exist_ok=True)
    shutil.copyfile(f"{W}/tmp/{f}", f"{D}/tools/{f}")
print("assembled")
