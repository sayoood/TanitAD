def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    # ---- 0. the DAG template really is the source of the installed DAG chain (so editing it edits what ran)
    dag_in = (DAGQ / "chain_v8f_dag.sh.in").read_text(encoding="utf-8").replace("\r\n", "\n")
    orc = (SHIP / "chain_v8f_orc.sh").read_text(encoding="utf-8")
    m = re.findall(r"^CKPT_SHA=\(.*\)\s*$", orc, flags=re.M)
    assert len(m) == 1
    rebuilt = dag_in.replace("@@CKPT_SHA@@", m[0].strip()).encode("utf-8")
    installed = (SHIP / "chain_v8f_dag.sh").read_bytes()
    if rebuilt != installed:
        sys.exit("the DAG template + the ORC CKPT_SHA line does not reproduce the installed chain_v8f_dag.sh: the template is not the source of what ran")
    # ---- 1. the DAG checkpoint / argv / summary hashes, COPIED from SHA256SUMS.txt
    S = [dag_sums(0), dag_sums(1)]
    ck = "CKPT_SHA=(" + " ".join(s["ckpt_last.pt"] for s in S) + ")      # DAG_s0 / DAG_s1 ckpt_last.pt\nARGV_SHA=(" + " ".join(s["argv.json"] for s in S) + ")      # DAG_s0 / DAG_s1 argv.json\nSUMM_SHA=(" + " ".join(s["summary.json"] for s in S) + ")      # DAG_s0 / DAG_s1 summary.json"
    # ---- 2. the export list
    clo = json.loads((HERE / "export_closure.json").read_text(encoding="utf-8"))
    exp = export_block(clo["files"], [(d["path"], d["opened_by"], d["why"]) for d in clo["data_reads"]])
    tmpl = build_template()
    assert tmpl.count("@@CKPT_SHA@@") == 1 and tmpl.count("@@EXPORT@@") == 1
    (OUT / "chain_v8f_dag2.sh.in").write_bytes(lf(tmpl))
    final = tmpl.replace("@@CKPT_SHA@@", ck).replace("@@EXPORT@@", exp)
    (OUT / "chain_v8f_dag2.sh").write_bytes(lf(final))
    (OUT / "v8f_dag2_chain_checks.py").write_bytes(lf(build_checks()))
    (OUT / "gate_dag2_assert.py").write_bytes(lf(build_assert()))
    guard, cmd, wake = build_misc()
    (OUT / "v8f_guard_dag2.sh").write_bytes(lf(guard))
    (OUT / "run_chain_v8f_dag2.cmd").write_bytes(cmd.encode("utf-8"))
    (OUT / "wake_v8fdag2.sh").write_bytes(lf(wake))
    print("wrote", sorted(p.name for p in OUT.glob("*")))
    print("CKPT_SHA", [s["ckpt_last.pt"][:12] for s in S], "ARGV_SHA", [s["argv.json"][:12] for s in S], "SUMM_SHA", [s["summary.json"][:12] for s in S])
    print("export:", len(clo["files"]), "py files +", len(clo["data_reads"]), "data paths")
    return 0


