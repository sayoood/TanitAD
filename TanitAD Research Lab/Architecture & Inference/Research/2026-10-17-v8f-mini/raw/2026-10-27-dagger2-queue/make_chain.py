def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def lf(text: str) -> bytes:
    return text.replace("\r\n", "\n").encode("utf-8")


class Edit:
    def __init__(self, text: str, name: str):
        self.t, self.name, self.log = text, name, []

    def rep(self, old: str, new: str, n: int = 1):
        c = self.t.count(old)
        if c != n:
            sys.exit(f"{self.name}: expected {n} x {old[:90]!r}, found {c}")
        self.t = self.t.replace(old, new)
        self.log.append((n, old[:60]))
        return self

    def sub_all(self, old: str, new: str):
        """every occurrence (count >= 1); the count is recorded."""
        c = self.t.count(old)
        if c < 1:
            sys.exit(f"{self.name}: {old[:90]!r} not found")
        self.t = self.t.replace(old, new)
        self.log.append((c, old[:60]))
        return self


def dag_sums(seed: int) -> dict:
    out = {}
    for line in (DAGART / f"M2b_s{seed}_dag" / "SHA256SUMS.txt").read_text(encoding="utf-8").splitlines():
        h, n = line.split(" ", 1)
        out[n.strip().lstrip("*")] = h
    return out


