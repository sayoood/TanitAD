"""Collect the logs, the counts and the mutation table into the deliverable dir (RESULTS.md), refresh stage/ + diff.patch + SHA256SUMS."""
import glob
import hashlib
import os
import re
import shutil
import subprocess

L = "F:/TanitAD-scratch/compose_tmp/logs"
D = "E:/Projects/TanitAD-artifacts/dagland/ego_dagger_compose"
SUITES = ["test_v8f_ego_dagger_compose", "test_v8f_ego_perturb", "test_v8f_dagger_train", "test_v8f_dagger", "test_v8f_init_ckpt_o_interface", "test_launch_gate_v8f", "test_v8f_orc_chain"]
os.makedirs(f"{D}/logs", exist_ok=True)
subprocess.run(["C:/Program Files/Git/bin/bash.exe", "F:/TanitAD-scratch/compose_tmp/stage.sh"], capture_output=True)
out = ["# RESULTS (generated by assemble.py from the logs in ./logs)", "", "Base: tip `66b6c80e05f4a13cd49a73be79bf7d24c251e451`. CPU only (`CUDA_VISIBLE_DEVICES=-1`), torch 2.11.0+cu128, one pytest file at a time, `python -m pytest stack/tests/<file>` from the tree root.", "",
       "## Suites (the changed tree)", "", "| file | result | failed |", "|---|---|---|"]
for s in SUITES:
    f = f"{L}/suite_{s}.log"
    if not os.path.exists(f):
        out.append(f"| {s} | NOT RUN | |")
        continue
    t = open(f, encoding="utf-8", errors="replace").read()
    last = [l for l in t.strip().splitlines() if re.search(r" (passed|failed|skipped|error)", l)]
    failed = re.findall(r"^(?:FAILED|ERROR) (\S+)", t, re.M)
    out.append(f"| {s} | {last[-1].strip() if last else 'NO SUMMARY LINE (killed?)'} | {', '.join(x.split('::')[-1] for x in failed) or '-'} |")
    shutil.copy(f, f"{D}/logs/suite_{s}.log")
out += ["", "## Mutation proof", ""]
mp = f"{D}/mutation.txt"
out.append(open(mp, encoding="utf-8").read() if os.path.exists(mp) else "mutation.txt NOT WRITTEN")
out += ["", "## sha256 of the changed files (`stage/`)", "", "```", open(f"{D}/SHA256SUMS.txt").read().strip(), "```", "",
        "Unmodified tip files (the golden was written by these, in `compose_pristine`): `v8f_mini_train.py` 30819a6fb947b2f4..., `v8f_mini_data.py` 0e4a8cea43853242...", ""]
for f in glob.glob(f"{L}/*.log") + glob.glob(f"{L}/*.out") + glob.glob(f"{L}/*progress*.txt"):
    shutil.copy(f, f"{D}/logs/{os.path.basename(f)}")
open(f"{D}/RESULTS.md", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("assembled")
