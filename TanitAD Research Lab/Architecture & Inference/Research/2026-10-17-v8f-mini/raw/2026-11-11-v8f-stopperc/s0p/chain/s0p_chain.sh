#!/usr/bin/env bash
# s0p_chain.sh -- the S0-P waiter chain (card PREREG_V8F_STOPPERC.md section 8; AMENDMENT_1_S0.md, AMENDMENT_2_S0P.md; ../README_S0P.md).  Detached bash on the dev box:
#   1 wait for the SLOWWM chain to end (DONE.txt "ZZ SLOWWM-DONE", or a non-empty STOP.txt whose head does not end in " rc=12") AND the shared busy marker to be absent; poll 5 min, give up after 72 h (STOP, rc 12)
#   2 claim C:/Users/Admin/box2_ship/BOX2_BUSY.txt with noclobber ("s0p chain <pid> <time>"); release on EXIT only if it still holds OUR mark, by mv into busy_aside/
#   3 ship s0p_lib.py + s0p_extract_train.py to D:\tanitad\stopperc\s0p\ (sha256 verified on box 2); pre-flight: v8f_t1_eval.py etc. exist, then a --dry-run job (pool + sample counts; its own asserts must pass)
#   4 K=4 shards, one at a time: disk check (box 2 D: >= shard + 1 GB; dev C: >= 8 GB after), detached extraction via launch.ps1, wait for its done/fail marker, pull every file with sha256 verify (3 attempts) to
#     C:/Users/Admin/s0p_pull/shard_<i>/, verify against the shard's own MANIFEST.sha256 + meta + array shapes, THEN delete that shard's box-2 copy (verified pulled copy, re-creatable from the seed; path + size logged)
#   5 release the busy marker (box 2 is then free), then s0p_fit.py all on the dev box, CPU only (CUDA_VISIBLE_DEVICES=-1 OMP_NUM_THREADS=2); the eval npz is read only; nothing is written to F:
# Sentinels in their OWN files, never in the chain log: $STATE/DONE.txt ("ZZ S0P-DONE ..."), $STATE/STOP.txt ("ZZ S0P-STOP <stage> <reason> rc=<n>").
# rc: 2 standing STOP/state collision; 4 dry-run refused; 5 job or transfer failed; 6 disk-low; 7 pulled copy differs; 8 package incomplete / transport / test hook in a real run; 9 fit failed; 11 timeout or unreadable probe; 12 predecessor not ended / box busy.
# Resume: after a STOP is inspected, rerun with S0P_RESUME=1: the STOP is renamed (never deleted); shards already pulled AND verified (done/shard_<i>.done) are skipped; a shard whose box-2 job still runs (RUN_SH<i>.txt without done/fail marker)
# is WAITED on, never launched a second time.
# Launch (do NOT start from here):  see launch.cmd (generated by s0p_chain_tool.py mklaunch) or:  S0P_SSH=$(cygpath -m "$(command -v ssh)") S0P_SFTP=$(cygpath -m "$(command -v sftp)") bash s0p_chain.sh
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; HERE="$(cygpath -m "$HERE" 2>/dev/null || echo "$HERE")"
export S0P_STATE="${S0P_STATE:-C:/Users/Admin/s0p_state}"; STATE="$S0P_STATE"
PYV="${S0P_PY:-C:/Users/Admin/venvs/tanitad/Scripts/python.exe}"; export S0P_PY="$PYV"
PULL="${S0P_PULL:-C:/Users/Admin/s0p_pull}"; WORK="${S0P_WORK:-C:/Users/Admin/s0p_work}"
EVAL_NPZ="${S0P_EVAL:-F:/TanitAD-scratch/stopperc_s0p/s0p_eval.npz}"; RESULT="${S0P_RESULT:-$STATE/RESULT_S0P.json}"
BUSY_DEV="${S0P_BUSY_DEV:-C:/Users/Admin/box2_ship/BOX2_BUSY.txt}"; ASIDE_DEV="${S0P_ASIDE_DEV:-C:/Users/Admin/box2_ship/busy_aside}"
PRED_STATE_DEV="${S0P_PRED_STATE:-C:/Users/Admin/slowwm_state}"
K="${S0P_K:-4}"; N_POS="${S0P_EXPECT_NPOS:-4000}"; N_NEG="${S0P_EXPECT_NNEG:-12000}"
SHARD_BYTES="${S0P_SHARD_BYTES:-900000000}"; B2_EXTRA_BYTES=1000000000; C_FLOOR_MB=8192            # shard ~0.85 GB ESTIMATED (README_S0P 3.3 GB / 4), 0.9 GB asked; +1 GB headroom on box 2; C: stays >= 8 GB
mkdir -p "$STATE/done" || exit 2
log() { echo "[$(date '+%F %T')] $*" | tee -a "$STATE/chain.log"; }
for other in C:/Users/Admin/slowwm_state C:/Users/Admin/stopbal_state C:/Users/Admin/stopbal_dose2_state "$PRED_STATE_DEV"; do
  [ "$(cygpath -u "$STATE" 2>/dev/null || echo "$STATE")" != "$(cygpath -u "$other" 2>/dev/null || echo "$other")" ] || { echo "REFUSED: S0P_STATE $STATE collides with $other" >&2; exit 2; }
done
refuse_early() { echo "ZZ S0P-STOP start $1 rc=$2" > "$STATE/STOP.txt"; echo "REFUSED: $1" >&2; exit "$2"; }
# test hooks exist only in test mode: a real run (S0P_DRY != 1) carrying one is refused
if [ "${S0P_DRY:-0}" != 1 ]; then
  for h in S0P_FAKE_C_FREE_MB S0P_FIT_SCRIPT S0P_EXPECT_NPOS S0P_EXPECT_NNEG S0P_SHARD_BYTES S0P_SRC S0P_K; do [ -z "${!h:-}" ] || refuse_early "test-hook-in-real-run ($h is set without S0P_DRY=1)" 8; done
fi
case "$K" in ''|*[!0-9]*) refuse_early "bad-K ($K)" 8;; esac
[ "$K" -ge 1 ] || refuse_early "bad-K ($K)" 8
( source "$HERE/s0p_common.sh" ) > /dev/null 2> "$STATE/transport.err" || refuse_early "transport-not-fail-closed ($(tr '\n' ' ' < "$STATE/transport.err" | head -c 300))" 16
if [ -e "$STATE/STOP.txt" ] && [ "${S0P_RESUME:-0}" != "1" ]; then echo "REFUSED: $STATE/STOP.txt exists ($(cat "$STATE/STOP.txt")); inspect, then rerun with S0P_RESUME=1" >&2; exit 2; fi
[ "${S0P_RESUME:-0}" = "1" ] && [ -e "$STATE/STOP.txt" ] && mv "$STATE/STOP.txt" "$STATE/STOP.$(date +%Y%m%d_%H%M%S).txt"
source "$HERE/s0p_common.sh"
for f in s0p_lib.py s0p_extract_train.py s0p_fit.py; do [ -e "$S0P_DIR/$f" ] || refuse_early "package-incomplete ($f missing in $S0P_DIR)" 8; done
[ -e "$TOOL" ] || refuse_early "package-incomplete (s0p_chain_tool.py)" 8
mkdir -p "$ASIDE_DEV" "$PULL" "$WORK" || refuse_early "cannot-create-dirs" 8
[ -n "${S0P_FIT_SCRIPT:-}" ] && FIT="$S0P_FIT_SCRIPT" || FIT="$S0P_DIR/s0p_fit.py"

OWN_MARK=""
release_box() { if [ -n "$OWN_MARK" ] && [ -e "$BUSY_DEV" ] && [ "$(cat "$BUSY_DEV" 2>/dev/null)" = "$OWN_MARK" ]; then mv "$BUSY_DEV" "$ASIDE_DEV/BOX2_BUSY.s0p.$(date +%Y%m%d_%H%M%S).txt"; OWN_MARK=""; fi; }
trap 'release_box' EXIT
stop() {                   # stop <stage> <reason> <rc>
  local detail=""; [ -s "$STATE/stage_detail.txt" ] && detail=" :: $(tr '\r\n' '  ' < "$STATE/stage_detail.txt" | head -c 500)"
  echo "ZZ S0P-STOP $1 $2 rc=$3$detail" > "$STATE/STOP.txt"; log "stop at stage $1: $2 (rc $3)"; release_box; exit "$3"
}
fail() { printf '%s\n' "$S0P_STAGE: $3" | head -c 600 > "$STATE/stage_detail.txt"; stop "$S0P_STAGE" "$2" "$1"; }   # fail <rc> <reason> <detail>

# ------------------------------------------------------------------------------------------------ which shards still need the box
shard_pulled() { [ -e "$STATE/done/shard_$1.done" ] && [ -d "$PULL/shard_$1" ]; }
NEED_BOX=0; for ((i=0; i<K; i++)); do shard_pulled "$i" || NEED_BOX=1; done
[ -e "$STATE/done/pre.done" ] || NEED_BOX=1

# ------------------------------------------------------------------------------------------------ 1 wait, 2 claim
pred_state() {   # DONE | STOP | STOP-BUSY | RUNNING   (the rule of dose2_chain.sh / slowwm_chain.sh)
  local f="$PRED_STATE_DEV/STOP.txt" head1
  if [ -s "$f" ]; then
    head1="$(head -n 1 "$f" | sed 's/ :: .*//')"
    if printf '%s' "$head1" | grep -Eq ' rc=12 *$'; then echo STOP-BUSY; else echo STOP; fi; return
  fi
  if [ -s "$PRED_STATE_DEV/DONE.txt" ] && head -c 40 "$PRED_STATE_DEV/DONE.txt" | grep -q '^ZZ SLOWWM-DONE'; then echo DONE; return; fi
  echo RUNNING
}
if [ "$NEED_BOX" = 1 ]; then
  # our own stale marker (a killed chain never ran its EXIT trap): moved aside under S0P_RESUME=1 only if its pid is gone
  if [ "${S0P_RESUME:-0}" = 1 ] && [ -e "$BUSY_DEV" ] && head -c 10 "$BUSY_DEV" | grep -q '^s0p chain '; then
    opid="$(awk '{print $3}' "$BUSY_DEV")"
    if ! ps -p "$opid" > /dev/null 2>&1; then mv "$BUSY_DEV" "$ASIDE_DEV/BOX2_BUSY.s0p_stale.$(date +%Y%m%d_%H%M%S).txt"; log "moved aside our own stale busy marker (pid $opid gone)"; fi
  fi
  n=0; while :; do
    ps_="$(pred_state)"
    if { [ "$ps_" = DONE ] || [ "$ps_" = STOP ]; } && [ ! -e "$BUSY_DEV" ]; then log "the SLOWWM chain ended ($ps_)"; break; fi
    [ "$n" -lt "${S0P_WAIT_POLLS:-864}" ] || refuse_early "predecessor-not-ended (no SLOWWM DONE and no non-busy SLOWWM STOP in $PRED_STATE_DEV, or $BUSY_DEV exists, after $n polls; last state $ps_)" 12
    n=$((n+1)); log "waiting for the SLOWWM chain to end (poll $n, state $ps_)"; sleep "${S0P_WAIT_POLL_S:-300}"
  done
  if ! ( set -o noclobber; echo "s0p chain $$ $(date '+%F %T')" > "$BUSY_DEV" ) 2>/dev/null; then echo "REFUSED: $BUSY_DEV exists (box 2 is busy)" >&2; exit 12; fi
  OWN_MARK="$(cat "$BUSY_DEV")"
fi

# ------------------------------------------------------------------------------------------------ 3 ship + pre-flight + dry run
S0P_STAGE=pre
pre() {
  local f gid out r why
  b2_mkdir "$B2_S0P" "$B2_OUT" "$B2_MD" "$(dirname "$B2_OUT")"
  for f in s0p_lib.py s0p_extract_train.py; do put_verified "$S0P_DIR/$f" "$B2_S0P/$f" || fail 5 job-or-transfer-failed "put $f: sha256 on box 2 differs from the dev box's"; done
  say "shipped s0p_lib.py + s0p_extract_train.py, sha256 verified on box 2"
  for f in "D:/tanitad/repo/stack/scripts/v8f_t1_eval.py" "D:/tanitad/venv/Scripts/python.exe" "D:/tanitad/runs/v8f_mini_full/join_train.npz" "D:/tanitad/cache_full/native_tracks.pt" "D:/tanitad/cache_full/train/clips" "D:/tanitad/cache_full/eval/manifest.jsonl" "D:/tanitad/launch.ps1"; do
    b2_exists "$f" || fail 4 preflight-refused "$f is missing on box 2"
  done
  say "pre-flight inputs exist on box 2 (v8f_t1_eval.py, venv python, join, tracks, train clips, eval manifest, launch.ps1)"
  gid="$(date +%Y%m%d_%H%M%S)"; out="$STATE/jobs"; mkdir -p "$out"
  "$PY" -I "$TOOL" mkjob --mode dry --gid "$gid" --out "$out/dry.$gid.cmd" || fail 8 package-incomplete "could not render the dry-run job"
  put_verified "$out/dry.$gid.cmd" "$B2_MD/dry.cmd" || fail 5 job-or-transfer-failed "put dry.cmd"
  b2_launch "$B2_MD/dry.cmd" "$B2_MD/dry.log" > /dev/null
  r="$(b2_wait "$B2_MD/DRY_$gid.done" "$B2_MD/DRY_$gid.fail" "${S0P_POLLS_DRY:-60}")"; say "dry-run marker=$r"
  [ "$r" != TIMEOUT ] || fail 11 box2-timeout-or-unreadable "the dry-run job did not finish ($B2_MD/dry.log)"
  b2_cat "$B2_MD/dry.log" > "$STATE/dry.log"
  [ "$r" = DONE ] || fail 4 dry-run-refused "the --dry-run job failed: $(tail -c 300 "$STATE/dry.log" | tr '\r\n' '  ')"
  "$PY" -I "$TOOL" check-dry --log "$STATE/dry.log" --n-pos "$N_POS" --n-neg "$N_NEG" > "$STATE/sample_sha.txt" 2> "$STATE/stage_detail.txt" || fail 4 dry-run-refused "dry-run asserts not shown in its log: $(cat "$STATE/stage_detail.txt")"
  rm -f "$STATE/stage_detail.txt"; say "dry run ok: pool equals the banked prevalence, clips disjoint, sample $(cat "$STATE/sample_sha.txt")"
}
if [ -e "$STATE/done/pre.done" ]; then log "skip pre (done)"; else log "start pre"; pre; echo "pre $(date '+%F %T') sample=$(cat "$STATE/sample_sha.txt")" > "$STATE/done/pre.done"; log "done pre"; fi
SAMPLE_SHA="$(cat "$STATE/sample_sha.txt")"

# ------------------------------------------------------------------------------------------------ 4 shards
shard() {
  local i="$1" RUNF="$B2_MD/RUN_SH$1.txt" SD="$B2_OUT/shard_$1" gid r f free need cmb d bytes names
  S0P_STAGE="shard$i"
  if shard_pulled "$i"; then log "skip shard $i (pulled and verified)"; return 0; fi
  log "start shard $i"
  rm -rf "${PULL:?}/shard_$i" "${PULL:?}/.partial_$i"                  # an unverified local copy (no done marker): its box copy still exists, so it is re-pulled
  gid=""
  if b2_exists "$RUNF"; then                                           # a job of this shard was launched earlier: NEVER start a second one while it may run
    gid="$(b2_cat "$RUNF" | head -n 1 | tr -d ' ')"; case "$gid" in ''|*[!0-9A-Za-z_]*) fail 11 box2-timeout-or-unreadable "unreadable $RUNF";; esac
    say "shard $i: a job (gid $gid) was launched earlier; waiting for its marker instead of launching another"
  fi
  if [ -z "$gid" ]; then
    free="$(b2_free_bytes)"; case "$free" in ''|*[!0-9]*) fail 11 box2-timeout-or-unreadable "box 2 D: free bytes unreadable (got '$free')";; esac
    need=$((SHARD_BYTES + B2_EXTRA_BYTES)); [ "$free" -ge "$need" ] || fail 6 disk-low "box 2 D: free $free bytes < $need (shard + 1 GB)"
    cmb="$(c_free_mb)"; case "$cmb" in ''|*[!0-9]*) fail 11 box2-timeout-or-unreadable "dev C: free unreadable";; esac
    [ "$cmb" -ge $((C_FLOOR_MB + SHARD_BYTES / 1048576)) ] || fail 6 disk-low "dev C: free $cmb MB < $((C_FLOOR_MB + SHARD_BYTES / 1048576)) MB (the pull must leave $C_FLOOR_MB MB)"
    gid="$(date +%Y%m%d_%H%M%S)"; mkdir -p "$STATE/jobs"
    "$PY" -I "$TOOL" mkjob --mode shard --i "$i" --k "$K" --gid "$gid" --out "$STATE/jobs/sh$i.$gid.cmd" || fail 8 package-incomplete "could not render the shard job"
    printf '%s\n' "$gid" > "$STATE/jobs/run_sh$i.txt"
    put_verified "$STATE/jobs/run_sh$i.txt" "$RUNF" || fail 5 job-or-transfer-failed "put RUN_SH$i.txt"
    put_verified "$STATE/jobs/sh$i.$gid.cmd" "$B2_MD/sh$i.cmd" || fail 5 job-or-transfer-failed "put sh$i.cmd"
    b2_launch "$B2_MD/sh$i.cmd" "$B2_MD/sh$i.log" > /dev/null; say "launched shard $i (gid $gid)"
  fi
  r="$(b2_wait "$B2_MD/SH${i}_$gid.done" "$B2_MD/SH${i}_$gid.fail" "${S0P_POLLS_SHARD:-240}")"; say "shard $i marker=$r"
  [ "$r" != TIMEOUT ] || fail 11 box2-timeout-or-unreadable "the shard $i job did not finish within the poll limit; it may still run ($B2_MD/sh$i.log); rerun with S0P_RESUME=1 to keep waiting"
  if [ "$r" != DONE ]; then
    b2_remove_file "$RUNF"                                              # our own marker: a resumed chain launches a new job, which RESUMES from progress.json
    fail 5 job-or-transfer-failed "shard $i job failed: $(b2_cat "$B2_MD/SH${i}_$gid.fail" | head -c 200 | tr '\n' ' ') (log $B2_MD/sh$i.log)"
  fi
  free="$(c_free_mb)"; [ "$free" -ge $((C_FLOOR_MB + SHARD_BYTES / 1048576)) ] || fail 6 disk-low "dev C: free $free MB: the pull of shard $i would leave less than $C_FLOOR_MB MB"
  d="$PULL/.partial_$i"; mkdir -p "$d"
  names="E.npy v40.npy v160.npy mean.npy y.npy clip.npy ws.npy eid.npy meta.json sample.json MANIFEST.sha256"
  for f in $names; do pull_verified "$SD/$f" "$d/$f" || fail 7 pull-sha-mismatch "shard $i file $f: the pulled copy differs from box 2's (3 attempts)"; done
  "$PY" -I "$TOOL" verify-shard --dir "$d" --i "$i" --k "$K" --sample-sha "$SAMPLE_SHA" --n-total $((N_POS + N_NEG)) > "$STATE/shard_$i.verify.json" 2> "$STATE/stage_detail.txt" || fail 7 pull-sha-mismatch "shard $i fails its own manifest/meta check: $(cat "$STATE/stage_detail.txt")"
  rm -f "$STATE/stage_detail.txt"
  mv "$d" "$PULL/shard_$i" || fail 7 pull-sha-mismatch "cannot move the verified shard $i into place"
  echo "shard$i $(date '+%F %T') $(cat "$STATE/shard_$i.verify.json")" > "$STATE/done/shard_$i.done"
  say "shard $i pulled and verified: $(cat "$STATE/shard_$i.verify.json")"
  # the verified pulled copy exists and the shard is re-creatable from the seed: delete box 2's copy by literal path, log path + size
  bytes="$(b2_dir_bytes "$SD")"; case "$bytes" in ''|*[!0-9]*) bytes=unknown;; esac
  b2_remove_dir "$SD"
  b2_exists "$SD" && fail 5 job-or-transfer-failed "box-2 copy $SD still exists after the delete"
  b2_remove_file "$RUNF"
  echo "$(date '+%F %T') deleted box-2 $SD ($bytes bytes): verified pulled copy $PULL/shard_$i, re-creatable from the seed" >> "$STATE/deletions.log"
  log "deleted box-2 $SD ($bytes bytes)"
}
for ((i=0; i<K; i++)); do shard "$i"; done

# ------------------------------------------------------------------------------------------------ 5 release box 2, fit
if [ -n "$OWN_MARK" ]; then   # our own box-2 leftovers: the dry run's sample.json (a copy of data the shards hold) and the then-empty s0p_out dir (rmdir refuses a non-empty one)
  if b2_exists "$B2_OUT/sample.json"; then b2_remove_file "$B2_OUT/sample.json"; echo "$(date '+%F %T') deleted box-2 $B2_OUT/sample.json (dry-run copy of the sample; re-creatable by --dry-run)" >> "$STATE/deletions.log"; fi
  b2_ssh "rmdir $(w "$B2_OUT")" > /dev/null 2>&1
fi
release_box
S0P_STAGE=fit
if [ -e "$STATE/done/fit.done" ] && [ -s "$RESULT" ]; then log "skip fit (done)"; else
  cmb="$(c_free_mb)"; [ "$cmb" -ge "$C_FLOOR_MB" ] || fail 6 disk-low "dev C: free $cmb MB < $C_FLOOR_MB MB before the fit (projections ~0.8 GB)"
  log "start fit (CPU only, 2 threads, ESTIMATED ~2 h)"
  rm -f "$STATE/fit.out"
  ( export CUDA_VISIBLE_DEVICES=-1 OMP_NUM_THREADS=2; "$PYV" "$FIT" all --train "$PULL" --eval "$EVAL_NPZ" --work "$WORK" --out "$RESULT" ) > "$STATE/fit.out" 2>&1; rc=$?
  [ "$rc" -eq 0 ] || fail 9 fit-failed "s0p_fit.py all rc=$rc: $(tail -c 300 "$STATE/fit.out" | tr '\r\n' '  ')"
  [ -s "$RESULT" ] || fail 9 fit-failed "no result file at $RESULT"
  "$PYV" -I -c "import json,sys; d=json.load(open(sys.argv[1], encoding='utf-8')); assert isinstance(d, dict) and d" "$RESULT" || fail 9 fit-failed "the result file is not a JSON object"
  echo "fit $(date '+%F %T')" > "$STATE/done/fit.done"; log "done fit"
fi
echo "ZZ S0P-DONE $(date '+%F %T') result=$RESULT sha256=$(sha256sum "$RESULT" | cut -d' ' -f1)" > "$STATE/DONE.txt"
log "chain complete"
exit 0
