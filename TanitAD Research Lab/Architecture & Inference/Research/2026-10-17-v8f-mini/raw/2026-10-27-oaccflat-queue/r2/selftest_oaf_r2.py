def run_real(mod, mut=None, mode="check"):
    d = SCR / "w" / "real_case"
    d.mkdir(parents=True, exist_ok=True)
    sc = copy.deepcopy(REAL_SC)
    if mut:
        mut(sc)
    p = d / "sc.json"
    p.write_text(json.dumps(sc), encoding="utf-8")
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        rc = mod.main([mode] + [str(x) for x in real_args(p, d)])
    return rc, buf.getvalue()


