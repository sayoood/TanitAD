# ================================================================================================ RC. the aside, executed
def digest(root: Path) -> dict:
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(root.rglob("*")) if p.is_file()}


def lib_bytes(snippet, env=None):
    p = subprocess.run([BASH, "-c", f"source '{posix(R2SHIP / 'oaf_r2_lib.sh')}'; {snippet}"], capture_output=True, stdin=subprocess.DEVNULL, env={**os.environ, **(env or {})})
    return p.returncode, p.stdout, p.stderr


def run_job(rs: Path):
    rc, job, err = lib_bytes('r2_aside_job_text "$RS_WIN"', {"RS_WIN": str(rs)})
    assert rc == 0, err
    jf = rs.parent / "r2aside.cmd"
    jf.write_bytes(job)
    p = subprocess.run(["cmd", "/c", str(jf)], capture_output=True, stdin=subprocess.DEVNULL, timeout=120)
    return p.returncode, p.stdout.decode("utf-8", "replace").replace("\r", ""), job


