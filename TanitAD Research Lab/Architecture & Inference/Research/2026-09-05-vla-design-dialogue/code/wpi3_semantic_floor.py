print("  CONTROLS %s" % ("PASS" if ctrl_ok else "FAIL -- results are not readable"))


def ep_boot(sc_a, sc_b, y, iters=2000, seed=0):
    """PAIRED episode-cluster bootstrap on the AUC difference (a - b)."""
    r = np.random.default_rng(seed)
    idx = {e: np.where(E == e)[0] for e in UE}
    d = []
    for _ in range(iters):
        pick = np.concatenate([idx[UE[i]] for i in r.integers(0, len(UE), len(UE))])
        if y[pick].sum() in (0, len(pick)):
            continue
        v = auc(sc_a[pick], y[pick]) - auc(sc_b[pick], y[pick])
        if v == v:
            d.append(v)
    d = np.array(d)
    if not len(d):
        return float("nan"), float("nan")
    return float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))


