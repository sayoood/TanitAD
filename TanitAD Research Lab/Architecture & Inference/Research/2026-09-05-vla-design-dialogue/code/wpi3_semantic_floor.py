# ------------------------------------------------------------- estimator ----
def auc(s, y):
    """Rank AUC with TIES AVERAGED. A constant predictor MUST return 0.5000."""
    p, n = y.sum(), (1 - y).sum()
    if p == 0 or n == 0:
        return float("nan")
    order = np.argsort(s, kind="mergesort")
    r = np.empty(len(s), float)
    r[order] = np.arange(1, len(s) + 1, dtype=float)
    ss = s[order]
    i = 0
    while i < len(ss):
        j = i
        while j + 1 < len(ss) and ss[j + 1] == ss[i]:
            j += 1
        if j > i:
            r[order[i:j + 1]] = r[order[i:j + 1]].mean()
        i = j + 1
    return float((r[y == 1].sum() - p * (p + 1) / 2) / (p * n))


LAMBDAS = (1e-1, 1.0, 10.0, 1e2, 1e3, 1e4, 1e5, 1e6)


class FoldCache:
    """Leave-one-EPISODE-out ridge with the label-independent algebra cached.

    Ridge is solved in the DUAL (Gram) form -- w = A^T (A A^T + lam I)^-1 y --
    which is algebraically identical to the primal and costs n^3 rather than
    d^3, so no arm is penalised for being wide (d ranges 72 to 24,576 here).
    The eigendecomposition of A A^T depends only on the FEATURES, so it is
    computed once per (arm, fold) and reused for every target and every
    permutation. That is what makes a 200-permutation null affordable.

    Held-out scores are standardised by the mean/sd of the fold's own TRAINING
    predictions -- statistics that never touch the held-out episode, so the
    calibration cannot leak, while removing the fold-offset channel that let
    v1's pooled AUC read episode identity (DEFECT 9).
    ⭐ EVERY per-lambda product is pushed into the eigenbasis at BUILD time.
    With `G = Q diag(ev) Q^T` and `alpha = Q (Q^T y)/(ev+lam)`:
        train predictions  G alpha   = Q (ev * ah)
        held-out scores    BA alpha  = (BA Q) ah
        inner-val scores   Xin alpha = (Xin Q2) ah2
    so `BAQ = BA @ Q` and `XinQ2 = Xin @ Q2` are cached and a whole lambda sweep
    costs elementwise scales plus one small mat-vec. Naively this panel is ~5 h;
    cached it is ~30 min, which is the difference between running the
    permutation null and quietly dropping it.
    """

    def __init__(self, F):
        self.folds = []
        for ep in UE:
            te = E == ep
            A = F[~te]
            B = F[te]
            mu, sd = A.mean(0), A.std(0) + 1e-8
            A, B = (A - mu) / sd, (B - mu) / sd
            ev, Q = np.linalg.eigh(A @ A.T)
            inner = np.arange(len(A)) % 4 != 0
            Ai = A[inner]
            ev2, Q2 = np.linalg.eigh(Ai @ Ai.T)
            self.folds.append({
                "te": te, "tr": ~te, "ev": ev, "Q": Q,
                "BAQ": (B @ A.T) @ Q, "inner": inner, "ev2": ev2, "Q2": Q2,
                "XinQ2": (A[~inner] @ Ai.T) @ Q2})
            del A, B, Ai

    def scores(self, y):
        out = np.zeros(len(y))
        for f in self.folds:
            ytr = y[f["tr"]]
            yi = ytr[f["inner"]]
            yo = ytr[~f["inner"]]
            Q2ty = f["Q2"].T @ yi
            best, bl = -np.inf, LAMBDAS[-1]
            for lam in LAMBDAS:
                a = auc(f["XinQ2"] @ (Q2ty / (f["ev2"] + lam)), yo)
                if a == a and a > best:
                    best, bl = a, lam
            ah = (f["Q"].T @ ytr) / (f["ev"] + bl)
            s_tr = f["Q"] @ (f["ev"] * ah)          # == G alpha, one mat-vec
            out[f["te"]] = (f["BAQ"] @ ah - s_tr.mean()) / (s_tr.std() + 1e-12)
        return out


def perm_labels(y, kind, r):
    if kind == "global":
        z = y.copy()
        r.shuffle(z)
        return z
    z = y.copy()                                   # WITHIN each episode
    for ep in UE:
        m = E == ep
        v = z[m]
        r.shuffle(v)
        z[m] = v
    return z


