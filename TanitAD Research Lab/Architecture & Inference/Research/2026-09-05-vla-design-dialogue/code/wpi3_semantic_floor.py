# ⛔⛔ THE GATE DEFECT, FIXED. v2 and v3 both required every arm's null mean to
# sit within 0.05 of 0.5000 -- which RE-IMPOSES EXACTLY THE ASSUMPTION A
# PERMUTATION TEST EXISTS TO AVOID. It printed "CONTROLS FAIL" on two sound
# panels (v2: the trunk's within-null 0.5786; v3: the pixel arm's 0.6053). The
# whole point of generating the null through the same pipeline is that the
# pipeline's bias is ABSORBED; demanding the null be centred at the theoretical
# value throws that away and turns a working control into a false alarm.
# ⇒ third time in this campaign that a control's DECISION RULE, not the control
#   and not the data, was the defect. The rule now derives from the control's
#   own distribution: the GLOBAL null must be near 0.5 (it permutes across
#   everything, so it genuinely has no structure left to fit), while the
#   WITHIN-episode null is ALLOWED to sit anywhere -- that offset IS the
#   estimator bias the p-value is measuring against.
global_null_ok = all(
    abs(res["vru<60m IN-FOV"]["arms"][a]["null"]["global"]["mean"] - 0.5) < 0.05
    for a in ARMS)
within_null_centres = {a: res["vru<60m IN-FOV"]["arms"][a]["null"]["within"]["mean"]
                       for a in ARMS}
