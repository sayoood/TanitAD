def auc(s, y):
    p, n = y.sum(), (1 - y).sum()
    if p == 0 or n == 0:
        return float("nan")
    o = np.argsort(s, kind="mergesort")
    r = np.empty(len(s), float)
    r[o] = np.arange(1, len(s) + 1, dtype=float)
    ss = s[o]
    i = 0
    while i < len(ss):
        j = i
        while j + 1 < len(ss) and ss[j + 1] == ss[i]:
            j += 1
        if j > i:
            r[o[i:j + 1]] = r[o[i:j + 1]].mean()
        i = j + 1
    return float((r[y == 1].sum() - p * (p + 1) / 2) / (p * n))


LAMBDAS = (1e-1, 1.0, 10.0, 1e2, 1e3, 1e4, 1e5, 1e6)
GAMMAS = (0.25, 1.0, 4.0)          # x 1/d ; swept INSIDE the fold, never on the score split


def _sq(A, B):
    return (np.einsum("ij,ij->i", A, A)[:, None] + np.einsum("ij,ij->i", B, B)[None, :]
            - 2.0 * (A @ B.T))


class FoldCache:
    """LOEO dual ridge; `kern` selects a linear or RBF Gram.

    The dual solve is indifferent to where the Gram came from, so the RBF arm
    reuses the exact folds, lambda sweep, calibration and permutation machinery
    the linear arms use -- no second estimator to validate.
    """

    def __init__(self, F, kern):
        self.folds = []
        for ep in UE:
            te = E == ep
            A, B = F[~te], F[te]
            mu, sd = A.mean(0), A.std(0) + 1e-8
            A, B = (A - mu) / sd, (B - mu) / sd
            inner = np.arange(len(A)) % 4 != 0
            gammas = [None] if kern == "linear" else [g / A.shape[1] for g in GAMMAS]
            # ⭐ THE SQUARED-DISTANCE MATRICES DO NOT DEPEND ON GAMMA. Computing
            # them inside the gamma loop repeated an O(n^2 d) product three times
            # per fold -- at d=45,056 that is ~90 s wasted per fold, i.e. hours
            # across the panel. Hoisted: the gamma sweep is now three cheap
            # elementwise exponentials over matrices computed once.
            if kern == "linear":
                sqA = sqB = sqXi = sqGi = None
            else:
                sqA, sqB = _sq(A, A), _sq(B, A)
                sqXi, sqGi = _sq(A[~inner], A[inner]), _sq(A[inner], A[inner])
            per = []
            for gm in gammas:
                if gm is None:
                    G, BA = A @ A.T, B @ A.T
                    Xi, Gi = A[~inner] @ A[inner].T, A[inner] @ A[inner].T
                else:
                    G, BA = np.exp(-gm * sqA), np.exp(-gm * sqB)
                    Xi, Gi = np.exp(-gm * sqXi), np.exp(-gm * sqGi)
                ev, Q = np.linalg.eigh(G)
                ev2, Q2 = np.linalg.eigh(Gi)
                per.append({"ev": ev, "Q": Q, "BAQ": BA @ Q, "ev2": ev2, "Q2": Q2,
                            "XinQ2": Xi @ Q2})
            self.folds.append({"te": te, "tr": ~te, "inner": inner, "per": per})

    def scores(self, y):
        out = np.zeros(len(y))
        for f in self.folds:
            ytr = y[f["tr"]]
            yi, yo = ytr[f["inner"]], ytr[~f["inner"]]
            # ⛔ A DEFAULT THAT IS ALWAYS VALID. If every (gamma, lambda) pair
            # scores NaN -- which happens whenever the fold's inner validation
            # split happens to contain no positives -- a `(-inf, None, None)`
            # seed leaves `c` as None and the solve dies with a TypeError. Worse
            # than dying would be silently skipping the fold, so the seed is the
            # most-regularised candidate: a defined, maximally conservative
            # choice rather than an absent one.
            best = (-np.inf, f["per"][0], LAMBDAS[-1])
            for c in f["per"]:
                Q2ty = c["Q2"].T @ yi
                for lam in LAMBDAS:
                    a = auc(c["XinQ2"] @ (Q2ty / (c["ev2"] + lam)), yo)
                    if a == a and a > best[0]:
                        best = (a, c, lam)
            _, c, lam = best
            ah = (c["Q"].T @ ytr) / (c["ev"] + lam)
            s_tr = c["Q"] @ (c["ev"] * ah)
            out[f["te"]] = (c["BAQ"] @ ah - s_tr.mean()) / (s_tr.std() + 1e-12)
        return out


def perm(y, kind, r):
    z = y.copy()
    if kind == "global":
        r.shuffle(z)
        return z
    for ep in UE:
        m = E == ep
        v = z[m]
        r.shuffle(v)
        z[m] = v
    return z


