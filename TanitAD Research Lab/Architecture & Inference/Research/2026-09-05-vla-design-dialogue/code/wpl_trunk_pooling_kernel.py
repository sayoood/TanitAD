def pooled(grid):
    """Derive a grid from the ONE banked feature map -- never a second forward."""
    t = torch.from_numpy(FMAP)
    return torch.nn.functional.adaptive_avg_pool2d(t, grid).reshape(
        len(t), -1).numpy().astype(np.float64)


