"""refcv8's frozen post-planner RE-TIMING stage -- the RUNTIME side (pure numpy, no torch).

WHAT IT DOES
------------
Keep the planner's PATH exactly and re-time only the PROGRESS along it.  With ``C`` the polyline through (0, 0) and
the plan's points at the instants ``t_k``::

    s_os(t_k)    = cumulative chord arc length of the plan          (L)
    s_prior(t_k) = cumulative chord arc length of the causal prior  (M)   ha0_ext_pose: measured v0, a0, yaw rate at t0
    s'(t_k)      = max( L + (1 - g_k) (M - L), 0 )                  g_k = gain_at(t_k, table)
    p(t_k)       = C(s'(t_k))        linear interpolation along the polyline; beyond its end, along the direction of the
                                     last positive-length segment, anchored at the END vertex

``g == 1`` gives ``s' == L`` bit for bit, i.e. the plan unchanged; ``g == 0`` puts the point at the prior's arc length on
the plan's own path.  Every re-timed point lies ON the plan's polyline (or its final extension ray).

PROVENANCE (PI 2026-10-19, D-R8-SHIP-RETIME + SHIP-R8 AMENDMENT 1, ``Project Steering/GOALS_AND_CLAIMS.md``)
    refcv8 ships with this stage iff SHIP-R8 passes at step 48,852, scored on the DEPLOYED table ``RETIME_DEPLOY`` =
    the frozen TRAIN gains (S2 at 0.5/1.0/1.5/2.0 s, S6 at 3/4/5/6 s as knots), piecewise-linear in time between knots and
    held constant outside them.  The table is ``configs/refcv8_retime_deploy_gains.json`` (+ ``.sha256``), generated by
    ``scripts/build_retime_deploy_table.py`` from the frozen file ``FROZEN_GAINS_RETIME_train.json`` (sha256 b208c9c1...).

THE GEOMETRY IS A PORT, NOT A REWRITE.  ``polyline_geometry`` / ``eval_polyline`` / ``retime_progress`` /
``retime_positions`` / ``prior_arc`` are copied statement for statement from the eval package's reference
``a0k0_headroom_retime_r8.py`` (sha256 842889130005dc108c10f53ad8454f6e9314646ae7bc0488c3519da452d78a67 at the time of the
port) -- the module SHIP-R8 is scored with.  ``tests/test_retime_stage.py`` pins the equivalence on banked windows.

CALLING CONVENTION -- READ BEFORE WIRING (the geometry is GRID-DEPENDENT)
    The polyline passes through (0, 0) and ONLY the plan points handed in.  SHIP-R8 scores two point sets separately:
    S2 = {0.5, 1.0, 1.5, 2.0} s and S6 = {1, 2, 3, 4, 5, 6} s.  Cumulative arc length at ``t_k`` depends only on points
    0..k, so a prefix is consistent, but ``C`` beyond a shorter point set is a straight extension while on a longer set it
    follows the plan's later points; and S6 skips the 0.5 / 1.5 s vertices, so its chords (hence arc lengths at 1 s, 2 s)
    differ from an 8-point call on a curved plan.  A call with the full 8-slot plan is therefore a THIRD function that no
    SHIP-R8 clause scored.  Call it on the SAME instants the verdict was computed on, and pass the prior sampled at those
    same instants.

NOT HERE: the prior.  The prior path is the model's own ``out["residual_prior_path"]`` (the forward emits it, with
``residual_prior_ctrl`` = (a0, kappa0) and ``residual_prior_v`` = v0, all read from the observed pose window at t0), or
``kinematic_prior.prior_path(a0, kappa0, v0, horizons)``.  See :func:`retime_from_forward_out`.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

__all__ = [
    "RetimeStageError", "DEPLOY_TABLE_PATH", "gain_at", "load_gains_table", "load_deploy_table", "polyline_geometry",
    "eval_polyline", "retime_progress", "retime_positions", "prior_arc", "retime_plan", "retime_from_forward_out",
]

#: the deployed table (SHIP-R8 AMENDMENT 1).  Sibling of this package's other frozen configs.
DEPLOY_TABLE_PATH: Path = Path(__file__).resolve().parent / "configs" / "refcv8_retime_deploy_gains.json"


_CRLF = bytes((13, 10))
_LF = bytes((10,))


class RetimeStageError(ValueError):
    """A refusal: a table whose sha does not match its sidecar, a malformed table or a malformed plan/prior pair."""


# ------------------------------------------------------------------------------------------------ the gain table
def _sha256_file(path: Path) -> str:
    """sha256 of the file's bytes with CRLF folded to LF.  The repo is checked out with CRLF on a Windows dev box
    (``core.autocrlf=true``) and LF on a pod; a digest over the raw bytes would then pass on one and REFUSE a faithful copy on
    the other.  The canonical form is LF; a one-character edit still changes it."""
    return hashlib.sha256(Path(path).read_bytes().replace(_CRLF, _LF)).hexdigest()


def _read_sidecar(path: Path) -> str:
    side = Path(str(path) + ".sha256")
    if not side.is_file():
        raise RetimeStageError(f"{path}: no sha256 sidecar {side.name} -- a gains table without a pinned hash is refused")
    tok = side.read_text(encoding="utf-8").strip().split()
    if not tok or len(tok[0]) != 64 or any(c not in "0123456789abcdef" for c in tok[0].lower()):
        raise RetimeStageError(f"{side}: not a sha256 hex digest")
    return tok[0].lower()


def _check_table(knots_s, gains) -> tuple[np.ndarray, np.ndarray]:
    k = np.asarray(knots_s, np.float64)
    g = np.asarray(gains, np.float64)
    if k.ndim != 1 or g.shape != k.shape or k.size < 1:
        raise RetimeStageError(f"knots_s and gains must be equal-length 1-D, non-empty (got {k.shape}, {g.shape})")
    if not (np.isfinite(k).all() and np.isfinite(g).all()):
        raise RetimeStageError("non-finite knot or gain")
    if k.size > 1 and not (np.diff(k) > 0).all():
        raise RetimeStageError("knots_s must be strictly increasing")
    return k, g


def load_gains_table(path, expected_sha256: str | None = None) -> dict:
    """Read a deployed-gains JSON, REFUSING unless its bytes hash to the digest in ``<path>.sha256`` (and to
    ``expected_sha256`` when given).  Returns ``{"knots_s": float64 [K], "gains": float64 [K], "meta": <the file's
    own provenance block>, "sha256": <hex>}``; the table itself is ``{"knots_s": [...], "gains": [...]}`` in the JSON."""
    p = Path(path)
    if not p.is_file():
        raise RetimeStageError(f"{p}: gains table not found")
    want = _read_sidecar(p)
    got = _sha256_file(p)
    if got != want:
        raise RetimeStageError(f"{p}: sha256 {got} != sidecar {want} -- the table was edited or corrupted; refusing")
    if expected_sha256 is not None and got != expected_sha256.lower():
        raise RetimeStageError(f"{p}: sha256 {got} != the pinned {expected_sha256.lower()}; refusing")
    d = json.loads(p.read_text(encoding="utf-8"))
    k, g = _check_table(d["knots_s"], d["gains"])
    return {"knots_s": k, "gains": g, "meta": {kk: vv for kk, vv in d.items() if kk not in ("knots_s", "gains")}, "sha256": got}


def load_deploy_table(expected_sha256: str | None = None) -> dict:
    """The SHIP-R8 ``RETIME_DEPLOY`` table (sha-verified)."""
    return load_gains_table(DEPLOY_TABLE_PATH, expected_sha256)


def gain_at(t_s, table) -> np.ndarray:
    """The gain at instants ``t_s``: piecewise-linear in time between the table's knots, HELD CONSTANT before the first
    and after the last (SHIP-R8 AMENDMENT 1).  ``table`` = a :func:`load_gains_table` result, or any mapping with
    ``knots_s`` / ``gains``.  At a knot the knot's gain is returned exactly."""
    k, g = _check_table(table["knots_s"], table["gains"])
    return np.interp(np.asarray(t_s, np.float64), k, g)


# ------------------------------------------------------------------------------------------------ geometry (PORT)
def polyline_geometry(O) -> dict:
    """The polyline of every window.  Vertices V_0 = (0,0), V_k = O[:, k-1] (k = 1..S); cumulative arc length L [n, S+1]
    (L[:, 0] = 0, L[:, k] = s(t_k)); unit directions u [n, S, 2] (0 on a zero-length segment); u_end [n, 2] = direction of
    the LAST POSITIVE-LENGTH segment, +x if the whole polyline has zero length (fallback [n] flags those windows).
    float64.  Non-finite input fails loud."""
    O = np.asarray(O, np.float64)
    if O.ndim != 3 or O.shape[-1] != 2:
        raise ValueError(f"plans must be [n, S, 2], got {O.shape}")
    if not np.isfinite(O).all():
        raise ValueError("non-finite plan position: the re-timing is undefined")
    n, S, _ = O.shape
    V = np.concatenate([np.zeros((n, 1, 2)), O], axis=1)
    seg = V[:, 1:] - V[:, :-1]
    ln = np.hypot(seg[..., 0], seg[..., 1])
    L = np.concatenate([np.zeros((n, 1)), np.cumsum(ln, axis=1)], axis=1)
    pos = ln > 0
    u = np.where(pos[..., None], seg / np.where(pos, ln, 1.0)[..., None], 0.0)
    last = np.where(pos.any(1), S - 1 - np.argmax(pos[:, ::-1], axis=1), 0)
    u_end = u[np.arange(n), last].copy()
    fb = ~pos.any(1)
    u_end[fb] = (1.0, 0.0)
    return {"V": V, "L": L, "u": u, "u_end": u_end, "fallback": fb}


def eval_polyline(geo: dict, s) -> np.ndarray:
    """C(s): linear interpolation along the polyline at arc length s [n] or [n, m] (s >= 0); at s >= L_S the point is
    V_S + (s - L_S) * u_end (anchored at the END vertex, so s == L_S returns V_S bit for bit).  Returns [n, 2] or
    [n, m, 2] float64."""
    V, L, u, u_end = geo["V"], geo["L"], geo["u"], geo["u_end"]
    s = np.asarray(s, np.float64)
    one = s.ndim == 1
    if one:
        s = s[:, None]
    n, S = s.shape[0], u.shape[1]
    idx = np.zeros(s.shape, np.int64)
    for j in range(1, S):
        idx += (s >= L[:, j:j + 1])
    rows = np.arange(n)[:, None]
    P = V[rows, idx] + (s - L[rows, idx])[..., None] * u[rows, idx]
    beyond = s >= L[:, S:S + 1]
    Pe = V[:, S:S + 1] + (s - L[:, S:S + 1])[..., None] * u_end[:, None, :]
    P = np.where(beyond[..., None], Pe, P)
    return P[:, 0] if one else P


def retime_progress(L, M, Gn) -> np.ndarray:
    """s' = L + (1 - g)(M - L) = s_prior + g (s_os - s_prior), clipped at >= 0.  L, M = s_os, s_prior [n, T]; Gn [n, T]
    or [T].  g == 1 -> s' == L bit for bit."""
    Gn = np.broadcast_to(np.asarray(Gn, np.float64), L.shape)
    return np.maximum(L + (1.0 - Gn) * (M - L), 0.0)


def retime_positions(geoO: dict, M, Gn):
    """Float64 re-timed positions [n, T, 2] and the progress s' [n, T]."""
    L = geoO["L"][:, 1:]
    s = retime_progress(L, M, Gn)
    P = np.empty(s.shape + (2,))
    for k in range(s.shape[1]):
        P[:, k] = eval_polyline(geoO, s[:, k])
    return P, s


def prior_arc(B) -> np.ndarray:
    """s_prior(t_k) = cumulative chord arc length of the prior through (0,0) and its points at the grid instants [n, T]."""
    return polyline_geometry(B)["L"][:, 1:]


# ------------------------------------------------------------------------------------------------ the stage
def retime_plan(plan_xy, prior_xy, t_s, table, *, cast: bool = True) -> np.ndarray:
    """Re-time ``plan_xy`` [..., T, 2] against ``prior_xy`` [..., T, 2] (the causal prior sampled at the SAME T instants
    ``t_s`` [T]) with the gains ``gain_at(t_s, table)``.

    The result has the plan's shape, every point lies on the plan's polyline (or its final extension ray), and ``g == 1``
    everywhere returns the plan unchanged.  ``cast=True`` (the reference's ``retime_apply`` default, and what SHIP-R8
    scored) returns the plan's own floating dtype; ``cast=False`` returns the float64 positions.
    Refuses non-finite input and a plan/prior/instants shape mismatch."""
    plan = np.asarray(plan_xy)
    prior = np.asarray(prior_xy)
    t = np.asarray(t_s, np.float64)
    if plan.ndim < 2 or plan.shape[-1] != 2:
        raise RetimeStageError(f"plan must be [..., T, 2], got {plan.shape}")
    if prior.shape != plan.shape:
        raise RetimeStageError(f"prior {prior.shape} must have the plan's shape {plan.shape} (same instants)")
    T = plan.shape[-2]
    if t.shape != (T,):
        raise RetimeStageError(f"t_s must be [{T}] to match the plan, got {t.shape}")
    if T > 1 and not (np.diff(t) > 0).all():
        raise RetimeStageError("t_s must be strictly increasing")
    if not (np.isfinite(plan).all() and np.isfinite(prior).all()):
        raise RetimeStageError("non-finite plan or prior position: the re-timing is undefined")
    lead = plan.shape[:-2]
    O = plan.reshape(-1, T, 2)
    B = prior.reshape(-1, T, 2)
    g = gain_at(t, table)
    P, _s = retime_positions(polyline_geometry(O), prior_arc(B), g)
    out = P.reshape(lead + (T, 2))
    return out.astype(plan.dtype) if (cast and plan.dtype.kind == "f") else out


def _as_numpy(x):
    if hasattr(x, "detach"):          # torch tensor, duck-typed: this module never imports torch
        x = x.detach().cpu().numpy()
    return np.asarray(x)


def retime_from_forward_out(out: dict, model_t_s, table, slots=None, *, cast: bool = True) -> np.ndarray:
    """The call a consumer of ``RefCModel.forward`` makes: re-time ``out["traj"]`` [B, S, 2] against
    ``out["residual_prior_path"]`` [B, S, 2] -- both emitted at the model's ``anchor_horizons`` -- and return the re-timed
    plan [B, len(slots), 2] as numpy.  ``model_t_s`` [S] = ``np.array(anchor_horizons) * anchor_dt`` (the instants of the
    S model slots); ``slots`` = the indices to use (S2: [0, 1, 2, 3]; S6: [1, 3, 4, 5, 6, 7]); ``None`` = all S (see the
    module docstring: the full 8-slot call is NOT a scored function).  Never mutates ``out`` -- ``out["traj"]`` stays the
    planner's own plan.  Refuses an ``off``-prior build (no ``residual_prior_path`` in ``out``)."""
    if "residual_prior_path" not in out:
        raise RetimeStageError("the forward emitted no `residual_prior_path` (residual_prior='off' build): there is no "
                               "prior to re-time against")
    t_all = np.asarray(model_t_s, np.float64)
    plan, prior = _as_numpy(out["traj"]), _as_numpy(out["residual_prior_path"])
    if plan.ndim != 3 or plan.shape[1] != t_all.shape[0]:
        raise RetimeStageError(f"out['traj'] {plan.shape} does not match model_t_s [{t_all.shape[0]}]")
    idx = list(range(t_all.shape[0])) if slots is None else [int(i) for i in slots]
    return retime_plan(plan[:, idx], prior[:, idx], t_all[idx], table, cast=cast)
