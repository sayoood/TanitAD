def test_the_bank_is_re_indexed_by_clip_name(pack, tmp_path):
    """The bank's `ci` is the GENERATOR's join index; the trainer's join may order the clips otherwise. A bank whose clips are numbered in another order (rotated by one) must give, after the load, the same
    records for the same clips: re-indexing is by NAME."""
    def rotate(arrays, header):
        n = len(header["clips"])
        arrays = {**arrays, "ci": ((arrays["ci"].astype(np.int64) + 1) % n).astype(np.int32)}
        header = copy.deepcopy(header)
        header["clips"] = {str((int(k) + 1) % n): v for k, v in header["clips"].items()}
        return arrays, header
    rotated = clone_bank(pack.bank, tmp_path / "rot", shard_fn=rotate)
    assert not np.array_equal(DG.DaggerBank.load(rotated).a["ci"], DG.DaggerBank.load(pack.bank).a["ci"]), "the control: the stored numbering really differs"
    a, cfg, model, opt, info, dag, J, wins, clips = gate_parts(pack, DAG(pack, 0.1, bank=rotated))
    ref = DG.DaggerBank.load(pack.bank, clip_names=J["clip"])
    assert np.array_equal(dag.bank.ci, ref.ci), "after the load every record points at the trainer's join row of ITS clip"
    assert np.array_equal(dag.bank.candidates(np.array([w[0] for w in wins]), np.array([w[1] for w in wins]))[0], ref.candidates(np.array([w[0] for w in wins]), np.array([w[1] for w in wins]))[0])


