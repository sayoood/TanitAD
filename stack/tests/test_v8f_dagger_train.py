def _swap_rows_hook(monkeypatch, fn):
    orig = DG.swap_rows

    def hooked(batch, rows, rec):
        r = orig(batch, rows, rec)
        return fn(batch, rows, r) or r
    monkeypatch.setattr(DG, "swap_rows", hooked)


