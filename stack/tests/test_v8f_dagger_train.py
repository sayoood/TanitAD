def _pre_swapped(batch, dag, only_first):
    """The batch with the (eligible, selected-at-p1) rows ALREADY holding the swap's values: probing it makes those rows' own ego bit-identical to the 'logged' one."""
    full = dag.apply(batch, dag.PROBE_STEP, p=1.0)
    sel = dag.last["sel"].clone()
    rows = sel.nonzero(as_tuple=True)[0][:1] if only_first else sel.nonzero(as_tuple=True)[0]
    b2 = {k: (v.clone() if torch.is_tensor(v) else v) for k, v in batch.items()}
    b2["lab_s"] = dict(batch["lab_s"])
    b2["lab_s"]["rc"] = batch["lab_s"]["rc"].clone()
    for k in DG.REBUILT:
        b2[k][rows] = full[k][rows]
    b2["lab_s"]["rc"][rows] = full["lab_s"]["rc"][rows]
    return b2, int(rows.numel())


