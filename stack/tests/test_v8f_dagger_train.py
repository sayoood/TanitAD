def _bank_sha(bank):
    """What an arm declares in ``--dagger-bank-sha256`` for ``bank`` (a merged directory or its bank.json): the sha256 of the manifest. Any path that is no file gets a placeholder (the load refuses it before the hash matters)."""
    p = Path(bank)
    p = p / "bank.json" if p.is_dir() else p
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.is_file() else "0" * 64


def DAG(pk, p=0.5, seed=3, bank=None, ck=None, sha=None):
    """The DAG arm's four flags (PREREG section 4: DAG names all four) + the init checkpoint."""
    b = bank or pk.bank
    return ["--init-ckpt", str(ck or pk.ck), "--dagger-p", str(p), "--dagger-bank", str(b), "--dagger-bank-sha256", sha or _bank_sha(b), "--dagger-seed", str(seed)]


def _changed(x, y):
    same = ((x == y) | (torch.isnan(x) & torch.isnan(y))) if x.is_floating_point() else (x == y)
    return (~same).reshape(x.shape[0], -1).any(1)


def _woken(model, seed=11):
    g = torch.Generator().manual_seed(seed)
    with torch.no_grad():
        w = model.head_o[2].weight
        w.copy_(torch.randn(w.shape, generator=g) * 0.05)                          # zero-init residual: wake it so a change in the input can be seen at O's output
    return model


def clone_bank(src, dst, shard_fn=None, common_fn=None, partial=None):
    """A bank in ``dst`` that is INTERNALLY CONSISTENT (every sha256 recomputed) but differs from ``src`` where the callbacks say: ``shard_fn(arrays, header)`` and ``common_fn(common)`` return the new ones."""
    src, dst = Path(src), Path(dst)
    dst.mkdir(parents=True, exist_ok=True)
    man = json.loads((src / "bank.json").read_text(encoding="utf-8"))
    shards = []
    for s in man["shards"]:
        arrays, header = DG.load_shard(src / s["file"])
        if shard_fn:
            arrays, header = shard_fn(arrays, header)
        DG.save_shard(dst / s["file"], arrays, header)
        shards.append({**s, "file_sha256": DG.sha256_file(dst / s["file"]), "content_sha256": DG.content_sha256(arrays)})
    man["shards"] = shards
    if common_fn:
        man["common"] = common_fn(man["common"])
    if partial is not None:
        man["partial"] = partial
    with open(dst / "bank.json", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(man, sort_keys=True, indent=1, default=DG._jsonable) + "\n")
    return dst


def rename_clip(pos_name, new):
    def fn(arrays, header):
        header = copy.deepcopy(header)
        k0 = sorted(header["clips"], key=int)[0] if pos_name is None else pos_name
        header["clips"][k0] = new
        return arrays, header
    return fn


def gate_parts(pk, extra=(), out=None):
    """What ``main`` has in hand when it builds the swap and runs the gate: (a, cfg, model, opt, info, dag, J, wins, clips)."""
    a = TR.build_parser().parse_args(["--out", str(out or pk.init_out), *GATE_ARGV, *extra])
    cfg = TR.make_config(a)
    store, J, wins, clips, info = TR.build_data(a, cfg)
    info["ds_window_start"] = D.effective_window_start(cfg.hist, cfg.window_start)
    mu, sd = M.cons_stats(J)
    model = M.V8FMini(cfg, M.P10Prior.synthetic(a.seed), mu, sd)
    if a.init_ckpt:
        info["init_ckpt"] = TR.load_init_ckpt(a.init_ckpt, model, cfg, apply=False)
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=a.lr, weight_decay=a.wd)
    dag = TR.make_dagger(a, J, wins, clips, info)
    return a, cfg, model, opt, info, dag, J, wins, clips


def dvb(parts, **kw):
    a, cfg, model, opt, info, dag = parts[:6]
    return TR.declared_vs_built(a, cfg, model, opt, info, kw.get("enc"), kw.get("ego", TR.make_ego_perturb(a)), TR.LRSchedule(a.lr, a.warmup, 10), kw.get("dag", dag))


def probe_parts(pk, p=0.5, n=24, wm="b", seed=0, only=None, bank_arrays=None):
    """(model, a real collated batch of the trainer's own dataset, cfg, the swap) -- hmax 16 and the world-model auxiliary, so the exact-zero WM control is live."""
    J = pk.J
    store = D.ClipStore(pk.world, "train", lru=8, kin_mode="yaw", tracks=D.load_native_tracks(pk.world / "native_tracks.pt"))
    wins = D.train_windows(store, J, D.select_train_clips(list(map(str, J["clip"])), 1.0))
    ds = D.V8FMiniWindows(store, J, wins, hmax=16)
    bank = DG.DaggerBank.load(pk.bank, clip_names=J["clip"])
    if bank_arrays is not None:
        bank = DG.DaggerBank(bank_arrays(dict(bank.a)), bank.header, clip_names=J["clip"], manifest=bank.manifest, sha256=bank.sha256, path=bank.path)
    if only == "ineligible":
        wins = [w for w in wins if bank.candidates([w[0]], [w[1]])[0][0] == 0]
    idx = np.random.default_rng(seed).choice(len(wins), n, replace=False)
    batch = D.collate([ds.item(wins[i][0], wins[i][1], 1, 3) for i in idx])
    cfg = M.V8FMiniConfig(**{**TINY, "hmax": 16, "wm": wm})
    mu, sd = M.cons_stats(J)
    model = _woken(M.V8FMini(cfg, M.P10Prior.synthetic(0), mu, sd))
    return model, batch, cfg, DG.DaggerSwap(bank, p=p, seed=1, kin_mode="yaw")


