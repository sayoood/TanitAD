def test_HOP5_the_model_forward_feeds_the_banded_head_from_map_encoder_not_encoder():
    """The banded logits change when ONLY ``map_encoder``'s weights change, and do not when ONLY ``encoder``'s do (the planner BEV ``map_hires_bev`` is the reverse)."""
    model, cfg = _build(True)
    with torch.no_grad():
        _, o0 = _forward(model, cfg)
        for p in model._map_hires.encoder.parameters():
            p.add_(0.05)
        _, o1 = _forward(model, cfg)
        for p in model._map_hires.encoder.parameters():
            p.sub_(0.05)
        for p in model._map_hires.map_encoder.parameters():
            p.add_(0.05)
        _, o2 = _forward(model, cfg)
    z = lambda o: [v for k, v in _leaves(o["perception"]["map_banded"])]                              # noqa: E731
    assert all(torch.equal(a, b) for a, b in zip(z(o0), z(o1)))                                        # encoder -> banded logits: NO path
    assert any(not torch.equal(a, b) for a, b in zip(z(o0), z(o2)))                                    # map_encoder -> banded logits: a path
    bev = lambda o: o["perception"]["map_hires_bev"] if "map_hires_bev" in o["perception"] else None  # noqa: E731
    if bev(o0) is not None:
        assert not torch.equal(bev(o0), bev(o1)) and torch.equal(bev(o0), bev(o2))                     # the planner BEV is encoder's, never map_encoder's


