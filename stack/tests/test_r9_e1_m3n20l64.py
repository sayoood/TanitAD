def test_GRAD_every_map_encoder_parameter_gets_a_nonzero_gradient_and_the_control_reads_exactly_zero(monkeypatch):
    on, cfg = _build(True)
    names = _mk_names(on)
    assert len(names) == 3 + 2 * 6
    g = _grads(on, cfg, "map")
    dead = [n for n in names + ["_map_hires.refine.inp.0.weight"] if g[n] is None or float(g[n].abs().sum()) == 0.0]
    assert dead == [], dead                                                                           # NON-ZERO on every map_encoder parameter
    # mirror: the map loss never reaches the shared `encoder` (it feeds only the planner BEV / box / agents), nor the shared lift via encoder
    enc = [n for n in g if n.startswith("_map_hires.encoder.")]
    assert enc and all(g[n] is None or float(g[n].abs().sum()) == 0.0 for n in enc), "the banded loss reached `encoder`"
    assert float(g["_map_hires.lift.proj.weight"].abs().sum()) > 0.0                                   # ... but the lift is SHARED: the map reaches it through map_encoder
    # CONTROL: every cell unobserved, max-entropy off -> the SAME parameters read EXACTLY 0.0 (the probe works at all)
    monkeypatch.setattr(MB, "MAXENT_W", 0.0)
    real = MB.unobs_masks
    monkeypatch.setattr(MB, "unobs_masks", lambda v, gm: [torch.ones_like(m) for m in real(v, gm)])
    g0 = _grads(on, cfg, "map")
    assert [n for n in names + ["_map_hires.refine.inp.0.weight"] if g0[n] is not None and float(g0[n].abs().sum()) != 0.0] == []


