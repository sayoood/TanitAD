#!/usr/bin/env node
/*
  Deterministic renderer for hicap_explainer.html.

  The page exposes window.renderFrame(t) (pure function of t). This script steps t at FPS, screenshots
  each 1920x1080 frame (JPEG q92) into a scratch directory, and encodes with ffmpeg
  (libx264, yuv420p, crf 20, preset slow, +faststart).

  Usage (from the repo root or anywhere):
    node render_video.js --check                       # caption timing / line-count audit, no rendering
    node render_video.js --start 0 --end 20 --out /tmp/claude-0/streamV/test20.mp4
    node render_video.js                               # full video -> hicap_explainer.mp4 (next to this script)
    node render_video.js --stills                      # one PNG per chapter (1280 px) + poster frame
    node render_video.js --storyboard                  # writes storyboard.md from the page's chapter data
  Options: --fps 30  --workers 4  --frames <dir>  --crf 20  --keep (keep frames)
*/
const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');
const { spawnSync } = require('child_process');

const HERE = __dirname;
const PAGE = 'file://' + path.join(HERE, 'hicap_explainer.html') + '?render=1';
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const flag = k => args.includes('--' + k);
const FPS = +opt('fps', 30);
const WORKERS = +opt('workers', 4);
const FRAMES = opt('frames', '/tmp/claude-0/streamV/frames');
const CRF = opt('crf', '20');

async function openPage(browser) {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
  const errs = [];
  page.on('pageerror', e => errs.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto(PAGE);
  await page.waitForFunction(() => window.READY === true, null, { timeout: 30000 });
  page._errs = errs;
  return page;
}
const shot = async (page, t, file, type) => {
  await page.evaluate(tt => window.renderFrame(tt), t);
  if (page._errs.length) throw new Error('page error at t=' + t + ': ' + page._errs.join(' | '));
  await page.screenshot({ path: file, type, quality: type === 'jpeg' ? 92 : undefined, clip: { x: 0, y: 0, width: 1920, height: 1080 } });
};
function ff(argv) {
  const r = spawnSync('/usr/bin/ffmpeg', argv, { stdio: ['ignore', 'inherit', 'inherit'] });
  if (r.status !== 0) throw new Error('ffmpeg failed: ' + argv.join(' '));
}

async function main() {
  const browser = await chromium.launch();
  const page0 = await openPage(browser);
  const TOTAL = await page0.evaluate(() => window.TOTAL);
  const SB = await page0.evaluate(() => window.STORYBOARD);

  if (flag('check')) {
    const caps = await page0.evaluate(() => window.checkCaptions());
    let bad = 0;
    for (const c of caps) {
      const ok = c.lines === 1 && c.dur >= 2.5 * c.lines;
      if (!ok) bad++;
      console.log(`${ok ? 'ok ' : 'BAD'} ch${c.ch} ${c.t0.toFixed(1)}-${c.t1.toFixed(1)} dur ${c.dur}s lines ${c.lines} w ${c.width}px  ${c.text}`);
    }
    // overlap check
    SB.forEach(ch => ch.caps.forEach((c, i) => { if (i && c[0] < ch.caps[i - 1][1] - 1e-9) { bad++; console.log('BAD overlap ch' + ch.n); } if (c[1] > ch.dur + 1e-9) { bad++; console.log('BAD caption beyond chapter end ch' + ch.n); } }));
    console.log(`total ${TOTAL}s, ${caps.length} captions, ${bad} problems`);
    await browser.close(); process.exit(bad ? 1 : 0);
  }

  if (flag('storyboard')) {
    const mmss = s => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}${(s % 1) ? '.' + Math.round((s % 1) * 10) : ''}`;
    let md = `# HiCAP explainer — storyboard\n\nGenerated by \`render_video.js --storyboard\` from the chapter data inside \`hicap_explainer.html\` (the captions below are byte-identical to what is rendered).\n\n`;
    md += `- Length **${mmss(TOTAL)}** (${TOTAL} s), 1920×1080, ${FPS} fps, ${SB.length} chapters, ${SB.reduce((a, c) => a + c.caps.length, 0)} captions; every caption is one line and stays on screen ≥ 2.5 s (audited by \`--check\`).\n`;
    md += `- Colour key: blue + lock = frozen · orange + spark = trained · green dashed = cached once · dotted = optional · red = pruning, rules, safety · violet = imagination, audio · yellow = selection / output.\n`;
    md += `- A persistent mini-map (top right) highlights the component each chapter explains.\n`;
    md += `- Evidence: every number is quoted from \`Paper/HiCAP/*.tex\`, \`Paper/HiCAP/design/HICAP_V10_SPEC.md\` or \`stack/tanitad/hicap/\`; on-screen chips carry MEASURED / PUBLISHED / ESTIMATED. Bars, posteriors and selections without numbers are **illustrative** and are labelled so on screen. **Nothing has been trained**; where a result would go, the video says "not yet trained".\n\n`;
    md += `| # | chapter | start | length |\n|---|---|---|---|\n`;
    SB.forEach(c => { md += `| ${c.n} | ${c.title} | ${mmss(c.start)} | ${c.dur} s |\n`; });
    SB.forEach(c => {
      md += `\n## ${c.n}. ${c.title} — ${mmss(c.start)}–${mmss(c.start + c.dur)}\n\n`;
      md += `**Visual.** ${c.vis}\n\n**Mini-map highlight.** ${c.map.join(', ')}\n\n**Sources.** ${c.src}\n\n**Captions (absolute time · exact text):**\n\n`;
      c.caps.forEach(k => { md += `- \`${mmss(c.start + k[0])}–${mmss(c.start + k[1])}\` ${k[2]}\n`; });
    });
    fs.writeFileSync(path.join(HERE, 'storyboard.md'), md);
    console.log('wrote storyboard.md');
    await browser.close(); return;
  }

  if (flag('stills')) {
    const dir = path.join(HERE, 'stills'); fs.mkdirSync(dir, { recursive: true });
    const tmp = path.join(FRAMES, '..', 'stills_tmp'); fs.mkdirSync(tmp, { recursive: true });
    const still = { 1: 14.4, 2: 23.4, 3: 23.4, 4: 19.4, 5: 19.4, 6: 27.4, 7: 25.4, 8: 19.4, 9: 27.4, 10: 25.4, 11: 17.4, 12: 25.4, 13: 14.6 };
    for (const c of SB) {
      const t = c.start + (still[c.n] ?? c.dur - 0.6);
      const raw = path.join(tmp, `ch${c.n}.png`);
      await shot(page0, t, raw, 'png');
      const slug = c.title.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
      ff(['-y', '-loglevel', 'error', '-i', raw, '-vf', 'scale=1280:-1:flags=lanczos', path.join(dir, `ch${String(c.n).padStart(2, '0')}_${slug}.png`)]);
      console.log('still', c.n, t.toFixed(1));
    }
    const pt = SB[5].start + 27.4;   // chapter 6, fully built hierarchy
    await shot(page0, pt, path.join(HERE, 'hicap_explainer_poster_frame.png'), 'png');
    console.log('poster frame at', pt);
    await browser.close(); return;
  }

  const t0 = +opt('start', 0), t1 = Math.min(+opt('end', TOTAL), TOTAL);
  const out = opt('out', path.join(HERE, 'hicap_explainer.mp4'));
  fs.rmSync(FRAMES, { recursive: true, force: true }); fs.mkdirSync(FRAMES, { recursive: true });
  const n = Math.round((t1 - t0) * FPS);
  const pages = [page0]; for (let i = 1; i < WORKERS; i++) pages.push(await openPage(browser));
  let done = 0; const tStart = Date.now();
  await Promise.all(pages.map(async (pg, w) => {
    for (let f = w; f < n; f += WORKERS) {
      await shot(pg, t0 + f / FPS, path.join(FRAMES, `f${String(f).padStart(5, '0')}.jpg`), 'jpeg');
      if (++done % 300 === 0) console.log(`${done}/${n} frames, ${((Date.now() - tStart) / 1000).toFixed(0)} s`);
    }
  }));
  await browser.close();
  console.log(`rendered ${n} frames in ${((Date.now() - tStart) / 1000).toFixed(0)} s; encoding`);
  ff(['-y', '-loglevel', 'error', '-framerate', String(FPS), '-i', path.join(FRAMES, 'f%05d.jpg'),
      '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', CRF, '-preset', 'slow', '-movflags', '+faststart', '-r', String(FPS), out]);
  console.log('wrote', out, (fs.statSync(out).size / 1e6).toFixed(1), 'MB');
  if (!flag('keep')) fs.rmSync(FRAMES, { recursive: true, force: true });
}
main().catch(e => { console.error(e); process.exit(1); });
